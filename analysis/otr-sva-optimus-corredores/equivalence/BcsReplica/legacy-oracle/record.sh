#!/usr/bin/env bash
# BcsReplica oracle (step 1 of modernize-transform): records the goldens of cases/ by executing the legacy cl.bcs.replica classes (EnviarTablaReplica, ReplicaUtils, IniciarReplicaFull,
# IniciarReplicaDelta, IniciarReplica) with their real helpers on H2 in memory: no HANA, no network, no credential, no .env. legacy/ is only READ; everything is compiled into a TEMPORARY
# directory (nothing is copied into legacy/ or modernized/).
#  - REAL (unmodified): ReplicaUtils, IniciarReplica; BcsUtils SQL, NamedParameterStatement, NamedCallableStatement, JavaCall, JavaCallMetadata, Gson*Deserializer, Fecha, BcsPojo;
#    Plataforma PlataformaUtils (MensajeSalida), Diccionario, FileLoader, BarraProgreso.
#  - COPIES with ONE edit, the wall clock: EnviarTablaReplica (LocalDateTime.now() -> cl.bcs.oracle.Clock.now(): the original stamps ResumenReplica.UltimaActualizacion with the real time) and
#    IniciarReplicaFull / IniciarReplicaDelta (System.currentTimeMillis() -> cl.bcs.oracle.Clock.millis(): the original stamps the WorkStack row with the real time). The script FAILS if a copy
#    differs from the legacy file in anything else (same precedent as the FechaDB copy of the FondoMutuo oracle).
#  - REGISTERED DOUBLES (collaborators outside the module): ObtenerDiaSiguiente and ConsultarEmpresa generated from the real sources by tools/gen_doubles.py (every declaration of the original,
#    bodies answered by the case), ConfiguracionSistema and Feriados written by hand with the real static signatures, the Utils shim generated by tools/gen_utils.py (verbatim printJson /
#    getGsonBuilder ...; getSecuencia and getFechaSistema scripted). Every call is recorded; an unscripted call fails loudly.
#  - the JDBC connection is the recording proxy harness/.../ConexionRegistradora.java (the SAME source file the JUnit tests use): it records every SQL sent and runs it on H2 after a mechanical
#    dialect translation; CREATE/DROP TRIGGER and the table functions with PLACEHOLDER are recorded as NO_EJECUTABLE_H2 (see ORACLE_NOTES.md).
#  - -Doracle.repeat=N (default 20, ORACLE_REPEAT): every case runs N times in fresh H2 databases and the dumps are compared; an unstable case is listed in $ORACLE_REPORT and gets NO golden (exit 4).
#   ./record.sh [caseNamePrefix]        e.g. ./record.sh REP-ENV   or   ./record.sh REP-ENV-001
# Knobs: ORACLE_WORK (scratch dir), ORACLE_SKIP_COMPILE=1, ORACLE_REPEAT, ORACLE_CASES, ORACLE_REPORT, JAVA_HOME, M2_REPO, PYTHON_CMD.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BASE="$(cd "$HERE/.." && pwd)"
WS="$(cd "$BASE/../../../.." && pwd)"
LEG="$WS/legacy/otr-sva-optimus-corredores/BSCL"
JH="${JAVA_HOME:-/c/Program Files/Eclipse Adoptium/jdk-25.0.4.101-hotspot}"
M2="${M2_REPO:-$HOME/.m2/repository}"
WORK="${ORACLE_WORK:-$(mktemp -d)}"
PY="${PYTHON_CMD:-py -3}"

SEP=":"; case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) SEP=";";; esac
mx() { if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else echo "$1"; fi; }
CP=""
for j in "com/h2database/h2/2.4.240/h2-2.4.240.jar" "com/google/code/gson/gson/2.13.2/gson-2.13.2.jar" \
         "commons-io/commons-io/2.11.0/commons-io-2.11.0.jar" "commons-beanutils/commons-beanutils/1.9.4/commons-beanutils-1.9.4.jar" \
         "commons-collections/commons-collections/3.2.2/commons-collections-3.2.2.jar" "commons-logging/commons-logging/1.2/commons-logging-1.2.jar" \
         "commons-lang/commons-lang/2.6/commons-lang-2.6.jar" "commons-configuration/commons-configuration/1.2/commons-configuration-1.2.jar" \
         "org/apache/logging/log4j/log4j-api/2.24.3/log4j-api-2.24.3.jar"; do
  [ -f "$M2/$j" ] || { echo "missing jar $M2/$j" >&2; exit 3; }
  CP="${CP:+$CP$SEP}$(mx "$M2/$j")"
done

REP="$LEG/Replica/JAVA/BcsReplica/src"; REPP="$REP/cl/bcs/replica"
PLS="$LEG/Plataforma/JAVA/BcsPlataformaServicios/src"; PLP="$PLS/cl/bcs/plataforma"
UT="$LEG/Plataforma/JAVA/BcsUtils/src/cl/bcs/utils"

echo "== generating the clock copies, the Utils shim and the doubles into $WORK/gen"
rm -rf "$WORK/gen"; mkdir -p "$WORK/gen/cl/bcs/replica" "$WORK/classes" "$WORK/run"
patch_clock() {  # $1 file  $2 from  $3 to
  sed "s/$2/$3/g" "$REPP/$1" > "$WORK/gen/cl/bcs/replica/$1"
  local d; d=$(diff <(tr -d '\r' < "$REPP/$1") <(tr -d '\r' < "$WORK/gen/cl/bcs/replica/$1") | grep -c '^>' || true)
  local want; want=$(grep -c "$2" "$REPP/$1" || true)
  [ "$d" = "$want" ] && [ "$want" -ge 1 ] || { echo "the clock copy of $1 differs from the legacy in $d lines (expected $want)" >&2; exit 5; }
}
patch_clock EnviarTablaReplica.java 'LocalDateTime\.now()' 'cl.bcs.oracle.Clock.now()'
patch_clock IniciarReplicaFull.java 'System\.currentTimeMillis()' 'cl.bcs.oracle.Clock.millis()'
patch_clock IniciarReplicaDelta.java 'System\.currentTimeMillis()' 'cl.bcs.oracle.Clock.millis()'
$PY -I "$HERE/tools/gen_utils.py" "$(mx "$UT/Utils.java")" "$(mx "$WORK/gen")"
$PY -I "$HERE/tools/gen_doubles.py" "$(mx "$WORK/gen")" "$(mx "$PLP/pla/ObtenerDiaSiguiente.java")" "$(mx "$PLP/pla/utils/ConsultarEmpresa.java")"

SRC=("$REPP/ReplicaUtils.java" "$REPP/IniciarReplica.java")
for c in SQL NamedParameterStatement NamedCallableStatement JavaCall JavaCallMetadata GsonTimestampDeserializer GsonDateDeserializer Fecha BcsPojo; do SRC+=("$UT/$c.java"); done
for c in pla/utils/PlataformaUtils pla/utils/Diccionario pla/utils/FileLoader pla/utils/BarraProgreso; do SRC+=("$PLP/$c.java"); done
: > "$WORK/sources.txt"
for f in "${SRC[@]}"; do echo "\"$(mx "$f")\"" >> "$WORK/sources.txt"; done
find "$WORK/gen" -name '*.java' | while read -r f; do echo "\"$(mx "$f")\"" >> "$WORK/sources.txt"; done
find "$HERE/shims" "$HERE/shims-replica" "$HERE/runner" "$HERE/harness" -name '*.java' | while read -r f; do echo "\"$(mx "$f")\"" >> "$WORK/sources.txt"; done

if [ -z "${ORACLE_SKIP_COMPILE:-}" ]; then
echo "== compiling oracle into $WORK/classes (release 11)"
rm -rf "$WORK/classes"; mkdir -p "$WORK/classes"
"$JH/bin/javac" --release 11 -encoding UTF-8 -proc:none -nowarn -Xlint:none -Xmaxerrs 200 -d "$(mx "$WORK/classes")" -cp "$CP" @"$(mx "$WORK/sources.txt")"
fi

echo "== running"
cd "$WORK/run"
REPORT="${ORACLE_REPORT:-$BASE/determinism.txt}"
OPTS=( "-Duser.timezone=UTC" "-Dfile.encoding=UTF-8" "-Duser.language=en" "-Dlog4j2.StatusLogger.level=OFF" "-Dlog4j2.statusLoggerLevel=OFF" "-Dorg.apache.logging.log4j.simplelog.level=OFF"
       "-Doracle.repeat=${ORACLE_REPEAT:-20}" "-Doracle.report=$(mx "$REPORT")" "-Doracle.cases=$(mx "${ORACLE_CASES:-$BASE/cases}")" )
RUNCP="$(mx "$WORK/classes")$SEP$CP$SEP$(mx "$REP")"
"$JH/bin/java" "${OPTS[@]}" ${JAVA_OPTS:-} -cp "$RUNCP" OracleRunnerReplica "$(mx "$BASE")" "${1:-}"
