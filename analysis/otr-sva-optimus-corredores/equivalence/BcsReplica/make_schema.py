#!/usr/bin/env python3
"""BcsReplica oracle: writes schema-replica.sql (H2) from the REAL HANA QA catalog exported by tools/HanaCatalogoReplica.java (catalog/replica_*.csv, read-only SELECT on SYS views).

  py -3 -I make_schema.py

Real: the 20 tables the Replica SQL writes or reads (columns, types, NOT NULL, defaults, primary keys, the identity of WorkStack.IdStack).
Assumed (stated in ORACLE_NOTES.md): the 4 analytic views that feed the Historica inserts (table functions with PLACEHOLDER in HANA) are tables with the columns of the table they feed, seeded by the case; the 13 Sebra source views `BSCL.Replica.BD.Vistas::Sebra.TBC*` are modelled as plain tables with the columns of the target table (the catalog
shows, for 3 of them (TBCTCIRV, TBCTGTIA, TBCPMSPC), that the view has every column of the target plus extra ones: IdPortafolio, Tipo); the other Replica/Plataforma/Custodia/CuentaInversion views and procedures are not modelled (their statements are NO_EJECUTABLE_H2).
HANA CHAR(n)/NVARCHAR(n) become VARCHAR(n); SECONDDATE becomes TIMESTAMP(0).
"""
import csv
import pathlib

BASE = pathlib.Path(__file__).resolve().parent
CAT = BASE / "catalog"

SEBRA = ["TBCTCIRV", "TBCTCURV", "TBCTCIRF", "TBCTCURF", "TBCTCIIF", "TBCTCTCL", "TBCTTRTP", "TBCTCIFM", "TBCTCUFM", "TBCPMSPC", "TBCPDTPC", "TBCTGTIA", "TBCTTRPT"]


VISTAS_ANALITICAS = {
    "BSCL.CuentaInversion.BD.Vistas::ConsultarSaldoCuentaInversionFechaEfectivaAnalitica": "BSCL.CuentaInversion.BD::CTA.SaldoFechaEfectiva",
    "BSCL.CuentaInversion.BD.Vistas::ConsultarSaldoCuentaInversionFechaMovimientoAnalitica": "BSCL.CuentaInversion.BD::CTA.SaldoFechaMovimiento",
    "BSCL.Custodia.BD.Vistas::CUS.ConsultarCustodiaFechaOperacionAnalitica": "BSCL.Custodia.BD::HIS.CustodiaFechaOperacion",
    "BSCL.Custodia.BD.Vistas::CUS.ConsultarCustodiaFechaLiquidacionAnalitica": "BSCL.Custodia.BD::HIS.CustodiaFechaLiquidacion",
}


def tipo(t, largo, escala):
    t = t.upper()
    if t in ("NVARCHAR", "VARCHAR", "CHAR"):
        return "VARCHAR(%s)" % largo
    if t == "DECIMAL":
        return "DECIMAL(%s, %s)" % (largo, escala or 0)
    if t == "SECONDDATE":
        return "TIMESTAMP(0)"
    if t == "TIMESTAMP":
        return "TIMESTAMP"
    if t in ("BIGINT", "INTEGER", "TINYINT", "DOUBLE", "DATE"):
        return t
    raise ValueError("type not mapped: " + t)


def leer(nombre):
    with open(CAT / nombre, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def main():
    columnas = {}
    for r in leer("replica_columnas_tablas.csv"):
        columnas.setdefault(r["TABLE_NAME"], []).append(r)
    claves = {}
    for r in leer("replica_claves.csv"):
        claves.setdefault(r["TABLE_NAME"], []).append((int(r["POSITION"]), r["COLUMN_NAME"]))
    vistas = {}
    for r in leer("replica_columnas_vistas.csv"):
        vistas.setdefault(r["VIEW_NAME"], []).append(r["COLUMN_NAME"])
    for v, cols in vistas.items():
        destino = v.replace("BD.Vistas::Sebra.", "BD::")
        assert set(c["COLUMN_NAME"] for c in columnas[destino]) <= set(cols), "Sebra view %s lacks a column of its target table" % v

    out = ["-- BcsReplica oracle and tests: H2 schema generated by make_schema.py from catalog/replica_*.csv (real HANA QA catalog). Do not edit by hand.",
           "CREATE SCHEMA IF NOT EXISTS BSCL;", "SET SCHEMA BSCL;", ""]

    def tabla(nombre, cols, pk, origen):
        lineas = []
        for c in cols:
            ddl = '    "%s" %s' % (c["COLUMN_NAME"], tipo(c["DATA_TYPE_NAME"], c["LENGTH"], c["SCALE"]))
            if c.get("GENERATION_TYPE") == "BY DEFAULT AS IDENTITY":
                ddl += " GENERATED BY DEFAULT AS IDENTITY"
            if c["DEFAULT_VALUE"]:
                d = c["DEFAULT_VALUE"]
                ddl += " DEFAULT " + (d if d.upper().startswith("CURRENT") or d.lstrip("-").isdigit() else "'%s'" % d)
            if c["IS_NULLABLE"] == "FALSE":
                ddl += " NOT NULL"
            lineas.append(ddl)
        if pk:
            lineas.append("    PRIMARY KEY (%s)" % ", ".join('"%s"' % x for _, x in sorted(pk)))
        out.append("-- %s" % origen)
        out.append('CREATE TABLE "%s" (' % nombre)
        out.append(",\n".join(lineas))
        out.append(");")
        out.append("")

    for nombre in sorted(columnas):
        tabla(nombre, columnas[nombre], claves.get(nombre), "HANA QA catalog")
    for t in SEBRA:
        destino = "BSCL.Replica.BD::" + t
        cols = [dict(c, IS_NULLABLE="TRUE", DEFAULT_VALUE="", GENERATION_TYPE="") for c in columnas[destino]]
        tabla("BSCL.Replica.BD.Vistas::Sebra." + t, cols, None, "ASSUMED: Sebra view modelled as a table with the columns of its target")
    for vista, destino in VISTAS_ANALITICAS.items():
        cols = [dict(c, IS_NULLABLE="TRUE", DEFAULT_VALUE="", GENERATION_TYPE="") for c in columnas[destino]]
        tabla(vista, cols, None, "ASSUMED: analytic view (a table function with PLACEHOLDER in HANA) modelled as a table with the columns of the table it feeds; the case seeds its rows")
    (BASE / "schema-replica.sql").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("schema-replica.sql:", len(columnas), "real tables +", len(SEBRA), "Sebra stand-ins +", len(VISTAS_ANALITICAS), "analytic view stand-ins")


if __name__ == "__main__":
    main()
