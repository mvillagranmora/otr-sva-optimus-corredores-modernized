#!/usr/bin/env python3
"""COPY of BcsFondoMutuoServicios/legacy-oracle/tools/gen_utils.py (unchanged logic) for the Custodia ConsultarFlujoCustodia oracle.

Generates the oracle shim cl.bcs.utils.Utils FROM the real legacy BcsUtils Utils.java (never edits legacy/).

The real Utils pulls json/jackson/guava/commons-codec/cl.bcs.nuam (not available here), so the oracle compiles a reduced class holding
VERBATIM copies of the methods the closure uses: printJson, List2Hash, getColumn, copyPojo (2), getGsonBuilder, the Secuencia holder.
Only getSecuencia is replaced (HANA SERIES_GENERATE_BIGINT does not exist in H2): same contract (List<Long> of `cantidad` values taken from the
sequence `nombreSecuencia`), implemented with the H2 sequence of the same name, and the request is recorded for the dump.

  py -3 -I gen_utils.py <legacy Utils.java> <outDir>
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_doubles import mask, match   # noqa: E402

COPY = ["printJson", "List2Hash", "getColumn", "copyPojo", "getGsonBuilder"]

HEAD = """package cl.bcs.utils;

import java.lang.reflect.Field;
import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;

/** ORACLE SHIM generated by gen_utils.py from the real Utils.java: verbatim methods + an H2 getSecuencia (see gen_utils.py). */
public class Utils {

    public static class Secuencia {
        public Long Id;
    }

    /** Same contract as the legacy getSecuencia; H2 sequences of the same (quoted) name replace SERIES_GENERATE_BIGINT. */
    public static List<Long> getSecuencia(Connection conn, String nombreSecuencia, Long cantidad) throws SQLException {
        List<Long> salida = new ArrayList<>();
        if (cantidad == null || cantidad <= 0) {
            return salida;
        }
        cl.bcs.oracle.Doubles.registrarSecuencia(nombreSecuencia, cantidad);
        for (long k = 0; k < cantidad; k++) {
            try (Statement st = conn.createStatement(); ResultSet rs = st.executeQuery("SELECT NEXT VALUE FOR \\"" + nombreSecuencia + "\\"")) {
                rs.next();
                salida.add(rs.getLong(1));
            }
        }
        return salida;
    }
"""


def main():
    src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    m = mask(src)
    parts = []
    for name in COPY:
        for mm in re.finditer(r"public\s+static\s+(<[^>]*>\s*)?[\w<>\[\],? ]+\s+" + name + r"\s*\(", m):
            ob = m.index("{", mm.end())
            cb = match(m, ob)
            ls = m.rfind("\n", 0, mm.start()) + 1
            # keep the @Deprecated / @SuppressWarnings lines right above the signature
            while True:
                prev = src[:ls].rstrip("\n")
                pl = prev[prev.rfind("\n") + 1:]
                if pl.strip().startswith("@"):
                    ls = prev.rfind("\n") + 1
                else:
                    break
            parts.append(src[ls:cb + 1])
    out = HEAD + "\n" + "\n\n".join(parts) + "\n}\n"
    d = os.path.join(sys.argv[2], "cl", "bcs", "utils")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "Utils.java"), "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("Utils shim:", len(parts), "methods copied verbatim")


if __name__ == "__main__":
    main()
