"""Helpers of the F3 W2 cases of CargarValorCuota (CVC, registry id 3035, the ONLY class of the wave and the only UI class that WRITES): case directories
cases-cvc/FMM-CVC-nnn_slug.

The case INPUTS (case.json, seed.sql), schema-cvc.sql and seed/base-cvc.sql are written here; the goldens (expected.json) are RECORDED by legacy-oracle/record_cvc.sh from
the UNMODIFIED legacy CargarValorCuota, never by this script. The cases live in their OWN directory (cases-cvc/, passed with -Doracle.cases): no other record script can run
them or touch their goldens.

What the oracle runs REAL: CargarValorCuota, RevisarRequisitosBasicos, ObtenerDiaAnterior (against REG.DiaFeriado), ConfiguracionSistema, Diccionario, MensajeSalida, SQL /
NamedParameterStatement (the real batch binder: BigDecimal -> scale 16 HALF_DOWN), Fecha, and the 8 SQL files of the class. What is a REGISTERED DOUBLE: Plataforma AgregarLog
(its legacy write part is inside try/catch(Exception){printStackTrace}, AgregarLog.java:239-241: the double models that swallow, see tools-cvc/tragar_agregarlog.py) and
ConsultarEmpresa (kit import, never called).

schema-cvc.sql (H2 STAND-INS, never run against HANA): FMM.ValorCuota is DROPPED and recreated with ALL the columns of the catalog (hana_qa_results/fmm_columnas_tablas.csv: REAL)
and WITH its real PRIMARY KEY (IdSerieFondo): one row per serie; FMM.ValorCuotaHistorico, the view and the sequence were verified against HANA QA (types, PKs, NOT NULL); only the view DEFINITION is assumed. Faults are injected by the case seed (CHECK constraints on the stand-in tables) to pin a failure in a given step of the write sequence.
"""
