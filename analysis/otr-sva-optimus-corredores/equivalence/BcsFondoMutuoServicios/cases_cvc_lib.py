def vc(serie="FM001A", fecha="2026-03-02", valor=1500.5, moneda="CLP", obs="Carga de prueba", msg="OK", isin=ABSENT, calculo=ABSENT, registro=ABSENT):
    """One element of p_ValorCuota. A value ABSENT omits the key (the pojo default applies), None writes an explicit null."""
    d = {"IDSERIEFONDO": serie, "FECHACIERRE": fecha, "VALORCUOTA": valor, "IDMONEDA": moneda, "OBSERVACION": obs, "MENSAJEVALIDACION": msg}
    if isin is not ABSENT:
        d["ISIN"] = isin
    if calculo is not ABSENT:
        d["FECHACALCULO"] = calculo
    if registro is not ABSENT:
        d["REGISTRO"] = registro
    return {k: v for k, v in d.items() if v is not ABSENT}


def sin(fila, *claves):
    return {k: v for k, v in fila.items() if k not in claves}


def entrada(filas, sim="N", todos="N", **campos):
    """Request. sim / todos: ABSENT omits p_SimularOperacion / p_AllFunds. Extra keyword fields replace or (with ABSENT) remove the standard ones."""
    d = {"p_IdEmpresa": 1, "p_IdUsuario": 7, "p_IdModulo": "FMM", "p_UsaReglasNegocio": "N", "p_SimularOperacion": sim, "p_AllFunds": todos, "p_ValorCuota": filas}
    for k, v in campos.items():
        d[k] = v
    return {k: v for k, v in d.items() if v is not ABSENT}


def caso(slug, ref, ent, seed=(), colaboradores=None, previas=None, **extra):
    """Writes cases-cvc/FMM-CVC-nnn_slug and returns the id. `ref` lists the cards (FM-CVC-nn) and defects (D-F3A-nn) the case pins. `previas` = requests executed BEFORE
    `ent` in the same H2 session, each with its own commit / rollback decision (a repeated load)."""
    _n["n"] += 1
    cid = "FMM-CVC-%03d_%s" % (_n["n"], slug)
    doc = {"servicio": SERVICIO, "ref": list(ref), "esquemasExtra": ["schema-cvc.sql", "seed/base-cvc.sql"], "entrada": ent, "tablas": TABLAS}
    if previas:
        doc["entradasPrevias"] = list(previas)
    doc.update(extra)
    if colaboradores:
        doc["colaboradores"] = colaboradores
    d = CASES / cid
    d.mkdir(parents=True, exist_ok=True)
    (d / "case.json").write_text(dumps(doc), encoding="utf-8", newline="\n")
    texto = "-- case seed on top of seed/base-fmm.sql + schema-cvc.sql + seed/base-cvc.sql (fake data)\n" + ("\n".join(seed) if seed else "SELECT 1;") + "\n"
    (d / "seed.sql").write_text(texto, encoding="utf-8", newline="\n")
    return cid


def config(codigo, valor, empresa=1):
    """Replaces a PLATAFORMA parameter (valor None deletes it)."""
    s = ['DELETE FROM %s WHERE "IdEmpresa" = %d AND "CodigoParametro" = %s;' % (CONFIG, empresa, q(codigo))]
    if valor is not None:
        s.append('INSERT INTO %s ("IdEmpresa", "CodigoParametro", "Valor") VALUES (%d, %s, %s);' % (CONFIG, empresa, q(codigo), q(valor)))
    return s


def historico(id_, serie="FM001A", fecha="2026-03-01", valor=100, ultima="S", empresa=1, moneda="CLP", obs="previa", carga="2026-03-01"):
    """A row of FMM.ValorCuotaHistorico (id < 1000)."""
    return ins(VCH, IdValorCuotaHistorico=id_, IdSerieFondo=serie, FechaCierre=fecha, ValorCuota=valor, IdMoneda=moneda, Observacion=obs, FechaCarga=carga,
               FechaIngresoRegistro="@TIMESTAMP '2026-02-20 10:00:00'", EsUltimaCargaDiaria=ultima, IdEmpresa=empresa)


def vigente(serie="FM001A", fecha="2026-03-01", valor=100, empresa=1, moneda="CLP", obs="previa", carga="2026-03-01"):
    """A row of FMM.ValorCuota (the table of the vigente value)."""
    return ins(VC, IdSerieFondo=serie, FechaCierre=fecha, ValorCuota=valor, IdMoneda=moneda, FechaCarga=carga, FechaIngresoRegistro="@TIMESTAMP '2026-02-20 10:00:00'",
               IdEmpresa=empresa, Observacion=obs)


def falla_en(tabla, condicion_valida):
    """Injected fault: a CHECK that the statement of one step of the write sequence violates (the seed of the case, never part of the schema)."""
    return 'ALTER TABLE "%s" ADD CONSTRAINT "FALLA_INYECTADA" CHECK (%s);' % (tabla, condicion_valida)


def log_cae(texto="log caido"):
    """AgregarLog double that fails: the legacy swallows it (catch + printStackTrace)."""
    return {"AgregarLog": {"respuestas": [{"error": texto}]}}
