"""Helpers of the F3 W1 front 2 cases (ConsultarFondoMutuoReinversion, read only): case directories cases-fmr/FMM-FMR-nn_slug.

Inputs only (case.json, seed.sql) and seed/base-fmr.sql; the goldens are RECORDED by legacy-oracle/record_fmr.sh from the unmodified legacy.
FAKE universe (see cases_lect_lib.SERIES): 12 series on top of FM001A (fund 10, CLP, issuer AGF1, regime GEN):
  S001 fund 61 AGF1 CLP FAM1 regimes 18Q+18T, quota 1234.5678      S002 fund 61 (same fund) regime 18Q only, quota 987.65, min 2500
  S003 AGF2 FAM2 regime 57BIS, NO quota row                        S004 foreign USD EXT1 FAM3 regimes 18Q+18T, quota 10.5
  S005 fund with BloqueoAporte S (IFM only)                        S006 RestringeAporte S (IFM only)       S007 IdEstado INA
  S008 FondoExtranjero 'X', AGF3, OWP/APV S, regime 18T            S009 regimes 18Q INA + GEN ACT          S010 no regime at all
  S011 company 2 (fund, series and regime row)                     S012 USD AGF2, regime NINGUNO
Regimes: 18Q (RescateConMandato S), 18T (AceptaMandatoEnReinversion S), 57BIS, NINGUNO, GEN (N / '').
"""
import pathlib
import sys

BASE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(BASE))
import cases_lect_lib as L  # noqa: E402
from cases_lect_lib import *  # noqa: F401,F403,E402

CASES = BASE / "cases-fmr"
ESQUEMA = "seed/base-fmr.sql"
TABLAS = [
    {"nombre": "BSCL.FondoMutuo.BD::FMM.ValorCuota", "orden": "\"IdSerieFondo\""},
    {"nombre": "BSCL.FondoMutuo.BD::FMM.RegimenSerieDeFondo", "orden": "\"IdSerieFondo\", \"IdRegimenFondoMutuo\""},
]
_n = {"n": 0}


def base_fmr():
    s = ["-- GENERATED by make_cases_fmr.py (cases_fmr_lib.base_fmr). FAKE universe of the FMM-FMR cases, on top of seed/base-fmm.sql."]
    s += L.DDL
    s += L.universo_series()
    return "\n".join(s) + "\n"


def entrada(estado="ACT", moneda="-", extranjero="-", familia="-", emisor="-", regimen="-", origen="-", empresa=1, usuario=7, modulo="FMM", **extra):
    d = {"p_IdEmpresa": empresa, "p_IdUsuario": usuario, "p_IdModulo": modulo, "p_IdEstado": estado, "p_IdMoneda": moneda, "p_FondoExtranjero": extranjero,
         "p_IdFamiliaFondo": familia, "p_IdEmisor": emisor, "p_IdRegimenFondoMutuo": regimen, "p_IdSerieFondoOrigen": origen}
    d.update(extra)
    return d


def caso(slug, ref, ent, seed=None, **cab):
    return L.escribir_caso(CASES, "FMM-FMR", _n, "ConsultarFondoMutuoReinversion", ESQUEMA, slug, ref, ent, seed=seed, tablas=TABLAS, **cab)
