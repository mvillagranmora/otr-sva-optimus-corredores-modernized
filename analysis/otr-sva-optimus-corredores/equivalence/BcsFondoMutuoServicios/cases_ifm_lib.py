"""Helpers of the F3 W1 front 3 cases (ConsultarInstrumentosFondosMutuos, read only): case directories cases-ifm/FMM-IFM-nn_slug.

Inputs only (case.json, seed.sql) and seed/base-ifm.sql; the goldens are RECORDED by legacy-oracle/record_ifm.sh from the unmodified legacy.
Same FAKE universe as FMR (cases_lect_lib.SERIES: S001..S012 on top of FM001A) plus the dictionary text UI_SIN_VALORES. See cases_fmr_lib for the table of series.
Reinversion origins worth remembering: S001 (regimes 18Q+18T; config 18Q->18T, 18T->57BIS, GEN->18Q), FM001A (GEN), S012 (NINGUNO), S010 (no regime).
"""
import pathlib
import sys

BASE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(BASE))
import cases_lect_lib as L  # noqa: E402
from cases_lect_lib import *  # noqa: F401,F403,E402

CASES = BASE / "cases-ifm"
ESQUEMA = "seed/base-ifm.sql"
TABLAS = [
    {"nombre": "BSCL.FondoMutuo.BD::FMM.ValorCuota", "orden": "\"IdSerieFondo\""},
    {"nombre": "BSCL.FondoMutuo.BD::FMM.RegimenSerieDeFondo", "orden": "\"IdSerieFondo\", \"IdRegimenFondoMutuo\""},
]
_n = {"n": 0}


def base_ifm():
    s = ["-- GENERATED by make_cases_ifm.py (cases_ifm_lib.base_ifm). FAKE universe of the FMM-IFM cases, on top of seed/base-fmm.sql."]
    s += L.DDL
    s += L.universo_series()
    s.append(insert(DICC, {"CodLenguaje": "es", "CodDiccionario": "UI_SIN_VALORES", "Descripcion": "No se ingresaron valores de busqueda"}))
    return "\n".join(s) + "\n"


def ef(**kw):
    """p_EntradaFondosMutuos with ONLY the given keys (the legacy InFondos constructor defaults the rest)."""
    return dict(kw)


def entrada(fondos="__default__", empresa=1, usuario=7, modulo="FMM", **extra):
    d = {"p_IdEmpresa": empresa, "p_IdUsuario": usuario, "p_IdModulo": modulo}
    if fondos != "__ausente__":
        d["p_EntradaFondosMutuos"] = {} if fondos == "__default__" else fondos
    d.update(extra)
    return d


def caso(slug, ref, ent, seed=None, **cab):
    return L.escribir_caso(CASES, "FMM-IFM", _n, "ConsultarInstrumentosFondosMutuos", ESQUEMA, slug, ref, ent, seed=seed, tablas=TABLAS, **cab)
