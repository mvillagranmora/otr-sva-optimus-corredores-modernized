"""F3 W2 (CargarValorCuota): copies, byte for byte, the FMM-CVC cases (case.json, seed.sql, expected.json recorded by record_cvc.sh), schema-cvc.sql, seed/base-cvc.sql and the
determinism report into the module test resources src/test/resources/fondomutuo-cvc/, and WRITES (derived from the goldens, never by hand) the index of literals
src/test/java/cl/bcs/fondomutuo/valorcuota/CvcTablasLiterales.java that CvcReglasTest checks rule by rule. A case without golden is NOT copied (the module test would fail).
Nothing under legacy/ or src/main is touched.

  py -3 -I legacy-oracle/sync_cvc.py
"""
import json
import pathlib
import shutil

HERE = pathlib.Path(__file__).resolve().parent
BASE = HERE.parent
WS = BASE.parents[3]
MOD = WS / "modernized" / "otr-sva-optimus-corredores" / "BcsFondoMutuoServicios"
DEST = MOD / "src" / "test" / "resources" / "fondomutuo-cvc"
LITERALES = MOD / "src" / "test" / "java" / "cl" / "bcs" / "fondomutuo" / "valorcuota" / "CvcTablasLiterales.java"


def main():
    (DEST / "cases").mkdir(parents=True, exist_ok=True)
    (DEST / "seed").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(BASE / "schema-cvc.sql", DEST / "schema-cvc.sql")
    shutil.copyfile(BASE / "seed" / "base-cvc.sql", DEST / "seed" / "base-cvc.sql")
    if (BASE / "determinism-cvc.txt").exists():
        shutil.copyfile(BASE / "determinism-cvc.txt", DEST / "determinism-cvc.txt")
    for old in (DEST / "cases").iterdir():
        if old.is_dir():
            shutil.rmtree(old)
    n = 0
    filas, excepciones = [], []
    for d in sorted((BASE / "cases-cvc").glob("FMM-CVC-*")):
        if not (d / "expected.json").exists():
            print("no golden, skipped:", d.name)
            continue
        t = DEST / "cases" / d.name
        t.mkdir()
        for f in ("case.json", "seed.sql", "expected.json"):
            if (d / f).exists():
                shutil.copyfile(d / f, t / f)
        n += 1
        slug = d.name[d.name.index("_") + 1:]
        caso = json.loads((d / "case.json").read_text(encoding="utf-8"))
        g = json.loads((d / "expected.json").read_text(encoding="utf-8"))
        refs = " ".join(caso["ref"])
        if "excepcion" in g:
            excepciones.append("%s|%s|%s|%s" % (slug, refs, g["excepcion"].split(":")[0], g["decisionServlet"]))
        else:
            s = g["salida"]
            filas.append("%s|%s|%s|%s|%s|%s" % (slug, refs, ",".join(r["DescEstado"] for r in s["P_OUT_RESULTADO"]), s["P_OUT_ERRORESCONTADOR"],
                                                 ",".join(m["codigo"] for m in s["P_OUT_MENSAJES"]), g["decisionServlet"]))
    java = ['package cl.bcs.fondomutuo.valorcuota;', '',
            '/**', ' * GENERATED by legacy-oracle/sync_cvc.py FROM THE RECORDED GOLDENS (never by hand; re-run the script after re-recording). Index of literals of the FMM-CVC cases:',
            ' * one line per case with the legacy outcome that {@code CvcReglasTest} asserts rule by rule. {@code slug|rules|states of the rows|counter|message codes|servlet decision}',
            ' * for the cases that return an output, {@code slug|rules|exception class|servlet decision} for the ones that throw.', ' */',
            'final class CvcTablasLiterales {', '', '    private CvcTablasLiterales() {', '    }', '', '    static final String RESULTADOS = """']
    java += ["            " + f for f in filas]
    java += ['            """;', '', '    static final String EXCEPCIONES = """']
    java += ["            " + f for f in excepciones]
    java += ['            """;', '}', '']
    LITERALES.write_text("\n".join(java), encoding="utf-8", newline="\n")
    print("FMM-CVC cases synced:", n, "(%d with output, %d that throw)" % (len(filas), len(excepciones)))


if __name__ == "__main__":
    main()
