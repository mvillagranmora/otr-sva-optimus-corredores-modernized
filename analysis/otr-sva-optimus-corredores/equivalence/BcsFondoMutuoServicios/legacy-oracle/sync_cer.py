"""F3 W3 T1 (CertificarSolicitudAporteRescate, fronts F-A and F-B): copies, byte for byte, the FMM-CER cases (case.json, seed.sql, expected.json recorded by record_cer.sh),
schema-cer.sql, seed/base-cer.sql, seed/doubles-cer.json and the determinism report into the module test resources src/test/resources/fondomutuo-cer/, and WRITES (derived from the
goldens, never by hand) the index of literals src/test/java/cl/bcs/fondomutuo/certificacion/CerTablasLiterales.java that CerReglasTest checks rule by rule. A case without golden is NOT
copied (the module test would fail).
Nothing under legacy/ or src/main is touched.

  py -3 -I legacy-oracle/sync_cer.py                       writes into modernized/.../BcsFondoMutuoServicios
  py -3 -I legacy-oracle/sync_cer.py <module directory>    writes into ANOTHER copy of the module (validation outside the repo)
"""
import json
import pathlib
import shutil
import sys

HERE = pathlib.Path(__file__).resolve().parent
BASE = HERE.parent
WS = BASE.parents[3]
MOD = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else WS / "modernized" / "otr-sva-optimus-corredores" / "BcsFondoMutuoServicios"
DEST = MOD / "src" / "test" / "resources" / "fondomutuo-cer"
LITERALES = MOD / "src" / "test" / "java" / "cl" / "bcs" / "fondomutuo" / "certificacion" / "CerTablasLiterales.java"


def modo(caso):
    if "T1-costura:parada" in caso["ref"]:
        return "parada"
    if "T1-costura:completo" in caso["ref"]:
        return "completo"
    return "terminal"


def main():
    (DEST / "cases").mkdir(parents=True, exist_ok=True)
    (DEST / "seed").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(BASE / "schema-cer.sql", DEST / "schema-cer.sql")
    shutil.copyfile(BASE / "seed" / "base-cer.sql", DEST / "seed" / "base-cer.sql")
    shutil.copyfile(BASE / "seed" / "doubles-cer.json", DEST / "seed" / "doubles-cer.json")
    if (BASE / "determinism-cer.txt").exists():
        shutil.copyfile(BASE / "determinism-cer.txt", DEST / "determinism-cer.txt")
    for old in (DEST / "cases").iterdir():
        if old.is_dir():
            shutil.rmtree(old)
    n = 0
    terminales, continuan = [], []
    for d in sorted((BASE / "cases-cer").glob("FMM-CER-*")):
        if not (d / "expected.json").exists():
            print("no golden, skipped:", d.name)
            continue
        t = DEST / "cases" / d.name
        t.mkdir()
        for f in ("case.json", "seed.sql", "expected.json"):
            if (d / f).exists():
                shutil.copyfile(d / f, t / f)
        n += 1
        slug = d.name[d.name.index("_") + 1:]
        caso = json.loads((d / "case.json").read_text(encoding="utf-8"))
        g = json.loads((d / "expected.json").read_text(encoding="utf-8"))
        refs = " ".join(r for r in caso["ref"] if not r.startswith("T1-costura"))
        m = modo(caso)
        if m == "terminal":
            if "excepcion" in g:
                terminales.append("%s|%s|EXC|%s|%s" % (slug, refs, g["excepcion"].split(":")[0], g["decisionServlet"]))
            else:
                s = json.loads(g["salidaCruda"])
                terminales.append("%s|%s|OUT|%s|%s|%s|%s" % (slug, refs, s["P_OUT_ERRORESCONTADOR"], ",".join(m_["codigo"] for m_ in s["P_OUT_MENSAJES"]),
                                                              ",".join("%s:%s" % (r["IdSolicitudAporteRescate"], r["Codigo"]) for r in s["P_OUT_RESULTADO"]), g["decisionServlet"]))
        elif m == "completo":
            s = json.loads(g["salidaCruda"])
            continuan.append("%s|%s|%s" % (slug, refs, ",".join("%s:%s:%s" % (r["IdSolicitudAporteRescate"], r["Estado"], r["Codigo"]) for r in s["P_OUT_RESULTADO"])))
    java = ['package cl.bcs.fondomutuo.certificacion;', '',
            '/**', ' * GENERATED by legacy-oracle/sync_cer.py FROM THE RECORDED GOLDENS (never by hand; re-run the script after re-recording). Index of literals of the FMM-CER cases that',
            ' * {@code CerReglasTest} asserts rule by rule against the new code.',
            ' * TERMINAL: {@code slug|rules|OUT|counter|message codes|id:code of every row of the output|servlet decision} when the legacy returns, {@code slug|rules|EXC|exception class|servlet decision}',
            ' * when it throws. CONTINUES (modo completo): {@code slug|rules|id:state:code of every row of the output of the whole recorded run}.',
            ' */',
            'final class CerTablasLiterales {', '', '    private CerTablasLiterales() {', '    }', '', '    static final String TERMINALES = """']
    java += ["            " + f for f in terminales]
    java += ['            """;', '', '    static final String CONTINUAN = """']
    java += ["            " + f for f in continuan]
    java += ['            """;', '}', '']
    LITERALES.parent.mkdir(parents=True, exist_ok=True)
    LITERALES.write_text("\n".join(java), encoding="utf-8", newline="\n")
    print("FMM-CER cases synced:", n, "(%d terminal, %d that continue past F-B in modo completo, the rest are the -parada variants)" % (len(terminales), len(continuan)))


if __name__ == "__main__":
    main()
