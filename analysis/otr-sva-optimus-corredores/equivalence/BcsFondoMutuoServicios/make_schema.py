#!/usr/bin/env python3
"""Writes schema-types.sql (column TYPES + nullability, isolated), schema-fmm.sql (structure + sequences) and schema-keys.sql (primary keys) from
schema_spec.py (the columns the 36 in-scope SQL touch) and the read-only HANA catalog exports.

Every column gets a H2 DOMAIN named "<object>.<column>" defined ONLY in schema-types.sql (type and NOT NULL as in HANA); schema-fmm.sql refers to
the domain, so replacing the types means regenerating schema-types.sql only. Catalog CSVs (TABLE_NAME|VIEW_NAME,COLUMN_NAME,POSITION,DATA_TYPE_NAME,
LENGTH,SCALE,IS_NULLABLE): hana_qa_results/cat_columnas_tablas.csv, cat_columnas_vistas.csv and fmm_columnas_tablas.csv / fmm_columnas_vistas.csv
(tools/HanaCatalogoFondoMutuoSolicitud.java). A column found there is tagged REAL, any other ASSUMED. Keys: fmm_claves.csv. Sequences:
fmm_secuencias.csv (start, min, max, cycle). Temporary tables: fmm_tablas_tipo.csv (IS_TEMPORARY) -> H2 LOCAL TEMPORARY table of the session.
  py -3 make_schema.py        (idempotent)
"""
import csv
import glob
import os

from schema_spec import SEQUENCES, TABLES

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.normpath(os.path.join(HERE, "..", "..", "hana_qa_results"))
BASIC = {"L": "BIGINT", "I": "INTEGER", "D": "DECIMAL(26,8)", "T": "TIMESTAMP", "Dt": "DATE"}


def assumed(code):
    return "NVARCHAR(%s)" % code[1:] if code[0] == "S" else BASIC[code]


def h2type(name, length, scale):
    n = name.upper()
    if n in ("NVARCHAR", "VARCHAR", "NCHAR", "CHAR", "ALPHANUM", "SHORTTEXT"):
        return "NVARCHAR(%s)" % length
    if n == "DECIMAL":
        return "DECIMAL(%s,%s)" % (length, scale or 0)
    if n in ("TIMESTAMP", "SECONDDATE"):
        return "TIMESTAMP"
    if n in ("BIGINT", "INTEGER", "SMALLINT", "TINYINT", "DATE", "DOUBLE", "REAL", "TIME"):
        return n
    return None


def rows(name):
    p = os.path.join(RES, name)
    if not os.path.exists(p):
        return []
    with open(p, encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def main():
    cat = {}
    for f in ("cat_columnas_tablas.csv", "cat_columnas_vistas.csv", "fmm_columnas_tablas.csv", "fmm_columnas_vistas.csv",
              "supuestos_columnas_tablas.csv", "supuestos_columnas_vistas.csv"):   # the last two: the 6 formerly ASSUMED objects (paso 2)
        for r in rows(f):
            t = h2type(r["DATA_TYPE_NAME"], r.get("LENGTH"), r.get("SCALE"))
            if t:
                cat[(r.get("TABLE_NAME") or r.get("VIEW_NAME"), r["COLUMN_NAME"])] = (t, r["IS_NULLABLE"].upper() != "FALSE", f)
    keys = {}
    for r in sorted(rows("fmm_claves.csv") + rows("supuestos_claves.csv"), key=lambda r: int(r["POSITION"])):
        if r["IS_PRIMARY_KEY"].upper() == "TRUE":
            keys.setdefault(r["TABLE_NAME"], []).append(r["COLUMN_NAME"])
    seqs = {r["SEQUENCE_NAME"]: r for r in rows("fmm_secuencias.csv")}
    temp = {r["TABLE_NAME"] for r in rows("fmm_tablas_tipo.csv") if r["IS_TEMPORARY"].upper() == "TRUE"}

    types = ["-- GENERATED by make_schema.py from schema_spec.py + the catalog CSVs. Do not edit by hand.",
             "-- One domain per column. REAL = type and NOT NULL read from the HANA catalog export (read only); ASSUMED = inferred (object not in any export).", ""]
    tables = ["-- GENERATED by make_schema.py. Structure only: every column uses the domain declared in schema-types.sql. H2 only, never executed on HANA.",
              "-- Views are H2 tables (seeded by the cases). Primary keys: schema-keys.sql. GLOBAL TEMPORARY tables of HANA are H2 LOCAL TEMPORARY tables of the session.", ""]
    pks = ["-- GENERATED by make_schema.py from fmm_claves.csv (PRIMARY KEY only when every key column is in schema_spec.py; otherwise a comment)", ""]
    real = assumed_n = 0
    assumed_objs = set()
    for tname, spec in TABLES.items():
        short = tname.split("::")[1]
        cols = []
        items, seen = [], set()
        for item in spec.split():
            if item.rsplit(":", 1)[0] not in seen:
                seen.add(item.rsplit(":", 1)[0])
                items.append(item)
        if any((tname, i.rsplit(":", 1)[0]) in cat for i in items):
            gone = [i for i in items if (tname, i.rsplit(":", 1)[0]) not in cat]
            if gone:
                print("note: %s exists in the catalog; columns not in it are dropped: %s" % (short, [i.rsplit(":", 1)[0] for i in gone]))
            items = [i for i in items if (tname, i.rsplit(":", 1)[0]) in cat]
        spec = " ".join(items)
        for item in items:
            col, code = item.rsplit(":", 1)
            dom = "%s.%s" % (tname, col)
            if (tname, col) in cat:
                t, nullable, src = cat[(tname, col)]
                tag = "REAL (%s)" % src
                real += 1
            else:
                t, nullable, tag = assumed(code), True, "ASSUMED"
                assumed_n += 1
                assumed_objs.add(tname)
            types.append('CREATE DOMAIN "%s" AS %s; -- %s%s' % (dom, t, tag, "" if nullable else " NOT NULL"))
            cols.append('  "%s" "%s"%s' % (col, dom, "" if nullable else " NOT NULL"))
        kind = "LOCAL TEMPORARY TABLE" if tname in temp else "TABLE"
        tables.append('CREATE %s "%s" ( -- %s\n%s\n);' % (kind, tname, short, ",\n".join(cols)))
        if tname in keys:
            have = {i.rsplit(":", 1)[0] for i in spec.split()}
            ks = ", ".join('"%s"' % c for c in keys[tname])
            if set(keys[tname]) <= have:
                pks.append('ALTER TABLE "%s" ADD PRIMARY KEY (%s);' % (tname, ks))
            else:
                pks.append('-- %s: key (%s) not added, some key column is outside schema_spec.py' % (tname, ks))
    for s in list(seqs) or list(SEQUENCES):
        r = seqs.get(s)
        if r:
            tables.append('CREATE SEQUENCE "%s" START WITH %s MINVALUE %s MAXVALUE %s INCREMENT BY %s %s; -- REAL (fmm_secuencias.csv)' % (
                s, r["START_NUMBER"], r["MIN_VALUE"], r["MAX_VALUE"], r["INCREMENT_BY"], "CYCLE" if r["IS_CYCLED"].upper() == "TRUE" else "NO CYCLE"))
        else:
            tables.append('CREATE SEQUENCE "%s" START WITH %d; -- ASSUMED' % (s, SEQUENCES[s]))
    types.append("")
    types.append("-- summary: %d columns REAL, %d ASSUMED (objects with ASSUMED columns: %s)" % (real, assumed_n, ", ".join(sorted(assumed_objs)) or "none"))
    for name, lines in (("schema-types.sql", types), ("schema-fmm.sql", tables), ("schema-keys.sql", pks)):
        with open(os.path.join(HERE, name), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
    print("columns REAL %d, ASSUMED %d, objects %d; assumed objects: %s" % (real, assumed_n, len(TABLES), sorted(assumed_objs)))


if __name__ == "__main__":
    main()
