def mov(id_, **c):
    """One SalidaMovimientoCustodiaFondoMutuo of ProcesarCustodiaFondoMutuo (a retired / entered cartera of a solicitud)."""
    d = {"IdGenerarMovimientoCustodia": id_, "TablaOrigen": "CUS.Cartera", "FolioCustodia": 5000 + id_, "IdCustodia": 9000 + id_, "Cantidad": 1,
         "CostoInversionEnFactorAjusteARetirar": 10.5, "ValorFactorAjusteaFechaCurseARetirar": 39000.5, "CostoInversionEnFactorAjusteOriginal": 10.5,
         "CostoInversionEnFactorAjusteActual": 10.5, "ValorFactorOriginal": 39000.5, "ValorFactorARetirar": 39000.5, "MontoCompraFactorOriginal": 2.5,
         "MontoCompraFactorARetirar": 2.5, "MontoCompraFactorActual": 2.5}
    d.update(c)
    return d


def err(id_, codigo="UI_ERROR_CUSTODIA_GENERAL", descripcion="Error general de custodia", tipo="ERROR"):
    return {"id": id_, "tipo": tipo, "codigo": codigo, "descripcion": descripcion}


def resp_custodia(movs=(), mensajes=(), contador=0):
    return {"P_OUT_ERRORESCONTADOR": contador, "P_OUT_MENSAJES": list(mensajes), "P_OUT_MOVIMIENTOS": list(movs)}


def custodia_script(specs, aportes=None, con=None, sin=None, extra_aportes=(), extra_rescates=()):
    """ProcesarCustodiaFondoMutuo: one answer per KIND of call, matched by the first movement of the request (aportes: IdTipoOperacion APORFM; rescates without regimen: IdRegimenTributario
    ''; rescates with regimen: the rest). By default each call answers one cartera per solicitud of its own group (so the two rescate calls never repeat a cartera, as the real service).
    `aportes` / `con` / `sin` replace the answer of that call (a dict made by resp_custodia). Returns the `colaboradores` fragment."""
    apo = [s["IdSolicitudAporteRescate"] for s in specs if s["TipoSolicitud"] == "APO"]
    res_con = [s["IdSolicitudAporteRescate"] for s in specs if s["TipoSolicitud"] == "RES" and s["IdRegimenTributario"] != ""]
    res_sin = [s["IdSolicitudAporteRescate"] for s in specs if s["TipoSolicitud"] == "RES" and s["IdRegimenTributario"] == ""]
    r_apo = aportes if aportes is not None else resp_custodia([mov(i) for i in apo] + list(extra_aportes))
    r_sin = sin if sin is not None else resp_custodia([mov(i) for i in res_sin] + list(extra_rescates))
    r_con = con if con is not None else resp_custodia([mov(i) for i in res_con])
    return {"ProcesarCustodiaFondoMutuo": {"respuestas": [
        {"cuando": {"0.p_Movimientos.0.IdTipoOperacion": "APORFM"}, "respuesta": r_apo},
        {"cuando": {"0.p_Movimientos.0.IdRegimenTributario": ""}, "respuesta": r_sin},
        {"cuando": {"0.p_Movimientos.0.IdTipoOperacion": "RESCFM"}, "respuesta": r_con}],
        "defecto": resp_custodia()}}


def calcula_custodia(*resultados):
    """CalculaCustodiaRescate answer. A result is a dict (IdSolicitudAporteRescate, Estado, CantidadDisponible, Monto, NumeroCuotas, ...)."""
    return {"CalculaCustodiaRescate": {"defecto": {"P_OUT_ERRORESCONTADOR": 0, "P_OUT_MENSAJES": [], "P_OUT_RESULTADO": list(resultados)}}}


