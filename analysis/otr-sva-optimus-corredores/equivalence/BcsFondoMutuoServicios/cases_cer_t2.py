def _paridad_benigna(specs, extra):
    base = C.paridades(specs)["CalcularParidad"]
    return {"CalcularParidad": {"respuestas": list(extra) + base["respuestas"], "defecto": base["defecto"]}}


def caso(slug, ref, ent, seed=(), colaboradores=None, front="F-C", excepcion=False, custodia=None, paridad=(), saldo=None, calcula=None, previas=None, reloj=None, **extra):
    """Writes cases-cer-t2/FMM-CER-nnn_slug. `custodia` = kwargs of custodia_script, `paridad` = extra answers of CalcularParidad (prepended), `saldo` = the SaldoFlujoCaja fragment,
    `calcula` = the CalculaCustodiaRescate fragment; `colaboradores` replaces whatever key it names. `excepcion=True`: the legacy is expected to throw inside F-C / F-D; `excepcion="posterior"`: it finishes F-C / F-D and throws in a later front (the golden then only shows
    what F-C / F-D sent to their collaborators)."""
    _n["n"] += 1
    sql, specs = C._aplanar(seed)
    colab = {}
    if specs and "EntregarPreciosTasas" not in (colaboradores or {}):
        colab.update(C.precios_por_defecto(specs))
    colab.update(C.benignos(specs))
    colab.update(custodia_script(specs, **(custodia or {})))
    colab.update(_paridad_benigna(specs, paridad))
    if saldo is not None:
        colab.update(saldo)
    if calcula is not None:
        colab.update(calcula)
    colab.update(colaboradores or {})
    cid = "FMM-CER-%03d_%s" % (_n["n"], slug)
    etiqueta = {False: "T2-costura:completo", True: "T2-costura:excepcion", "posterior": "T2-costura:excepcion-posterior"}[excepcion]
    refs = list(ref) + ["front:" + front, etiqueta]
    doc = {"servicio": L.SERVICIO, "ref": refs, "esquemasExtra": ESQUEMAS, "entrada": ent, "tablas": TABLAS}
    if previas:
        doc["entradasPrevias"] = list(previas)
    if reloj:
        doc["reloj"] = reloj
    doc.update(extra)
    if colab:
        doc["colaboradores"] = colab
    d = CASES_T2 / cid
    d.mkdir(parents=True, exist_ok=True)
    (d / "case.json").write_text(L.dumps(doc), encoding="utf-8", newline="\n")
    texto = "-- case seed on top of seed/base-fmm.sql + schema-cer.sql + seed/base-cer.sql + seed/base-cer-t2.sql (fake data)\n" + ("\n".join(sql) if sql else "SELECT 1;") + "\n"
    (d / "seed.sql").write_text(texto, encoding="utf-8", newline="\n")
    return cid


def ap(id_, pf=None, **c):
    """an aporte that F-C sends to SaldoFlujoCaja (MueveCta S, manual origin); the portfolio is `pf` or the IdPortafolio keyword (default 500)"""
    pf = c.pop("IdPortafolio", 500 if pf is None else pf)
    c.setdefault("CodigoPortafolio", "PF%d" % pf)
    return aporte(id_, IdPortafolio=pf, MueveCta="S", **c)


def origen(id_, **c):
    """The rescate of origin of a reinversion aporte: BOTH rows (table and view) but NOT in the request (a plain list: no spec). `reCalcularCostoUFAportes` reads it with SelectSolicitudes."""
    return list(L.rescate(id_, estado="CRT", **c))


def reinv(id_, relacionado, **c):
    """An APOREINV aporte whose origin is `relacionado` (C:2939-3019)."""
    d = dict(IdTipoMovimientoFondoMutuo="APOREINV", IdSolicitudAporteRescateRelacionado=relacionado, ValorUFFechaInversion=Num("38000.5"), MontoMonedaSistema=1200000)
    d.update(c)
    return ap(id_, **d)


