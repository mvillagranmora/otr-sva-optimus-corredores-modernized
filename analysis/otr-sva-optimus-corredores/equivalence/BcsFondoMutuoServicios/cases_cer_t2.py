def paridad_uf(monto_local, resultado="OK"):
    """CalcularParidad answer of reCalcularCostoUFAportes (C:2939-3019; UF -> CLP of the date of the aporte): the FIRST entry of the answer is the one it takes (findAny)."""
    r = {"IdTrabajo": 1, "IdInterno": 1, "Resultado": resultado}
    if monto_local is not None:
        r["MontoLocal"] = monto_local
    return {"cuando": {"0.p_IdTrabajo": 1, "0.p_CalculosEntrada.0.IdMonedaOrigen": "UF"}, "respuesta": {"p_out_CalculosSalida": [r]}}


def paridad_utm(monto, resultado="OK", id_interno=1):
    """CalcularParidad answer of calcularCostoUFRentabilidadRescates (C:1524-1578; UTM -> CLP; IdInterno 1..n by date): MontoDestino is the value of the UTM."""
    return {"cuando": {"0.p_IdTrabajo": 1, "0.p_CalculosEntrada.0.IdMonedaOrigen": "UTM"},
            "respuesta": {"p_out_CalculosSalida": [{"IdTrabajo": 1, "IdInterno": id_interno, "MontoDestino": monto, "Resultado": resultado}]}}


def paridad_comision(id_, local, sistema=None, *otros):
    """CalcularParidad answer of CalcularComisiones (the REAL class of the legacy, FM-COM) for the rescate `id_`: the commission converted to the currency of the operation (IdInterno id*5+1,
    `local` is MontoDestino) and to the system currency (id*5+2); the two exchange rates (id*5+3, id*5+4) are 1. `otros` = more (id, local) pairs answered by the SAME call (the request
    carries one entry group per rescate; the answer is chosen by the first one). Without an answer for an IdInterno the legacy values it at 1 (D-COM-5)."""
    filas = []
    for (i, loc, sis) in [(id_, local, local if sistema is None else sistema)] + [(o[0], o[1], o[1] if len(o) < 3 else o[2]) for o in otros]:
        base = i * 5
        filas += [{"IdTrabajo": 1, "IdInterno": base + 1, "MontoDestino": loc, "Resultado": "OK"}, {"IdTrabajo": 1, "IdInterno": base + 2, "MontoDestino": sis, "Resultado": "OK"},
                  {"IdTrabajo": 1, "IdInterno": base + 3, "MontoDestino": 1, "Resultado": "OK"}, {"IdTrabajo": 1, "IdInterno": base + 4, "MontoDestino": 1, "Resultado": "OK"}]
    return {"cuando": {"0.p_IdTrabajo": 1, "0.p_CalculosEntrada.0.IdInterno": id_ * 5 + 1}, "respuesta": {"p_out_CalculosSalida": filas}}


