def resp_mov_comp(movs=(), mensajes=(), contador=0):
    """CrearMovimientoComprobante answer (CrearMovimientoComprobante_Salida): the movements generated (NumeroMvtoCmbte = id of the solicitud, IdMovimientoComprobante), messages, counter"""
    return {"P_OUT_ERRORESCONTADOR": contador, "P_OUT_MENSAJES": list(mensajes), "p_out_Movimientos": list(movs)}


def mov_sal(numero, id_movimiento):
    return {"NumeroMvtoCmbte": numero, "IdMovimientoComprobante": id_movimiento, "IdOperacion": 0}


def resp_comprobante(mensajes=(), contador=0):
    """CrearComprobante answer (CrearComprobante_Salida)"""
    return {"P_OUT_ERRORESCONTADOR": contador, "P_OUT_MENSAJES": list(mensajes), "P_OUT_COMPROBANTE": []}


def facturacion(movimiento=None, comprobante=None):
    d = {}
    if movimiento is not None:
        d["CrearMovimientoComprobante"] = {"defecto": movimiento}
    if comprobante is not None:
        d["CrearComprobante"] = {"defecto": comprobante}
    return d


def msg_fact(id_, codigo="UI_ERROR_FACTURACION", descripcion="Error al crear el movimiento de comprobante", tipo="ERROR"):
    return msg(id_, codigo, descripcion, tipo)


def res_ar(id_interno, id_solicitud, switch="N", canal="OPT", **c):
    """ResultadoSolicitud of the answer of AR: IdInterno = the correlative of the aporte (the legacy replaces it by the id of the rescate), IdSolicitudAporteRescate = the new aporte"""
    d = {"IdInterno": id_interno, "IdSolicitudAporteRescate": id_solicitud, "Switch": switch, "IdTipoCanalIngreso": canal}
    d.update(c)
    return {k: v for k, v in d.items() if v is not ABSENT}


def resp_ar(resultados=(), mensajes=(), contador=0):
    """CrearSolicitudAporteReinversion answer (SalidaCrearSolicitudAporteReinversion)"""
    return {"P_OUT_ERRORESCONTADOR": contador, "P_OUT_MENSAJES": list(mensajes), "P_OUT_RESULTADO": list(resultados)}


def ar(resp, extra=()):
    """the script of AR: `resp` answers every call; `extra` = answers of `respuestas` tried before (e.g. a different answer for the child's own call)"""
    d = {"defecto": resp}
    if extra:
        d["respuestas"] = list(extra)
    return {"CrearSolicitudAporteReinversion": d}


def msg_ar(id_, codigo="UI_ERROR_REINVERSION", descripcion="Error al crear la solicitud de aporte por reinversion", tipo="ERROR"):
    return msg(id_, codigo, descripcion, tipo)


def destino(id_rr, rescate, serie_destino, porcentaje, regimen="GEN", switch="N", fecha_final="2026-12-31", **c):
    """a row of FMM.ReinversionSerieFondoDestino: the destination (series, percentage, regime, switch) of the reinversion of the rescate"""
    return ins(T_RESERIE, IdReinversionSerieFondo=id_rr, IdSolicitudAporteRescate=rescate, IdSerieFondoDestino=serie_destino, Porcentaje=porcentaje, IdRegimenTributario=regimen,
               IdCarga=c.get("IdCarga", 0), Switch=switch, PorcentajeReal=c.get("PorcentajeReal", porcentaje), FechaFinalReinversion=fecha_final)


