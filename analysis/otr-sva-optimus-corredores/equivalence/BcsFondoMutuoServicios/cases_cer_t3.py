def resp_spot(operaciones=(), mensajes=(), contador=0, contador_nulo=False):
    """ProcesarIngresoOperacionSpot answer. `operaciones`: dicts {IdInterno (text), Estado, IdOperacionSpot} (CrearOperacionSpot.OperacionObjOut)."""
