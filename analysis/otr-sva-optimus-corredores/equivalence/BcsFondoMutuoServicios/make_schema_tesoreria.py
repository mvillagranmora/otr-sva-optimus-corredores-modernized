"""F2 W1B: builds schema-tesoreria-fm.sql = the H2 stand-in of the Tesoreria objects (BcsTesoreriaServicios src/test/resources/tesoreria-a/
schema-tesoreria-a.sql, the schema its family-A oracle and tests use, read only) MERGED onto the FondoMutuo oracle schema without touching it:

  - a table/view of Tesoreria that the FondoMutuo schema does not have: copied as is;
  - a table/view that both have (17: PLA.Empresa, ACC.Usuario, POR.Portafolio, ...): the FondoMutuo definition (REAL catalog types) stays and every
    column only Tesoreria needs is added with ALTER TABLE ... ADD COLUMN IF NOT EXISTS (Tesoreria's assumed type);
  - a sequence or alias that FondoMutuo already defines: skipped (ADD_SECONDS, TO_BIGINT, TO_NVARCHAR keep the FondoMutuo implementation; DUMMY too);
  - the two sequences CrearIngresoEgreso draws through Utils.getSecuencia (IngresoEgreso, IngresoEgresoFormaDePago: in Tesoreria's oracle they came
    from the case script) are created with Tesoreria's case values 5000 / 6000.
Only the W1B cases load it (case.json "esquemasExtra"); schema-fmm.sql and every earlier golden are unchanged.

    py -3 make_schema_tesoreria.py
"""
import pathlib
import re

BASE = pathlib.Path(__file__).resolve().parent
WS = BASE.parents[3]
TES = WS / "modernized" / "otr-sva-optimus-corredores" / "BcsTesoreriaServicios" / "src" / "test" / "resources" / "tesoreria-a" / "schema-tesoreria-a.sql"
FM_ALIAS = {"ADD_SECONDS", "TO_BIGINT", "TO_NVARCHAR"}


def fm_objetos():
    texto = "".join((BASE / f).read_text(encoding="utf-8") for f in ("schema-fmm.sql", "schema-session.sql"))
    return set(re.findall(r'CREATE (?:LOCAL TEMPORARY |GLOBAL TEMPORARY )?(?:TABLE|VIEW|SEQUENCE) "?([^"\s(]+)"?', texto))


def sentencias(texto):
    limpio = "\n".join(l for l in texto.split("\n") if not l.strip().startswith("--"))
    return [s.strip() for s in re.split(r";\s*\n", limpio) if s.strip()]


def main():
    fm = fm_objetos()
    out = ["-- GENERATED by make_schema_tesoreria.py from BcsTesoreriaServicios tesoreria-a/schema-tesoreria-a.sql (do not edit; re-generate).",
           "-- F2 W1B layer 2: Tesoreria objects merged onto the FondoMutuo oracle schema (see the generator). Assumed types of Tesoreria's stand-in."]
    nuevos, ampliados, saltados = 0, 0, []
    for s in sentencias(TES.read_text(encoding="utf-8")):
        m = re.match(r'CREATE (TABLE|SEQUENCE|ALIAS) ("?)([^"\s(]+)\2', s)
        if not m:
            if s.upper().startswith("INSERT INTO DUMMY"):
                saltados.append("INSERT DUMMY")
                continue
            out.append(s + ";")
            continue
        clase, nombre = m.group(1), m.group(3)
        if clase == "ALIAS":
            if nombre in FM_ALIAS:
                saltados.append("ALIAS " + nombre)
                continue
            out.append(s.replace("CREATE ALIAS ", "CREATE ALIAS IF NOT EXISTS ", 1) + ";")
            continue
        if nombre in fm:
            if clase == "SEQUENCE":
                saltados.append("SEQUENCE " + nombre)
                continue
            for col, tipo in re.findall(r'^\s*"([^"]+)"\s+([^,\n]+?),?\s*$', s[s.index("(") + 1:s.rindex(")")], re.M):
                out.append('ALTER TABLE "%s" ADD COLUMN IF NOT EXISTS "%s" %s;' % (nombre, col, tipo.strip()))
            ampliados += 1
            continue
        out.append(s + ";")
        nuevos += 1
    out.append('CREATE SEQUENCE "BSCL.Tesoreria.BD.Secuencias::IngresoEgreso" START WITH 5000;')
    out.append('CREATE SEQUENCE "BSCL.Tesoreria.BD.Secuencias::IngresoEgresoFormaDePago" START WITH 6000;')
    (BASE / "schema-tesoreria-fm.sql").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("tables new %d, merged %d, skipped %s" % (nuevos, ampliados, saltados))


if __name__ == "__main__":
    main()
