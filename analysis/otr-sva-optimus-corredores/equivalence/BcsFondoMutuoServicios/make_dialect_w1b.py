"""F2 W1B: reviewed H2 equivalents of Tesoreria SQL that the H2 stand-in cannot run as written, for Tesoreria's dialect bridge (H2Hana: an entry of
h2-dialect/index.txt replaces the statement whose whitespace-normalised text equals the HANA source). Each entry changes ONLY what H2 types differently
from HANA, and says why. Written to:
  legacy-oracle/h2-dialect-w1b/tesoreria-a/h2-dialect/   (oracle: first on the run classpath, shadows Tesoreria's empty index)
  modernized/.../BcsFondoMutuoServicios/src/test/resources/fondomutuo-tes/h2-dialect/   (module tests: the module's H2Hana copy reads it)

    py -3 make_dialect_w1b.py
"""
import pathlib

BASE = pathlib.Path(__file__).resolve().parent
WS = BASE.parents[3]
TSQL = WS / "legacy" / "otr-sva-optimus-corredores" / "BSCL" / "Tesoreria" / "JAVA" / "BcsTesoreriaServicios" / "src" / "cl" / "bcs" / "tesoreria" / "sql"
# (directory, classpath of the HANA source there: the legacy resource in the oracle, the byte-identical one of the tesoreria-service jar in the module)
DESTINOS = [(BASE / "legacy-oracle" / "h2-dialect-w1b" / "tesoreria-a" / "h2-dialect", "cl/bcs/tesoreria/sql/"),
            (WS / "modernized" / "otr-sva-optimus-corredores" / "BcsFondoMutuoServicios" / "src" / "test" / "resources" / "fondomutuo-tes" / "h2-dialect", "sql/")]

# (file, why, [(text, replacement)])
ENTRADAS = [
    ("CrearIngresoEgreso_SelectIngresoEgresoFormaDePagoProceso.sql",
     "SUM(CASE .. THEN 1 ELSE 0 END) is INTEGER on HANA and BIGINT on H2; the legacy maps it with field.set onto an Integer field",
     [('COALESCE(ARG."ExisteDescuadreEnMontos",0) AS', 'CAST(COALESCE(ARG."ExisteDescuadreEnMontos",0) AS INTEGER) AS'),
      ('COALESCE(ARG."ExisteDiferenciaMoneda",0) AS', 'CAST(COALESCE(ARG."ExisteDiferenciaMoneda",0) AS INTEGER) AS')]),
]


def main():
    for d, ruta in DESTINOS:
        d.mkdir(parents=True, exist_ok=True)
        indice = ["# F2 W1B: generated by make_dialect_w1b.py (analysis/.../BcsFondoMutuoServicios); do not edit"]
        for archivo, motivo, cambios in ENTRADAS:
            texto = (TSQL / archivo).read_text(encoding="utf-8")
            for a, b in cambios:
                assert a in texto, (archivo, a)
                texto = texto.replace(a, b)
            nombre = "w1b-" + archivo
            (d / nombre).write_text("-- HANA-SOURCE: " + ruta + archivo + "\n-- " + motivo + "\n" + texto, encoding="utf-8", newline="\n")
            indice.append(nombre)
        (d / "index.txt").write_text("\n".join(indice) + "\n", encoding="utf-8", newline="\n")
    print("dialect entries: %d" % len(ENTRADAS))


if __name__ == "__main__":
    main()
