def schema_cpfchain():
    s = ["-- GENERATED by make_cases_cpfchain.py (cases_cpfchain_lib.schema_cpfchain). ADDS to schema-cpf.sql (CPF stand-ins, loaded first, unchanged) what the five ConsultarCustodiaPortafolioFFMM_*.sql read.",
         "-- Types: REAL when a catalog CSV of hana_qa_results or the owner's HANA QA read-only check (2026-10-28) has them, ASSUMED otherwise. Views are tables here. No data: seed/base-cpfchain.sql and the cases fill them.",
         "-- columns FFMM reads that the CPF stand-ins (which only needed IdCliente / IdSocioDeNegocio) lack",
         'ALTER TABLE "%s" ADD COLUMN IF NOT EXISTS "IdPersona" BIGINT; -- ASSUMED' % CLI,
         'ALTER TABLE "%s" ADD COLUMN IF NOT EXISTS "IdEmpresa" BIGINT; -- ASSUMED' % CLI,
         'ALTER TABLE "%s" ADD COLUMN IF NOT EXISTS "IdPersona" BIGINT; -- ASSUMED' % SOCT]
    for tabla, c, t, tag in F.AGREGADAS:
        if tabla in (F.SOCV, F.PORV):
            s.append('ALTER TABLE "%s" ADD COLUMN IF NOT EXISTS "%s" %s; -- %s' % (tabla, c, t, tag))
    s.append("-- the F1 schema holds a REDUCED CUS.Cartera (11 columns, no rows, no constraint): replaced by the full set of columns the SQL read")
    s.append('DROP TABLE "%s";' % CUS)
    s += F.ddl_custodia()
    for tabla, cols, tag in F.NUEVAS:
        if tabla in (F.REL, F.INSV):
            s.append("-- %s | %s" % (tabla, tag))
            s.append('CREATE TABLE "%s" (\n%s\n);' % (tabla, ",\n".join('  "%s" %s' % c for c in cols)))
    return "\n".join(s) + "\n"


def base_cpfchain():
    s = ["-- GENERATED by make_cases_cpfchain.py (cases_cpfchain_lib.base_cpfchain). Rows FFMM needs on top of seed/base-cpf.sql (the CPF universe, loaded first, unchanged)."]
    # persons of the CPF clients (CLI view and business partners); client 99 = the corredora (person 1), client 102 gets a business partner too
    for idc, per in ((100, 7100), (101, 7101), (102, 7102)):
        s.append(upd(CLI, {"IdPersona": per, "IdEmpresa": 1}, '"IdCliente" = %d' % idc))
    s.append(F.ins(CLI, IdCliente=99, DocumentoIdentidad="76000000-0", RazonSocial="Corredora Ficticia", IdPersona=1, IdEmpresa=1))
    s.append(upd(SOCT, {"IdPersona": 7100}, '"IdSocioDeNegocio" = 1100'))
    s.append(upd(SOCT, {"IdPersona": 7101}, '"IdSocioDeNegocio" = 1101'))
    s.append(F.ins(SOCT, IdSocioDeNegocio=1102, IdPersona=7102, IdCliente=102))
    s.append(F.ins(SOCT, IdSocioDeNegocio=1099, IdPersona=1, IdCliente=99))
    for ids, per, idc in ((1099, 1, 99), (1100, 7100, 100), (1101, 7101, 101), (1102, 7102, 102)):
        s.append(F.ins(SOCV, IdSocioDeNegocio=ids, IdPersona=per, IdCliente=idc, IdEmpresa=1))
    # portfolios 504 (client 99) and 505 (client 102); the view the solicitudes branch joins has ALL of them
    for idp, cod, idc in ((504, "PF504", 99), (505, "PF505", 102)):
        s.append(F.ins(PORT, IdPortafolio=idp, CodigoPortafolio=cod, IdCliente=idc, IdEstado="ACT", Proposito="PROPGEN", IdMatrizAgrupadorAPV=0))
    for idp, cod, mat in ((500, "PF500", 0), (501, "APV-B", 7), (502, "PF502", 0), (503, "PF503", None), (504, "PF504", 0), (505, "PF505", 0)):
        s.append(F.ins(PORV, IdPortafolio=idp, IdMatrizAgrupadorAPV=mat, CodigoPortafolio=cod) if mat is not None else F.ins(PORV, IdPortafolio=idp, CodigoPortafolio=cod))
    # the instruments of the view FFMM joins (same classification / type as INS.Instrumento of the CPF seed)
    for i, (emi, nemo) in INSTRUMENTOS.items():
        tipo = "FMX" if i == 902 else "FM"
        s.append(F.ins(INSV, IdInstrumento=i, IdClasificacionTipoInstrumento="FM", NombreClasificacionTipoInstrumento="Fondos Mutuos", IdTipoInstrumento=tipo,
                       NombreTipoInstrumento="Fondo Mutuo Extranjero" if i == 902 else "Fondo Mutuo", IdEmisor=emi))
    s.append(relacion(1, 7101, "ACT"))
    s.append(relacion(1, 7102, "INA"))
    return "\n".join(s) + "\n"


# ---- case writer -------------------------------------------------------------------------------------------------------------------------------------
_n = {"n": 0}


def empresa(persona=1, cliente_id=99):
    return F.empresa(persona, cliente_id)


def caso(slug, ref, ent, filas=(), seed=(), colaboradores=None, **extra):
    """Writes cases-cpfchain/FM-CHAIN-nnn_slug and returns the id. `seed` is loaded BEFORE `filas` (the CPF solicitud rows)."""
    datos = []
    for x in list(seed) + list(filas):
        datos += x if isinstance(x, (list, tuple)) else [x]
    _n["n"] += 1
    cid = "FM-CHAIN-%03d_%s" % (_n["n"], slug)
    doc = {"servicio": SERVICIO, "ref": ref, "esquemasExtra": ESQUEMAS, "entrada": ent, "tablas": TABLAS}
    doc.update(extra)
    col = dict(colaboradores or {})
    for k, v in (("EntregarPreciosTasas", precios()), ("CalcularParidad", paridad(final=1)), ("ConsultarEmpresa", empresa())):
        if k not in col:
            col.update(v)
    doc["colaboradores"] = col
    d = CASES / cid
    d.mkdir(parents=True, exist_ok=True)
    (d / "case.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    texto = "-- case seed on top of seed/base-fmm.sql + schema-cpf.sql + seed/base-cpf.sql + schema-cpfchain.sql + seed/base-cpfchain.sql (fake data)\n" + ("\n".join(datos) if datos else "SELECT 1;") + "\n"
    (d / "seed.sql").write_text(texto, encoding="utf-8", newline="\n")
    return cid
