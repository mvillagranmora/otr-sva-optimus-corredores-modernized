ESQUEMAS = ["schema-cpf.sql", "seed/base-cpf.sql", "schema-cpfchain.sql", "seed/base-cpfchain.sql"]
TABLAS = list(TABLAS_CPF) + [{"nombre": CUS, "orden": '"IdCartera"'}]
