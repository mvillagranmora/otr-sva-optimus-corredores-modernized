"""Helpers of the F3 W1 front 9 part B cases: the CHAIN ConsultarCustodiaPortafolioFondoMutuo (CPF) + ConsultarCustodiaPortafolioFFMM (FFMM), BOTH legacy classes REAL and unmodified, on ONE H2 (the
tables of CPF and the custody tables). Case directories cases-cpfchain/FM-CHAIN-nnn_slug.

What is different from the CPF front (cases-cpf/, whose goldens are NOT touched): there FFMM was a scripted DOUBLE, so every custody row was invented by the case; here the custody rows are what
the real FFMM computes from CUS.Cartera / HIS.Cartera / GTA.Garantia / HIS.Garantia and the solicitudes in transit (RULES_FONDOMUTUO_F3_C.md FM-CPFF-22). The collaborators outside the module are
still scripted: CalcularParidad, EntregarPreciosTasas and ConsultarEmpresa (called TWICE: FFMM first, CPF later, D-F3A-07).

Schema and seed: schema-cpf.sql / seed/base-cpf.sql of the CPF front are loaded UNCHANGED (byte copies are kept in the module resources) and then schema-cpfchain.sql / seed/base-cpfchain.sql, which
ONLY ADD what FFMM needs: the custody tables (CUS.Cartera is DROPPED and re-created: the F1 stand-in has 11 columns), the views REL.ConsultarRelacionPersona and INS.ConsultarInstrumento, the columns
CLI.IdPersona / CLI.IdEmpresa, SOC.IdPersona, SOC.ConsultarSocioDeNegocio.IdEmpresa and ConsultarPortafolio.CodigoPortafolio, and the rows that give the CPF clients their persons. The standing
universe is the one of the CPF front: PLA.FechaSistema 2026-03-02, series FM001A .. FM006E (instruments 900 .. 905), clients 100 / 101 / 102, portfolios 500 .. 503 (+ 504 of the corredora client 99
and 505 of client 102 added here).
"""
