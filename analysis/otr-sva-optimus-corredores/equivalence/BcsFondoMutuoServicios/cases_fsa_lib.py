def base_fsa():
    """seed/base-fsa.sql: the FAKE rows every FMM-FSA case adds on top of seed/base-fmm.sql (loaded through esquemasExtra)."""
    s = ["-- GENERATED by make_cases_fsa.py (cases_fsa_lib.base_fsa). FAKE universe of the FMM-FSA cases, on top of seed/base-fmm.sql."]
    s += fin_de_semana(56, 840)
    s.append(feriado("2026-03-05", 56))
    # the date configuration of the five date types with every valuta and calendar flag open (so the series/solicitud days reach the dates)
    s += cfg_borrar()
    orig = {"DIGITA": "", "CURSE": "DIGITA", "VCUOTA": "CURSE", "CERTIF": "CURSE", "LIQUID": "CURSE"}
    flags = {"DIGITA": {}, "CURSE": {"vcurse": "S"}, "VCUOTA": {"vvc": "S"}, "CERTIF": {"vcert": "S"}, "LIQUID": {"vret": "S"}}
    for t in ("DIGITA", "CURSE", "VCUOTA", "CERTIF", "LIQUID"):
        s.append(cfg(t, 0 if t != "LIQUID" else 0, modalidad="UNITARIO", origen=orig[t], ce="S", cf="S", cm="S", **flags[t]))
    # money / countries
    for sid, (fondo, emisor, ext, pais_fondo, pais_emisor, mon, instr, apo, res) in SERIES.items():
        fo = {"IdEmisor": emisor, "IdPaisEmisor": pais_emisor, "IdPaisOrigen": pais_fondo, "Nemotecnico": sid[:5], "NombreFondo": "Fondo " + sid, "FondoExtranjero": ext,
              "IdMoneda": mon, "EstadoAporteComercial": "A", "EstadoAporteBackoffice": "C", "EstadoRescateComercial": "A", "EstadoRescateBackoffice": "C",
              "EstadoLiquidezComercial": "A", "EstadoLiquidezBackoffice": "C"}
        se = {"IdInstrumento": instr, "NombreSerieFondo": "Serie " + sid, "DiasRetencionesAporte": apo[0], "DiasValutaValorCuotaAporte": apo[1],
              "DiasValutaCertificacionAporte": apo[2], "DiasValutaCurseAporte": apo[3], "DiasRetencionesRescate": res[0], "DiasValutaValorCuotaRescate": res[1],
              "DiasValutaCertificacionRescate": res[2], "DiasValutaCurseRescate": res[3]}
        s += clonar_serie(sid, fondo, fondo=fo, serie=se)
    # fund 42 (FSN02): the states of rescue differ from those of contribution, so the choice EstadoAporte* / EstadoRescate* by type shows through the date configuration
    s.append(update(FONDO, {"EstadoRescateComercial": "R", "EstadoRescateBackoffice": "T"}, "\"IdFondo\" = '42'"))
    # users: 8 back office, 9 without profile, 10 both profiles, 11 not active
    s.append(insert(CONFPERFIL, {"Key": "PERFIL_BACKOFFICE", "Value": "6"}))
    for uid in (8, 9, 10, 11):
        s.append(insert(USUARIO, {"IdUsuario": uid, "IdEmpresa": 1, "IdEstado": "INA" if uid == 11 else "ACT", "TipoEntidad": "EMP", "IdEntidad": 70 + uid}))
    s.append(insert(PERFILES, {"IdPerfil": 6, "IdUsuario": 8}))
    s.append(insert(PERFILES, {"IdPerfil": 5, "IdUsuario": 10}))
    s.append(insert(PERFILES, {"IdPerfil": 6, "IdUsuario": 10}))
    s.append(insert(PERFILES, {"IdPerfil": 5, "IdUsuario": 11}))
    for cod, txt in (("NO_SE_INGRESARON_SOLICITUDES", "No se ingresaron solicitudes"), ("USUARIO_NO_EXISTE", "El usuario no existe"),
                     ("USUARIO_NO_VIGENTE", "El usuario no esta vigente"), ("MODULO_NO_EXISTE", "El modulo no existe"),
                     ("EMPRESA_NO_EXISTE", "La empresa no existe")):
        s.append(insert(DICC, {"CodLenguaje": "es", "CodDiccionario": cod, "Descripcion": txt}))
    return "\n".join(s) + "\n"


def sol(i, serie, tipo="RES", emision="2026-03-02", moneda=None, pago=None, **extra):
    """One request of p_SolicitudAporteRescate. moneda/pago None = key omitted (the legacy constructor leaves them as the empty text)."""
    d = {"IdInterno": i, "FechaEmision": emision, "IdSerieFondo": serie, "TipoSolicitud": tipo}
    if moneda is not None:
        d["IdMoneda"] = moneda
    if pago is not None:
        d["IdMonedaPago"] = pago
    d.update(extra)
    return d


def entrada(sols, usuario=7, **cab):
    d = {"p_IdEmpresa": 1, "p_IdUsuario": usuario, "p_IdModulo": "FMM", "p_SimularOperacion": "N", "p_UsaReglasNegocio": "S", "p_SolicitudAporteRescate": sols}
    d.update(cab)
    return d


_n = {"n": 0}


def caso(slug, ref, ent, seed=None, colaboradores=None, **cab):
    """Writes cases/FMM-FSA-nn_slug (nn = order of the call) and returns the id."""
    _n["n"] += 1
    cid = "FMM-FSA-%02d_%s" % (_n["n"], slug)
    doc = {"servicio": "ConsultarFechaSolicitudAporteRescate", "ref": ref, "consultarFechaReal": True, "esquemasExtra": ["seed/base-fsa.sql"], "entrada": ent,
           "tablas": TABLAS}
    doc.update(cab)
    if colaboradores:
        doc["colaboradores"] = colaboradores
    d = CASES / cid
    d.mkdir(parents=True, exist_ok=True)
    (d / "case.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    texto = "-- case seed on top of seed/base-fmm.sql + seed/base-fsa.sql (fake data)\n" + ("\n".join(seed) if seed else "SELECT 1;") + "\n"
    (d / "seed.sql").write_text(texto, encoding="utf-8", newline="\n")
    return cid


