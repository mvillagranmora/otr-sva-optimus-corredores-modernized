SELECT Transaccion."IdTransaccion",
	Transaccion."Folio",
	Transaccion."IdClasificacionTipoInstrumento",
	Transaccion."IdCondicionDeLiquidacion",
	Transaccion."IdMoneda",
	Transaccion."IdBolsa",
	Transaccion."IdTipoInstrumento",
	Transaccion."IndicadorOrdenDirecta",	
	Transaccion."IdComprobanteTesoreria",
	Transaccion."EsBilateral",
	Transaccion."IdCamara",
	Transaccion."Tasa",
	Transaccion."Precio",
	Transaccion."Cantidad",
	Transaccion."NemotecnicoSubyacente" AS "Nemotecnico",
	Transaccion."GastosCorresponsal",
	Transaccion."MontoLiquidacionCorresponsal",
	Transaccion."TipoCambioCorresponsal",
	Transaccion."IdMonedaLiquidacionCorresponsal",
	Transaccion."IdCorredorCorresponsal",
	Transaccion."Monto",
	Transaccion."IdClasificacionTipoInstrumento",
	Transaccion."IdTipoInstrumento",
	Transaccion."MontoRetencion",
	COALESCE(TipoOperacion."AccionOrden", '-999') AS "AccionOrden",
	TO_VARCHAR(Transaccion."FechaSistemaCreacion") AS "FechaSistemaCreacion",
	Transaccion."Folio" || '_' ||Transaccion."FechaSistemaCreacion" || '_' || Transaccion."NemotecnicoSubyacente" || '_' || COALESCE(TipoOperacion."AccionOrden", '-999') as "Hash"
FROM "BSCL.Orden.BD::ORD.Transaccion" as Transaccion
LEFT JOIN "BSCL.Plataforma.BD::INS.TipoOperacion" as TipoOperacion on (Transaccion."IdTipoOperacion" = TipoOperacion."IdTipoOperacion") 
WHERE Transaccion."IdEstado" = 'ING' and ( Transaccion."Folio" || '_' ||Transaccion."FechaSistemaCreacion" || '_' || Transaccion."NemotecnicoSubyacente" || '_' || COALESCE(TipoOperacion."AccionOrden", '-999') IN (:Llave))