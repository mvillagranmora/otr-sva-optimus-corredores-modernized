FROM
	"BSCL.Normativa.BD.Vistas::CIR.ConsultarDatosCIR1985" AS "DATACIR"
LEFT OUTER JOIN ---RELACIONADO
     			(SELECT COALESCE(RELHOM."ValorDestino" ,CAST (REL."CodigoValorIndicador" AS  nvarchar(100))) AS "RELACION",REL."IdCliente"
	     			 FROM "BSCL.Plataforma.BD.Vistas::IND.ConsultarIndicadoresCliente" REL
					 LEFT OUTER JOIN "BSCL.Normativa.BD::DOC.Homologacion" RELHOM
		     			ON ((CAST (REL."CodigoValorIndicador" AS  nvarchar(100))= RELHOM."ValorOrigen" AND RELHOM."Tipo"='RELACION' 
		     			AND RELHOM."Esquema" = (SELECT TOP 1 "Esquema" FROM "BSCL.Normativa.BD::DOC.TipoDocumento" WHERE "IdTipoDocumento" = 'EJECORD')
		     			AND RELHOM."Version"= (SELECT TOP 1 "P_OUT_VERSION" FROM "BSCL.Normativa.BD.Utilitarios::NOR.ObtenerVersionEsquema"('EJECORD',TO_VARCHAR (:p_FechaSistema, 'DD-MM-YYYY')))
							))
				 	 WHERE (REL."IdUso"='IND' AND REL."CodigoTipoIndicador"='1064PROP' AND REL."CodigoValorIndicador" <>'')
	     		) RELNOR ON (RELNOR."IdCliente" = "DATACIR"."IdCliente")	
WHERE TO_DATE(COALESCE("DATACIR"."FechaReferencia", "DATACIR"."FechaEjecucion")) = TO_DATE(:p_FechaSistema)