/********************************************************** 
Proposito	COALESCE(: Script para recuperar informacion de las tablas de Custodia
autor		COALESCE(: NRM
fecha		COALESCE(: 28/05/2017
***********************************************************/

SELECT 	 M."IdCustodia"
		,M."FolioCustodia" 	
		,M."FechaOperacion"
		,M."FechaVencimientoOperacion"
		,M."PlazoEnDiasOperacion"
		,M."IdTipoOperacion"
		,M."IdClasificacionTipoInstrumento"		
		,I."IdInstrumento"
		,I."IdTipoInstrumento"
		,I."Nemotecnico"
		,I."IdMoneda" AS "IdMonedaInstrumento"
		,I."IdTipoReajuste" AS "IdTipoReajusteInstrumento"
		,CAST(I."FechaVencimiento" AS NVARCHAR(10)) AS "FechaVencimiento"
		,CAST(I."FechaEmision" AS NVARCHAR(10)) AS "FechaEmision"
		,I."TieneCupon" AS "TieneCorteDeCupon"
		,I."ValorizaPor"
		----------------------------------------------------------------------------
		,M."Cantidad"
		,M."ValorRescate"
		,M."Precio"
		,M."Tasa"
		,M."Monto"
		,M."PrecioSubyacente"
		,M."TasaSubyacente"
		,M."PrecioGarantia"
		,M."TasaGarantia"
		,M."TasaTIF"
		----------------------------------------------------------------------------
		,M."INGCantidad"
		,M."INGValorRescate"
		,M."INGPrecio"
		,M."INGTasa"
		,M."INGMonto"
		----------------------------------------------------------------------------
		,M."EGRCantidad"
		,M."EGRValorRescate"
		,M."EGRPrecio"
		,M."EGRTasa"
		,M."EGRMonto"
		----------------------------------------------------------------------------
		,M."IdCliente"
		,M."IdPortafolio"
		,M."TablaOrigen"
FROM (
	SELECT   "IdCartera" AS "IdCustodia"
			,"FolioCartera" AS "FolioCustodia"
			,CAST("FechaOperacion" AS NVARCHAR(10)) AS "FechaOperacion"
			,CAST("FechaVencimientoOperacion" AS NVARCHAR(10)) AS "FechaVencimientoOperacion"
			,"PlazoEnDiasOperacion"
			,"IdTipoOperacion"
			,"IdClasificacionTipoInstrumento"
			,"IdInstrumento"
			----------------------------------------------------------------------------
			,"Cantidad"
			,"ValorRescate"
			,"PrecioCompra" AS "Precio"
			,"TasaCompra" AS "Tasa"
			,"MontoCompraMonedaInstrumento" as "Monto"
			,CAST(0 as decimal(26,8)) as "PrecioSubyacente"
			,CAST(0 as decimal(26,8)) as "TasaSubyacente"
			,CAST(0 as decimal(26,8)) as "PrecioGarantia"
			,CAST(0 as decimal(26,8)) as "TasaGarantia"
			,CAST(0 as decimal(26,8)) as "TasaTIF"
			----------------------------------------------------------------------------
			,"INGCantidad"
			,"INGValorRescate"
			,"INGPrecioCompra" as "INGPrecio"
			,"INGTasaCompra" as "INGTasa"
			,"INGMontoCompraActualMonedaInstrumento" as "INGMonto"
			----------------------------------------------------------------------------
			,"EGRCantidad"
			,"EGRValorRescate"
			,"EGRPrecio"
			,"EGRTasa"
			,"EGRMontoMonedaInstrumento" as "EGRMonto"
			----------------------------------------------------------------------------
			,"IdCliente"
			,"IdPortafolio"
			,'CARTERA' AS "TablaOrigen"				
	FROM "BSCL.Custodia.BD::CUS.Cartera"
	WHERE "IdCartera" in (:IdTablaOrigen)
	UNION ALL
	SELECT   "IdSubyacente" AS "IdCustodia"
			,"FolioSubyacente" AS "FolioCustodia"
			,CAST("INGFechaOperacion" AS NVARCHAR(10)) AS "FechaOperacion"
			,'0001-01-01' AS "FechaVencimientoOperacion"
			,0 AS "PlazoEnDiasOperacion"
			,'' as "IdTipoOperacion"
			,"IdClasificacionTipoInstrumento"
			,"IdInstrumento"
			----------------------------------------------------------------------------
			,"Cantidad"
			,"ValorRescate"
			,CAST(0 as decimal(26,8)) AS "Precio"
			,CAST(0 as decimal(26,8)) AS "Tasa"
			,"PrecioSubyacente" as "PrecioSubyacente"
			,"TasaSubyacente" as "TasaSubyacente"
			,CAST(0 as decimal(26,8)) as "PrecioGarantia"
			,CAST(0 as decimal(26,8)) as "TasaGarantia"
			,CAST(0 as decimal(26,8)) as "TasaTIF"
			,"MontoSubyacenteMonedaInstrumento" as "Monto"
			----------------------------------------------------------------------------
			,"INGCantidad"
			,"INGValorRescate"
			,"INGPrecioSubyacente" as "INGPrecio"
			,"INGTasaSubyacente" as "INGTasa"
			,"INGMontoSubyacenteActualMonedaInstrumento" as "INGMonto"
			----------------------------------------------------------------------------
			,"EGRCantidad"
			,"EGRValorRescate"
			,"EGRPrecio"
			,"EGRTasa"
			,"EGRMontoMonedaInstrumento" AS "EGRMonto"
			----------------------------------------------------------------------------
			,0 as "IdCliente"
			,0 as "IdPortafolio"
			,'SUBYACENTE' AS "TablaOrigen"				
	FROM "BSCL.Custodia.BD::CUS.Subyacente"
	WHERE "IdSubyacente" in (:IdTablaOrigen)
	UNION ALL
	SELECT   "IdGarantia" AS "IdCustodia"
			,"FolioGarantia" AS "FolioCustodia"
			,CAST("FechaOperacion" AS NVARCHAR(10)) AS "FechaOperacion"
			,'0001-01-01' AS "FechaVencimientoOperacion"
			,0 AS "PlazoEnDiasOperacion"
			,'' as "IdTipoOperacion"
			,"IdClasificacionTipoInstrumento"
			,"IdInstrumento"
			----------------------------------------------------------------------------
			,"Cantidad"
			,"ValorRescate"
			,CAST(0 as decimal(26,8)) AS "Precio"
			,CAST(0 as decimal(26,8)) AS "Tasa"														
			,CAST(0 as decimal(26,8)) as "PrecioSubyacente"
			,CAST(0 as decimal(26,8)) as "TasaSubyacente"
			,"PrecioGarantia" as "PrecioGarantia"
			,"TasaGarantia" as "TasaGarantia"
			,CAST(0 as decimal(26,8)) as "TasaTIF"
			,"MontoGarantiaMonedaInstrumento" as "Monto"
			----------------------------------------------------------------------------
			,"INGCantidad"
			,"INGValorRescate"
			,"INGPrecioGarantia" as "INGPrecio"
			,"INGTasaGarantia" as "INGTasa"
			,"INGMontoGarantiaActualMonedaInstrumento" as "INGMonto"
			----------------------------------------------------------------------------
			,"EGRCantidad"
			,"EGRValorRescate"
			,"EGRPrecio"
			,"EGRTasa"
			,"EGRMontoMonedaInstrumento" as "EGRMonto"
			----------------------------------------------------------------------------
			,"IdCliente"
			,"IdPortafolio"
			,'GARANTIA' AS "TablaOrigen"				
	FROM "BSCL.Custodia.BD::GTA.Garantia"
	WHERE "IdOrigenGarantia" = 'CUS'
	 AND "IdGarantia" in (:IdTablaOrigen)
) AS M
INNER JOIN "BSCL.Plataforma.BD::INS.Instrumento" AS I ON I."IdInstrumento" = M."IdInstrumento";