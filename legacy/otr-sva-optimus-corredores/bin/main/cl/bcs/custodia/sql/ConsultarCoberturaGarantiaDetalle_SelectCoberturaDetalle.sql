SELECT 
	 GAR."NombreCliente"
	,GAR."DocumentoIdentidad"
	,GAR."IdCliente"
	,GAR."IdPortafolio"
	,GAR."CodigoPortafolio"
	,GAR."PropositoPortafolio"
	,GAR."FolioGarantia"
	,GAR."FolioCarteraGarantizada"
	,GAR."IdTipoInstrumentoGarantizado"
	,GAR."NombreTipoInstrumentoGarantizado"
	,GAR."IdInstrumentoCarteraGarantizada"
	,GAR."IdContraparteGarantia"
	,GAR."RazonSocialContraparte"
	,GAR."EsEspecifica"	
	,COALESCE(GAR."IdOperacionOrigenGarantia",0) AS "IdOperacionOrigenGarantia"
	,COALESCE(GAR."NombreOrigenGarantia",'') AS "NombreOrigenGarantia"
	,GAR."CantidadGarantia"
	,GAR."MontoValorizado"
	,GAR."MontoCoberturaEntidad"
	,GAR."PorcentajeCoberturaEntidad"
	,GAR."MontoCoberturaCorredora"
	,GAR."PorcentajeCoberturaCorredora"
	,GAR."PrecioGarantia" 
	,COALESCE(GAR."IdBolsaOperacionOrigen",'') AS "IdBolsaOperacionOrigen"
	,GAR."IdConcepto"
	,GAR."NombreConcepto"
	,GAR."FechaLiquidacion"
	,COALESCE (ORD."IdMonedaLiquidacionOrden",'')as "IdMonedaLiquidacionOperacion"
	,GAR."IdClasificacionTipoInstrumento"
	,GAR."Nemotecnico"
	,GAR."NemoGarantizado"
	,GAR."IdInstrumento"
	,GAR."IdTipoInstrumento"
	,GAR."NombreTipoInstrumento"
	,GAR."IdMonedaInstrumento"
	,GAR."IdTipoReajuste"
FROM "BSCL.Custodia.BD.Vistas::GTA.ConsultarCoberturaGarantiaDetalle" AS GAR
LEFT JOIN "BSCL.Orden.BD::ORD.Orden" AS ORD ON ORD."IdOrden" = GAR."IdOperacionOrigenGarantia" 
WHERE GAR."IdCliente"	 					= (CASE WHEN COALESCE(:p_IdCliente,0) <> 0 THEN :p_IdCliente ELSE GAR."IdCliente" END)
AND	  GAR."IdPortafolio" 					= (CASE WHEN COALESCE(:p_IdPortafolio,0) <> 0 THEN :p_IdPortafolio ELSE GAR."IdPortafolio" END)	
AND	  GAR."IdTipoInstrumentoGarantizado"	= (CASE WHEN :p_IdTipoInstrumentoGarantizado <> '' THEN :p_IdTipoInstrumentoGarantizado ELSE GAR."IdTipoInstrumentoGarantizado" END)
AND   GAR."IdEstado"						= 'VIG'