SELECT 
	  CAR."IdCliente"
	, CAR."IdCartera"
	, CAR."IdPortafolio"
	, CAR."IdEstado"
	, CAR."IdInstrumento"
	, CAR."IdTipoOperacion"
	, CAR."IdTipoComprobante"
	, CAR."IdTipoReajuste"
	, CAR."IdMonedaEmision"
	, CAR."IdModulo"
	, CAR."FolioComprobante"
	, CAR."Cantidad"
	, CAR."ValorRescate"
	, CAR."Nemotecnico"
	, CASE WHEN CAR."IdEstado" = 'LIQ' THEN 0.0 ELSE CAR."INGCantidad" END AS "INGCantidad"
	, CAR."INGTasaCompra"
	, CAR."INGPrecioCompra"
	, CAR."INGFechaLiquidacion"
	, CAR."EGRCantidad"
	, CAR."EGRFolioComprobante"
	, CAR."EGRValorRescate"
	, CAR."INGValorRescate"
	, CAR."FolioCartera"
	,'CARTERA' 													AS "TipoCartera"
	, CAR."IdEmisor"
	, CAR."FechaVencimientoInstrumento"
	, CAR."FechaVencimientoOperacion"
	, CAR."FechaEmisionInstrumento"
	, CAR."CorteMinimo"
	, CAR."PlazoEnDiasOperacion"
	, CAR."IdConcepto"
	, CAR."FechaLiquidacion"
	, CAR."IdBoveda"
	, CAR."IdMovimientoCarteraEnTransito"
	, CAR."EGRIdOperacion"
	, CAR."IdClasificacionTipoInstrumento"
	, CAR."IdMonedaAdicional"
	, CAR."IdMonedaInstrumento"
	, CAR."MontoCompra"
	, CAR."IdMesa"
	, CAR."IdBolsa"
	, CAR."IdCondicionLiquidacion"
	, CAR."IdAgente"
	, CAR."IdSucursal"
	, CAR."IdTipoCanalIngreso"
	, CAR."FolioExternoReferencia"
	, CAR."IdTipoProducto"
	, CAR."EsFungible"
	, CAR."NemoSVS"
FROM "BSCL.Custodia.BD::CUS.Cartera" AS CAR
INNER JOIN (
	SELECT 
		  "IdMovimientoCarteraEnTransito"
		, "IdCartera"
		, RANK() OVER(PARTITION BY "IdMovimientoCarteraEnTransito" ORDER BY "IdCartera" DESC) AS "Rank"	
	FROM "BSCL.Custodia.BD::CUS.Cartera"
	WHERE "FolioCartera"  IN (:FolioCarteraOrigen)
) AS CU ON CU."IdCartera" = CAR."IdCartera" AND CU."Rank" = 1;