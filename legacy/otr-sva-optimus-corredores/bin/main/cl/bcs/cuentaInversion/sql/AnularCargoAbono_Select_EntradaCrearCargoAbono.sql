SELECT
	CAST(ROW_NUMBER() over (order by CAM."IdPortafolio",CAM."IdMoneda") as BIGINT) as "NumeroCargoAbono"
	,CAM."IdPortafolio"
	,CAM."IdMoneda"
	,CASE WHEN CAM."IdTipoMovimiento" = 'MOVCAR' THEN 'MOVABN' ELSE 'MOVCAR' END as "IdTipoMovimiento" 
	,CAM."IdConcepto"
	,CAM."GlosaAnulacion" as "Descripcion"
	,COALESCE(CL."IdCondicionDeLiquidacion",'T0') as "IdCondicionDeLiquidacion"
	,TO_NVARCHAR(CASE WHEN CAM."FechaEfectivaMovimiento" <= :FechaMovimiento THEN :FechaMovimiento ELSE CAM."FechaEfectivaMovimiento" END, 'YYYY-MM-DD') as "FechaCondicionDeLiquidacion"
	,CAM."Monto"
	,CAM."IdEjecutivo"
	,CAM."IdSucursal"
	,CAM."IdTipoProducto"
	,CAM."IdTipoOperacion"
	,CAM."IdOperacion"
	,TO_NVARCHAR(CAM."FechaOperacion", 'YYYY-MM-DD') AS "FechaOperacion"
	,TO_NVARCHAR(CAM."FechaLiquidacionOperacion", 'YYYY-MM-DD') AS "FechaLiquidacionOperacion" 
	,TO_NVARCHAR(CAM."FechaVencimientoOperacion", 'YYYY-MM-DD') AS "FechaVencimientoOperacion"
	,CAM."IdMonedaOperacion"
	,CAM."MontoOperacion"
	,CAM."TipoCambioOperacion"
	,CAM."IdContraparte"
	,CAM."IdTipoComprobante"
	,CAM."IdComprobante"
	,CAM."FolioComprobante"
	,CAM."IdComprobanteDetalle"
	,CAM."IdComprobanteFormaDePago"
	,CAM."IdTipoMovimientoAsociado"
	,CAM."IdMovimientoAsociado"
	,TO_NVARCHAR(CAM."FechaComprobante", 'YYYY-MM-DD') AS "FechaComprobante"
	,CAM."IdPersonaPagoCobro"
	,CAM."IdInstrumento"
	,CAM."IdTipoInstrumento"
	,0.0 AS "Cantidad"
	,CAM."Nemo"
	,CAM."EsIndicadorBilateral"
	,'N' as "EsCargoAbonoPorTraspaso"
	,TO_BIGINT(0) as "IdPortafolioTraspaso"
	,CAM."GeneroContraparteEnTesoreria"
	,'N' as "CertificadoAutomatico"
FROM "BSCL.CuentaInversion.BD::CTA.AnularCargoAbono_SRV_Movimientos_Anular" as CAM
LEFT JOIN "BSCL.Plataforma.BD::PLA.ObtenerPlazo_Fechas" AS TP ON TP."FechaHasta" = CAM."FechaEfectivaMovimiento"
LEFT JOIN "BSCL.Plataforma.BD::PLA.CondicionDeLiquidacion" AS CL ON CL."PlazoEnDias" = TP."Plazo"
WHERE CAM."IdEmpresa" = :IdEmpresa;