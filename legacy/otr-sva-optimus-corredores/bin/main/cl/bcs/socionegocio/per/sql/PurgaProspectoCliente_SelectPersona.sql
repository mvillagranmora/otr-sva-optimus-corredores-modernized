SELECT 
	 PER."IdPersona"
	,COALESCE(CLI."IdCliente", 0) AS "IdCliente"
	,DOC."DocumentoIdentidad" AS "RutTitular"
	,PER."Nombres"
    ,PER."ApellidoPaterno"
	,PER."ApellidoMaterno" 
	,PER."IdRangoPatrimonio"
	,PER."Sexo"
	,PER."IdPaisNacimiento"
	,PER."EstadoCivil"
	,PER."IdProfesion"
	,PER."IdPaisResidencia"
	,TO_NVARCHAR(PER."FechaNacimiento") AS "FechaNacimiento"
	,TO_NVARCHAR(PER."FechaDefuncion") AS "FechaDefuncion"
	,PER."CodigoRangoRenta"
	,PER."IdDireccionFisicaPrincipal"
	,PER."IdDireccionElectronicaPrincipal"
	,PER."IdTelefonoPrincipal"
	,CASE WHEN PER."IdCarga" <> 0 THEN 'S' ELSE 'N' END AS "EsClienteSebra"
FROM "BSCL.SocioNegocio.BD::PER.DocumentoIdentidad" DOC 
INNER JOIN "BSCL.SocioNegocio.BD::PER.Persona" PER ON DOC."IdPersona" = PER."IdPersona" AND PER."IdDocumentoIdentidad" = DOC."IdDocumentoIdentidad"
LEFT JOIN "BSCL.SocioNegocio.BD::CLI.Cliente" CLI ON PER."IdPersona" = CLI."IdPersona" 
WHERE DOC."DocumentoIdentidad" IN (:DocumentosIdentidad);