SELECT 
     PER."Tipo" AS "IdTipoPersona"
    ,PER."IdPersona" AS "IdPersona"
    ,DOCI."IdTipoDocumentoIdentidad" AS "TipoDocumento"
	,DOCI."DocumentoIdentidad" AS "NumeroDocumento"
	,PER."Nombres"
	,PER."ApellidoPaterno"
	,PER."ApellidoMaterno"
	,COALESCE(PER."Sexo", '') AS "IdGenero"
	,PER."RazonSocial"
	,COALESCE(PER."IdPaisNacimiento", 0) AS "IdPaisNacimientoConstitucion"
	,COALESCE(TO_NVARCHAR(PER."FechaNacimiento", 'YYYY-MM-DD'), '0001-01-01') AS "FechaNacimientoConstitucion"
	,COALESCE(PER."EstadoCivil", '') AS "IdEstadoCivil"
	,COALESCE(PER."RegimenConyugal", '')  AS "IdRegimenConyugal"
	,COALESCE(PER."IdPaisResidencia", 0) AS "IdPaisResidenciaCasaMatriz"
	,COALESCE(DIRF."IdCiudad", 0) AS "IdCiudad"
	,COALESCE(DIRF."IdDivisionPais", 0) AS "IdComuna"
	,COALESCE(DIRF."Calle",'') AS "Calle"
	,COALESCE(DIRF."Numero",'') AS "Numero"
	,COALESCE(DIRF."Departamento",'') AS "Complemento"
	,COALESCE(TEL."IdTipoTelefono",'') AS "TipoTelefono"
	,COALESCE(TEL."Numero",'') AS "Telefono"
	,COALESCE(DIRE."Direccion",'') AS "Email"
	,COALESCE(PER."IdPersonaConyuge", 0) AS "IdPersonaConyuge"
	,TEL."IdTelefono" AS "IdTelefono" 
	,DIRE."IdDireccionElectronica" AS "IdDireccionElectronica" 
	,DIRF."IdDireccionFisica" AS "IdDireccionFisica"
	,COALESCE(PER."IdSituacionLaboral",'') AS "IdSituacionLaboral"
FROM "BSCL.SocioNegocio.BD::PER.Persona" AS PER
LEFT JOIN "BSCL.SocioNegocio.BD::PER.DocumentoIdentidad" AS DOCI ON PER."IdPersona" = DOCI."IdPersona"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.DireccionFisica" AS DIRF ON PER."IdPersona" = DIRF."IdPersona" AND PER."IdDireccionFisicaPrincipal" = DIRF."IdDireccionFisica"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.DireccionElectronica" AS DIRE ON PER."IdPersona" = DIRE."IdPersona" AND PER."IdDireccionElectronicaPrincipal" = DIRE."IdDireccionElectronica"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.Telefono" AS TEL ON PER."IdPersona" = TEL."IdPersona" AND PER."IdTelefonoPrincipal" = TEL."IdTelefono"
WHERE DOCI."DocumentoIdentidad" = (:DocumentoIdentidad);