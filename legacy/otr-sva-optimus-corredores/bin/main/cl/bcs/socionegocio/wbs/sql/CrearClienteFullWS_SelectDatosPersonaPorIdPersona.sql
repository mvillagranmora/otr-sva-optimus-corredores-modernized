SELECT 
	PERS."Tipo" AS "IdTipoPersona",
	PERS."Nombres", 
	PERS."ApellidoPaterno",
	PERS."ApellidoMaterno",
	COALESCE(PERS."Sexo", '') AS "IdGenero",
	PERS."RazonSocial",
	COALESCE(PERS."IdPaisNacimiento", 0 ) AS "IdPaisNacimientoConstitucion",
	--PERS."FechaNacimiento" AS "FechaNacimientoConstitucion",
	COALESCE(TO_NVARCHAR(PERS."FechaNacimiento", 'YYYY-MM-DD'), '0001-01-01') AS "FechaNacimientoConstitucion",
	COALESCE(PERS."EstadoCivil", '') AS "IdEstadoCivil",
	COALESCE(PERS."RegimenConyugal", '') AS "IdRegimenConyugal",
	PERS."IdPersonaConyuge" AS "IdPersonaConyuge",
	COALESCE(PERS."IdPersonaEmpleador", 0) AS "IdPersonaEmpleador",
	COALESCE(PERS."IdPaisResidencia", 0 ) AS "IdPaisResidenciaCasaMatriz",
	COALESCE(PERS."ResidenciaTributariaExtranjera", '') AS "ResidenciaTriburariaFueraChile",
	COALESCE(PERS."IdPaisNacionalidadPrincipal", 0 ) AS "IdPaisNacionalidadPrincipal",
	COALESCE(PERS."IdGiroPrincipal", 0 ) AS "IdGiro",
	COALESCE(PERS."IdProfesion", 0 ) AS "IdProfesionActividad",
	PERS."Cargo",
	PERS."DetalleCargo",
	COALESCE(PERS."IdRangoPatrimonio", 0 ) AS "RangoPatrimonio",
	--PERS."FechaInicioActividad" AS "InicioActividad",
	COALESCE(TO_NVARCHAR(PERS."FechaInicioActividad", 'YYYY-MM-DD'), '0001-01-01')  AS "InicioActividad",
	PERS."GlobalLegalEntity" AS "GlobalLegal",
	COALESCE(PERS."IdSituacionLaboral", '') AS "IdSituacionLaboral",
	COALESCE(PERS."IdTipoCanalIngresoCorredor", '') AS "IdTipoCanalIngresoCorredor"
FROM "BSCL.SocioNegocio.BD::PER.Persona" AS PERS  
WHERE PERS."IdPersona" IN (:IdPersona);