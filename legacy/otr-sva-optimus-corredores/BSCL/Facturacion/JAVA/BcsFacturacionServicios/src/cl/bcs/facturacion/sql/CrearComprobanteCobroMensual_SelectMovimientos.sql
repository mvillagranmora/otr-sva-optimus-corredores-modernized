       'N' AS "ActualizarCustodia", 
       'S' AS "ActualizarCuentaInversion", 
       'S' AS "ActualizarTesoreria", 
       CAST(:idsFechaSistema AS nvarchar(10)) As "FechaMovimientoComprobante", 
       '0001-01-01' AS "FechaTipoCambio",       
       'N' AS "ActualizarCustodiaRelacionado",
       Max("IdMonedaMovimientoComprobante") AS "IdMonedaMovimientoComprobante", 
       Sum("MontoMovimientoComprobante") AS "MontoMovimientoComprobante",       
       Sum("MontoLiquidacion") AS "MontoLiquidacion",        
       '' AS "IdMonedaSpot",
       'N' AS "EsFungible",
       :idsCrearComprobanteAutomatico AS "CrearComprobanteAutomatico",
       Max('T0') AS "IdCondicionLiquidacion", ----revisar
       CAST(0 AS BIGINT) AS "IdInstrumentoRelacionado",
       'MODPREFNORM' AS "ModPrefFact"
FROM (
       SELECT 
		       "IdMovimientoComprobante",
		       CAST(:idsEmpresa AS BigInt) AS "IdEmpresa",
		       Max('') As "SecuenciaAgrupacion", 
		       MvtoCmbte."IdCliente", 
		       MvtoCmbte."IdPortafolio", 
		       Max("IdEmpleadoDigitador") AS "IdEmpleadoDigitador", 
		       Max("IdSucursalEmpleadoDigitador") AS "IdSucursalEmpleadoDigitador", 
		       Max("IdEmpleadoEjecutivoPortafolio") AS "IdEmpleadoEjecutivoPortafolio", 
		       Max("IdSucursalEmpleadoEjecutivoPortafolio") AS "IdSucursalEmpleadoEjecutivoPortafolio", 
		       MvtoCmbte."IdTipoProducto", 
		       Max("IdMoneda") AS "IdMoneda",
		       CASE
		         WHEN Max(TipOpe."Accion") = 'COMPRA' Then 'COMMOC'         
		       ELSE 'VENMOC'
		       END AS "IdTipoOperacion", 
		       Max("IdBoveda") AS "IdBoveda",
		       "IdBolsa" AS "IdBolsa", 
		       Max("IdTipoConvenio") AS "IdTipoConvenio",
		       Max("IdFormaCustodia") AS "IdFormaCustodia",
		       "IdTipoCanalIngreso",  
		       (SELECT Sum("MontoCobro")
		       FROM "BSCL.Facturacion.BD::FAC.MovimientoComprobanteCobro" AS MontoCob
		       WHERE MontoCob."IdMovimientoComprobante" = MvtoCmbte."IdMovimientoComprobante") AS "Monto",
		       Max(Conc."Nombre" || ' ' || :idsMesProcesar || ' ' || TipOpe."Nombre") As "Glosa",
		       Max("DocumentoIdentidad") AS "DocumentoIdentidad", 
		       Max("TipoDocumentoIdentidad") AS "TipoDocumentoIdentidad", 
		       Max("NombreLargoCliente") AS "NombreLargoCliente", 
		       Max("DireccionFacturacion") AS "DireccionFacturacion",
		       Max("NombreEmpleadoDigitador") AS "NombreEmpleadoDigitador", 
		       Max("NombreSucursalEmpleadoDigitador") AS "NombreSucursalEmpleadoDigitador", 
		       Max("NombreEmpleadoEjecutivoPortafolio") AS "NombreEmpleadoEjecutivoPortafolio", 
		       Max("NombreSucursalEmpleadoEjecutivoPortafolio") AS "NombreSucursalEmpleadoEjecutivoPortafolio", 
		       Max("EsCuentaPropia") AS "EsCuentaPropia",
		       Max("IndicadorOrdenDirecta") AS "IndicadorOrdenDirecta",
		       Max("EsPrecioPrima") AS "EsPrecioPrima", 
		       Max("EsEnRueda") AS "EsEnRueda", 
		       Max("EsRuteo") AS "EsRuteo", 
		       Max("EsIngresoAutomatico") AS "EsIngresoAutomatico",        
		       "IdMonedaLiquidacion",        
		       Max("IdMonedaMovimientoComprobante") AS "IdMonedaMovimientoComprobante", 
		       (SELECT Sum("MontoMovimientoComprobanteCobro")
		       FROM "BSCL.Facturacion.BD::FAC.MovimientoComprobanteCobro" AS MontoCobMvto
		       WHERE MontoCobMvto."IdMovimientoComprobante" = MvtoCmbte."IdMovimientoComprobante") AS "MontoMovimientoComprobante",
		       (SELECT Sum("MontoLiquidacionCobro")
		       FROM "BSCL.Facturacion.BD::FAC.MovimientoComprobanteCobro" AS MontoCobLiquidacion
		       WHERE MontoCobLiquidacion."IdMovimientoComprobante" = MvtoCmbte."IdMovimientoComprobante") AS "MontoLiquidacion"    
       FROM "BSCL.Facturacion.BD::FAC.MovimientoComprobante" As MvtoCmbte
         INNER JOIN "BSCL.Plataforma.BD::PLA.Concepto" AS Conc
            ON Conc."IdConcepto" = 'COMMEN'
         LEFT JOIN "BSCL.Plataforma.BD::INS.TipoOperacion" AS TipOpe
            ON TipOpe."IdTipoOperacion" = MvtoCmbte."IdTipoOperacion"  
       WHERE MvtoCmbte."IdComprobante" IN (:idsComprobante)  
       GROUP BY "IdMovimientoComprobante", "IdCliente", "IdPortafolio", "IdBolsa", "IdMonedaLiquidacion", MvtoCmbte."IdTipoProducto", 
                MvtoCmbte."IdTipoOperacion", "IdTipoCanalIngreso"
     ) AS MvtoTotCobros
GROUP BY "IdCliente", "IdPortafolio", "IdBolsa", "IdMonedaLiquidacion", "IdTipoProducto", "IdTipoOperacion", "IdTipoCanalIngreso";
