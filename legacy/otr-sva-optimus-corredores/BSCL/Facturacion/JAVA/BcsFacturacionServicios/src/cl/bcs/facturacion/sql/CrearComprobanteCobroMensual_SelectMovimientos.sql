      Max("IdMovimientoComprobante") As "NumeroMvtoCmbte",
      Max("IdEmpresa") AS "IdEmpresa",
	  'COMMEN' AS "IdConcepto",
      '' As "SecuenciaAgrupacion",  
      "IdCliente", 
      "IdPortafolio", 
      Max("IdEmpleadoDigitador") AS "IdEmpleadoDigitador", 
      Max("IdSucursalEmpleadoDigitador") AS "IdSucursalEmpleadoDigitador", 
      Max("IdEmpleadoEjecutivoPortafolio") AS "IdEmpleadoEjecutivoPortafolio", 
      Max("IdSucursalEmpleadoEjecutivoPortafolio") AS "IdSucursalEmpleadoEjecutivoPortafolio",
      CAST(0 AS Bigint) AS "IdInstrumento", 
      CAST(0 AS BIGINT) AS "IdInstrumentoSubyacente", 
      '' AS "IdTipoInstrumento", 
       '' AS "IdTipoInstrumentoSubyacente",
       '' AS "IdClasificacionTipoInstrumento", 
       "IdTipoProducto", 
       Max("IdMoneda") AS "IdMoneda",
       'FOE' AS "IdTipoComprobante",
       0 AS "IdComprobante",
       "IdTipoOperacion",
       CAST(0 AS BIGINT) AS "IdMovimientoRelacionado", 
       Max("IdBoveda") AS "IdBoveda", 
       CAST(0 AS BIGINT) AS "IdCorredoraContraparte",
       CAST(:idsFechaSistema AS nvarchar(10)) AS "FechaLiquidacion",       
       CAST(:idsFechaSistema AS nvarchar(10)) AS "FechaVencimiento",
       "IdBolsa" AS "IdBolsa", 
       '' AS "IdTipoReajuste", 
       Max("IdTipoConvenio") AS "IdTipoConvenio",
       Max("IdFormaCustodia") AS "IdFormaCustodia",
       '' AS "IdEmisor", 
       'ING' As "IdEstadoFacturacion", 
       CAST(0 AS BIGINT) AS "IdOrden", 
       CAST(0 AS BIGINT) AS "IdAsignacion",
