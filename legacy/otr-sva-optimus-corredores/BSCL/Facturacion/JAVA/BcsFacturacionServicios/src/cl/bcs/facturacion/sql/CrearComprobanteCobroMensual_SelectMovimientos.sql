       CAST(0 AS DECIMAL(26,8)) AS "MontoAPlazo", 
       CAST(0 AS DECIMAL(26,8)) AS "PrecioAPlazo", 
       0 AS "IdMovimientoOdRelacionado", 
       '' AS "IdMonedaSubyacente",
       "IdMonedaLiquidacion", 
       CAST(0 AS DECIMAL(26,8)) AS "ValorTipoCambio", 
       'N' AS "EsVentaCorta", 
       CAST(0 AS BIGINT) As "IdComprobanteReferencia",
       '' As "IdTipoComprobanteReferencia", 
       0 As "FolioComprobanteReferencia",
       '' As "FechaComprobanteReferencia", 
