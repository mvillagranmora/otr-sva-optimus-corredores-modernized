       '0001-01-01' AS "FechaTransaccion",
       '0001-01-01' AS "FechaParidad",       
       CAST(0 AS DECIMAL(26,8)) AS "ValorParidad", 
       CAST(0 AS DECIMAL(26,8)) AS "ValorCaptacionMonedaOrigen", 
       0 As "FolioComprobante", 
       CAST(0 AS DECIMAL(26,8)) AS "Tasa", 
       CAST(0 AS DECIMAL(26,8)) AS "Cantidad", 
       CAST(0 AS DECIMAL(26,8)) AS "Precio", 
       Sum("Monto") AS "Monto",         
       CAST(0 AS DECIMAL(26,8)) AS "MontoDescuento",
       CAST(0 AS DECIMAL(26,8)) AS "MontoInteres",       
       Max("Glosa") As "Glosa",
       CAST(0 AS DECIMAL(26,8)) AS "ValorRescate", 
       CAST(0 AS DECIMAL(26,8)) AS "TasaAgente", 
       CAST(0 AS DECIMAL(26,8)) AS "Spread", 
       CAST(0 AS DECIMAL(26,8)) AS "DiasPlazo", 
       '' AS "CodigoCanalIngreso", 
       Max("DocumentoIdentidad") AS "DocumentoIdentidad", 
       Max("TipoDocumentoIdentidad") AS "TipoDocumentoIdentidad", 
       Max("NombreLargoCliente") AS "NombreLargoCliente", 
       Max("DireccionFacturacion") AS "DireccionFacturacion",
       Max("NombreEmpleadoDigitador") AS "NombreEmpleadoDigitador", 
       Max("NombreSucursalEmpleadoDigitador") AS "NombreSucursalEmpleadoDigitador", 
       Max("NombreEmpleadoEjecutivoPortafolio") AS "NombreEmpleadoEjecutivoPortafolio", 
       Max("NombreSucursalEmpleadoEjecutivoPortafolio") AS "NombreSucursalEmpleadoEjecutivoPortafolio",
       CAST(0 AS BIGINT) AS "FolioCartera", 
       '' AS "CodigoTipoProducto", 
       '' AS "CodigoTipoOperacion", 
       '' AS "CodigoBolsa", 
       '' AS "NombreTipoInstrumento",
       '' AS "NombreTipoInstrumentoSubyacente", 
       '' AS "NombreClasificacionTipoInstrumento", 
       '' AS "NemotecnicoInstrumento", 
       '' AS "NemotecnicoSubyacente", 
       '' AS "RazonSocialEmisor",       
       '0001-01-01' AS "FechaEmision",       
       CAST(0 AS DECIMAL(26,8)) AS "TasaEmision",
       CAST(0 AS DECIMAL(26,8)) AS "TasaOperacion",
       CURRENT_UTCTIMESTAMP As "FechaIngresoRegistro", 
       CAST(:idsFechaSistema AS nvarchar(10)) AS "FechaSistema", 
       'N' AS "EsComprobIndividual", 
       Max("EsCuentaPropia") AS "EsCuentaPropia",
       Max("IndicadorOrdenDirecta") AS "IndicadorOrdenDirecta",
       Max("EsPrecioPrima") AS "EsPrecioPrima", 
       Max("EsEnRueda") AS "EsEnRueda", 
       Max("EsRuteo") AS "EsRuteo", 
