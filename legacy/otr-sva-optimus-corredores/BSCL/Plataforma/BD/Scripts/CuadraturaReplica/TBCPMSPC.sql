--CABECERA
--cantidad de registros por rut, secuencia y tipo
	select * from 
	(
		SELECT count(1) AS registros,RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM 
		FROM BSCL."2022_05_31_TBCPMSPC" 
		WHERE "COD_PER" = '2022-05' AND "ESTADO" = 'E' and FEC_OPERAC  = '2022-05-31'
		GROUP BY RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM
	) as sebra
	left join 
	(
		SELECT count(1) AS registros,RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM 
		FROM BSCL."BSCL.Replica.BD.Vistas::Sebra.TBCPMSPC" 
		WHERE "COD_PER" = '2022-05' AND "ESTADO" = 'E' and FEC_OPERAC  = '2022-05-31'
		GROUP BY RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM
	) as optimus
	on sebra.RUT_CLI = optimus.RUT_CLI 
	AND sebra.SEC_RUT_CLI = optimus.SEC_RUT_CLI 
	AND sebra.TIPO_COMPROM = optimus.TIPO_COMPROM
	where  sebra.registros != optimus.registros or optimus.registros is null
	
--CANTIDAD ( solo hay estados E)
		
	select *	
	from 
	(
		SELECT RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC, SUM(CANTIDAD_CAPITAL) AS cant
		FROM BSCL."2022_05_31_TBCPMSPC" 
		WHERE "COD_PER" = '2022-05' AND "ESTADO" = 'E'  and FEC_OPERAC  = '2022-05-31'
		GROUP BY RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC
	) as sebra
	,
	(
		SELECT RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC, SUM(CANTIDAD_CAPITAL) AS cant
		FROM BSCL."BSCL.Replica.BD.Vistas::Sebra.TBCPMSPC" 
		WHERE "COD_PER" = '2022-05' AND "ESTADO" = 'E'  and FEC_OPERAC  = '2022-05-31'
		GROUP BY RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC
	) as optimus
	where sebra.RUT_CLI = optimus.RUT_CLI 
	AND sebra.SEC_RUT_CLI = optimus.SEC_RUT_CLI 
	AND sebra.TIPO_COMPROM = optimus.TIPO_COMPROM
	AND sebra.FEC_OPERAC = optimus.FEC_OPERAC
	AND sebra.cant != optimus.cant
	--AND abs(sebra.cant-optimus.cant ) > 0.001
	
--MONTOS ( solo hay estados E)
		
	select ABS(sebra.mont-optimus.mont),sebra.mont,optimus.mont,* 	
	from 
	(
		SELECT RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC, SUM(MONTO_CAPITAL) AS mont
		FROM BSCL."2022_05_31_TBCPMSPC" 
		WHERE "COD_PER" = '2022-05' AND "ESTADO" = 'E'  and FEC_OPERAC  = '2022-05-31'
		GROUP BY RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC
	) as sebra
	,
	(
		SELECT RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC, SUM(MONTO_CAPITAL) AS mont
		FROM BSCL."BSCL.Replica.BD.Vistas::Sebra.TBCPMSPC" 
		WHERE "COD_PER" = '2022-05' AND "ESTADO" = 'E'  and FEC_OPERAC  = '2022-05-31'
		GROUP BY RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC
	) as optimus
	where sebra.RUT_CLI = optimus.RUT_CLI 
	AND sebra.SEC_RUT_CLI = optimus.SEC_RUT_CLI 
	AND sebra.TIPO_COMPROM = optimus.TIPO_COMPROM
	AND sebra.FEC_OPERAC = optimus.FEC_OPERAC
	AND ABS(sebra.mont-optimus.mont) > 0.0001
	
--cantidad_comprom
		
	select 
	sebra.cant,optimus.cant,* 	
	from 
	(
		SELECT RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC, SUM(CANTIDAD_COMPROM) AS cant
		FROM BSCL."2022_05_31_TBCPMSPC" 
		WHERE "COD_PER" = '2022-05' AND "ESTADO" = 'E' AND "TIPO_COMPROM" = 'VP'  and FEC_OPERAC  = '2022-05-31'
		GROUP BY RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC
	) as sebra
	,
	(
		SELECT RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC, SUM(CANTIDAD_COMPROM) AS cant
		FROM BSCL."BSCL.Replica.BD.Vistas::Sebra.TBCPMSPC" 
		WHERE "COD_PER" = '2022-05' AND "ESTADO" = 'E' AND "TIPO_COMPROM" = 'VP'  and FEC_OPERAC  = '2022-05-31'
		GROUP BY RUT_CLI,SEC_RUT_CLI,TIPO_COMPROM,FEC_OPERAC
	) as optimus
	where sebra.RUT_CLI = optimus.RUT_CLI 
	AND sebra.SEC_RUT_CLI = optimus.SEC_RUT_CLI 
	AND sebra.TIPO_COMPROM = optimus.TIPO_COMPROM
	AND sebra.FEC_OPERAC = optimus.FEC_OPERAC
	AND (sebra.cant != optimus.cant)
	

	
