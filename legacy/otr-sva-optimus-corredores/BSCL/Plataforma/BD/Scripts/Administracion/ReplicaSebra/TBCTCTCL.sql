SALDO_COMIS_DIA_CALC, SALDO_COMIS_DIA_MIN, SALDO_COMPROM, SALDO_DERECHOS, SALDO_DISP, SALDO_GASTOS, SALDO_LIBRE_01, SALDO_LIBRE_02, SALDO_LIBRE_03, 
SALDO_NEG_INST, SALDO_RETEN, SALDO_TP, COMPRAS_24, VENTAS_24, COMPRAS_48, VENTAS_48, RECIBIR_24, TRANSF_24, TRANSF_48, APORTES_24, APORTES_48, 
RESCATE_24, RESCATE_48, RESCATE_72, RESCATE_96, RESCATE_120, SALDO_AFECTO_GMF, MONTO_RETENIDO, COMPRAS_72, VENTAS_72, TRANSF_72, SALDO_HABERES 
FROM BSCL.TBCTCTCL WHERE COD_PER = '2021-04' AND rut_cli = ' 76328896-K'

SELECT COD_PER, RUT_CLI, SEC_RUT_CLI, CTA_CLI, FEC_COBRO_GASTO, FEC_SALDO_NEG, FEC_ULT_OPE, MONTO_OPE_ACC, SALDO_COMIS, SALDO_COMIS_DIA, 
SALDO_COMIS_DIA_CALC, SALDO_COMIS_DIA_MIN, SALDO_COMPROM, SALDO_DERECHOS, SALDO_DISP, SALDO_GASTOS, SALDO_LIBRE_01, SALDO_LIBRE_02, SALDO_LIBRE_03, 
SALDO_NEG_INST, SALDO_RETEN, SALDO_TP, COMPRAS_24, VENTAS_24, COMPRAS_48, VENTAS_48, RECIBIR_24, TRANSF_24, TRANSF_48, APORTES_24, APORTES_48, 
RESCATE_24, RESCATE_48, RESCATE_72, RESCATE_96, RESCATE_120, SALDO_AFECTO_GMF, MONTO_RETENIDO, COMPRAS_72, VENTAS_72, TRANSF_72, SALDO_HABERES 
FROM "BSCL"."BSCL.Replica.BD.Vistas::Sebra.TBCTCTCL" ctcl
WHERE COD_PER = '2021-04' AND "IdCarga" > 0

--cuadre cantidad de registros
SELECT SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI,OPT.RUT_CLI,OPT.SEC_RUT_CLI,OPT.CTA_CLI
FROM BSCL.TBCTCTCL SEBRA
LEFT JOIN "BSCL"."BSCL.Replica.BD.Vistas::Sebra.TBCTCTCL" OPT ON OPT.SEC_RUT_CLI NOT IN ('APV-AN','APV-A') AND OPT."IdCarga" > 0 AND SEBRA.RUT_CLI = OPT.RUT_CLI AND SEBRA.SEC_RUT_CLI = OPT.SEC_RUT_CLI AND OPT.CTA_CLI = SEBRA.CTA_CLI
WHERE SEBRA.COD_PER = '2021-04' AND OPT.RUT_CLI IS NULL;

--saldo disponible
SELECT SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI,SUM(SEBRA.SALDO_DISP),SUM(OPT.SALDO_DISP),SUM(SEBRA.SALDO_RETEN),SUM(OPT.SALDO_RETEN),SUM(SEBRA.saldo_tp),SUM(OPT.saldo_tp)
FROM BSCL.TBCTCTCL SEBRA
LEFT JOIN "BSCL"."BSCL.Replica.BD.Vistas::Sebra.TBCTCTCL" OPT ON OPT.SEC_RUT_CLI NOT IN ('APV-AN','APV-A') AND OPT."IdCarga" > 0 AND SEBRA.RUT_CLI = OPT.RUT_CLI AND SEBRA.SEC_RUT_CLI = OPT.SEC_RUT_CLI AND OPT.CTA_CLI = SEBRA.CTA_CLI
WHERE SEBRA.COD_PER = '2021-04'
GROUP BY  SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI
HAVING SUM(SEBRA.SALDO_DISP) != SUM(OPT.SALDO_DISP)
--AND SUM(SEBRA.SALDO_DISP + sebra.SALDO_RETEN) != SUM(OPT.SALDO_DISP + opt.SALDO_RETEN);

--saldo retenido
SELECT SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI,SUM(SEBRA.SALDO_RETEN),SUM(OPT.SALDO_RETEN),SUM(SEBRA.SALDO_DISP),SUM(OPT.SALDO_DISP),SUM(SEBRA.saldo_tp),SUM(OPT.saldo_tp),SUM(SEBRA.SALDO_LIBRE_01),SUM(OPT.SALDO_LIBRE_01)
FROM BSCL.TBCTCTCL SEBRA
LEFT JOIN "BSCL"."BSCL.Replica.BD.Vistas::Sebra.TBCTCTCL" OPT ON OPT.SEC_RUT_CLI NOT IN ('APV-AN','APV-A') AND OPT."IdCarga" > 0 AND SEBRA.RUT_CLI = OPT.RUT_CLI AND SEBRA.SEC_RUT_CLI = OPT.SEC_RUT_CLI AND OPT.CTA_CLI = SEBRA.CTA_CLI
WHERE SEBRA.COD_PER = '2021-04'
GROUP BY  SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI
HAVING SUM(SEBRA.SALDO_RETEN) != SUM(OPT.SALDO_RETEN)
AND SUM(SEBRA.SALDO_DISP + sebra.SALDO_RETEN) != SUM(OPT.SALDO_DISP + opt.SALDO_RETEN);

--saldo garantia
SELECT SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI,SUM(SEBRA.SALDO_LIBRE_01),SUM(OPT.SALDO_LIBRE_01),SUM(SEBRA.SALDO_DISP),SUM(OPT.SALDO_DISP),SUM(SEBRA.SALDO_RETEN),SUM(OPT.SALDO_RETEN),SUM(SEBRA.SALDO_TP),SUM(OPT.SALDO_TP)
FROM BSCL.TBCTCTCL SEBRA
LEFT JOIN "BSCL"."BSCL.Replica.BD.Vistas::Sebra.TBCTCTCL" OPT ON OPT.SEC_RUT_CLI NOT IN ('APV-AN','APV-A') AND OPT."IdCarga" > 0 AND SEBRA.RUT_CLI = OPT.RUT_CLI AND SEBRA.SEC_RUT_CLI = OPT.SEC_RUT_CLI AND OPT.CTA_CLI = SEBRA.CTA_CLI
WHERE SEBRA.COD_PER = '2021-04'
GROUP BY  SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI
HAVING SUM(SEBRA.SALDO_LIBRE_01) != SUM(OPT.SALDO_LIBRE_01)

--saldo plazo
SELECT opt."IdPortafolio",SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI,SUM(SEBRA.saldo_tp),SUM(OPT.saldo_tp),SUM(SEBRA.SALDO_LIBRE_01),SUM(OPT.SALDO_LIBRE_01),
SUM(SEBRA.SALDO_DISP),SUM(OPT.SALDO_DISP),SUM(SEBRA.SALDO_RETEN),SUM(OPT.SALDO_RETEN)
FROM BSCL.TBCTCTCL SEBRA
LEFT JOIN "BSCL"."BSCL.Replica.BD.Vistas::Sebra.TBCTCTCL" OPT ON OPT.SEC_RUT_CLI NOT IN ('APV-AN','APV-A') AND OPT."IdCarga" > 0 AND SEBRA.RUT_CLI = OPT.RUT_CLI AND SEBRA.SEC_RUT_CLI = OPT.SEC_RUT_CLI AND OPT.CTA_CLI = SEBRA.CTA_CLI
WHERE SEBRA.COD_PER = '2021-04'
GROUP BY  SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.CTA_CLI,opt."IdPortafolio"
HAVING abs(SUM(SEBRA.SALDO_TP) - SUM(OPT.SALDO_TP)) > 1
AND SUM(SEBRA.SALDO_DISP + SEBRA.SALDO_TP) != SUM(OPT.SALDO_DISP + OPT.SALDO_TP);
