FROM TBCTCURV SEBRA
LEFT JOIN "BSCL.Replica.BD.Vistas::Sebra.TBCTCURV" OPT ON SEBRA.RUT_CLI = OPT.RUT_CLI AND SEBRA.SEC_RUT_CLI = OPT.SEC_RUT_CLI
AND TRIM(SEBRA.NEMO) = OPT.NEMO AND CASE SEBRA.COD_BOVEDA WHEN 'TOT' THEN 'TOT' ELSE 'DCV' END = OPT.COD_BOVEDA
WHERE SEBRA.COD_PER = '2024-10' AND OPT.NEMO IS NOT NULL  AND SEBRA.RUT_CLI != 'OFICINA    '
GROUP BY SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.NEMO,SEBRA.COD_BOVEDA
HAVING SUM(SEBRA.CAN_COM_PLAZO) != sum(OPT.CAN_COM_PLAZO)

