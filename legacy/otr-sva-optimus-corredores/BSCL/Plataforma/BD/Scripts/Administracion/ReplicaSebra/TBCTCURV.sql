SELECT * FROM "BSCL.Replica.BD.Vistas::Sebra.TBCTCURV"
  
--cantidad de registros
SELECT SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.NEMO,SEBRA.COD_BOVEDA,SEBRA.CAN_CUSTODIA,SEBRA.CAN_COM_PLAZO,SEBRA.CAN_VEN_PLAZO,OPT.NEMO
FROM TBCTCURV SEBRA
LEFT JOIN "BSCL.Replica.BD.Vistas::Sebra.TBCTCURV" OPT ON UPPER(SEBRA.RUT_CLI) = OPT.RUT_CLI AND SEBRA.SEC_RUT_CLI = OPT.SEC_RUT_CLI
AND TRIM(SEBRA.NEMO) = OPT.NEMO --AND CASE SEBRA.COD_BOVEDA WHEN 'TOT' THEN 'TOT' ELSE 'DCV' END = OPT.COD_BOVEDA
AND TRIM(SEBRA.COD_BOVEDA) = TRIM(OPT.COD_BOVEDA)
WHERE SEBRA.COD_PER = '2024-10' AND OPT.NEMO IS NULL  AND SEBRA.RUT_CLI != 'OFICINA    ' 

--can custodia
SELECT SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.NEMO,SEBRA.COD_BOVEDA,OPT.COD_BOVEDA,SUM(SEBRA.CAN_CUSTODIA),sum(OPT.CAN_CUSTODIA),SUM(SEBRA.CAN_COM_PLAZO),SUM(OPT.CAN_COM_PLAZO),SUM(SEBRA.CAN_GARANTIA),SUM(OPT.CAN_GARANTIA),SUM(SEBRA.CAN_VEN_PLAZO),SUM(OPT.CAN_VEN_PLAZO)
FROM TBCTCURV SEBRA
LEFT JOIN "BSCL.Replica.BD.Vistas::Sebra.TBCTCURV" OPT ON SEBRA.RUT_CLI = OPT.RUT_CLI AND SEBRA.SEC_RUT_CLI = OPT.SEC_RUT_CLI
AND TRIM(SEBRA.NEMO) = OPT.NEMO AND CASE SEBRA.COD_BOVEDA WHEN 'TOT' THEN 'TOT' ELSE 'DCV' END = OPT.COD_BOVEDA
WHERE SEBRA.COD_PER = '2024-10' AND OPT.NEMO IS NOT NULL  AND SEBRA.RUT_CLI != 'OFICINA    '
GROUP BY SEBRA.RUT_CLI,SEBRA.SEC_RUT_CLI,SEBRA.NEMO,SEBRA.COD_BOVEDA,OPT.COD_BOVEDA
HAVING SUM(SEBRA.CAN_CUSTODIA + SEBRA.CAN_COM_PLAZO - SEBRA.CAN_VEN_PLAZO) != sum(OPT.CAN_CUSTODIA + OPT.CAN_COM_PLAZO - OPT.CAN_VEN_PLAZO)

--can com plazo
