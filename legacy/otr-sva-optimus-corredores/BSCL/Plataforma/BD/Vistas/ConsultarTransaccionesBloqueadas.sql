SET SCHEMA "BSCL";
DROP VIEW "BSCL.Plataforma.BD.Vistas::ConsultarTransaccionesBloqueadas";
CREATE VIEW "BSCL.Plataforma.BD.Vistas::ConsultarTransaccionesBloqueadas" as
SELECT 
	top 50
	B.HOST, B.PORT, B.BLOCKED_TRANSACTION_ID AS BLOCKED_TRANSACTION_ID, 
	MAP(TP.CONNECTION_ID, NULL, T.CONNECTION_ID, TP.CONNECTION_ID) AS LOCK_OWNER_CONNECTION_ID, 
	B.LOCK_OWNER_TRANSACTION_ID AS LOCK_OWNER_TRANSACTION_ID, B.BLOCKED_TIME AS BLOCKED_TIME, B.WAITING_RECORD_ID AS WAITING_RECORD_ID, 
	B.WAITING_SCHEMA_NAME AS WAITING_SCHEMA_NAME, B.WAITING_TABLE_NAME AS WAITING_TABLE_NAME, B.LOCK_TYPE AS LOCK_TYPE, B.LOCK_MODE AS LOCK_MODE, 
	C.CLIENT_HOST AS LOCK_OWNER_HOST, C.CLIENT_PID AS LOCK_OWNER_PID, C.USER_NAME AS LOCK_OWNER_USER_NAME, C.LAST_ACTION AS LOCK_OWNER_LAST_ACTION, 
	P.STATEMENT_STRING AS BLOCKED_STATEMENT_STRING 
FROM SYS.M_BLOCKED_TRANSACTIONS B 
JOIN SYS.M_TRANSACTIONS T ON (B.HOST, B.PORT, B.LOCK_OWNER_TRANSACTION_ID) = (T.HOST, T.PORT, T.TRANSACTION_ID) 
LEFT OUTER JOIN SYS.M_TRANSACTIONS TP ON (T.VOLUME_ID, T.PRIMARY_TRANSACTION_ID) = (TP.VOLUME_ID, TP.TRANSACTION_ID) AND TP.TRANSACTION_TYPE = 'USER TRANSACTION' 
JOIN SYS.M_CONNECTIONS C ON MAP(TP.CONNECTION_ID, NULL, T.CONNECTION_ID, TP.CONNECTION_ID) = C.CONNECTION_ID 
JOIN SYS.M_TRANSACTIONS TB ON (B.HOST, B.PORT, B.BLOCKED_TRANSACTION_ID) = (TB.HOST, TB.PORT, TB.TRANSACTION_ID) 
LEFT OUTER JOIN SYS.M_TRANSACTIONS TBP ON (TB.VOLUME_ID, TB.PRIMARY_TRANSACTION_ID) = (TBP.VOLUME_ID, TBP.TRANSACTION_ID) AND TBP.TRANSACTION_TYPE = 'USER TRANSACTION' 
JOIN SYS.M_CONNECTIONS CB ON MAP(TBP.CONNECTION_ID, NULL, TB.CONNECTION_ID, TBP.CONNECTION_ID) = CB.CONNECTION_ID 
LEFT OUTER JOIN SYS.M_ACTIVE_STATEMENTS P ON CB.CURRENT_STATEMENT_ID = P.STATEMENT_ID
WITH READ ONLY;
GRANT SELECT ON "BSCL.Plataforma.BD.Vistas::ConsultarTransaccionesBloqueadas" TO BCS_DESARROLLADOR WITH GRANT OPTION;
