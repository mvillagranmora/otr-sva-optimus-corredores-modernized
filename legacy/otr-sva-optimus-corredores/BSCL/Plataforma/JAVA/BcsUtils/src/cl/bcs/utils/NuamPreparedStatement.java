package cl.bcs.utils;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;

/**
 * Wrapper de PreparedStatement para el proyecto Optimus.
 * Intercepta y traduce el dialecto HANA a PostgreSQL en tiempo de preparación.
 */
public class NuamPreparedStatement {

    /**
     * Prepara la sentencia aplicando la transpilación JIT si la conexión es PostgreSQL.
     * 
     * @param conn Conexión activa.
     * @param sql Query en dialecto HANA.
     * @return PreparedStatement listo para ser parametrizado.
     * @throws SQLException
     */
    public static PreparedStatement prepare(Connection conn, String sql) throws SQLException {
        if (sql == null) return null;

        String dbName = conn.getMetaData().getDatabaseProductName().toUpperCase();
        String translatedSql = sql;

        // Si detectamos PostgreSQL, pasamos la query por nuestro motor de traducción
        if (dbName.contains("POSTGRESQL")) {
            translatedSql = SQL.translateToPostgresDialect(sql);
        }

        // Retornamos el PreparedStatement nativo, pero con la query ya transpilada
        return conn.prepareStatement(translatedSql);
    }

    /**
     * Sobrecarga para soportar la recuperación de llaves generadas (muy común en inserts).
     */
    public static PreparedStatement prepare(Connection conn, String sql, int autoGeneratedKeys) throws SQLException {
        String dbName = conn.getMetaData().getDatabaseProductName().toUpperCase();
        String translatedSql = dbName.contains("POSTGRESQL") ? SQL.translateToPostgresDialect(sql) : sql;
        
        return conn.prepareStatement(translatedSql, autoGeneratedKeys);
    }
}