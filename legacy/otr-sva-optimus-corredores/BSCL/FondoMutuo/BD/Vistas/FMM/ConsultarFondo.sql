CREATE VIEW "BSCL.FondoMutuo.BD.Vistas::FMM.ConsultarFondo"  
AS
SELECT
DISTINCT
 "Fondo"."IdFondo"
, "Fondo"."IdEmisor"
, "Fondo"."IdPaisEmisor"
, "PaisEmisor"."NombrePais" AS "NombrePaisEmisor"
, "Fondo"."Nemotecnico"
, "Fondo"."NombreFondo"
, "Fondo"."IdTipoFondo"
, "Fondo"."IdPaisOrigen"
, "Fondo"."CodigoSVS"
, "Fondo"."MoneyMarket"
, CASE "Fondo"."MoneyMarket" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "EsMoneyMarketUI"
, "Fondo"."IdCategoriaPerfilFondoMutuo"
, "Fondo"."FechaCreacion"
, "Fondo"."FechaConstitucion"
, "Fondo"."FechaCierre"
, "Fondo"."Vigencia"
, "Fondo"."IdTipoInstrumento"
, "Fondo"."IdMoneda"
, "SerieDeFondo"."IdFamiliaFondo"
, "Fondo"."FondoExtranjero"
, COALESCE("TipoFondo"."NombreCorto",'') AS "NombreCorto"
, COALESCE("TipoFondo"."Descripcion",'') AS "Descripcion"
, "SerieDeFondo"."IdSerieFondo"
, "SerieDeFondo"."IdSerieFondo" AS "IdSerieFondoNombre"
, CONCAT(CONCAT("SerieDeFondo"."IdSerieFondo", ' - '),"SerieDeFondo"."NombreSerieFondo") AS "IdSerieFondoNombreNombreSerieFondo"
, "SerieDeFondo"."IdInstrumento"
, "SerieDeFondo"."NombreSerieFondo"
, "SerieDeFondo"."CodigoSerie"
, "SerieDeFondo"."MontoMinimo"
, "SerieDeFondo"."MontoMaximo"
, "SerieDeFondo"."Omnibus"
, CASE "SerieDeFondo"."Omnibus" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "OmnibusUI"
, "SerieDeFondo"."CobraComision"
, CASE "SerieDeFondo"."CobraComision" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "CobraComisionUI"
, "SerieDeFondo"."IdEstado"
, "SerieDeFondo"."DecimalesValorCuota"
, "SerieDeFondo"."DecimalesCuota"
, "SerieDeFondo"."PatrimonioMinimo"
, "SerieDeFondo"."DiasRetencionesAporte"
, "SerieDeFondo"."DiasRetencionesRescate"
, "SerieDeFondo"."ExcluyeGarantia"
, CASE "SerieDeFondo"."ExcluyeGarantia" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "ExcluyeGarantiaUI"
, "SerieDeFondo"."Diferido"
, "SerieDeFondo"."CambioFondo"
, CASE "SerieDeFondo"."Diferido" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "EsDiferidoUI"
, CASE "SerieDeFondo"."CambioFondo" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "CambioFondoUI"
, "SerieDeFondo"."InstrumentoDCV"
, "Fondo"."EstadoAporteComercial"
, "Fondo"."EstadoRescateComercial"
, CASE WHEN "Fondo"."EstadoAporteComercial" = 'A' THEN 'UI_ABIERTO' ELSE 'UI_CERRADO' END AS "EstadoAporteComercialUI"
, CASE WHEN "Fondo"."EstadoRescateComercial" = 'A' THEN 'UI_ABIERTO' ELSE 'UI_CERRADO' END AS "EstadoRescateComercialUI"
, CASE WHEN "Fondo"."EstadoReinversionComercial" = 'A' THEN 'UI_ABIERTO' ELSE 'UI_CERRRADO' END AS "EstadoReinversionComercialUI"
, "Fondo"."EstadoReinversionComercial"
, "Fondo"."EstadoLiquidezComercial"
, "Fondo"."EstadoAporteBackoffice"
, "Fondo"."EstadoRescateBackoffice"
, CASE "Fondo"."EstadoAporteBackoffice" WHEN 'A' THEN 'UI_ABIERTO' ELSE 'UI_CERRADO' END AS "EstadoAporteBackOfficeUI"
, CASE "Fondo"."EstadoRescateBackoffice" WHEN 'A' THEN 'UI_ABIERTO' ELSE 'UI_CERRADO' END AS "EstadoRescateBackOfficeUI"
, CASE "Fondo"."EstadoReinversionBackoffice" WHEN 'A' THEN 'UI_ABIERTO' ELSE 'UI_CERRADO' END AS "EstadoReinversionBackofficeUI"
, "Fondo"."EstadoReinversionBackoffice"
, "Fondo"."EstadoLiquidezBackoffice"
, CASE WHEN "Fondo"."UsaHorarioAporteDefault" 		= 'N' THEN 'N' ELSE 'S' END AS "UsaHorarioAporteDefault"
, CASE WHEN "Fondo"."UsaHorarioRescateDefault" 		= 'N' THEN 'N' ELSE 'S' END AS "UsaHorarioRescateDefault"
, CASE WHEN "Fondo"."UsaHorarioReinversionDefault" 	= 'N' THEN 'N' ELSE 'S' END AS "UsaHorarioReinversionDefault"
, CASE WHEN "Fondo"."UsaHorarioLiquidezDefault" 		= 'N' THEN 'N' ELSE 'S' END AS "UsaHorarioLiquidezDefault"
, CASE "Fondo"."UsaHorarioAporteDefault" 	 WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "UsaHorarioAporteDefaultUI"
, CASE "Fondo"."UsaHorarioRescateDefault"	 WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "UsaHorarioRescateDefaultUI"
, CASE "Fondo"."UsaHorarioReinversionDefault" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "UsaHorarioReinversionDefaultUI"
, CASE "Fondo"."UsaHorarioLiquidezDefault" 	 WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "UsaHorarioLiquidezDefaultUI"
, "Fondo"."HoraCierreAporteComercial"
, "Fondo"."HoraCierreRescateComercial"
, "Fondo"."HoraCierreReinversionComercial"
, "Fondo"."HoraCierreLiquidezComercial"
, "Fondo"."HoraCierreAporteBackoffice"
, "Fondo"."HoraCierreRescateBackoffice"
, "Fondo"."HoraCierreReinversionBackoffice"
, "Fondo"."HoraCierreLiquidezBackoffice"
, "Fondo"."BloqueoAporte"
, CASE WHEN "Fondo"."BloqueoAporte" = 'N' THEN 'UI_NO' ELSE 'UI_SI' END AS "BloqueoAporteUI"
, "Fondo"."BloqueoRescate"
, CASE WHEN "Fondo"."BloqueoRescate" = 'N' THEN 'UI_NO' ELSE 'UI_SI' END AS "BloqueoRescateUI"
, CASE WHEN "SerieDeFondo"."PatrimonioMinimo" > 0  THEN 'UI_SI' ELSE 'UI_NO' END AS "EsPatrimonioMinimoUI"
, CASE WHEN "SerieDeFondo"."PatrimonioMinimo" > 0  THEN 'S'     ELSE 'N'     END AS "EsPatrimonioMinimo"
, "SerieDeFondo"."IdCliente"
, "SerieDeFondo"."IdPortafolio"
, "SocioNegocio"."IdSocioDeNegocio"
, "SocioNegocio"."IdPersona"
, "SerieDeFondo"."IdMedioDePagoAbono"
, "SerieDeFondo"."IdMedioDePagoCargo"
, "MedioPagoCargo"."Nombre" AS "NombreMedioPagoCargo"
, "MedioPagoAbono"."Nombre" AS "NombreMedioPagoAbono"
, "SerieDeFondo"."DiasValutaCurseAporte"
, "SerieDeFondo"."DiasValutaCurseRescate"
, "SerieDeFondo"."DiasValutaValorCuotaAporte"
, "SerieDeFondo"."DiasValutaValorCuotaRescate"
, "SerieDeFondo"."DiasValutaCertificacionAporte"
, "SerieDeFondo"."DiasValutaCertificacionRescate"
, "SerieDeFondo"."DiasComision"
, "SerieDeFondo"."PorcentajeComision"
, "SerieDeFondo"."PorcentajeRemuneracion"
, "SerieDeFondo"."PorcentajeGastoOpera"
, "SerieDeFondo"."PorcentajeCostoAdm"
, "FamiliaFondo"."NombreFamilia"
,CASE "ConsultarEmisor"."Tipo" 
	WHEN 'N' THEN  "ConsultarEmisor"."Nombres" ||' '||  "ConsultarEmisor"."ApellidoPaterno" || ' ' ||  "ConsultarEmisor"."ApellidoMaterno" 
	ELSE  "ConsultarEmisor"."RazonSocial" END AS "RazonSocialEmisor"	
, COALESCE("ValorCuota"."ValorCuota",0) AS "ValorCuota"
, COALESCE("ValorCuota"."FechaCierre",'0001-01-01') AS "FechaValorCuota"
, "TipoCambio"."ValorDolarAporte"
, "TipoCambio"."ValorDolarRescate"
, "SerieDeFondo"."IdEmpresa" AS "IdEmpresa"
, "Estado"."Nombre" AS "NombreEstado"
, "TipoInstrumento"."Nombre" AS "NombreTipoInstrumento"
, CASE WHEN COALESCE("ComisionSalida"."IdComision",0)  != 0  THEN 'UI_SI' ELSE 'UI_NO' END AS "EsComisionSalidaUI"
, CASE WHEN COALESCE("ComisionSalida"."IdComision", 0) != 0  THEN 'S'     ELSE 'N'	   END AS "EsComisionSalida"
, CASE WHEN COALESCE("ComisionEntrada"."IdComision",0) != 0  THEN 'UI_SI' ELSE 'UI_NO' END AS "EsComisionEntradaUI"
, CASE WHEN COALESCE("ComisionEntrada"."IdComision",0) != 0  THEN 'S'     ELSE 'N'     END AS "EsComisionEntrada"
, CASE "FondoExtranjero" WHEN 'S' THEN 'N' ELSE 'S' END AS "EsFondoNacional"
, CASE "FondoExtranjero" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "EsFondoExtranjeroUI"
, COALESCE("CategoriaPerfil"."Jerarquia",999) AS "Jerarquia"
, "CategoriaPerfil"."NombreCategoriaPerfilFondoMutuo"
, "Pais"."NombrePais"
, CASE "ConsultarCliente"."Tipo" 
	WHEN 'N' THEN  "ConsultarCliente"."Nombres" ||' '||  "ConsultarCliente"."ApellidoPaterno" || ' ' ||  "ConsultarCliente"."ApellidoMaterno" 
	ELSE  "ConsultarCliente"."RazonSocial" END AS "NombreClienteAGF"
, "ConsultarPortafolio"."CodigoPortafolio" AS "CodigoPortafolioAGF"
, "Fondo"."FechaFondo"
, "Fondo"."AperturaAutomaticaFondo"
, "Fondo"."UltimoFechaHoraCierreAporteComercial"
, "Fondo"."UltimoFechaHoraCierreRescateComercial"
, "Fondo"."UltimoFechaHoraCierreReinversionComercial"
, "Fondo"."UltimoFechaHoraCierreLiquidezComercial"
, "Fondo"."UltimoFechaHoraCierreAporteBackOffice"
, "Fondo"."UltimoFechaHoraCierreRescateBackOffice"
, "Fondo"."UltimoFechaHoraCierreReinversionBackOffice"
, "Fondo"."UltimoFechaHoraCierreLiquidezBackOffice"
, CASE "Fondo"."AperturaAutomaticaFondo" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "AperturaAutomaticaFondoUI"
, "Fondo"."FondoNormativo"
, CASE "Fondo"."FondoNormativo" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "FondoNormativoUI"
, "Fondo"."IdTipoDocumentoIdentidadFondo"
, "DocFondo"."NombreTipoDocumentoIdentidad" AS "NombreTipoDocumentoIdentidadFondo"
, "Fondo"."DocumentoIdentidadFondo"
, "SerieDeFondo"."MontoMinimo" AS "MontoMinimoInvertir"
, "SerieDeFondo"."PatrimonioMinimo" AS "LimiteAltoPatrimonio"
, "SerieDeFondo"."AportesAltos"
, "SerieDeFondo"."PatrimonioAltos"
, "SerieDeFondo"."MontoPatrimonioEmisor"
, CASE "SerieDeFondo"."AportesAltos" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "AportesAltosUI"
, CASE "SerieDeFondo"."PatrimonioAltos" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "PatrimonioAltosUI"
, "SerieDeFondo"."InstrumentoOWP"
, "SerieDeFondo"."EsAPV"
, CASE "SerieDeFondo"."InstrumentoOWP" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "InstrumentoOWPUI"
, CASE "SerieDeFondo"."EsAPV" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "EsAPVUI"
, "Fondo"."IdMercadoFondoMutuo"
, COALESCE("MercadoFondoMutuo"."Nombre",'') AS "NombreMercadoFondoMutuo"
,"SerieDeFondo"."RestringeAporte"
,"SerieDeFondo"."RestringeRescate"
, CASE "SerieDeFondo"."RestringeAporte" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "RestringeAporteUI"
, CASE "SerieDeFondo"."RestringeRescate" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "RestringeRescateUI"
,"SerieDeFondo"."NemoCMF"
FROM "BSCL.FondoMutuo.BD::FMM.Fondo" AS "Fondo"
INNER JOIN "BSCL.FondoMutuo.BD::FMM.SerieDeFondo" AS "SerieDeFondo" ON ("SerieDeFondo"."IdFondo" = "Fondo"."IdFondo")
LEFT OUTER JOIN "BSCL.FondoMutuo.BD::FMM.TipoFondo" AS "TipoFondo" ON ("Fondo"."IdTipoFondo" = "TipoFondo"."IdTipoFondo")
LEFT OUTER JOIN "BSCL.FondoMutuo.BD::FMM.FamiliaFondo" AS "FamiliaFondo" ON ("FamiliaFondo"."IdFamiliaFondo" = "SerieDeFondo"."IdFamiliaFondo")
LEFT OUTER JOIN "BSCL.Plataforma.BD::MER.Emisor" AS "EMI" ON ("EMI"."IdEmisor" = "Fondo"."IdEmisor")
LEFT OUTER JOIN "BSCL.SocioNegocio.BD::PER.Persona" AS "ConsultarEmisor" ON  ( "ConsultarEmisor"."IdPersona" = "EMI"."IdPersona" )
LEFT OUTER JOIN "BSCL.FondoMutuo.BD::FMM.ValorCuota" AS "ValorCuota" ON ("ValorCuota"."IdSerieFondo" = "SerieDeFondo"."IdSerieFondo")
LEFT OUTER JOIN "BSCL.FondoMutuo.BD::FMM.ValorTipoCambio" AS "TipoCambio" ON ("TipoCambio"."IdSerieFondo" = "SerieDeFondo"."IdSerieFondo")
LEFT OUTER JOIN "BSCL.FondoMutuo.BD::FMM.Comision" AS "ComisionSalida" ON ("ComisionSalida"."IdSerieFondo" = "SerieDeFondo"."IdSerieFondo" AND "ComisionSalida"."TipoComision" = 'SALIDA')
LEFT OUTER JOIN "BSCL.FondoMutuo.BD::FMM.Comision" AS "ComisionEntrada" ON ("ComisionEntrada"."IdSerieFondo" = "SerieDeFondo"."IdSerieFondo" AND "ComisionEntrada"."TipoComision" = 'ENTRADA')
LEFT OUTER JOIN "BSCL.Plataforma.BD::PLA.Estado" AS "Estado" ON ("Estado"."IdEstado" = "SerieDeFondo"."IdEstado")
LEFT OUTER JOIN "BSCL.Plataforma.BD::INS.TipoInstrumento" AS "TipoInstrumento" ON ("Fondo"."IdTipoInstrumento" = "TipoInstrumento"."IdTipoInstrumento")
LEFT OUTER JOIN "BSCL.SocioNegocio.BD::SOC.SocioDeNegocio" AS "SocioNegocio" ON  ( "SocioNegocio"."IdCliente" = "SerieDeFondo"."IdCliente")
LEFT OUTER JOIN "BSCL.Portafolio.BD::POR.Portafolio" AS "ConsultarPortafolio" ON  ( "ConsultarPortafolio"."IdPortafolio" = "SerieDeFondo"."IdPortafolio" )
LEFT OUTER JOIN "BSCL.SocioNegocio.BD::CLI.Cliente" AS "CLI" ON  ( "CLI"."IdCliente" = "SerieDeFondo"."IdCliente" )
LEFT OUTER JOIN "BSCL.SocioNegocio.BD::PER.Persona" AS "ConsultarCliente" ON  ( "ConsultarCliente"."IdPersona" = "CLI"."IdPersona" )
LEFT OUTER JOIN "BSCL.FondoMutuo.BD::FMM.CategoriaPerfilFondoMutuo" AS "CategoriaPerfil" ON ("CategoriaPerfil"."IdCategoriaPerfilFondoMutuo" = "Fondo"."IdCategoriaPerfilFondoMutuo")
LEFT OUTER JOIN "BSCL.Plataforma.BD::REG.Pais" AS "Pais" ON ("Pais"."IdPais" = "Fondo"."IdPaisOrigen")
LEFT OUTER JOIN "BSCL.Plataforma.BD::REG.Pais" AS "PaisEmisor" ON ("PaisEmisor"."IdPais" = "Fondo"."IdPaisEmisor")
LEFT OUTER JOIN "BSCL.Plataforma.BD::REG.TipoDocumentoIdentidad" AS "DocFondo" ON ("DocFondo"."IdTipoDocumentoIdentidad" = "Fondo"."IdTipoDocumentoIdentidadFondo")
LEFT OUTER JOIN "BSCL.Plataforma.BD::PAG.MedioDePago" AS "MedioPagoCargo" ON ("MedioPagoCargo"."IdMedioDePago" = "SerieDeFondo"."IdMedioDePagoCargo")
LEFT OUTER JOIN "BSCL.Plataforma.BD::PAG.MedioDePago" AS "MedioPagoAbono" ON ("MedioPagoAbono"."IdMedioDePago" = "SerieDeFondo"."IdMedioDePagoAbono")
LEFT OUTER JOIN "BSCL.FondoMutuo.BD::FMM.MercadoFondoMutuo" AS "MercadoFondoMutuo" ON ("MercadoFondoMutuo"."IdMercadoFondoMutuo" = "Fondo"."IdMercadoFondoMutuo");
GO
