			CM."IdCargoAbonoMovimiento"
		   ,CM."FechaSistema"
		   ,CM."FechaIngresoRegistro"
		   ,CM."IdCuentaInversion"
		   ,CM."CodigoCuentaInversion"
		   ,CM."NombreCuentaInversion"
		   ,CM."IdCliente"
		   ,CM."NombreCliente"
		   ,CM."IdPortafolio"
		   ,CM."IdMoneda"
		   ,CM."CodigoMoneda"
		   ,CM."NombreMoneda"
		   ,CM."SimboloMoneda"
		   ,CM."DecimalesMoneda"
		   ,CM."IdTipoMovimiento"
		   ,CM."TipoMovimiento"
		   ,CM."NombreTipoMovimiento"
		   ,CM."IdConcepto"
		   ,CM."NombreConcepto"
		   ,CM."OrigenConcepto"
		   ,CM."Descripcion"
		   ,CM."IdCondicionDeLiquidacion"
		   ,CM."CodigoCondicionDeLiquidacion"
		   ,CM."NombreCondicionDeLiquidacion"
		   ,CM."PlazoCondicionDeLiquidacion"
		   ,CM."FechaEfectivaMovimiento"
		   ,CM."Monto"
		   ,CM."SaldoPorFechaEfectiva"
		   ,CM."SaldoPorFechaMovimiento"
		   ,CM."IdModulo"
		   ,CM."IdTipoProducto"
		   ,CM."CodigoTipoProducto"
		   ,CM."NombreTipoProducto"
		   ,CM."IdTipoOperacion"
		   ,CM."CodigoTipoOperacion"
		   ,CM."NombreTipoOperacion"
		   ,CM."AccionTipoOperacion"
		   ,CM."IdOperacion"
		   ,CM."FechaOperacion"
		   ,CM."FechaLiquidacionOperacion"
		   ,CM."FechaVencimientoOperacion"
		   ,CM."IdMonedaOperacion"
		   ,CM."MontoOperacion"
		   ,CM."TipoCambioOperacion"
		   ,CM."IdTipoInstrumento"
		   ,CM."NombreTipoInstrumento"
		   ,CM."IdClasificacionTipoInstrumento"
		   ,CM."NombreClasificacionTipoInstrumento"
		   ,CM."IdInstrumento"
		   ,CM."Cantidad"
		   ,CM."NemotecnicoOriginal"
		   ,CM."EsCargoAbonoPorTraspaso"
		   ,CM."EsCargoAbonoPorTraspasoTraducido"
		   ,CM."IdCargoAbonoRelacionadoTraspaso"
		   ,CM."NombreClienteRelacionado"
		   ,CM."CodigoPortafolioRelacionado"
		   ,CM."IdTipoComprobante"
		   ,CM."CodigoTipoComprobante"
		   ,CM."NombreTipoComprobante"
		   ,CM."IdComprobante"
		   ,CM."FolioComprobante"
		   ,CM."EsVentaCorta"
		   ,CM."FechaComprobante"
		   ,CM."IdComprobanteDetalle"
		   ,CM."IdPersonaPagoCobro"
		   ,CM."EsCertificadoAutomatico"
		   ,CM."IdUsuarioCertificador"
		   ,CM."FechaCertificacion"
		   ,CM."IdContraparte"
		   ,CM."EsIndicadorBilateral"
		   ,CM."IdEmpresa"
		   ,CM."CodigoEmpresa"
		   ,CM."NombreEmpresa"
		   ,CM."EsIngresoManual"
		   ,CM."IdEvento"
		   ,CM."IdUsuario"
		   ,CM."NombreUsuario"
		   ,CM."IdEstado"
		   ,CM."NombreEstado"
		   ,CM."NombreUsuarioCert"
		   ,CASE
		   		WHEN CM."IdTipoMovimiento" = 'MOVCAR' THEN "Monto"
		   		WHEN CM."IdTipoMovimiento" = 'MOVABN' THEN 0
			END AS "Cargo"
		   ,CASE
		   		WHEN CM."IdTipoMovimiento" = 'MOVCAR' THEN 0
		   		WHEN CM."IdTipoMovimiento" = 'MOVABN' THEN "Monto"
			END AS "Abono"
		   ,CAST(COALESCE(CMP."Saldo_Inicial",0) + 
		   		SUM(CASE
		   				WHEN CM."IdEstado" = 'ANU' THEN 0
		   				ELSE CASE
		   						WHEN CM."IdTipoMovimiento" = 'MOVCAR' THEN (-1 * "Monto")
				   	     		WHEN CM."IdTipoMovimiento" = 'MOVABN' THEN "Monto"
				   	     	 END		     	    
			       	 END) over (partition by CM."IdCuentaInversion" 
			       	 			order by (CASE WHEN CMP."SaldoPorFechaEfectiva" = 'S' THEN CM."FechaEfectivaMovimiento" ELSE CM."FechaSistema" END),
			       	 					 (CASE WHEN CMP."SaldoPorFechaEfectiva" = 'S' THEN CM."FechaCertificacion" ELSE CM."FechaIngresoRegistro" END), 
										 CM."IdCargoAbonoMovimiento"
			       	            rows between unbounded preceding and current row) as DECIMAL(26,8)) as "SaldoSimulado"
		    ,Portafolio."IdMatrizAgrupador"
		    ,Portafolio."EsADC"
		FROM "BSCL.CuentaInversion.BD::CTA.ConsultarCartolaDeMovimiento_Proceso" as CMP
		INNER JOIN "BSCL.CuentaInversion.BD.Vistas::ConsultarCartolaDeMovimientos" as CM ON CM."IdPortafolio" = CMP."IdPortafolio" AND CM."IdMoneda" = CMP."IdMoneda"
	    LEFT JOIN "BSCL.Portafolio.BD.Vistas::ConsultarPortafolio" AS Portafolio ON Portafolio."IdPortafolio" = CMP."IdPortafolio"
		WHERE (CASE WHEN CMP."SaldoPorFechaEfectiva" = 'S' THEN CM."FechaEfectivaMovimiento" ELSE CM."FechaSistema" END) BETWEEN CMP."FechaDesde" and CMP."FechaHasta"
		AND Portafolio."IdMatrizAgrupador" = CASE WHEN CMP."IdMatrizAgrupador" IS NOT NULL THEN CMP."IdMatrizAgrupador" ELSE Portafolio."IdMatrizAgrupador" END
		AND Portafolio."EsADC" = CASE WHEN CMP."EsADC" IS NOT NULL THEN CMP."EsADC" ELSE Portafolio."EsADC" END
		AND CM."IdEstado" = COALESCE(CMP."IdEstado", CM."IdEstado")
		ORDER BY
			-- El orden depende si la consulta es por Fecha Adquisicion  o por Fecha Movimiento
			(CASE WHEN CMP."SaldoPorFechaEfectiva" = 'S' THEN CM."FechaCertificacion" ELSE CM."FechaSistema" END), "IdCargoAbonoMovimiento" ASC;