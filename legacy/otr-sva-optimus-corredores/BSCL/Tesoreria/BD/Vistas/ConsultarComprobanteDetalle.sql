SET SCHEMA "BSCL";
DROP VIEW "BSCL.Tesoreria.BD.Vistas::ConsultarComprobanteDetalle";

CREATE VIEW "BSCL.Tesoreria.BD.Vistas::ConsultarComprobanteDetalle" AS
SELECT 
	 ComprobanteDetalle."IdComprobanteDetalle"
	,ComprobanteDetalle."NroLinea"
	,ComprobanteDetalle."IdTipoMovimiento"
	,TipoMovimiento."Tipo" AS "TipoMovimiento"
	,TipoMovimiento."Nombre" AS "NombreTipoMovimiento"
	,ComprobanteDetalle."IdConcepto"
	,Concepto."Nombre" AS "NombreConcepto"
	,ComprobanteDetalle."IdMoneda"
	,ComprobanteDetalle."Monto"
	,ComprobanteDetalle."SecuenciaAgrupacion"
	,ComprobanteDetalle."SecuenciaRelacionada"
	,ComprobanteDetalle."IdEmpleadoDigitador"
	,ComprobanteDetalle."IdSucursalEmpleadoDigitador"
	,ComprobanteDetalle."IdTipoComprobanteOrigen"
	,ComprobanteDetalle."IdComprobanteOrigen"
	,ComprobanteDetalle."FechaComprobanteOrigen"
	,ComprobanteDetalle."FechaLiquidacionComprobanteOrigen"
	,ComprobanteDetalle."IdTipoProducto"
	,TipoProducto."Nombre" AS "NombreTipoProducto"
	,ComprobanteDetalle."IdTipoOperacion"
	,TipoOperacion."Nombre" AS "NombreTipoOperacion"
	,ComprobanteDetalle."IdBolsa"
	,ComprobanteDetalle."IdMonedaOperacion"
	,ComprobanteDetalle."MontoOperacion"
	,ComprobanteDetalle."FechaParidad"
	,ComprobanteDetalle."IdTipoReajuste"
	,ComprobanteDetalle."ValorParidad"
	,ComprobanteDetalle."FolioCartera"
	,ComprobanteDetalle."IdInstrumento"
	,INS."Nemotecnico"
	,ComprobanteDetalle."IdTipoInstrumento"
	,ComprobanteDetalle."IdClasificacionTipoInstrumento"
	,ComprobanteDetalle."IdCarga"
	,ComprobanteDetalle."IdEstado"
	,Estado."Nombre" AS "NombreEstado"
	
	,Comprobante."IdComprobante"
	,Comprobante."IdEmpresa"
	,Comprobante."IdUsuario"
	,Comprobante."TipoComprobante"
	,Comprobante."IdTipoMovimiento"			AS "IdTipoMovimientoComprobante"
	,Comprobante."IdConcepto" 				AS "IdConceptoComprobante"
	,Comprobante."IdCaja"
	,Comprobante."IdMoneda"					AS "IdMonedaComprobante"
	,Comprobante."Monto" 					AS "MontoComprobante"
	,Comprobante."FechaLiquidacion"
	,Comprobante."FechaIngresoRegistro"
	,Comprobante."FechaMovimiento"
	,Comprobante."IdTipoPersona"
	,Comprobante."IdPersona"
	,Comprobante."NombrePersona"
	,Comprobante."IdTipoDocumentoIdentidad"
	,Comprobante."DocumentoIdentidad"	
	,Comprobante."TitularPago"
	,Comprobante."IdTipoPersonaTitularPago"
	,Comprobante."IdPersonaTitularPago"
	,Comprobante."NombrePersonaTitularPago"
	,Comprobante."IdPortafolioTitularPago"
	,Comprobante."EsBilateral"
	,"BSCL.Plataforma.BD.Utilitarios::ObtenerTraduccion"("ComprobanteNeteado") as "ComprobanteNeteado"
	,"BSCL.Plataforma.BD.Utilitarios::ObtenerTraduccion"("SeparadoPorConcepto") as "SeparadoPorConcepto"
	,Comprobante."IdEstado" AS "IdEstadoComprobante"
FROM "BSCL.Tesoreria.BD::TES.ComprobanteDetalle" AS ComprobanteDetalle
INNER JOIN "BSCL.Tesoreria.BD::TES.Comprobante" AS Comprobante ON Comprobante."IdComprobante" = ComprobanteDetalle."IdComprobante"
LEFT OUTER JOIN "BSCL.Plataforma.BD::PLA.TipoMovimiento" AS TipoMovimiento ON  TipoMovimiento."IdTipoMovimiento" = ComprobanteDetalle."IdTipoMovimiento"         
LEFT OUTER JOIN "BSCL.Plataforma.BD::PLA.Estado" AS Estado ON ComprobanteDetalle."IdEstado" = Estado."IdEstado" 
LEFT OUTER JOIN "BSCL.Plataforma.BD::PLA.Concepto" AS Concepto ON (Concepto."IdConcepto" = ComprobanteDetalle."IdConcepto")
LEFT OUTER JOIN "BSCL.Plataforma.BD::INS.Instrumento" AS INS ON INS."IdInstrumento" = ComprobanteDetalle."IdInstrumento"
LEFT OUTER JOIN "BSCL.Plataforma.BD::INS.TipoProducto" AS TipoProducto ON (TipoProducto."IdTipoProducto" = ComprobanteDetalle."IdTipoProducto")
LEFT OUTER JOIN "BSCL.Plataforma.BD::INS.TipoOperacion" AS TipoOperacion ON (TipoOperacion."IdTipoOperacion" = ComprobanteDetalle."IdTipoOperacion")
WITH READ ONLY; 

GRANT SELECT ON "BSCL.Tesoreria.BD.Vistas::ConsultarComprobanteDetalle" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
