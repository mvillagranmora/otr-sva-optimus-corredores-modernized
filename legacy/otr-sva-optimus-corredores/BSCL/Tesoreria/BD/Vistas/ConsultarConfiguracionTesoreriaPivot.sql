SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Tesoreria.BD.Vistas::ConsultarConfiguracionTesoreriaPivot"; 
 
CREATE VIEW "BSCL.Tesoreria.BD.Vistas::ConsultarConfiguracionTesoreriaPivot" As 
SELECT  "IdEmpresa",
		
		--Configuracion creacion comprobante
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORCONCEPTO' THEN "Valor" END) AS "SEPARAPORCONCEPTO",
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORAGENTE' THEN "Valor" END) AS "SEPARAPORAGENTE",
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORSUCURSAL' THEN "Valor" END) AS "SEPARAPORSUCURSAL",
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORCORREDORACONTRAPARTE' THEN "Valor" END) AS "SEPARAPORCORREDORACONTRAPARTE",		
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORTIPOCOMPROBANTE' THEN "Valor" END) AS "SEPARAPORTIPOCOMPROBANTE",		
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORTIPOPRODUCTO' THEN "Valor" END) AS "SEPARAPORTIPOPRODUCTO",
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORTIPOOPERACION' THEN "Valor" END) AS "SEPARAPORTIPOOPERACION",
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORBOLSA' THEN "Valor" END) AS "SEPARAPORBOLSA",
		MAX(CASE WHEN "CodigoParametro" = 'SEPARAPORCONDICIONLIQUIDACION' THEN "Valor" END) AS "SEPARAPORCONDICIONLIQUIDACION",
		
		--Configuracion liquidacion comprobante
		
		MAX(CASE WHEN "CodigoParametro" = 'LIQUIDARPORCOMPROBANTE' THEN "Valor" END) AS "LIQUIDARPORCOMPROBANTE",
		MAX(CASE WHEN "CodigoParametro" = 'LIQUIDACIONPARCIALENVIAACTA' THEN "Valor" END) AS "LIQUIDACIONPARCIALENVIAACTA",
				
		--Configuracion Cleaning				
		MAX(CASE WHEN "CodigoParametro" = 'CLEARINGINCLUYERFPM' THEN "Valor" END) AS "CLEARINGINCLUYERFPM",
		MAX(CASE WHEN "CodigoParametro" = 'CLEARINGINCLUYEIFPM' THEN "Valor" END) AS "CLEARINGINCLUYEIFPM",
		MAX(CASE WHEN "CodigoParametro" = 'CLEARINGINCLUYERFPH' THEN "Valor" END) AS "CLEARINGINCLUYERFPH",
		MAX(CASE WHEN "CodigoParametro" = 'CLEARINGINCLUYEIFPH' THEN "Valor" END) AS "CLEARINGINCLUYEIFPH",

		--Configuracion Cheques
		MAX(CASE WHEN "CodigoParametro" = 'UNIDADMEDIDAIMPRESIONCHEQUES' THEN "Valor" END) AS "UNIDADMEDIDAIMPRESIONCHEQUES",
		
		--Otros
		MAX(CASE WHEN "CodigoParametro" = 'CAMBIOSCCLV' THEN "Valor" END) AS "CAMBIOSCCLV"
  FROM (
		SELECT "IdEmpresa","CodigoParametro","Valor"
		  FROM "BSCL.Tesoreria.BD::TES.ConfiguracionTesoreria"
		 ORDER BY "CodigoParametro"
	   )
 GROUP BY "IdEmpresa";

GRANT SELECT ON "BSCL.Tesoreria.BD.Vistas::ConsultarConfiguracionTesoreriaPivot" TO BCS_DESARROLLADOR WITH GRANT OPTION; 
