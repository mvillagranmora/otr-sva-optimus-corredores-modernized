SELECT "IdComprobante" ,"IdTipoMovimiento" ,'CLI' AS "AfectaCuentaInversion"
FROM "BSCL.Tesoreria.BD.Vistas::ConsultarComprobante"
WHERE (:IdTipoMovimiento = '-1' OR 	"IdTipoMovimiento" = :IdTipoMovimiento)		 
AND (:IdPersona = -1 OR "IdPersona" = :IdPersona)
AND (:IdPortafolioTitularPago = -1 OR  "IdPortafolioTitularPago" =:IdPortafolioTitularPago)
AND (:IdCaja =	-1	OR "IdCaja" = :IdCaja)	 
AND (:IdMoneda = '-1' OR "IdMoneda" = :IdMoneda)
AND ( "IdEstado" !='LIQ' AND (:IdEstado ='-1' OR "IdEstado" = :IdEstado))
AND (:IdConcepto= '-1' OR "IdConcepto"= :IdConcepto)
AND  (TO_VARCHAR( :FechaLiquidacionDesde,'YYYY-MM-DD' )<=  TO_VARCHAR("FechaLiquidacion" ,'YYYY-MM-DD' ))			 
AND (TO_VARCHAR(:FechaLiquidacionHasta,'YYYY-MM-DD' ) >= TO_VARCHAR("FechaLiquidacion" ,'YYYY-MM-DD' ))	
AND (:IdTipoPersona = '-1' OR "IdTipoPersona" = :IdTipoPersona)
AND (:IdMedioDePago = '-1' OR "IdMedioDePago" = :IdMedioDePago)				 
AND (:NombreBancoSocio = '-1' OR "NombreBancoSocio" = :NombreBancoSocio)
AND (:NombreBancoCorredora = '-1' OR "NombreBancoCorredora" = :NombreBancoCorredora)
AND (:AliasBanco = '-1' OR  "AliasBanco" = :AliasBanco)
AND (:NumeroCuentaBancariaCorredora = '-1' OR "NumeroCuentaBancariaCorredora" = :NumeroCuentaBancariaCorredora) 				 
AND (:IdClasificacionTipoInstrumento = '-1' OR "IdClasificacionTipoInstrumento" = :IdClasificacionTipoInstrumento)
AND (:IdTipoInstrumento = '-1' OR "IdTipoInstrumento" = :IdTipoInstrumento)
AND (:FechaComprobanteOrigen IS NULL  OR TO_VARCHAR("FechaComprobanteOrigen",'YYYY-MM-DD') = TO_VARCHAR(:FechaComprobanteOrigen,'YYYY-MM-DD' ))					 
