CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaTBTEDCTO" AS


		SELECT 
			WST."IdStack" AS "IDSTACK", "Action" AS ACTION,
			IEFP."RUT_EMPRESA" || ':' ||  IEFP."TIPO_MON" || ':' ||  IEFP."TIPO_DOCUM" || ':' ||  IEFP."SEC_DOCUM"   AS TABLE_KEY, 
			TIPO_CAJA,RUT_EMPRESA,TIPO_MON,TIPO_DOCUM,SEC_DOCUM,EST_DOCUM,EST_CMBTE,IND_ING_EGR,COD_CAJA,COD_BCO_DOCUM,FEC_LIQUID,TIPO_CMBTE,FOLIO_CMBTE,IND_MARCA_ESP,ALIAS_BANCO,SEC_ENVIO,SEC_DEVOL,CTA_BCO_DOCUM,MONTO_DOCUM,EMITIDO_A,FEC_CMBTE,FEC_DOCUM,GEN_DOCUM,IND_CHEQUE,NUM_DEPOSITO,NUM_DOCUM,PLAZO,SERIE_DOCUM,TIPO_DEPOSITO,FPA_ID,FECHA_PAGO,NUM_VALUTA,COD_SUC,COD_BCO_PAGO,CTA_BCO_PAGO,IND_TRASPASO

			FROM  "BSCL.Replica.BD.Vistas::Sebra.TBTEDCTO" IEFP
	        left JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'TBTEDCTO' AND WST."Key" = IEFP."RUT_EMPRESA" || ':' ||  IEFP."TIPO_MON" || ':' ||  IEFP."TIPO_DOCUM" || ':' ||  IEFP."SEC_DOCUM"


WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaTBTEDCTO" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
                                    
