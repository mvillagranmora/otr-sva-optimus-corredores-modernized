	AND WST."Key" = COD_PER  || ':' || TRIM(RUT_CLI) || ':' ||  SEC_RUT_CLI || ':' ||  trim(NEMO) || ':' ||  COD_BOVEDA
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaTBCTCURV" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
