SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaASIGNACION_RF"; 

-- select * from BSCL."BSCL.Replica.BD.Vistas::ReplicaASIGNACION_RF" 

CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaASIGNACION_RF" AS
SELECT
	WST."IdStack" AS "IDSTACK",	
	"Action" AS ACTION,
	cast(ASIG.SEC_ASIGNACION  AS varchar) AS TABLE_KEY,
	*
FROM "BSCL.Replica.BD.Vistas::Sebra.ASIGNACION_RF" ASIG
LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'ASIGNACION_RF' AND WST."Key" = ASIG.SEC_ASIGNACION

WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaASIGNACION_RF" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
