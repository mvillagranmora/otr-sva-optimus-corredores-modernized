SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaFMTASASCURVA"; 
CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaFMTASASCURVA" AS

SELECT
	WST."IdStack" AS "IDSTACK", "Action" AS ACTION,
	TO_VARCHAR(IDPRECIOTASA) AS TABLE_KEY,
	"TIPOTASA",-- CHAR(10)
	"FUENTE",-- CHAR(10) 
	"FECHA",-- CHAR(10)  
	"MONEDA",-- INT  
	"MERCADO",-- CHAR(10)  
	"PERIODO",-- INT
	"FEC_VCTO",-- CHAR(10)
	"TASA",-- DECIMAL(20,10)
	"TASAMID",-- DECIMAL(20,10)
	"TASABID",-- DECIMAL(20,10)
	"TASAASK",-- DECIMAL(20,10) 
	"TASAVPAR",-- DECIMAL(20,10)
	"TASAEST",-- DECIMAL(20,10)
	"TASAESTMIN",-- DECIMAL(20,10)
	"TASAESTMAX",-- DECIMAL(20,10)
	"ARCHIVO",-- CHAR(40)
	"USRULTMOD",-- CHAR(20)
	"FECULTMOD",-- DATETIME
	"ESTADOCARGA",-- CHAR(1)
	"MONTO",-- DECIMAL(17,2)
	"NEMO"-- CHAR(16)
FROM "BSCL.Replica.BD.Vistas::Sebra.FMTASASCURVA" FMT
LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'FMTASASCURVA' AND WST."Key" = FMT.IdPrecioTasa
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaFMTASASCURVA" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
