SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaEMPLEADO_CORREDORA"; 

CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaEMPLEADO_CORREDORA" AS

	Select WST."IdStack" AS "IDSTACK", "Action" AS ACTION,
		EMP_CODIGO  AS TABLE_KEY,
		EMP_CODIGO
		,EMP_COD_FM
		,EMP_COD_REF
		,PER_ID
		,PAR_TEN_ID
		,PAR_TPA_ID
		,PAR_TIF_ID
		,CEN_ID
		,SUB_ID
		,EST_ID
		,EMP_FEC_INGRESO
		,EMP_FEC_MODIFICA
		,EMP_CARGO
		,EMP_FEC_MODIFICA_CARGO
		,EMP_CODIGO_SIAM
		,USUARIO
		,FEC_INICIO_FUNCIONES
		,FEC_TERMINO_FUNCIONES
		,FEC_ACREDITACION
		,INFORMACION_PRIVILEGIADA
		,EMP_CORREDORA
		,"IdEmpleado" AS IDEMPLEADO
	FROM "BSCL.Replica.BD.Vistas::Sebra.EMPLEADO_CORREDORA" CE
	LEFT  JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'EMPLEADO_CORREDORA' AND WST."Key" = EMP_CODIGO

WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaEMPLEADO_CORREDORA" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
                                    