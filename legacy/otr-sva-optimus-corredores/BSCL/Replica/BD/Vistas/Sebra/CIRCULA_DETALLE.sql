SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::Sebra.CIRCULA_DETALLE"; 

CREATE VIEW "BSCL.Replica.BD.Vistas::Sebra.CIRCULA_DETALLE" AS

Select
		0 AS ID,					--DECIMAL(15,0)
		'' AS PERIODO,				--CHAR(7)
		'' AS RUT_CLI,				--CHAR(11)
		0 AS CUENTA,				--DECIMAL(2,0)
		'' AS MERCADO,				--CHAR(2)
		'' AS DESCRIPCION_MERCADO,	--CHAR(50)
		'' AS NEMO_EMISOR,			--CHAR(16)
		0 AS CANTIDAD,				--DECIMAL(18,4)
		0 AS PRECIO_CIERRE,			--DECIMAL(15,4)
		0 AS VALOR_PRESENTE,		--DECIMAL(22,4)
		'' AS MONEDA,				--CHAR(3)
		0 AS TASA,					--DECIMAL(17,6)
		'' AS TIPO_OPERACION,		--CHAR(5)
		'' AS FECHA_VENCIMIENTO		--CHAR(10)
        FROM DUMMY WHERE 1=2
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::Sebra.CIRCULA_DETALLE" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
