SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::Sebra.GIRO_COMERCIAL"; 

CREATE VIEW "BSCL.Replica.BD.Vistas::Sebra.GIRO_COMERCIAL" AS

SELECT 
	CAST(GIR_ID AS INT) AS GIR_ID,
	CAST(GIR_COD_SII AS INT) AS GIR_COD_SII,
	CAST(GIR_DESCRIPCION AS VARCHAR(260)) AS GIR_DESCRIPCION,
	CAST(GIR_TIPO AS CHAR(3)) AS GIR_TIPO
FROM (
	SELECT 
		PROF."IdProfesion" AS GIR_ID,
		PROF."Codigo" AS GIR_COD_SII,
		PROF."Nombre" AS GIR_DESCRIPCION,
		'PRO' AS GIR_TIPO
	FROM "BSCL.Plataforma.BD::REG.Profesion" PROF
	UNION ALL
	SELECT
		GIRO."IdGiro" AS GIR_ID,
		GIRO."Codigo" AS GIR_COD_SII,
		GIRO."Nombre" AS GIR_DESCRIPCION,
		'ACT' AS GIR_TIPO
	FROM "BSCL.Plataforma.BD::REG.Giro" GIRO
)
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::Sebra.GIRO_COMERCIAL" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
