SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::Sebra.MODELO_FACTURACION"; 

CREATE VIEW "BSCL.Replica.BD.Vistas::Sebra.MODELO_FACTURACION" AS

	SELECT CAST(CLI."IdTipoCliente" AS VARCHAR(10)) as "PAR_MFA_ID",
	CAST(CLI."IdTipoCliente" AS VARCHAR(30)) as "MFA_NOMBRE",
	CAST('S' AS VARCHAR(1))								AS "MFA_GAS_FACTURA", 																	-- CHAR(1)
	MAX(CASE TIND."CodigoTipoIndicador" WHEN 'FAC_FLFPPR' THEN COALESCE(INDMODELO."ValorIndicador",'N') ELSE NULL END) AS "MFA_FUS_FACPRECIO",
	MAX(CASE TIND."CodigoTipoIndicador" WHEN 'FAC_SFPINS' THEN COALESCE(INDMODELO."ValorIndicador",'N') ELSE NULL END) AS "MFA_SEP_INS",
	MAX(CASE TIND."CodigoTipoIndicador" WHEN 'FAC_SLFPTR' THEN COALESCE(INDMODELO."ValorIndicador",'N') ELSE NULL END) AS "MFA_SEP_PALO",
	MAX(CASE TIND."CodigoTipoIndicador" WHEN 'TES_NIE' THEN COALESCE(INDMODELO."ValorIndicador",'N') ELSE NULL END) AS "MFA_NET_CARABO",
	'N' AS "MFA_FAC_SIMP",
	'N' AS "MFA_SEP_COMVTA"
	FROM "BSCL.SocioNegocio.BD::CLI.TipoCliente" CLI
	LEFT JOIN "BSCL.Plataforma.BD::IND.TipoIndicador" as TIND ON TIND."IdTipoEntidad" = 'PORTAFOLIO'
	LEFT JOIN "BSCL.Plataforma.BD::IND.Indicador" AS INDMODELO ON INDMODELO."IdTipoIndicador" = TIND."IdTipoIndicador" AND 
		INDMODELO."ModeloCliente" = CLI."IdTipoCliente" AND INDMODELO."IdEntidad" = 0
	WHERE TIND."CodigoTipoIndicador" IN ('FAC_FLFPPR','FAC_SFPINS','FAC_SLFPTR','TES_NIE')
	GROUP BY CLI."IdTipoCliente"
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::Sebra.MODELO_FACTURACION" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
