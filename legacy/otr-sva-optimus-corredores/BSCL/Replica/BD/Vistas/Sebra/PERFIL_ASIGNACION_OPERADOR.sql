SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::Sebra.PERFIL_ASIGNACION_OPERADOR"; 

CREATE VIEW "BSCL.Replica.BD.Vistas::Sebra.PERFIL_ASIGNACION_OPERADOR" AS

	Select 
             COALESCE (CAST('' AS VARCHAR(40)),'')  AS "EMP_CODIGO", -- VARCHAR(40)
            COALESCE ( '1900-01-01' , '1900-01-01' )  AS "PAO_FEC_INGRESO", -- DATETIME
            COALESCE (CAST('' AS VARCHAR(1)),'')  AS "INDICADOR_VIGENCIA", -- CHAR(1)
            COALESCE (CAST('' AS VARCHAR(1)),'')  AS "PAO_IND_OPERACION" -- CHAR(1)

        from dummy 

WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::Sebra.PERFIL_ASIGNACION_OPERADOR" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
