SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::Sebra.PAIS"; 

CREATE VIEW "BSCL.Replica.BD.Vistas::Sebra.PAIS" AS

SELECT
	CAST(PAIS."CodigoPais" AS CHAR(2)) AS PAI_ISO,
	CAST(PAIS."NombrePais" AS VARCHAR(50)) AS PAI_NOMBRE,
	CAST(PAIS."NombrePais" AS VARCHAR(50)) AS PAI_GENTILICIO,
	PAIS."IdPais"

FROM "BSCL.Plataforma.BD::REG.Pais" PAIS						
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::Sebra.PAIS" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
