SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaFMPagos"; 
CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaFMPagos" AS

SELECT
	WST."IdStack" AS "IDSTACK", "Action" AS ACTION,
	ID AS TABLE_KEY,
	"ID",-- INT  
	"FOLIOTRANSACCION",-- NUMERIC(10) 
	"INDPAGOCOBRO",-- VARCHAR(2)  
	"FOLIOPAGO",-- INT  
	"FOLIOOPERACION",-- NUMERIC(10)  
	"CODMONPAGO",-- INT
	"CODFORMAPAGO",-- INT
	"MONTO",-- DECIMAL(18,4)
	"FECHAMOVTO",-- DATETIME
	"FECHAPAGO",-- DATETIME
	"ORIGENPAGO",-- CHAR(2) 
	"NOMCHEQUE",-- VARCHAR(50)
	"ESTADO",-- CHAR(1)
	"OBSERVACIONFO",-- VARCHAR(200)
	"OBSERVACIONBO",-- VARCHAR(200)
	"CODBANCOCORRESP",-- CHAR(10)
	"NROCUENTACORRIENTE",-- VARCHAR(30)
	"CODBANCOGIRADOR",-- CHAR(10)
	"USUARIOCREADOR",-- VARCHAR(15)
	"FECHACREACION",-- DATETIME
	"CODBANCOCORRESPCLI",-- CHAR(10)
	"NROCUENTACORRIENTECLI",-- VARCHAR(20)
	"IDGRUPO",-- INT
	"CODBANCOCORR",-- CHAR(10)
	"NROCUENTACORR",-- VARCHAR(20)
	"CODBANCOCLI",-- CHAR(10)
	"NROCUENTACLI",-- VARCHAR(20)
	"CODSUCURSAL"-- CHAR(4)
FROM "BSCL.Replica.BD.Vistas::Sebra.FMPagos" FMP
LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'FMPagos' AND WST."Key" = FMP.ID
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaFMPagos" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
