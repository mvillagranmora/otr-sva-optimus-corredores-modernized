CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaENCUESTA_INVERSIONISTA_CALIFICADOS_HIST_CLIENTE" AS

        Select WST."IdStack" AS "IDSTACK", "Action" AS ACTION,
        	CAST(REG."ENC_ID_HISTORICA" AS varchar) AS TABLE_KEY,    
        	"ENC_ID_HISTORICA", -- INT
            "PER_ID", -- INT
            "CATEGORIA", -- VARCHAR(90)
            "FECHA_ASIGNACION", -- DATETIME
            "PUNTAJE_OBTENIDO", -- INT
            "ENCUESTA", -- TEXT
            "ESTADO", -- CHAR(1)
            "CANAL", -- CHAR(3)
            "DIN_ID", -- VARCHAR(50)
            "ID_USER", -- INT
            "PLANTILLA_PRODUCTO" -- VARCHAR(80)
        FROM "BSCL.Replica.BD.Vistas::Sebra.ENCUESTA_INVERSIONISTA_CALIFICADOS_HIST_CLIENTE" REG
        LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'ENCUESTA_INVERSIONISTA_CALIFICADOS_HIST_CLIENTE' AND WST."Key" = REG."ENC_ID_HISTORICA"

WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaENCUESTA_INVERSIONISTA_CALIFICADOS_HIST_CLIENTE" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
