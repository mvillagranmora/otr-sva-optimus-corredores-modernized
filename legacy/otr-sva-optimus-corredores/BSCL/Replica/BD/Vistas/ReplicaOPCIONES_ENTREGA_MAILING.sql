CREATE VIEW "BSCL.Replica.BD.Vistas::Sebra.OPCIONES_ENTREGA_MAILING" AS

	SELECT 
		WST."IdStack" AS "IDSTACK", 
		"Action" AS ACTION,
		C.PERID || C.CUENTA|| C.DIR_ID_PRIMARIO AS TABLE_KEY,
		PERID,					--INT
		CUENTA,					--INT
		NOTIFICACION_DIARIA,	--INT
		DIR_ID_PRIMARIO,		--INT
		DIR_ID_SECUNDARIO,		--INT
		SUSPENCION_INICIO,		--VARCHAR(10)
		SUSPENCION_FIN,			--VARCHAR(10)
		SUSPENCION				--INT
	FROM "BSCL.Replica.BD.Vistas::Sebra.OPCIONES_ENTREGA_MAILING2" C
	LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'OPCIONES_ENTREGA_MAILING' AND WST."Key" = C.PERID || C.CUENTA|| C.DIR_ID_PRIMARIO
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaOPCIONES_ENTREGA_MAILING" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
                                    
