SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaTBTECMBT"; 
CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaTBTECMBT" AS

SELECT
	WST."IdStack" AS "IDSTACK", "Action" AS ACTION,
	RUT_EMPRESA || TIPO_MON || TIPO_CMBTE || FOLIO_CMBTE AS TABLE_KEY,
	"RUT_EMPRESA",-- CHAR(11)
	"TIPO_MON",-- CHAR(2) 
	"TIPO_CMBTE",-- CHAR(2)  
	"FOLIO_CMBTE",-- DECIMAL(8,0)   
	"FEC_LIQUID",-- DECIMAL(8,0) 
	"COD_BCO_PAGO",-- CHAR(4)
	"COD_CAJA",-- CHAR(4)
	"CONCEPTO_MVTO",-- CHAR(2)
	"EMITIDO_A",-- CHAR(40))
	"EST_CMBTE",-- CHAR(2))
	"FEC_ING",-- CHAR(10))
	"FORMA_PAGO",-- CHAR(10))
	"HORA_ING",-- CHAR(26))
	"IND_CHEQUE",-- CHAR(1))
	"IND_DEST",-- CHAR(1))
	"IND_ING_EGR",-- CHAR(1))
	"IND_MARCA_ESP",-- CHAR(1))
	"IND_PAGO_COBRO",-- CHAR(1))
	"MONTO",-- DECIMAL(17,2)
	"MONTO_ACUM",-- DECIMAL(17,2)
	"OBSERVACION",-- CHAR(40))
	"RUT_DEST",-- CHAR(11))
	"SEC_MOVTO",-- DECIMAL(8,0))
	"SEC_RUT_DEST",-- DECIMAL(2,0))
	"TIPO_CAJA",-- CHAR(2))
	"UNIDAD_DES",-- CHAR(2))
	"UNIDAD_SOL",-- CHAR(2))
	"USUARIO_CER",-- DECIMAL(7,0))
	"USUARIO_SOL",-- DECIMAL(7,0))
	"TIPO_PROV",-- CHAR(2))
	"IND_TRASPASO",-- CHAR(1))
	"PORTAFOLIO",-- CHAR(10))
	"FPA_ID"-- CHAR(2))	
FROM "BSCL.Replica.BD.Vistas::Sebra.TBTECMBT" CMBT
LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'TBTECMBT' AND WST."Key" = CMBT.RUT_EMPRESA || CMBT.TIPO_MON || CMBT.TIPO_CMBTE || CMBT.FOLIO_CMBTE
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaTBTECMBT" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
