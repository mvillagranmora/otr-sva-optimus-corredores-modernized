SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaGIRO_COMERCIAL"; 

CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaGIRO_COMERCIAL" AS

SELECT
	WST."IdStack"  AS "IDSTACK" ,
	"Action" AS ACTION,
	CAST (GIROCOM.GIR_ID || GIROCOM.GIR_TIPO AS NVARCHAR)  AS TABLE_KEY,
	GIR_ID, 			--INT
	GIR_COD_SII,		--INT
	GIR_DESCRIPCION,	--VARCHAR(260)
	GIR_TIPO			--CHAR(3)

FROM "BSCL.Replica.BD.Vistas::Sebra.GIRO_COMERCIAL" GIROCOM
LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'GIRO_COMERCIAL' AND WST."Key" = GIROCOM.GIR_ID || GIROCOM.GIR_TIPO
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaGIRO_COMERCIAL" TO  BCS_DESARROLLADOR WITH GRANT OPTION;