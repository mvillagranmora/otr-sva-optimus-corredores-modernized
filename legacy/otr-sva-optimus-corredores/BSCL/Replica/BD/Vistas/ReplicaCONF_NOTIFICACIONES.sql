SET SCHEMA "BSCL";
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaCONF_NOTIFICACIONES";


CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaCONF_NOTIFICACIONES" AS

	SELECT
		WST."IdStack" AS "IDSTACK", 
		"Action" AS ACTION,
		C.CODNOTIFICACION || C.PERID || C.CUENTA AS TABLE_KEY,
		CODNOTIFICACION,		--VARCHAR(5)
		PERID,					--INT
		CUENTA,					--INT
		ACTIVO,					--INT
		EMAIL,					--INT
		RUT_CLI					--VARCHAR(11)
	FROM "BSCL.Replica.BD.Vistas::Sebra.CONF_NOTIFICACIONES" C
	LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'CONF_NOTIFICACIONES' AND WST."Key" = C.CODNOTIFICACION || C.PERID || C.CUENTA
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaCONF_NOTIFICACIONES" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
                                    
