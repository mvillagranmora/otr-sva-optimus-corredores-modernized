SET SCHEMA "BSCL"; 
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaTBCEDVRV"; 

CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaTBCEDVRV" AS

SELECT 
	WST."IdStack" AS "IDSTACK",
	"Action" AS ACTION,
	(CEDVRV.SEC_EVE || CEDVRV.RUT_CLI || CEDVRV.SEC_RUT_CLI || CEDVRV.NEMO) as TABLE_KEY,
	CEDVRV.EJERCICIO,		--DECIMAL(4,0)
	CEDVRV.MERCADO,			--CHAR(2)
	CEDVRV.TIPO_REG,		--CHAR(1)
	CEDVRV.RUT_CLI,			--CHAR(11)
	CEDVRV.SEC_RUT_CLI,		--DECIMAL(2,0)
	CEDVRV.NEMO,			--CHAR(16)
	CEDVRV.FECHA,			--CHAR(10)
	CEDVRV.SEC_EVE,			--DECIMAL(8,0)
	CEDVRV.RUT_SOC,			--CHAR(11)
	CEDVRV.NUM_CER_CLI,		--DECIMAL(8,0)
	CEDVRV.CANTIDAD,		--DECIMAL(12,0)
	CEDVRV.COD_BOVEDA,		--CHAR(3)
	CEDVRV.IND_INSCRITO,	--CHAR(1)
	CEDVRV.IND_PRI_EMI,		--CHAR(1)
	CEDVRV.MONTO,			--DECIMAL(17,2)
	CEDVRV.SEC_MOVTO,		--DECIMAL(8,0)
	CEDVRV.TIPO_FONDO,		--CHAR(1)
	CEDVRV.MONEDA			--CHAR(3)
FROM "BSCL.Replica.BD.Vistas::Sebra.TBCEDVRV" CEDVRV
left JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'TBCEDVRV' AND WST."Key" = CEDVRV.SEC_EVE || CEDVRV.RUT_CLI || CEDVRV.SEC_RUT_CLI || CEDVRV.NEMO
WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaTBCEDVRV" TO  BCS_DESARROLLADOR WITH GRANT OPTION;