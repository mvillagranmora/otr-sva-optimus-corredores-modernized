SET SCHEMA "BSCL";
DROP VIEW "BSCL.Replica.BD.Vistas::ReplicaCIRCULA_DETALLE";


CREATE VIEW "BSCL.Replica.BD.Vistas::ReplicaCIRCULA_DETALLE" AS

	SELECT DISTINCT
		WST."IdStack" AS "IDSTACK", 
		"Action" AS ACTION,
		C.RUT_CLI || C.CUENTA || C.NEMO_EMISOR  AS TABLE_KEY, 
		ID,							--DECIMAL(15,0)
		PERIODO,					--CHAR(7)
		RUT_CLI,					--CHAR(11)
		CUENTA,						--DECIMAL(2,0)
		MERCADO,					--CHAR(2)
		DESCRIPCION_MERCADO,		--CHAR(50)
		NEMO_EMISOR,				--CHAR(16)
		CANTIDAD,					--DECIMAL(18,4)
		PRECIO_CIERRE,				--DECIMAL(15,4)
		VALOR_PRESENTE,				--DECIMAL(22,4)
		MONEDA,						--CHAR(3)
		TASA,						--DECIMAL(17,6)
		TIPO_OPERACION,				--CHAR(5)
		FECHA_VENCIMIENTO			--CHAR(10)
	FROM "BSCL.Replica.BD.Vistas::Sebra.CIRCULA_DETALLE" C
	LEFT JOIN "BSCL.Replica.BD.Vistas::RegistrosPendientesReplicaActualizacion" WST ON  WST."Table" = 'CIRCULA_DETALLE' AND WST."Key" = C.RUT_CLI || C.CUENTA || C.NEMO_EMISOR


WITH READ ONLY;

GRANT SELECT ON "BSCL.Replica.BD.Vistas::ReplicaCIRCULA_DETALLE" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
                                    
