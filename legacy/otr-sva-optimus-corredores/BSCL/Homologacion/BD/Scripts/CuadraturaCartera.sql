set schema BSCL;

--TOTALES GLOBALES DE CANTIDAD
SELECT (SELECT SUM("CAN_ACTUAL") FROM "BSCL_VIRTUAL"."GES_TBCTCIRV"
WHERE "COD_PER" = '2015-08')
+
(SELECT SUM("CANTIDAD") FROM "BSCL_VIRTUAL"."GES_TBCTTRTP"
WHERE "COD_PER" = '2015-08')
+
(SELECT SUM("CAN_ACTUAL") FROM "BSCL_VIRTUAL"."GES_TBCTCIRF"
WHERE "COD_PER" = '2015-08') AS TOTAL_CARTERA_MIGRADA
,
(SELECT SUM("Cantidad") FROM "BSCL"."BSCL.Custodia.BD::CUS.Cartera"
WHERE "INGFecha" = '2015-08-31' 
AND "IdCarga" = 88
AND "IdUsuario" = 0
) AS TOTAL_CARTERA_SAP_MIGRADA
FROM DUMMY;


-- TOTAL SIMULTANEA 
SELECT 
(SELECT SUM("CANTIDAD") FROM "BSCL_VIRTUAL"."GES_TBCTTRTP"
WHERE "COD_PER" = '2015-08') AS CARTERA_SIMULTANEA
,
(SELECT SUM("Cantidad") FROM "BSCL"."BSCL.Custodia.BD::CUS.Cartera"
WHERE "INGFecha" = '2015-08-31' 
AND "IdCarga" = 88
AND "IdTipoInstrumento" = 'SIM'
) AS TOTAL_CARTERA_SAP_MIGRADA
FROM DUMMY;

--TOTAL RF
SELECT 
(SELECT SUM("CAN_ACTUAL") FROM "BSCL_VIRTUAL"."GES_TBCTCIRF"
WHERE "COD_PER" = '2015-08')
,
(SELECT SUM("Cantidad") FROM "BSCL"."BSCL.Custodia.BD::CUS.Cartera"
WHERE "INGFecha" = '2015-08-31' 
AND "IdCarga" = 88
AND "IdClasificacionTipoInstrumento" = 'RF'
AND "IdUsuario" = 0
) AS TOTAL_CARTERA_SAP_MIGRADA
FROM DUMMY;

--TOTAL RV

SELECT 
(SELECT SUM("CAN_ACTUAL") FROM "BSCL_VIRTUAL"."GES_TBCTCIRV"
WHERE "COD_PER" = '2015-08')
,
(SELECT SUM("Cantidad") FROM "BSCL"."BSCL.Custodia.BD::CUS.Cartera"
WHERE "INGFecha" = '2015-08-31' 
AND "IdCarga" = 88
AND "IdClasificacionTipoInstrumento" = 'RV'
AND "IdUsuario" = 0
) AS TOTAL_CARTERA_SAP_MIGRADA
FROM DUMMY;

-- CUADRAR GARANTIAS

SELECT 
(SELECT SUM("CAN_GARANTIA") FROM "BSCL_VIRTUAL"."GES_TBCTCIRV"
 WHERE "COD_PER" = '2015-08')
, 
(SELECT SUM("Cantidad") FROM "BSCL"."BSCL.Custodia.BD::GTA.Garantia"
WHERE "INGFecha" = '2015-08-31' 
AND "IdCarga" = 88
AND "IdClasificacionTipoInstrumento" = 'RV'
) AS TOTAL_CARTERA_SAP_MIGRADA  
FROM DUMMY;



















