SET SCHEMA "BSCL"; 
 
DROP VIEW "BSCL.Mesa.BD.Vistas::MRF.ConsultarPactosAnalitica";
 
CREATE VIEW "BSCL.Mesa.BD.Vistas::MRF.ConsultarPactosAnalitica" AS
SELECT 	distinct 
		"IdOperacion"
		,"FolioOperacion"
		,"FolioCartera"
		,TO_NVARCHAR("FechaOperacion",'YYYY-MM-DD HH24:MI:SS') AS "FechaOperacion"
		,"IdTipoProducto"
		,"IdTipoOperacion"
		,"NombreTipoOperacion"
		,"Intermesa"
		,"IdMesaOrigen"
		,"NombreMesaOrigen"
		,case when "IdMesaDestino" = 0 then NULL else "IdMesaDestino" end as "IdMesaDestino"
		,"NombreMesaDestino"
		,"IdSocioDeNegocio"
		,"IdCliente"
		,"NombreCompleto"
		,"DocumentoIdentidad"
		,"IdClienteCorredor"
		,"IdPortafolio"
		,"CodigoPropositoPortafolio"
		,"AfectaCustodia"
		,"IdPortafolioCorredor"
		,"IdEmpresa"
		,"MontoOperacionInicial"
		,"MontoOperacionFinal"
		,"IdTipoReajuste"
		,"Tasa"
		,"IdMoneda"
		,"MontoOperacionInicialMoneda"
		,"MontoOperacionFinalMoneda"
		,"IdMonedaLiquidacion"
		,"PlazoEnDias"
		,TO_NVARCHAR("FechaVencimiento",'YYYY-MM-DD HH24:MI:SS') AS "FechaVencimiento"
		,TO_NVARCHAR("FechaLiquidacion",'YYYY-MM-DD HH24:MI:SS') AS "FechaLiquidacion"
		,"IdCondicionLiquidacion"
		,"NombreCondicionLiquidacion"
		,TO_NVARCHAR("FechaCondicionLiquidacion",'YYYY-MM-DD HH24:MI:SS') AS "FechaCondicionLiquidacion"
		,case when "IdAgente" = 0 then NULL else "IdAgente" end as "IdAgente" 
		,coalesce ("NombreEjecutivo",'') as "NombreEjecutivo"
		,"IdEstado"
		,"NombreEstado"
		,TO_NVARCHAR("FechaCreacion",'YYYY-MM-DD HH24:MI:SS') AS "FechaCreacion"
		,case when "IdUsuarioCreacion" = 0 then null else "IdUsuarioCreacion" end as "IdUsuarioCreacion"
		,"CodigoUsuario"
		,"IdTipoCanalIngreso"
		,"Glosa"
		,"MontoOperacionInicialAnticipo"
		,"MontoOperacionFinalAnticipo"
		,"TasaAnticipo"
		,"MontoOperacionInicialMonedaAnticipo"
		,"MontoOperacionFinalMonedaAnticipo"
		,case when "IdMonedaLiquidacionAnticipo" = '' then NULL else "IdMonedaLiquidacionAnticipo" end as "IdMonedaLiquidacionAnticipo"
		,case when "IdCondicionLiquidacionAnticipo" = '' then NULL else "IdCondicionLiquidacionAnticipo" end as "IdCondicionLiquidacionAnticipo" 
		,coalesce("NombreCondicionLiquidacionAnticipo",'')  as "NombreCondicionLiquidacionAnticipo"
		,TO_NVARCHAR("FechaCondicionLiquidacionAnticipo",'YYYY-MM-DD') AS "FechaCondicionLiquidacionAnticipo"
	FROM "BSCL.Mesa.BD.Vistas::MRF.ConsultarDetalleOperacionesMesaRF"	
	WHERE 	"IdTipoOperacion" IN ('VENPAC','COMPAC')
	AND 	"IdEstado" <> 'ANU';

GRANT SELECT ON "BSCL.Mesa.BD.Vistas::MRF.ConsultarPactosAnalitica" TO  BCS_DESARROLLADOR WITH GRANT OPTION;