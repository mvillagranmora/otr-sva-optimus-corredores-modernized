SELECT 
"BSCL.Orden.BD.Secuencias::MarketData_IdInterno".NEXTVAL as "IdInterno",
cm."TipoMensaje" AS "_TipoMensaje",
cm."IdMensaje1" AS "_IdMensaje1",
cm."IdMensaje2" AS "_IdMensaje2",
TO_BIGINT(COALESCE(tr."ID",0)) AS "ID",
COALESCE(tr."TRADEREPORTID",'') AS "TRADEREPORTID",
COALESCE(tr."TRADEID",'') AS "TRADEID",
TO_BIGINT(COALESCE(tr."TRADEREPORTTYPE",0)) AS "TRADEREPORTTYPE",
TO_BIGINT(COALESCE(tr."TRDTYPE",0)) AS "TRDTYPE",
COALESCE(tr."TRADEHANDLINGINSTR",'') AS "TRADEHANDLINGINSTR",
COALESCE(tr."ORIGTRADEID",'') AS "ORIGTRADEID",
COALESCE(tr."EXECTYPE",'') AS "EXECTYPE",
COALESCE(tr."TRADELINKID",'') AS "TRADELINKID",
COALESCE(tr."TRDMATCHID",'') AS "TRDMATCHID",
COALESCE(tr."SECONDARYEXECID",'') AS "SECONDARYEXECID",
COALESCE(tr."PREVIOUSLYREPORTED", false) AS "PREVIOUSLYREPORTED",
COALESCE(tr."VENUETYPE",'') AS "VENUETYPE",
COALESCE(tr."MARKETSEGMENTID",'') AS "MARKETSEGMENTID",
COALESCE(tr."MARKETID",'') AS "MARKETID",
COALESCE(tr."LASTQTY",0) AS "LASTQTY",
COALESCE(tr."LASTPX",0) AS "LASTPX",
COALESCE(tr."LASTMKT",'') AS "LASTMKT",
COALESCE(tr."TRADEDATE",'') AS "TRADEDATE",
TO_NVARCHAR(COALESCE(TO_TIMESTAMP(tr."TRANSACTTIME", 'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"'), TIMESTAMP '1970-01-01 00:00:00')) AS "TRANSACTTIME",
COALESCE(tr."SETTLDATE",'') AS "SETTLDATE",
COALESCE(tr."MATCHSTATUS",'') AS "MATCHSTATUS",
COALESCE(tr."MATCHTYPE",'') AS "MATCHTYPE",
COALESCE(tr."COPYMSGINDICATOR",false) AS "COPYMSGINDICATOR",
COALESCE(tr."SIDE",'') AS "SIDE",
COALESCE(tr."SIDETRADEID",'') AS "SIDETRADEID",
COALESCE(tr."SYMBOL",'') AS "SYMBOL",
COALESCE(tr."SECURITYID",'') AS "SECURITYID",
COALESCE(tr."SECURITYIDSOURCE",'') AS "SECURITYIDSOURCE",
COALESCE(tr."ENTERINGFIRM",'') AS "ENTERINGFIRM",
COALESCE(tr."ENTERINGTRADER",'') AS "ENTERINGTRADER",
COALESCE(tr."EXECUTINGFIRM",'') AS "EXECUTINGFIRM",
COALESCE(tr."EXECUTINGTRADER",'') AS "EXECUTINGTRADER",
COALESCE(tr."CUSTOMERACCOUNT",'') AS "CUSTOMERACCOUNT",
COALESCE(tr."CONTRAFIRM",'') AS "CONTRAFIRM",
COALESCE(tr."ORDERID",'') AS "ORDERID",
COALESCE(tr."CLORDID",'') AS "CLORDID",
COALESCE(tr."ORDERCAPACITY",'') AS "ORDERCAPACITY",
COALESCE(tr."AGGRESSORINDICATOR",'') AS "AGGRESSORINDICATOR",
TO_NVARCHAR(tr."TIMESTAMP") as "TIMESTAMP",
COALESCE(ex."TEXTT",'') AS "TEXT",
COALESCE(co."Fondo",'') AS "FONDO",
COALESCE(co."CodigoOperadorAsociado",'') AS "CODIGOOPERADORASOCIADO"
FROM "BSCL.Orden.BD::ORD.ControlMercado" cm 
LEFT JOIN "BSCL.Orden.BD::MME.PALOS_RV_DROP" tr on cm."IdMensaje1" = TO_NVARCHAR(tr."TIMESTAMP") and cm."IdMensaje2" = tr."SIDETRADEID" || tr."TRADEREPORTTYPE"
LEFT JOIN "BSCL.Orden.BD::MME.EXECUTIONREPORT_RV_DROP" ex ON tr."TRDMATCHID" = ex."TRDMATCHID" AND tr."SIDE"=ex."SIDE"
LEFT JOIN "BSCL.Plataforma.BD::TRA.ConfiguracionOperador" co ON ex.SELFMATCHPREVENTIONID = co."CodigoOperador" AND co."Fondo" <> ''
LEFT JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarCorredoraEmpresa" buyer on buyer."CodigoCorredoraFix" = CASE WHEN tr."SIDE"=1 THEN RIGHT(tr."EXECUTINGFIRM",3) WHEN tr."SIDE" IN (2,5) THEN RIGHT(tr."CONTRAFIRM",3) END
LEFT JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarCorredoraEmpresa" seller on seller."CodigoCorredoraFix" = CASE WHEN tr."SIDE"=1 THEN RIGHT(tr."CONTRAFIRM",3) WHEN tr."SIDE" IN (2,5) THEN RIGHT(tr."EXECUTINGFIRM",3) END
WHERE cm."Procesado" = 'N' and cm."TipoMensaje" = 'MARKET_DATA_PALO_RV_MME' and (buyer."CodigoCorredoraFix" is not null or seller."CodigoCorredoraFix" is not null)
ORDER BY tr."TRANSACTTIME",tr."TIMESTAMP",tr."SIDETRADEID", tr."TRADEREPORTTYPE";