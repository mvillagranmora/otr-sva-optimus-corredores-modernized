WITH Transaccion AS (
	SELECT "TIMESTAMP", "SIDETRADEID", 
  	ROW_NUMBER () OVER (PARTITION BY "SIDETRADEID" ORDER BY "TIMESTAMP" DESC) AS "Row"
	FROM "BSCL.Orden.BD::MME.HIS_PALOS_RV_DROP"
	WHERE REPLACE(REPLACE(REPLACE(REPLACE(REPLACE("TRANSACTTIME",'-',''),'T',''),':',''),'.',''),'Z','') = :TradeTime AND "SIDETRADEID" = :Folio
)
SELECT TO_BIGINT(0) AS "IdInterno",
'' AS "_TipoMensaje",
'' AS "_IdMensaje1",
'' AS "_IdMensaje2",
TO_BIGINT(COALESCE(HIS."ID",0)) AS "ID",
COALESCE(HIS."TRADEREPORTID",'') AS "TRADEREPORTID",
COALESCE(HIS."TRADEID",'') AS "TRADEID",
TO_BIGINT(COALESCE(HIS."TRADEREPORTTYPE",0)) AS "TRADEREPORTTYPE",
TO_BIGINT(COALESCE(HIS."TRDTYPE",0)) AS "TRDTYPE",
COALESCE(HIS."TRADEHANDLINGINSTR",'') AS "TRADEHANDLINGINSTR",
COALESCE(HIS."ORIGTRADEID",'') AS "ORIGTRADEID",
COALESCE(HIS."EXECTYPE",'') AS "EXECTYPE",
COALESCE(HIS."TRADELINKID",'') AS "TRADELINKID",
COALESCE(HIS."TRDMATCHID",'') AS "TRDMATCHID",
COALESCE(HIS."SECONDARYEXECID",'') AS "SECONDARYEXECID",
COALESCE(HIS."PREVIOUSLYREPORTED", false) AS "PREVIOUSLYREPORTED",
COALESCE(HIS."VENUETYPE",'') AS "VENUETYPE",
COALESCE(HIS."MARKETSEGMENTID",'') AS "MARKETSEGMENTID",
COALESCE(HIS."MARKETID",'') AS "MARKETID",
COALESCE(HIS."LASTQTY",0) AS "LASTQTY",
COALESCE(HIS."LASTPX",0) AS "LASTPX",
COALESCE(HIS."LASTMKT",'') AS "LASTMKT",
COALESCE(HIS."TRADEDATE",'') AS "TRADEDATE",
COALESCE(HIS."TRANSACTTIME",'') AS "TRANSACTTIME",
COALESCE(HIS."SETTLDATE",'') AS "SETTLDATE",
COALESCE(HIS."MATCHSTATUS",'') AS "MATCHSTATUS",
COALESCE(HIS."MATCHTYPE",'') AS "MATCHTYPE",
COALESCE(HIS."COPYMSGINDICATOR",false) AS "COPYMSGINDICATOR",
COALESCE(HIS."SIDE",'') AS "SIDE",
COALESCE(HIS."SIDETRADEID",'') AS "SIDETRADEID",
COALESCE(HIS."SYMBOL",'') AS "SYMBOL",
COALESCE(HIS."SECURITYID",'') AS "SECURITYID",
COALESCE(HIS."SECURITYIDSOURCE",'') AS "SECURITYIDSOURCE",
COALESCE(HIS."ENTERINGFIRM",'') AS "ENTERINGFIRM",
COALESCE(HIS."ENTERINGTRADER",'') AS "ENTERINGTRADER",
COALESCE(HIS."EXECUTINGFIRM",'') AS "EXECUTINGFIRM",
COALESCE(HIS."EXECUTINGTRADER",'') AS "EXECUTINGTRADER",
COALESCE(HIS."CUSTOMERACCOUNT",'') AS "CUSTOMERACCOUNT",
COALESCE(HIS."CONTRAFIRM",'') AS "CONTRAFIRM",
COALESCE(HIS."ORDERID",'') AS "ORDERID",
COALESCE(HIS."CLORDID",'') AS "CLORDID",
COALESCE(HIS."ORDERCAPACITY",'') AS "ORDERCAPACITY",
COALESCE(HIS."AGGRESSORINDICATOR",'') AS "AGGRESSORINDICATOR",
TO_NVARCHAR(HIS."TIMESTAMP") as "TIMESTAMP",
COALESCE(ex."TEXTT",'') AS "TEXT"
FROM Transaccion AS T
INNER JOIN "BSCL.Orden.BD::MME.HIS_PALOS_RV_DROP" AS HIS ON (HIS."TIMESTAMP" = T."TIMESTAMP" AND  T."SIDETRADEID" = HIS."SIDETRADEID")
LEFT JOIN "BSCL.Orden.BD::MME.EXECUTIONREPORT_RV_DROP" ex ON HIS."TRDMATCHID" = ex."TRDMATCHID" AND HIS."SIDE"=ex."SIDE"
WHERE T."Row" = 1;
