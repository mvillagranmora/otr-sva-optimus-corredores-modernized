	 LEFT JOIN "BSCL.Plataforma.BD::INS.TipoOperacion" TIOP ON (TIOP."IdTipoOperacion" = INS."IdTipoOperacion")
	 LEFT JOIN "BSCL.Plataforma.BD::INS.TipoOperacion" TIOPINS ON (TIOPINS."IdTipoOperacion" = INS."IdTipoOperacionInstruccion")
