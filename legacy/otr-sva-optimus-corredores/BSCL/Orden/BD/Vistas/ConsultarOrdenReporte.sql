INNER JOIN "BSCL.Plataforma.BD::PLA.Configuracion" CONF ON ("CodigoParametro"='PLA.IdiomaSistema' and ORD."IdEmpresa" = CONF."IdEmpresa")
LEFT JOIN ( SELECT "CodDiccionario","CodLenguaje","Descripcion","Abreviado"
                   ,CASE WHEN DIC."CodDiccionario"='UI_SI' THEN 'S'
                         WHEN DIC."CodDiccionario"='UI_NO' THEN 'N'
                         ELSE ''
                    END AS "EsConfirmada"
            FROM "BSCL.Plataforma.BD::PLA.Diccionario" DIC
            WHERE DIC."CodDiccionario" in ('UI_SI','UI_NO')) DICCIONARIO ON (ORD."EsConfirmada"= DICCIONARIO."EsConfirmada" AND CONF."Valor" = DICCIONARIO."CodLenguaje")
WHERE ORD."IdClasificacionTipoInstrumento" = 'RE';


