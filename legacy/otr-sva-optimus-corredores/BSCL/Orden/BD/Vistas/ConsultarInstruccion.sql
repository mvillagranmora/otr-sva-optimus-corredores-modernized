SET SCHEMA "BSCL"; 

DROP VIEW "BSCL.Orden.BD.Vistas::ConsultarInstruccion";

CREATE VIEW "BSCL.Orden.BD.Vistas::ConsultarInstruccion" AS
SELECT DISTINCT "INS"."IdInstruccion"
, "INS"."IdEstadoInstruccion"
, "EST"."Nombre" AS "NombreEstado"
, "INS"."FechaTrade"
, TO_NVARCHAR("INS"."FechaTrade", 'YYYY-MM-DD') AS "FechaTradeString"
, "INS"."FechaLiquidacion"
, TO_NVARCHAR("INS"."FechaLiquidacion", 'YYYY-MM-DD') AS "FechaLiquidacionString"
, "INS"."IdClasificacionTipoInstrumento", "INS"."IdClasificacionTipoInstrumentoInstruccion"
, "SUB"."NombreTipoInstrumentoSubyacente" AS "Mercado"
, "INS"."IdTipoInstrumentoInstruccion"
, "INS"."IdTipoInstrumento"
, "TIPI"."NombreLargoTipoInstrumento" AS "Proposito"
, "TIPI"."Accion" ||' INSTRUCCION' AS "Tipo"
, "INS"."IdTipoOperacion"
, "INS"."IdTipoOperacionInstruccion"
, "TOPE"."Nombre" AS "NombreTipoOperacion"
, "TOPEIN"."Nombre" AS "NombreTipoOperacionInstruccion"
, "INS"."IdInstrumento"
, "INS"."IdEmisor"
, "INS"."Nemotecnico"
, "INS"."NemotecnicoSVS"
, "INS"."IdCliente"
, "INS"."IdPortafolioCliente"
, "POR"."CodigoPropositoPortafolio"
, "INS"."IdCuentaCustodioPortafolio"
, "INS"."DocumentoIdentidad"
, "INS"."NombreCompleto"
, "INS"."IdBolsa"
, "INS"."IdBoveda"
, "BOV"."NombreCompletoPersona" AS "NombreBoveda"
, "INS"."IdIntermediario"
, "INT"."NombreCompleto" AS "Intermediario"
, "INS"."FolioFactura"
, "INS"."FolioPoliza"
, "INS"."IdMonedaLiquidacion"
, "INS"."IdCondicionDeLiquidacion"
, "INS"."Cantidad" AS "Cantidad"
, "INS"."PrecioInstruccion"
, "INS"."MontoNeto"
, "INS"."TotalCobros"
, "INS"."MontoLiquidacion"
, "INS"."TirTasa"
, "INS"."PorcentajeCobros"
, CASE WHEN "INS"."IdTipoInstrumentoInstruccion" = 'IFI' THEN "INS"."ValorRescate" ELSE 0 END AS "ValorRescate"
, CASE WHEN "INS"."IdTipoInstrumentoInstruccion" = 'IRF' THEN "INS"."ValorNominal" ELSE 0 END AS "ValorNominal"
, "INS"."IdTipoCanalIngreso"
, "CAN"."Nombre" AS "NombreCanalIngreso"
, "INS"."IdTipoCanalDistribucion"
, "INS"."IdEmpresa", "INS"."FechaIngreso"
, TO_NVARCHAR("INS"."FechaIngreso", 'YYYY-MM-DD') AS "FechaIngresoString"
, "INS"."FechaUltimaModificacion"
, TO_NVARCHAR("INS"."FechaUltimaModificacion", 'YYYY-MM-DD') AS "FechaUltimaModificacionString"
, "INS"."FechaVencimiento"
, TO_NVARCHAR("INS"."FechaVencimiento", 'YYYY-MM-DD') AS "FechaVencimientoString"
, "INS"."PlazoVencimiento"
, "INS"."IdTipoReajuste"
, "INS"."Glosa"
, "INS"."IdTransaccion"
, "INS"."IdOrden"
, "INS"."IdAsignacion"
, "INS"."IdMovimientoComprobante"
, "INS"."IdComprobante"
, "INS"."EsFungible"
, "INS"."CorteMinimo" 
, "INS"."IdMotivo" 
, "INSMOT"."Motivo" 
FROM "BSCL.Orden.BD::ORD.Instruccion" AS "INS" 
INNER JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarTipoInstrumento" AS "TIPI" 
	ON "INS"."IdTipoInstrumentoInstruccion" = "TIPI"."IdTipoInstrumento" 
		AND "INS"."IdTipoOperacionInstruccion" = "TIPI"."IdTipoOperacion" 
INNER JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarTipoInstrumentoSubyacente" AS "SUB" 
	ON  "INS"."IdTipoInstrumento" = "SUB"."IdTipoInstrumentoSubyacente" 
		AND "INS"."IdClasificacionTipoInstrumentoInstruccion" = "SUB"."IdClasificacionTipoInstrumento" 
		AND "INS"."IdClasificacionTipoInstrumento" = "SUB"."IdClasificacionTipoInstrumentoSubyacente" 
INNER JOIN "BSCL.Portafolio.BD.Vistas::ConsultarPortafolio" AS "POR" 
	ON "INS"."IdPortafolioCliente" = "POR"."IdPortafolio" 
INNER JOIN "BSCL.Orden.BD.Vistas::ConsultarEstadoOrden" AS "EST" 
	ON "INS"."IdEstadoInstruccion" = "EST"."IdEstado" 
		AND "EST"."NombreEntidad" = 'INSTRUCCION' 
INNER JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarCorredoraCodigos" AS "INT" 
	ON "INS"."IdIntermediario" = "INT"."IdCorredora" 
		AND "TIPI"."IdBolsa" = "INT"."IdBolsa" 
LEFT JOIN "BSCL.Plataforma.BD.Vistas::PLA.ConsultarBoveda" AS "BOV" 
	ON "BOV"."IdBoveda" = "INS"."IdBoveda" 
INNER JOIN "BSCL.Plataforma.BD::PLA.TipoCanalIngreso" AS "CAN" 
	ON "CAN"."IdTipoCanalIngreso" = "INS"."IdTipoCanalIngreso" 
INNER JOIN "BSCL.Plataforma.BD::INS.TipoOperacion" AS "TOPE" 
	ON "TOPE"."IdTipoOperacion" = "INS"."IdTipoOperacion" 
INNER JOIN "BSCL.Plataforma.BD::INS.TipoOperacion" AS "TOPEIN" 
	ON "TOPEIN"."IdTipoOperacion" = "INS"."IdTipoOperacionInstruccion"
LEFT JOIN "BSCL.Orden.BD::ORD.InstruccionMotivo" AS "INSMOT" 
	ON "INSMOT"."IdMotivo" = "INS"."IdMotivo";

GRANT SELECT ON "BSCL.Orden.BD.Vistas::ConsultarInstruccion" TO  BCS_DESARROLLADOR WITH GRANT OPTION;