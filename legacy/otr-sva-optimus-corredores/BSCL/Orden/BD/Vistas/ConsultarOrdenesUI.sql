CREATE VIEW "BSCL.Orden.BD.Vistas::ConsultarOrdenesUI" AS
WITH Ordenes AS  (
	SELECT
		ORD."IdOrden"
	   ,ORD."Folio" as "FolioOrden"
	   ,ORD."FechaRecepcion"
	   ,ORD."FechaIngresoRegistro"
	   ,ORD."FechaIngresoRegistroCorta"
	   ,ORD."FechaSolicitudAnulacion"
	   ,ORD."FechaAnulacion"
	   ,ORD."FechaOferta"
	   ,ORD."FechaOperacion" AS "FechaOperacionOrden"
	   ,ORD."FechaVigencia"
	   ,ORD."FechaVencimiento"
	   ,ORD."FechaEmision"
	   ,ORD."FechaLiquidacion"
	   ,ORD."MontoLiquidacion"
	   ,ORD."FechaAceptacion"
	   ,ORD."FechaAutorizacion"
	   ,ORD."IdTipoVigenciaOrden"
	   ,"TipoFechaVigenciaOrden"."Nombre" as "NombreTipoVigenciaOrden"
	   ,ORD."Glosa" as "GlosaOrden"
	   ,CASE WHEN ORD."OrdenVigente" = 'S' AND COALESCE(estAsig."IdEstadoAsignacion",'SAS') != 'SAS' THEN 
	   		CASE WHEN "ConsultarDisponibleOrden_$4"."CantidadAsignada" = ORD."Cantidad" THEN 
	   			'EJE'
	   		ELSE 
	   			'EJP'
	   		END
	    ELSE 
	    	ORD."IdEstadoOrden"
	   END AS "IdEstadoOrden"
	   ,"ESTORDEN"."Nombre" AS "EstadoOrden"
	   ,(IFNULL(ORD."Cantidad",0) - IFNULL(ORDREF."Cantidad",0))  AS "CantidadOrden"
	   ,(IFNULL(ORD."MontoOrden",0) - IFNULL(ORDREF."MontoOrden",0)) AS "MontoOrden"
	   ,CASE
	   		WHEN ORD."IdTipoInstrumento" = 'SIM' THEN ORD."PlazoSimultanea"
			WHEN ORD."EsVentaCorta" = 'S' THEN ORD."PlazoVentaCorta"
			WHEN ORD."IdClasificacionTipoInstrumento" = 'IF' THEN ORD."PlazoIF"
			WHEN ORD."IdClasificacionTipoInstrumento" = 'RE' THEN ORD."PlazoReporte"
			ELSE 0
		END AS "Plazo"
	   ,CASE
	   		WHEN ORD."IdTipoInstrumento" = 'SIM' THEN ORD."TasaSimultanea"
			WHEN ORD."EsVentaCorta" = 'S' THEN ORD."TasaVentaCorta"
			WHEN ORD."IdClasificacionTipoInstrumento" = 'RF' THEN ORD."TasaRFIF"
			WHEN ORD."IdClasificacionTipoInstrumento" = 'IF' THEN ORD."TasaRFIF"
			WHEN ORD."IdClasificacionTipoInstrumento" = 'RE' THEN ORD."TasaReporte"
			ELSE 0
		END AS "Tasa"
	   ,ORD."IdBoveda"
	   ,ORD."IdFormaCustodia"
	   ,"FormaCustodia"."Nombre" as "NombreFormaCustodia"
	   ,"visi"."Nombre" as "PorcentajeVisibilidad"  
	   ,"visi"."IdPorcentajeVisibilidad"
	   ,ORD."ValorRescate"
	   ,ORD."IdTipoReajuste"
	   ,ORD."PrecioOrden"
	   ,ORD."PrecioMercado"
	   ,ORD."TasaSimultanea"
	   ,ORD."TasaVentaCorta"
	   ,ORD."TasaRFIF"
	   ,ORD."TasaReporte"
	   ,ORD."PlazoVentaCorta"
	   ,ORD."PlazoSimultanea"
	   ,ORD."PlazoIF"
	   ,ORD."PlazoReporte"
	   ,ORD."EsVentaCorta"
	   ,"BSCL.Plataforma.BD.Utilitarios::ObtenerTraduccion"(ORD."EsVentaCorta") as "EsVentaCortaUI"
	   ,ORD."IndicadorFacturacionInmediata"
	   ,ORD."IdTipoPrecio"
	   ,ORD."IdTipoCanalDistribucion"
	   ,"CanalDistribucion"."Nombre" as "NombreCanalDistribucion"
	   ,ORD."EspecificaBolsa"
	   ,ORD."Reservado"
	   ,ORD."Bloqueado"
	   ,"TipoPrecioOrden"."Nombre" as "TipoPrecio"
	   ,ORD."IdTipoTasa"
	   ,ORD."ValorCaptacion"
	   ,ORD."IdCondicionDeLiquidacion"
	   ,"CondicionDeLiquidacion_$3"."Codigo" AS "CodigoCondicionDeLiquidacion"
	   ,"CondicionDeLiquidacion_$3"."Nombre" AS "NombreCondicionDeLiquidacion"
	   ,ORD."IdTipoOperacion"
	   ,"TipoOperacion_$12"."IdTipoProducto"
	   ,ORD."IdCliente"
	   ,"Persona"."RazonSocial"
	   ,"PersonaNombreCompleto"."NombreCompleto"
	   ,"DocumentoIdentidad"."DocumentoIdentidad"
	   ,ORD."IdPortafolioCliente" as "IdPortafolio"
	   ,"ConsultarPortafolio_$0"."CodigoPortafolio"
	   ,ORD."IdGrupoCobro"
	   ,ORD."IdTipoCanalIngreso"
	   ,"TipoCanalIngreso_$11"."Nombre" AS "NombreCanal"
	   ,ORD."IdLibroOrdenes"
	   ,"LibroOrden"."NombreLibroOrdenes"
	   ,"LibroOrden"."IdTipoLibroOrden"
	   ,ORD."IdEmisor"
	   ,ORD."IdEmpresa"
	   ,ORD."IdBolsa"
	   ,CASE ORD."IdBolsa" WHEN '0' THEN 'Todas las bolsas' ELSE "Bolsa_$1"."Nombre" END as "NombreBolsa"
	   ,ORD."IdInstrumento"
	   ,"Instrumento_$8"."Nemotecnico" AS "Instrumento"
	   ,"TipoInstrumento_$9"."IdTipoInstrumento" AS "IdTipoInstrumento"
	   ,"TipoInstrumento_$9"."Nombre" AS "NombreTipoInstrumento"
	   ,"TipoInstrumento_$9"."IdClasificacionTipoInstrumento" AS "IdClasificacionTipoInstrumento"
	   ,"ClasificacionTipoInstrumento_$10"."Nombre" AS "NombreClasificacionTipoInstrumento"
		--SUBYACENTE-------
	   ,ORD."IdInstrumentoSubyacente" as "IdInstrumentoSubyacente"
	   ,"Instrumento_ASOC"."Nemotecnico" AS "InstrumentoSubyacente"
	   ,"TipoInstrumento_ASOC"."IdTipoInstrumento" AS "IdTipoInstrumentoSubyacente"
	   ,"TipoInstrumento_ASOC"."Nombre" AS "NombreTipoInstrumentoSubyacente"
	   ,"TipoInstrumento_ASOC"."IdClasificacionTipoInstrumento" AS "IdClasificacionTipoInstrumentoSubyacente"
	   ,"ClasificacionTipoInstrumento_ASOC"."Nombre" AS "NombreClasificacionTipoInstrumentoSubyacente"
	   	--MEZCLADO
	   ,CASE WHEN "TipoInstrumento_$9"."IdTipoInstrumento" = 'SIM' OR "TipoInstrumento_$9"."IdClasificacionTipoInstrumento" = 'RE' THEN ORD."IdInstrumentoSubyacente" ELSE ORD."IdInstrumento" END AS "IdInstrumentoUI"
	   ,CASE
		   WHEN "TipoInstrumento_$9"."IdTipoInstrumento" = 'SIM' OR "TipoInstrumento_$9"."IdClasificacionTipoInstrumento" = 'RE' THEN "Instrumento_ASOC"."Nemotecnico" 
	       WHEN ORD."IdClasificacionTipoInstrumento"='IF' THEN ORD."NemotecnicoSVS"     
		   ELSE "Instrumento_$8"."Nemotecnico" END AS "InstrumentoUI"
	   ,ORD."OrdenVigente"
	   ,"BSCL.Plataforma.BD.Utilitarios::ObtenerTraduccion"(ORD."OrdenVigente") as "OrdenVigenteUI"
	   --, ORD."IdEstadoAsignacion"
	   ,estAsig."IdEstadoAsignacion"
	   ,"ESTASIGNACION"."Nombre" AS "EstadoOrdenAsignacion"
	   ,"Instrumento_$8"."Tamano"
	   ,"Instrumento_$8"."IdMoneda" AS "IdMonedaInstrumento"
	   ,ORD."IdMonedaOrden" AS "IdMonedaOrden"
	   ,ORD."IdMonedaLiquidacionOrden" AS "IdMonedaLiquidacionOrden"
	   ,"TipoOperacion_$12"."Nombre" AS "NombreTipoOperacion"
	   ,"TipoOperacion_$12"."Accion" AS "AccionTipoOperacion"
	   ,"TipoOperacion_$12"."AccionOrden" AS "AccionOrden"
	   ,CASE WHEN ORD."IdTipoOperacion" = 'COMSIM' AND ORD."IdTipoCanalIngreso" = 'AGE' AND "ConsultarDisponibleOrden_$4"."CantidadDisponible" < 0 THEN 0 ELSE "ConsultarDisponibleOrden_$4"."CantidadDisponible" END AS "CantidadDisponibleOrden"
	   ,"ConsultarDisponibleOrden_$4"."CantidadAsignada" AS "CantidadAsignadaOrden"
	   ,"ConsultarDisponibleOrden_$4"."MontoDisponible" AS "MontoDisponibleOrden"
	   ,"ConsultarDisponibleOrden_$4"."MontoAsignado" AS "MontoAsignadoOrden"
	   ,"ConsultarDisponibleOrden_$4"."PrecioPromedioAsignacion" AS "PrecioPromedioAsignacion"
	   ,ORD."SecOrdenMigracion"
	   ,ORD."TipoCambio"
	   ,ORD."IdEmpleadoPortafolio"
	   ,"EmpleadoPortafolio"."CodigoEmpleado" as "CodigoEmpleadoPortafolio"
	   ,"EmpleadoPortafolioNombreCompleto"."NombreCompleto" as "NombreEmpleadoPortafolio"
	   ,SU1."NombreSucursal" AS "NombreSucursalEmpleadoPortafolio"
	   ,SU2."NombreSucursal" AS "NombreSucursalEmpleadoDigitador"
	   ,ORD."IdEmpleadoDigitador"
	   ,"EmpleadoDigitador"."CodigoEmpleado" as "CodigoEmpleadoDigitador"
	   ,"EmpleadoDigitadorNombreCompleto"."NombreCompleto" as "NombreEmpleadoDigitador"
	   ,ORD."CodigoClaseOrden"
	   ,ORD."CodigoProcedenciaOrden"
	   ,"DetalleTipoIndicador_1"."DetalleIndicador" as "NombreProcedenciaOrden"
	   ,"DetalleTipoIndicador_2"."DetalleIndicador" as "NombreClaseOrden"
	   ,"CorredorCorresponsal"."CodigoCorredor" as  "CodigoCorredorCorresponsal"
	   ,ORD."IdPersonaAutorizadoDarOrdenes" as "IdPersonaAutorizadoDarOrdenes"
	   --,"AutorizadoDarOrdenes"."NombreCompleto" as "NombreAutorizadorOrden"
	   ,CASE WHEN ORD."IdOrdenReferencia" IS NOT NULL THEN CONCAT(IFNULL("AutorizadoNombreCompleto"."NombreCompleto",''),CONCAT(' ANULA SALDO ORDEN ', ORD."IdOrdenReferencia")) ELSE "AutorizadoNombreCompleto"."NombreCompleto" END as "NombreAutorizadorOrden"
	   ,ORD."EsOrdenEspecial"
	   ,"BSCL.Plataforma.BD.Utilitarios::ObtenerTraduccion"(ORD."EsOrdenEspecial") as "OrdenEspecialUI"
	   ,ORD."EsConfirmada"
	   ,ORD."MontoOrdenPlazo"
	   ,ORD."PrecioPlazo"
	   ,ORD."MontoLiquidacionPlazo"
	   ,ORD."MontoLocalPlazo"
	   ,ORD."TasaPromedioReporte"
	   ,ORD."BaseTasa"
	   ,ORD."TipoInteres"
	   ,ORD."IdSistemaBursatil"
	   ,ORD."EsPorMonto"
	   ,"BSCL.Plataforma.BD.Utilitarios::ObtenerTraduccion"(ORD."EsPorMonto") as "EsPorMontoUI"
	   ,ORD."MercadoSMV"
	   ,ORD."ModalidadSMV"
	   ,ORD."EsClienteFinal"
	   ,ORD."IdPersonaBroker"
	   ,"BrokerExtranjero"."Codigo" as "CodigoBrokerExtranjero"
	   ,"FormaDePagoOrden"."IdMedioDePago"
	   ,COALESCE("MedioPago"."Nombre",'SIN DEFINIR') AS "NombreMedioDePago"
	   ,"Instrumento_$8"."EsPutEsCall"
	   ,"Instrumento_$8"."PrecioStrike"
	   	--OPCIONES CL
	   ,"Instrumento_$8"."ModalidadLiquidacion" AS "IdModalidadLiquidacion"
	   ,CASE WHEN "Instrumento_$8"."ModalidadLiquidacion" = 'P' THEN 'FISICA' WHEN "Instrumento_$8"."ModalidadLiquidacion" = 'C' THEN 'FINANCIERA' ELSE '' END AS "ModalidadLiquidacion"
	   ,"Instrumento_$8"."ModalidadEjercicio" AS "IdModalidadEjercicio"
	   ,CASE WHEN "Instrumento_$8"."ModalidadEjercicio" = 'A' THEN 'AUTOMATICA' WHEN "Instrumento_$8"."ModalidadEjercicio" = 'M' THEN 'MANUAL' ELSE '' END AS "ModalidadEjercicio"
	   ,"Instrumento_$8"."EsPutEsCall" AS "TipoOpcion"
	   ,CASE WHEN "Instrumento_$8"."EsPutEsCall" = 'CALL' THEN 'C' WHEN "Instrumento_$8"."EsPutEsCall" = 'PUT' THEN 'P' ELSE '' END AS "IdTipoOpcion"
	   ,"Instrumento_$8"."EstiloOpcion" AS "IdEstiloOpcion"
	   ,CASE WHEN "Instrumento_$8"."EstiloOpcion" = 'A' THEN 'AMERICANA' WHEN "Instrumento_$8"."EstiloOpcion" = 'E' THEN 'EUROPEA' ELSE '' END AS "EstiloOpcion"
	   ,BOV."Nombre" AS "NombreBoveda"
	   	--CUENTA CUSTODIO
	   ,"CuentaCustodioPortafolio"."IdCuentaCustodioPortafolio"
	   ,CASE WHEN COALESCE("CuentaCustodioPortafolio"."IdPersonaBancoCustodio",0)=0 THEN 'N' ELSE 'S' END AS "IndicadorBancoCustodio"
	   ,"CuentaCustodioPortafolio"."CodigoBancoCustodio" as "CodigoBancoCustodio"
	   ,"CuentaCustodioPortafolio"."Codigo" as "CodigoBoveda"
	   ,"CuentaCustodioPortafolio"."CodigoBancoLiquidador" as "CodigoBancoLiquidador"
	   ,"CuentaCustodioPortafolio"."NombreModeloCustodia" as "NombreModeloCustodia"
	   ,"CuentaCustodioPortafolio"."NombreTipoCustodia" as "NombreTipoCustodia"
	   ,"CuentaCustodioPortafolio"."NombreCompletoBancoCustodio" as "NombreCompletoBancoCustodio"
	   ,"CuentaCustodioPortafolio"."NombreCompletoBancoLiquidador" as "NombreCompletoBancoLiquidador"
	   ,MatrizAgrupador."Producto" AS "Producto"
	   ,MAP(MatrizAgrupador."IdProductoAgrupador",NULL,0,MatrizAgrupador."IdProductoAgrupador") AS "IdProductoAgrupador"
	   ,ConsultarAsignadoDiaOrden."AsignadoDia"
	   ,ORD."EnAnulacion"
	   ,ORD."FechaConfirmacion"
	   ,ORD."FechaConfirmacionPlazo"
	   ,ORD."IdEstadoConfirmacion"
	   ,COALESCE("ESTORDENCONFIRMACION"."Nombre",'') AS "EstadoConfirmacion"
	   ,"ConsultarPortafolio_$0"."Alias" AS "RazonSocialPortafolio"
	   ,COALESCE(MATRIZ."IdMatrizAgrupador",0) AS "IdMatrizAgrupador"
	   ,COALESCE(TIPOLIQ."TipoLiquidacion",'') AS "TipoLiquidacion"
	   ,COALESCE("DetalleTipoIndicador_3"."DetalleIndicador",'') AS "ModoFacturacion"
	   ,"Instrumento_Negociacion"."IdInstrumento" AS "IdInstrumentoNegociacion"
	   ,"Instrumento_Negociacion"."Nemotecnico" AS "InstrumentoNegociacion"
	   ,ORD."IdMonedaOrden" AS "IdMonedaNegociacion"
	   ,ORD."GeneraSpot"
	   ,EVT."IdTipoEventoBitacora"
	   ,TIPEVT."DescripcionTipoEventoBitacora" AS "EstadoOrdenRuteo"
	   ,RANK() OVER (PARTITION BY EVT."IdOrden" ORDER BY "FechaEventoBitacora" DESC, EVT."IdEventoBitacora" DESC) AS "Rank"
	
	FROM "BSCL.Orden.BD::ORD.Orden" AS ORD
	LEFT JOIN "BSCL.Orden.BD.Vistas::ConsultarEstadoAsignacionOrden" as estAsig on estAsig."IdOrden" = ORD."IdOrden"
	LEFT JOIN "BSCL.Plataforma.BD::INS.Bolsa" AS "Bolsa_$1" ON "Bolsa_$1"."IdBolsa" = ORD."IdBolsa"
	LEFT JOIN "BSCL.Orden.BD::ORD.PorcentajeVisibilidad" AS "visi" ON "visi"."IdPorcentajeVisibilidad" = ORD."IdPorcentajeVisibilidad"
	LEFT JOIN "BSCL.Portafolio.BD::POR.Portafolio" AS "ConsultarPortafolio_$0" ON ORD."IdPortafolioCliente" = "ConsultarPortafolio_$0"."IdPortafolio"
	LEFT JOIN "BSCL.Portafolio.BD.Vistas::ConsultarPortafolioMatriz" MATRIZ ON MATRIZ."IdPortafolio" = "ConsultarPortafolio_$0"."IdPortafolio"
	LEFT JOIN "BSCL.SocioNegocio.BD::CLI.Cliente" AS "ConsultarCliente_$2" ON "ConsultarCliente_$2"."IdCliente" = "ConsultarPortafolio_$0"."IdCliente"
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.Persona" AS "Persona" ON "Persona"."IdPersona" = "ConsultarCliente_$2"."IdPersona"
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.DocumentoIdentidad" AS "DocumentoIdentidad" ON "DocumentoIdentidad"."IdDocumentoIdentidad" = "Persona"."IdDocumentoIdentidad"
	LEFT JOIN "BSCL.SocioNegocio.BD.Vistas::PER.ConsultarPersonaNombreCompleto" AS "PersonaNombreCompleto" ON "PersonaNombreCompleto"."IdPersona" = "ConsultarCliente_$2"."IdPersona"
	LEFT JOIN "BSCL.Plataforma.BD::PLA.CondicionDeLiquidacion" AS "CondicionDeLiquidacion_$3" ON "CondicionDeLiquidacion_$3"."IdCondicionDeLiquidacion" = ORD."IdCondicionDeLiquidacion"
	LEFT JOIN "BSCL.Orden.BD.Vistas::ConsultarDisponibleOrden" AS "ConsultarDisponibleOrden_$4" ON "ConsultarDisponibleOrden_$4"."IdOrden" = ORD."IdOrden"
	LEFT JOIN "BSCL.Orden.BD::ORD.TipoPrecioOrden" AS "TipoPrecioOrden" ON "TipoPrecioOrden"."IdTipoPrecioOrden" = ORD."IdTipoPrecio"
	--estado orden
	LEFT JOIN "BSCL.Orden.BD::ORD.EstadoOrden" AS "EstadoOrden_$5" ON  ( "EstadoOrden_$5"."IdEstado" = CASE WHEN ORD."OrdenVigente" = 'S' AND COALESCE(estAsig."IdEstadoAsignacion",'SAS') != 'SAS' THEN 
	   																										CASE WHEN "ConsultarDisponibleOrden_$4"."CantidadAsignada" = ORD."Cantidad" THEN 
	   																											'EJE'
	   																										ELSE 
	   																											'EJP'
	   																										END
	   																									ELSE 
	    																									ORD."IdEstadoOrden"
	   																									END )  
	   																	AND  ( "EstadoOrden_$5"."NombreEntidad" = 'ORDEN' )
	LEFT JOIN "BSCL.Plataforma.BD::PLA.Estado" AS "ESTORDEN" ON "ESTORDEN"."IdEstado" = "EstadoOrden_$5"."IdEstado"
	--estado orden asignacion
	LEFT JOIN "BSCL.Orden.BD::ORD.EstadoOrden" AS "EstadoOrden_$6" ON  ( "EstadoOrden_$6"."IdEstado" = estAsig."IdEstadoAsignacion" )  AND  ( "EstadoOrden_$6"."NombreEntidad" = 'ORDEN.ASIGNACION' )
	LEFT JOIN "BSCL.Plataforma.BD::PLA.Estado" AS "ESTASIGNACION" ON "ESTASIGNACION"."IdEstado" = "EstadoOrden_$6"."IdEstado"
	
	--estado confirmacion
	LEFT JOIN "BSCL.Orden.BD::ORD.EstadoOrden" AS "EstadoOrdenConf" ON  ( "EstadoOrdenConf"."IdEstado" = ORD."IdEstadoConfirmacion" )  AND  ( "EstadoOrdenConf"."NombreEntidad" = 'ORDEN.CONFIRMACION' )
	LEFT JOIN "BSCL.Plataforma.BD::PLA.Estado" AS "ESTORDENCONFIRMACION" ON "ESTORDENCONFIRMACION"."IdEstado" = "EstadoOrdenConf"."IdEstado"
	
	--tipo vigencia
	LEFT JOIN "BSCL.Orden.BD.Vistas::ConsultarTipoFechaVigenciaOrden" AS "TipoFechaVigenciaOrden" ON  "TipoFechaVigenciaOrden"."IdTipoVigenciaOrden" = ORD."IdTipoVigenciaOrden"
	--empleado portafolio
	LEFT JOIN "BSCL.SocioNegocio.BD::EMP.Empleado" AS "EmpleadoPortafolio" ON "EmpleadoPortafolio"."IdEmpleado" = ORD."IdEmpleadoPortafolio"
	LEFT JOIN "BSCL.SocioNegocio.BD.Vistas::PER.ConsultarPersonaNombreCompleto" AS "EmpleadoPortafolioNombreCompleto" ON "EmpleadoPortafolioNombreCompleto"."IdPersona" = "EmpleadoPortafolio"."IdPersona"
	
	LEFT JOIN "BSCL.Plataforma.BD::PLA.Sucursal" AS SU1 ON SU1."IdSucursal" = ORD."IdSucursalEmpleadoPortafolio"
	--empleado digitador
	LEFT JOIN "BSCL.SocioNegocio.BD::EMP.Empleado" AS "EmpleadoDigitador" ON "EmpleadoDigitador"."IdEmpleado" = ORD."IdEmpleadoDigitador"
	LEFT JOIN "BSCL.SocioNegocio.BD.Vistas::PER.ConsultarPersonaNombreCompleto" AS "EmpleadoDigitadorNombreCompleto" ON "EmpleadoDigitadorNombreCompleto"."IdPersona" = "EmpleadoDigitador"."IdPersona"
	
	LEFT JOIN "BSCL.Plataforma.BD::PLA.Sucursal" AS SU2 ON SU2."IdSucursal" = ORD."IdSucursalEmpleadoDigitador"
	--procedencia
	LEFT JOIN "BSCL.Plataforma.BD.Vistas::IND.ConsultarDetalleTipoIndicador" AS "DetalleTipoIndicador_1" ON "DetalleTipoIndicador_1"."CodigoTipoIndicador" = 'PROCEDENC' and ORD."CodigoProcedenciaOrden" = "DetalleTipoIndicador_1"."Codigo" and ORD."IdEmpresa" = "DetalleTipoIndicador_1"."IdEmpresa"
