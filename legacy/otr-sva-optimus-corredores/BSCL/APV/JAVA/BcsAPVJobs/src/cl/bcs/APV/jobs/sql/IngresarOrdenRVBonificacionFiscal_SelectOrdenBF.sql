SELECT 	Orden."IdOrden" AS "IdInterno"
,Orden."IdCliente"
,TO_NVARCHAR(Orden."FechaRecepcion",'YYYY-MM-DD') as "FechaRecepcion"
,TO_NVARCHAR(Orden."FechaVigencia",'YYYY-MM-DD') as "FechaVigencia"
,TO_NVARCHAR(Orden."FechaEmision",'YYYY-MM-DD') as "FechaEmision"
,TO_NVARCHAR(Orden."FechaOperacion",'YYYY-MM-DD') as "FechaOperacion"
,Orden."IdCondicionDeLiquidacion"
,Orden."IdTipoOperacion"
,Orden."IdTipoVigenciaOrden" AS "IdTipoVigencia"
,Orden."Glosa"
,Orden."Cantidad"
,Orden."MontoOrden" AS "MontoNeto"
,Orden."ValorRescate" 
,Orden."IdBoveda"
,Orden."IdFormaCustodia"
,Orden."PrecioOrden" AS "PrecioLimite"
,'N' AS "EsFacturaInmediata"
,Orden."IdTipoPrecio"
,PortaBonif."IdPortafolio" AS "IdPortafolio"
,Orden."IdTipoCanalIngreso"
,Orden."IdTipoReajuste"
,Orden."IdEmisor"
,Orden."IdBolsa"
,Orden."IdPorcentajeVisibilidad"
,Orden."EspecificaBolsa"
,Orden."IdMonedaLiquidacionOrden"
,Orden."TipoCambio"
,Orden."IdInstrumento"
,Orden."IdInstrumentoSubyacente"
,Orden."IdCondicionDeLiquidacion" AS "IdCondicionDeLiquidacionPlazo"
,Orden."TasaVentaCorta"
,Orden."PlazoVentaCorta"
,Orden."EsVentaCorta"
,Orden."TasaSimultanea"
,Orden."PlazoSimultanea"
,Orden."PlazoIF"
,Orden."TasaRFIF"
,CASE WHEN "CodigoClaseOrden" = '' THEN 'N'
	ELSE 'S' END AS "EsOD"
,Orden."EsFungible"
,NULL AS "IdTipoLibroOrden"
,NULL AS "IdLibroOrdenes"
,Orden."IdCuentaCustodioPortafolio"
,Orden."EsPorMonto"
,Orden."IdCorredorCorresponsal"
,Orden."IdPersonaAutorizadoDarOrdenes"
,Orden."IdTipoCanalDistribucion"
,Orden."EsOrdenEspecial"
,'S' AS "PagoCobroCuentaInversion"
,Orden."IdPortafolioCliente" AS "IdPreferenciaPagoPortafolio"
,Orden."BaseTasa"
,Orden."TipoInteres"
,'OM' AS "IdMecanismoCaptacion"
,TipoOperacion."AccionOrden"
,Orden."IdTipoInstrumento"
FROM  "BSCL.Orden.BD::ORD.Orden" Orden
INNER JOIN "BSCL.Portafolio.BD.Vistas::ConsultarPortafolio" PortaBonif ON Orden."IdCliente" = PortaBonif."IdCliente"
AND PortaBonif."TienePropositoAPV" = 'S'
AND PortaBonif."IdEstado" = 'ACT'
INNER JOIN "BSCL.Plataforma.BD::INS.TipoOperacion" TipoOperacion 
ON (TipoOperacion."IdTipoOperacion" = Orden."IdTipoOperacion")
INNER JOIN "BSCL.Portafolio.BD::POR.MatrizAgrupadorAPV" MatrizBonif
ON PortaBonif."IdMatrizAgrupadorAPV" = MatrizBonif."IdMatrizAgrupadorAPV"
INNER JOIN "BSCL.APV.BD::REC.RegimenTributario" RegimenBonif
ON RegimenBonif."IdRegimenTributario" = MatrizBonif."IdRegimenTributario"
AND RegimenBonif."Codigo" = 'BF'
WHERE "IdOrden" in (:IdsOrden)
ORDER BY "IdOrden" DESC