SELECT "IdPreferenciaPagoPortafolio"
	,POR."IdPortafolio"
	,PPP."IdPreferenciaPago"
	,PPP."IdCuentaBancaria"
	,PPP."IdTarjetaBancaria"
	,PPP."FechaCreacion"
	,PPP."FechaModificacion"
	,PPP."IdUsuarioCreador"
	,PPP."IdEstado"
	,PPP."IdEmpresa"		
	,PPP."FechaIngreso"			 
	,PPP."IdEstadoAutorizacion"
	,PPP."PorDefecto"
	,PP."IdTipoOperacion"
	,PP."IdMoneda"								
FROM "BSCL.Portafolio.BD::POR.Portafolio" AS POR
INNER JOIN "BSCL.Portafolio.BD::POR.PreferenciaPagoPortafolio"  AS PPP ON POR."IdPortafolio" != PPP."IdPortafolio"
INNER JOIN "BSCL.Plataforma.BD::PAG.PreferenciaPago" PP ON PP."IdPreferenciaPago" = PPP."IdPreferenciaPago" 
WHERE PP."IdEmpresa" = :IdEmpresa AND PPP."IdPreferenciaPago" = :IdPreferenciaPagoPortafolio AND POR."IdEstado" <> 'INA';