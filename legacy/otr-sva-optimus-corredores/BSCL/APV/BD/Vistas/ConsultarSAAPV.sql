   ,CON."Telefono"
   ,CON."TelefonoFijo"
   ,CON."TelefonoMovil"
   ,CON."TelefonoLaboral"
   ,CON."Email"
   ,CON."IdPais"
   ,CON."Pais"
   ,CON."IdRegion"
   ,CON."Region"
   ,CON."IdComuna"
   ,CON."Comuna"
   ,CON."IdCiudad"
   ,CON."Ciudad"
   ,CON."FechaNacimiento"
   ,CON."EstadoCivil"
   ,CON."Genero"
   ,CON."IdCargoPersona"
   ,CON."Canal"
   ,CON."DescripcionCanal"
   ,CON."Pago"
   ,CON."PagoUnico"
   ,EMP."IdClienteEmpleador"
   ,EMP."IdPersonaEmpleador"
   ,EMP."RutEmpleador"
   ,EMP."RazonSocialEmpleador"
   ,EMP."NombreFantasiaEmpleador"
   ,EMP."DireccionEmpleador"
   ,EMP."NumeroDireccionEmpleador"
   ,EMP."TelefonoEmpleador"
   ,EMP."IdPaisEmpleador"
   ,EMP."PaisEmpleador"
   ,EMP."IdRegionEmpleador"
   ,EMP."RegionEmpleador"
   ,EMP."IdComunaEmpleador"
   ,EMP."ComunaEmpleador"
   ,EMP."IdCiudadEmpleador"
   ,EMP."CiudadEmpleador"
   ,EMP."NombreEncargado"
   ,EMP."EmailEncargado"
   ,EMP."TelefonoEncargado"
   ,OTR."IdEmpresa"
   ,OTR."IdPlan"
   ,OTR."NombrePlan"
   ,OTR."FechaSuscripcion"
   ,OTR."FechaCreacion"
   ,OTR."FechaAprobacion"
   ,OTR."FechaNotificacion"
   ,OTR."FechaRecepcion"
   ,OTR."Folio"
   ,OTR."IdCategoriaInversionista"
   ,OTR."IdPerfilComercial"
   ,OTR."IdMedioRecaudacionTrabajador"
   ,OTR."IdEntidadRecaudadora"
   ,OTR."CodigoPrevision"
   ,OTR."Pensionado"
   ,OTR."Trabajador"
   ,OTR."FormaDePago"
   ,OTR."IdMedioRecaudacionFormaPago"
   ,OTR."DiaDescuento"
   ,OTR."Institucion"
   ,OTR."ComisionTransferencia"
   ,OTR."CodigoTipoSolicitud"
   ,OTR."TipoMovimiento"
   ,OTR."RazonRetiro"
   ,OTR."IdPersonaOrigen"
   ,OTR."TipoDeAhorro"
   ,OTR."FondoDeOrigen"
   ,OTR."NombreEntidadOrigen"
   ,OTR."RutEntidadOrigen"
   ,OTR."TipoTraspaso"
   ,OTR."MontoTraspaso"
   ,OTR."UFTraspaso"
   ,OTR."PorcentajeTraspaso"
   ,OTR."IdEstadoEnvioNotificacion"
   ,OTR."IdEstadoSolicitud"
   ,OTR."IdCargaMasiva"
   ,OTR."IdEmpleador"
   ,OTR."IdPropositoPortafolio"
   ,OTR."IdMatrizAgrupador"
   ,OTR."CodigoAgrupador"
   ,OTR."Descripcion"
   ,OTR."EsADC"
FROM
(
	SELECT
		ContratoSAAPV."IdCliente"									AS "IdCliente"
	   ,ContratoSAAPV."IdPersona"									AS "IdPersona"
	   ,DocumentoIdentidad."DocumentoIdentidad"						AS "DocumentoIdentidad"
	   ,ContratoSAAPV."IdEstado"									AS "Estado"
	   ,ContratoSAAPV."FolioContratoSAAPV"							AS "FolioContratoSAAPV"
	   ,ContratoSAAPV."IdContratoSAAPV"								AS "IdContratoSAAPV"
	   ,Persona."Nombres"											AS "Nombres"
	   ,Persona."ApellidoPaterno"									AS "ApellidoPaterno"
	   ,Persona."ApellidoMaterno"									AS "ApellidoMaterno"
	   ,DireccionFisica."Calle"										AS "Direccion"
	   ,DireccionFisica."Numero"									AS "NumeroDireccion"
	   ,Telefono."Numero"											AS "Telefono"
	   ,ContratoSAAPV."TelefonoCliente"								AS "TelefonoFijo"
	   ,ContratoSAAPV."TelefonoCelularCliente"						AS "TelefonoMovil"
	   ,ContratoSAAPV."TelefonoComercialCliente"					AS "TelefonoLaboral"
	   ,ContratoSAAPV."EmailCliente"								AS "Email"
	   ,Pais."IdPais"												AS "IdPais"
	   ,Pais."NombrePais"											AS "Pais"
	   ,ClasificacionDivisionPais."IdClasificacionDivisionPais"		AS "IdRegion"
	   ,ClasificacionDivisionPais."NombreClasificacionDivisionPais"	AS "Region"
	   ,DivisionPais."IdDivisionPais"								AS "IdComuna"
	   ,DivisionPais."NombreDivisionPais"							AS "Comuna"
	   ,Ciudad."IdCiudad"											AS "IdCiudad"
	   ,Ciudad."NombreCiudad"										AS "Ciudad"
	   ,Persona."FechaNacimiento"									AS "FechaNacimiento"
	   ,Persona."EstadoCivil"										AS "EstadoCivil"
	   ,Persona."Sexo"												AS "Genero"
	   ,ContratoSAAPV."IdTipoCargoPersona"							AS "IdCargoPersona"
	   ,ContratoSAAPV."Canal"										AS "Canal"
	   ,COALESCE(Canal."Nombre",'')									AS "DescripcionCanal"
	   ,COALESCE(PortafolioContratoSAAPV."Pago",'')								AS "Pago"
	   ,CASE WHEN PortafolioContratoSAAPV."Pago" = 'UNI' THEN 'S' ELSE 'N' END	AS "PagoUnico"
	FROM "BSCL.APV.BD::SCS.ContratoSAAPV" AS ContratoSAAPV
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.Persona" AS Persona ON Persona."IdPersona" = ContratoSAAPV."IdPersona"
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.DocumentoIdentidad" AS DocumentoIdentidad ON DocumentoIdentidad."IdDocumentoIdentidad" = Persona."IdDocumentoIdentidad"
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.DireccionFisica" AS DireccionFisica ON DireccionFisica."IdDireccionFisica" = Persona."IdDireccionFisicaPrincipal"
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.Telefono" AS Telefono ON Telefono."IdTelefono" = Persona."IdTelefonoPrincipal"
	LEFT JOIN "BSCL.Plataforma.BD::REG.DivisionPais" AS DivisionPais ON DivisionPais."IdDivisionPais" = DireccionFisica."IdDivisionPais"
	LEFT JOIN "BSCL.Plataforma.BD::REG.ClasificacionDivisionPais" AS ClasificacionDivisionPais ON ClasificacionDivisionPais."IdClasificacionDivisionPais" = DivisionPais."IdClasificacion1"
	LEFT JOIN "BSCL.Plataforma.BD::REG.Ciudad" AS Ciudad ON Ciudad."IdCiudad" = DireccionFisica."IdCiudad"
	LEFT JOIN "BSCL.Plataforma.BD::REG.Pais" AS Pais ON Pais."IdPais" = ClasificacionDivisionPais."IdPais"
	LEFT JOIN "BSCL.Plataforma.BD::PLA.TipoCanalIngreso" Canal ON Canal."IdTipoCanalIngreso" = ContratoSAAPV."Canal"
	LEFT JOIN "BSCL.APV.BD::SCS.PortafolioContratoSAAPV" AS PortafolioContratoSAAPV ON ContratoSAAPV."IdContratoSAAPV" = PortafolioContratoSAAPV."IdContratoSAAPV"
)
AS CON
LEFT JOIN
(
	SELECT
		ContratoSAAPV."IdContratoSAAPV"								AS "IdContratoSAAPV"
	   ,Cliente."IdCliente"											AS "IdClienteEmpleador"
	   ,ContratoSAAPV."IdEmpleador"									AS "IdPersonaEmpleador"
	   ,DocumentoIdentidad."DocumentoIdentidad"						AS "RutEmpleador"
	   ,Persona."RazonSocial"										AS "RazonSocialEmpleador"
	   ,''															AS "NombreFantasiaEmpleador"
	   ,DireccionFisica."Calle"										AS "DireccionEmpleador"
	   ,DireccionFisica."Numero"									AS "NumeroDireccionEmpleador"
	   ,Telefono."Numero"											AS "TelefonoEmpleador"
	   ,Pais."IdPais"												AS "IdPaisEmpleador"
	   ,Pais."NombrePais"											AS "PaisEmpleador"
	   ,ClasificacionDivisionPais."IdClasificacionDivisionPais"		AS "IdRegionEmpleador"
	   ,ClasificacionDivisionPais."NombreClasificacionDivisionPais"	AS "RegionEmpleador"
	   ,DivisionPais."IdDivisionPais"								AS "IdComunaEmpleador"
	   ,DivisionPais."NombreDivisionPais"							AS "ComunaEmpleador"
	   ,Ciudad."IdCiudad"											AS "IdCiudadEmpleador"
	   ,Ciudad."NombreCiudad"										AS "CiudadEmpleador"
	   ,ContratoSAAPV."NombreEncargado"								AS "NombreEncargado"
	   ,ContratoSAAPV."EmailEncargado"								AS "EmailEncargado"
	   ,ContratoSAAPV."TelefonoEncargado"							AS "TelefonoEncargado"
	FROM "BSCL.APV.BD::SCS.ContratoSAAPV" AS ContratoSAAPV
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.Persona" AS Persona ON Persona."IdPersona" = ContratoSAAPV."IdEmpleador"
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.DocumentoIdentidad" AS DocumentoIdentidad ON DocumentoIdentidad."IdDocumentoIdentidad" = Persona."IdDocumentoIdentidad"
	LEFT JOIN "BSCL.SocioNegocio.BD::CLI.Cliente" AS Cliente ON Cliente."IdPersona" = Persona."IdPersona"
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.DireccionFisica" AS DireccionFisica ON DireccionFisica."IdDireccionFisica" = Persona."IdDireccionFisicaPrincipal"
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.Telefono" AS Telefono ON Telefono."IdTelefono" = Persona."IdTelefonoPrincipal"
	LEFT JOIN "BSCL.Plataforma.BD::REG.DivisionPais" AS DivisionPais ON DivisionPais."IdDivisionPais" = DireccionFisica."IdDivisionPais"
	LEFT JOIN "BSCL.Plataforma.BD::REG.ClasificacionDivisionPais" AS ClasificacionDivisionPais ON ClasificacionDivisionPais."IdClasificacionDivisionPais" = DivisionPais."IdClasificacion1"
	LEFT JOIN "BSCL.Plataforma.BD::REG.Ciudad" AS Ciudad ON Ciudad."IdCiudad" = DireccionFisica."IdCiudad"
	LEFT JOIN "BSCL.Plataforma.BD::REG.Pais" AS Pais ON Pais."IdPais" = ClasificacionDivisionPais."IdPais"
	WHERE
		ContratoSAAPV."IdEmpleador" IS NOT NULL
	AND ContratoSAAPV."IdEmpleador" != 0
)
AS EMP ON EMP."IdContratoSAAPV" = CON."IdContratoSAAPV"
LEFT JOIN
(
	SELECT
		ContratoSAAPV."IdContratoSAAPV"																											AS "IdContratoSAAPV"
	   ,ContratoSAAPV."IdEmpresa"																												AS "IdEmpresa"
	   ,ContratoSAAPV."IdPlan"																													AS "IdPlan"
	   ,ContratoSAAPV."NombrePlan"																												AS "NombrePlan"
	   ,ContratoSAAPV."FechaSuscripcion"																										AS "FechaSuscripcion"
	   ,ContratoSAAPV."FechaCreacion"																											AS "FechaCreacion"
	   ,ContratoSAAPV."FechaAprobacion"																											AS "FechaAprobacion"
	   ,ContratoSAAPV."FechaNotificacion"																										AS "FechaNotificacion"
	   ,ContratoSAAPV."FechaRecepcion"																											AS "FechaRecepcion"
	   ,ContratoSAAPV."Folio"																													AS "Folio"
	   ,Cliente."IdCategoriaInversionista"																										AS "IdCategoriaInversionista"
	   ,Portafolio."IdPerfilComercialBaseOrigen"																								AS "IdPerfilComercial"
	   ,ContratoSAAPV."IdMedioRecaudacionTrabajador"																							AS "IdMedioRecaudacionTrabajador"
	   ,ContratoSAAPV."IdEntidadRecaudadora"																									AS "IdEntidadRecaudadora"
	   ,ContratoSAAPV."CodigoPrevision"																											AS "CodigoPrevision"
	   ,ContratoSAAPV."Pensionado"																												AS "Pensionado"
	   ,ContratoSAAPV."Trabajador"																												AS "Trabajador"
	   ,ContratoSAAPV."FormaDePago"																												AS "FormaDePago"
	   ,ContratoSAAPV."IdMedioRecaudacionFormaPago"																								AS "IdMedioRecaudacionFormaPago"
	   ,MAP(ContratoSAAPV."FormaDePago",'DIRECTA',MAP(ContratoSAAPV."IdMedioRecaudacionFormaPago",3,ContratoSAAPV."DiaDescuento",NULL),NULL)	AS "DiaDescuento"
	   ,MAP(ContratoSAAPV."FormaDePago",'INDIRECTA',EntidadRecaudadora."Nombre",NULL)															AS "Institucion"
	   ,ContratoSAAPV."ComisionTransferencia"																									AS "ComisionTransferencia"
	   ,ContratoSAAPV."CodigoTipoSolicitud"																										AS "CodigoTipoSolicitud"
	   ,Traspaso."TipoMovimiento"																												AS "TipoMovimiento"
	   ,Traspaso."RazonRetiro"																													AS "RazonRetiro"
	   ,0																																		AS "IdPersonaOrigen"
	   ,ContratoSAAPV."TipoDeAhorro"																											AS "TipoDeAhorro"
	   ,ContratoSAAPV."FondoDeOrigen"																											AS "FondoDeOrigen"
	   ,ContratoSAAPV."NombreEntidadOrigen"																										AS "NombreEntidadOrigen"
	   ,ContratoSAAPV."RutEntidadOrigen"																										AS "RutEntidadOrigen"
	   ,ContratoSAAPV."TipoTraspaso"                                              																AS "TipoTraspaso"
	   ,ContratoSAAPV."MontoTraspaso"                                             																AS "MontoTraspaso"
	   ,ContratoSAAPV."UFTraspaso"                                                																AS "UFTraspaso"
	   ,ContratoSAAPV."PorcentajeTraspaso"																										AS "PorcentajeTraspaso"
	   ,ContratoSAAPV."IdEstadoEnvioNotificacion"																								AS "IdEstadoEnvioNotificacion"
	   ,ContratoSAAPV."IdEstadoSolicitud"																										AS "IdEstadoSolicitud"
	   ,ContratoSAAPV."IdCargaMasiva"																											AS "IdCargaMasiva"
	   ,ContratoSAAPV."IdEmpleador"																												AS "IdEmpleador"
	   ,Portafolio."Proposito"																													AS "IdPropositoPortafolio"
	   ,CASE WHEN COALESCE(Portafolio."IdMatrizAgrupadorAPV",0) != 0 THEN COALESCE(Portafolio."IdMatrizAgrupadorAPV",0) ELSE COALESCE(MAT_NOAPV."IdMatrizAgrupadorNOAPV",0) END	AS "IdMatrizAgrupador"
	   ,MatrizAgrupador."CodigoAgrupador"																										AS "CodigoAgrupador"
	   ,ContratoSAAPV."DescripcionGlosa"																										AS "Descripcion"
       ,CASE WHEN COALESCE(Portafolio."IdMatrizAgrupadorAPV",0) != 0 THEN COALESCE(MatrizAgrupador."EsADC",'N') ELSE COALESCE(MAT_NOAPV."EsADC",'N') END AS "EsADC"
	FROM "BSCL.APV.BD::SCS.ContratoSAAPV" AS ContratoSAAPV
	LEFT JOIN "BSCL.SocioNegocio.BD::PER.Persona" AS Persona ON Persona."IdPersona" = ContratoSAAPV."IdPersona"
	LEFT JOIN "BSCL.SocioNegocio.BD::CLI.Cliente" AS Cliente ON Cliente."IdPersona" = Persona."IdPersona"
	LEFT JOIN "BSCL.APV.BD::SCS.PortafolioContratoSAAPV" AS PortafolioContratoSAAPV ON PortafolioContratoSAAPV."IdContratoSAAPV" = ContratoSAAPV."IdContratoSAAPV"
	LEFT JOIN "BSCL.Portafolio.BD::POR.Portafolio" AS Portafolio ON Portafolio."IdPortafolio" = PortafolioContratoSAAPV."IdPortafolio"
	LEFT JOIN "BSCL.Portafolio.BD::POR.MatrizAgrupadorAPV" AS MatrizAgrupador ON MatrizAgrupador."IdMatrizAgrupadorAPV" = Portafolio."IdMatrizAgrupadorAPV"
	LEFT JOIN "BSCL.APV.BD::SCS.EntidadRecaudadora" AS EntidadRecaudadora ON EntidadRecaudadora."Codigo" = ContratoSAAPV."CodigoPrevision"
	LEFT JOIN "BSCL.APV.BD::TRA.Traspaso" AS Traspaso ON Traspaso."IdContratoSAAPV" = ContratoSAAPV."IdContratoSAAPV"
	LEFT JOIN "BSCL.Portafolio.BD::POR.MatrizAgrupadorAPV" MAT ON MAT."IdMatrizAgrupadorAPV" = Portafolio."IdMatrizAgrupadorAPV"
	LEFT JOIN "BSCL.Portafolio.BD::POR.MatrizAgrupadorNOAPV" MAT_NOAPV ON MAT_NOAPV."CodigoPortafolio" = Portafolio."CodigoPortafolio" AND  Portafolio."IdMatrizAgrupadorAPV" = 0
	WHERE Portafolio."IdEstado" <> 'INA'
)
AS OTR ON OTR."IdContratoSAAPV" = CON."IdContratoSAAPV"
ORDER BY
	CON."IdContratoSAAPV";
