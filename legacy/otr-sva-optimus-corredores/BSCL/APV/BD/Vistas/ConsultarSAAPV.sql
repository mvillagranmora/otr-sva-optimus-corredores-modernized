SELECT
	CON."IdCliente"
   ,CON."IdPersona"
   ,CON."DocumentoIdentidad"
   ,CON."Estado"
   ,CON."FolioContratoSAAPV"
   ,CON."IdContratoSAAPV"
   ,CON."Nombres"
