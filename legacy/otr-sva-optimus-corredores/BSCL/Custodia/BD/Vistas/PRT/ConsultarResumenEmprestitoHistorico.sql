SET SCHEMA "BSCL";

DROP VIEW "BSCL.Custodia.BD.Vistas::PRT.ConsultarResumenEmprestitoHistorico";

CREATE VIEW "BSCL.Custodia.BD.Vistas::PRT.ConsultarResumenEmprestitoHistorico"
AS 
SELECT
	sby."IdInstrumento" 					as "IdInstrumentoSubyacente",
	sby."IdEmisor" 							as "IdEmisorSubyacente",
	sby."Nemotecnico"						as "NemoSubyacente",
	sby."NemoSVS" 							as "NemoSVSSubyacente",
	sby."EsFungible" 						as "EsFungibleSubyacente",
	sby."IdTipoInstrumento"					as "IdTipoInstrumentoSubyacente",
	sby."IdClasificacionTipoInstrumento"	as "IdClasificacionTipoInstrumentoSubyacente",
	sby."IdMonedaInstrumento" as "IdMonedaSubyacente",
	sby."IdTipoReajusteSubyacente", 
	emp."IdBoveda" as "IdBovedaSubyacente",
	emp."IdCartera",
	emp."IdEmpresa",
	emp."FolioCartera" as "FolioEmprestito",
	emp."FolioCarteraRelacionada" as "FolioPrestamo",
	emp."IdEstado",
	estado."Nombre" AS "NombreEstado",
	emp."IdMonedaSistema",
	emp."IdMonedaInstrumento",
	emp."IdOperacion",
	emp."IdTipoOperacion",
	emp."IdBoveda",
	emp."IdTipoReajuste",
	emp."IdTipoProducto",
	emp."IdSucursal",
	emp."IdAgente",
	emp."IdBolsa",
	emp."IdConcepto",
	Concepto."Nombre" as "NombreConcepto",
	emp."IdCondicionLiquidacion",
	emp."IdModulo",
	emp."IdCliente",
	Cli."DocumentoIdentidad",
	emp."IdPortafolio",
	Port."CodigoPortafolio",
	Cli."NombreCompleto" as "RazonSocial",
	emp."Nemotecnico" as "NemotecnicoEmprestito",
	emp."NemoSVS",
	emp."IdInstrumento" as "IdInstrumentoEmprestito", 
	emp."IdClasificacionTipoInstrumento",
	emp."IdTipoInstrumento",
	emp."IdEmisor",
	emp."FechaOperacion" as "FechaEmprestito",
	emp."IdTipoComprobante",
	emp."FolioComprobante",
	emp."FechaComprobante",
	emp."Cantidad",
	emp."CorteMinimo",
	emp."PrecioCompra" as "PrecioInstrumento",
	emp."MontoCompra" as "MontoInstrumento",
	emp."TasaCompra" as "TasaEmprestito",
	emp."ValorRescate",
	emp."FechaVencimientoOperacion" as "FechaVencimientoEmprestito",
	emp."FechaEmisionInstrumento",
	emp."FechaVencimientoInstrumento",
	emp."PlazoEnDiasOperacion",
	emp."EsFungible",
	emp."CodigoIFRS",
	emp."FechaIngresoRegistro",
	emp."FechaModificacionRegistro",
	emp."TasaAgente",
	emp."FechaLiquidacion",
	emp."IdTipoPrestamo",
	Instrumento."Nemotecnico" as "NombreTipoPrestamo",
	tpres."MinimoDiasAnticipo",
	tpres."MaximoDiasPrestamo",
	tpres."EsDiaHabilPlazoPrestamo",
	tpres."EsDiaHabilParaCalculoInteres",
	emp."UsaGarantiaEspecifica",
	emp."FolioExternoReferencia" as "FolioEntidad",
	emp."CobraPrimaAlInicio",
	emp."IdTipoCanalIngreso",
	emp."INGGlosa",
	emp."INGFechaOperacion",
	emp."INGFechaLiquidacion",
	emp."INGCantidad",
	emp."INGValorRescate",
	emp."INGPrecioAPlazo" 					as "INGMontoPremio",
	emp."INGPrecioAPlazo" 					as "INGMontoPrima",
	emp."INGMontoAPlazo" 					as "INGMontoTotalEmprestito",
	emp."INGPrecioCompra"		 			as "INGPrecioInstrumento",
	emp."INGTasaCompra" 					as "INGTasaEmprestito",
	emp."INGMontoATasaCompraActual" 		as "INGMontoInstrumento",
	emp."INGFechaPrecioTasaMercadoActual",
	emp."INGPrecioMercadoActual" 			as "INGPrecioMercadoInstrumento",
	emp."INGTasaMercadoActual",
	emp."INGMontoATasaMercadoActual" 		as "INGMontoMercadoInstrumento",	 
	emp."EGRGlosa",
	emp."EGRFechaOperacion",
	emp."EGRIdTipoOperacion",
	emp."EGRIdOperacion",
	emp."EGRIdMovimientoCarteraEnTransito",
	emp."EGRIdTipoCanalIngreso",
	emp."EGRIdCondicionLiquidacion",
	emp."EGRFechaLiquidacion",
	emp."EGRIdTipoComprobante",
	emp."EGRFolioComprobante",
	emp."EGRFechaComprobante",
	emp."EGRFolioExternoReferencia",
	emp."EGRIdModulo",
	emp."EGRIdConcepto",
	emp."EGRIdUsuario",
	emp."EGRIdSucursal",
	emp."EGRIdAgente",
	emp."EGRFechaCurseRetiro",
	CASE WHEN emp."IdEstado" = 'MOD' THEN emp."INGCantidad" ELSE emp."EGRCantidad" END AS "EGRCantidad",
	emp."EGRValorRescate",
	emp."EGRPrecio",
	emp."EGRTasa",
	emp."EGRMonto",
	emp."EGRMontoMonedaInstrumento",
	emp."EGRSpread",
	emp."EGRPrecioAPlazo",
	emp."EGRMontoAPlazo",
	emp."EGRMontoAPlazoMonedaInstrumento",
	emp."EGRIdMonedaLiquidacion",
	emp."EGRMontoLiquidacion",
	emp."EGRMontoLiquidacionMonedaPrincipal",
	emp."INGPrecioPromedioCompra",
	emp."INGMontoPrecioPromedioCompra",
	emp."IdCuentaCustodioPortafolio",
	CASE emp."IdEstado" WHEN 'ANT' THEN emp."EGRMonto" ELSE 0 END AS "EGRMontoAnticipo",
	CASE emp."IdEstado" WHEN 'ANT' THEN emp."EGRFechaOperacion" ELSE '0001-01-01' END AS "EGRFechaAnticipo",
	CASE WHEN emp."PrecioSucio" = 0 THEN emp."PrecioCompra" ELSE emp."PrecioSucio" END AS "PrecioCompraInicial"
FROM "BSCL.Custodia.BD::CUS.Cartera" as emp
	INNER JOIN "BSCL.Custodia.BD.Vistas::CUS.ConsultarUltimoMovimientoSubyacente" as ultSub on (emp."FolioCartera" = ultSub."FolioCarteraRelacionada")
	INNER JOIN "BSCL.Custodia.BD.Vistas::CUS.ConsultarUltimoMovimientoCartera" as ultPrt on (emp."IdEmpresa" = ultPrt."IdEmpresa" and emp."FolioCarteraRelacionada" = ultPrt."FolioCartera")
	INNER JOIN "BSCL.Custodia.BD::CUS.Cartera" as prt on (prt."IdCartera" = ultPrt."IdCartera")
	LEFT JOIN "BSCL.Portafolio.BD.Vistas::ConsultarPortafolio" as Port ON Port."IdPortafolio" = emp."IdPortafolio" 
	LEFT JOIN "BSCL.SocioNegocio.BD.Vistas::CLI.ConsultarCliente" as Cli ON Cli."IdCliente" = emp."IdCliente" 
	LEFT JOIN "BSCL.Custodia.BD.Vistas::CUS.ConsultarCarteraSubyacenteBasica" as sby on sby."IdSubyacente" = ultSub."IdSubyacente"
	LEFT JOIN "BSCL.Plataforma.BD::PLA.Concepto" as Concepto ON emp."IdConcepto" = Concepto."IdConcepto" 
	LEFT JOIN "BSCL.Plataforma.BD::INS.Instrumento" as Instrumento ON emp."IdInstrumento" = Instrumento."IdInstrumento"
	LEFT JOIN "BSCL.Custodia.BD.Vistas::PRT.ConsultarTipoPrestamo" as tpres on tpres."IdInstrumentoPrestamo" = prt."IdInstrumento"
	LEFT JOIN "BSCL.Plataforma.BD::PLA.Estado" AS estado ON estado."IdEstado" = emp."IdEstado" 
		LEFT JOIN "BSCL.Plataforma.BD::INS.BolsaInstrumentoPrecio" precios on precios."IdInstrumento" = sby."IdInstrumento" and precios."Fecha" = emp."FechaOperacion"  and precios."IdBolsa" = prt."IdBolsa"

WHERE emp."IdTipoInstrumento" IN ('EMP','ERF') AND emp."IdEstado" <> 'VIG'
WITH READ ONLY;


GRANT SELECT ON "BSCL.Custodia.BD.Vistas::PRT.ConsultarResumenEmprestitoHistorico" TO BCS_DESARROLLADOR WITH GRANT OPTION; 
