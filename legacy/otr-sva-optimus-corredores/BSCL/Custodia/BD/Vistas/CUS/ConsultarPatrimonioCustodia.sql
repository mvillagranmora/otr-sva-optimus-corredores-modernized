SET SCHEMA "BSCL"; 

DROP VIEW "BSCL.Custodia.BD.Vistas::CUS.ConsultarPatrimonioCustodia";

CREATE VIEW "BSCL.Custodia.BD.Vistas::CUS.ConsultarPatrimonioCustodia"
AS
SELECT
CUS."IdPatrimonioCustodia"
,CUS."IdCliente"
,CUS."IdPortafolio"
,CUS."IdInstrumento"
,CUS."Nemotecnico"
,CUS."FechaPatrimonio"
,CUS."TipoFechaConsulta"
,CUS."CantidadPatrimonio"
,CUS."MontoPatrimonio"
,CUS."CantidadCustodia"
,CUS."MontoMercadoCustodia"
,CUS."CantidadGarantia"
,CUS."MontoMercadoGarantia"
,CUS."CantidadSimulCom"
,CUS."MontoMercadoSimulCom"
,CUS."CantidadSimulVen"
,CUS."MontoMercadoSimulVen"
,CUS."CantidadPrestamo"
,CUS."MontoMercadoPrestamo"
,CUS."CantidadEmpresti"
,CUS."MontoMercadoEmpresti"
,CUS."CantidadPactosV"
,CUS."MontoMercadoPactosV"
,CUS."CantidadPactosC"
,CUS."MontoMercadoPactosC"
,CUS."CantidadTranomEgr"
,CUS."MontoMercadoTransEgrNom"
,CUS."CantidadTranomIng"
,CUS."MontoMercadoTransIngNom"
,CUS."CantidadTransIng"
,CUS."MontoMercadoTransIng"
,CUS."CantidadTransEgr"
,CUS."MontoMercadoTransEgr"
,CUS."CantidadTransVenDesEgr"
,CASE WHEN INS."IdClasificacionTipoInstrumento" != 'FM' THEN CUS."PrecioMercadoCustodia" ELSE TO_DECIMAL(0,38,16) END AS "PrecioMercadoCustodia"
,CASE WHEN INS."IdClasificacionTipoInstrumento" = 'FM' THEN CUS."PrecioMercadoCustodia" ELSE TO_DECIMAL(0,38,16) END AS "ValorCuota"
,CUS."IdMonedaSistema"
,CASE COALESCE(CUS."IdRegimenTributario",'') WHEN '' THEN COALESCE(MAT."Codigo",'') ELSE CUS."IdRegimenTributario" END AS "IdRegimenTributario"
,DOC."DocumentoIdentidad"
,CASE PER."Tipo" WHEN 'N' THEN PER."Nombres" ||' '|| PER."ApellidoPaterno" || ' ' ||PER."ApellidoMaterno" 
				ELSE PER."RazonSocial" END  as "NombreCompleto"
,CASE WHEN CASE WHEN "PORT"."IdMatrizAgrupadorAPV" = 0 THEN 'N' ELSE 'S' END  = 'N' THEN 'NO APV' ELSE 'APV' END "TipoAhorro"
,COALESCE(PORT."IdMatrizAgrupadorAPV",0) AS "IdMatrizAgrupadorAPV"
,PORT."CodigoPortafolio"
,PORT."Proposito"
,COALESCE(MAT."NombrePlan",'NA') AS "PlanAPV"
,COALESCE(MAT."Producto",'NA') AS "CategoriaAPV"
,COALESCE(FONDO."NombreFondo",'NA') AS "Fondo"
,COALESCE(SERIE."CodigoSerie",'NA') AS "Serie"
,INS."IdClasificacionTipoInstrumento"
,INS."IdMoneda"
,CASE WHEN CUS."IdEstado" = 'ACT' THEN 'V' ELSE 'NV' END AS "Vigencia"
,CUS."FechaFuente"
,INS."IdTipoInstrumento"
,CUS."MontoComision"
,CUS."PorcentajeCobroComision"
,CUS."IdEstadoComision"
,COALESCE(ESTCOM."Nombre", CUS."IdEstadoComision") AS "NombreEstadoComision"
FROM "BSCL.Custodia.BD::CUS.PatrimonioCustodia" CUS
LEFT JOIN "BSCL.Portafolio.BD::POR.Portafolio" PORT ON PORT."IdPortafolio" = CUS."IdPortafolio"
LEFT JOIN "BSCL.SocioNegocio.BD::CLI.Cliente" CLI ON CLI."IdCliente" = CUS."IdCliente"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.Persona" PER ON PER."IdPersona" = CLI."IdPersona"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.DocumentoIdentidad" DOC ON DOC."IdDocumentoIdentidad" = PER."IdDocumentoIdentidad"
LEFT JOIN "BSCL.Portafolio.BD.Vistas::ConsultarMatrizAgrupador" MAT ON PORT."IdMatrizAgrupadorAPV" = MAT."IdMatrizAgrupadorAPV"
LEFT JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarInstrumento" INS ON INS."IdInstrumento" = CUS."IdInstrumento"
LEFT JOIN "BSCL.FondoMutuo.BD::FMM.SerieDeFondo" SERIE ON SERIE."IdInstrumento" = INS."IdInstrumento"
LEFT JOIN "BSCL.FondoMutuo.BD::FMM.Fondo" FONDO ON (FONDO."IdFondo" = SERIE."IdFondo")
LEFT JOIN "BSCL.Plataforma.BD::PLA.Estado" ESTCOM ON ESTCOM."IdEstado" = CUS."IdEstadoComision";

GRANT SELECT ON "BSCL.Custodia.BD.Vistas::CUS.ConsultarPatrimonioCustodia"  TO  BCS_DESARROLLADOR WITH GRANT OPTION;
