WITH CarteraSimultanea AS (
SELECT 
		"FechaRespaldo",
		"FolioCartera", 
        "AccionOperacion",
       	TipOpeContraria."Accion" || ' A PLAZO' as "AccionOperacionPlazo",
        "FechaInversion",
        "FechaVencimientoOperacion",
        "MontoCompra",
        "MontoAPlazo",
        "EGRFechaOperacion",
        "INGCantidad",
        "INGPrecioCompra",
        "INGTasaCompra",
        ROUND("INGMontoATasaCompraActual",0) AS "INGMontoATasaCompraActual",
        "INGMontoAPlazo",
        "INGFechaLiquidacion",
        "EGRFechaLiquidacion",
        "suby_Nemotecnico",
        "FolioComprobante",
        "suby_NombreTipoInstrumento",
        "Cliente",
        "Proposito",
        "CodigoPortafolio",
        "FechaLiquidacion",
        "IdEstado",
        TO_VARCHAR("PaloNormal") AS "PaloNormal",
        TO_VARCHAR("PaloPlazo") AS "PaloPlazo",
        "NombreCorredora",
        "IdCorredoraContraparte",
        "IdBolsa",
        "NombreEjecutivo",
        "FechaLiquidacionMovtoContado",
        "PrecioInicial",
        "PrecioAPlazo",
        "suby_INGPrecioMercadoActual",
        "PrecioActualCalculado",
        "NombreLargo",
        "IdCondicionLiquidacion",
        "IdTipoComprobante",
        "IdTipoInstrumentoOperacion",
        car."IdTipoOperacion",
        car."IdTipoProducto",
        "DocumentoIdentidad",
        "EGRCantidad",
        "EGRCostoRetiroenFactorAjuste",
        "EGRFechaComprobante",
        "suby_IdMonedaInstrumento",
        "INGMontoInteresCompraAnterior",
        "INGMontoInteresCompraAnteriorMonedaInstrumento",
        "INGMontoInteresCompraAnteriorMonedaAdicional",
        "INGMontoInteresCorridoCompraActual",
        "INGMontoInteresCorridoCompraActualMonedaInstrumento",
        "INGMontoInteresCorridoCompraActualMonedaAdicional",
        "INGMontoInteresCompraProximo",
        "INGMontoInteresCompraProximoMonedaInstrumento",
        "INGMontoInteresCompraProximoMonedaAdicional",
        "INGMontoInteresMercadoAnterior",
        "INGMontoInteresMercadoAnteriorMonedaInstrumento",
        "INGMontoInteresMercadoAnteriorMonedaAdicional",
        "INGMontoInteresCorridoMercadoActual",
        "INGMontoInteresCorridoMercadoActualMonedaInstrumento",
        "INGMontoInteresCorridoMercadoActualMonedaAdicional",
        "INGMontoInteresMercadoProximo",
        "INGMontoInteresMercadoProximoMonedaInstrumento",
        "INGMontoInteresMercadoProximoMonedaAdicional",
        "suby_IdEmisor",
        "NombreLargoCliente"
FROM "BSCL.Custodia.BD.Vistas::SIM.ConsultarCarteraSimultaneaHis" as car
LEFT JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarTipoOperacion" as TipOpe ON (TipOpe."IdTipoOperacion" = Car."IdTipoOperacion")
LEFT JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarTipoOperacion" as TipOpeContraria ON (TipOpeContraria."IdTipoOperacion" = TipOpe."IdTipoOperacionRelacionada") 
WHERE "FechaVencimientoOperacion"	>	TO_DATE(:FechaVencimientoOperacion) 
	AND ("EGRFechaOperacion"			>	TO_DATE(:EGRFechaOperacion) OR "EGRFechaOperacion" = TO_DATE('0001-01-01')) 
	AND "INGFechaOperacion"			<=	TO_DATE(:INGFechaOperacion)
	AND ("IdCliente"					IN (:IdCliente)					OR 1 = :FiltroCliente)
	AND ("IdPortafolio"					IN (:IdPortafolio)				OR 1 = :FiltroPortafolio)
	AND (car."IdTipoOperacion"				IN (:IdTipoOperacion)			OR 1 = :FiltroTipoOperacion)
	AND ("suby_IdInstrumento"			IN (:IdInstrumentoSubyacente)	OR 1 = :FiltroInstrumentoSubyacente)
	AND (TO_VARCHAR("PaloNormal")					IN (:PaloNormal)				OR 
		TO_VARCHAR("PaloPlazo")						IN (:PaloPlazo) 				OR 1 = :FiltroPalo)
)

SELECT 
		"FolioCartera", 
        "AccionOperacion",
        "AccionOperacionPlazo",
        "FechaInversion",
        "FechaVencimientoOperacion",
        "MontoCompra",
        "MontoAPlazo",
        "EGRFechaOperacion",
        "INGCantidad",
        "INGPrecioCompra",
        "INGTasaCompra",
        ROUND("INGMontoATasaCompraActual",0) AS "INGMontoATasaCompraActual",
        "INGMontoAPlazo",
        "INGFechaLiquidacion",
        "EGRFechaLiquidacion",
        "suby_Nemotecnico",
        "FolioComprobante",
        "suby_NombreTipoInstrumento",
        "Cliente",
        "Proposito",
        "CodigoPortafolio",
        "FechaLiquidacion",
        CARSIM."IdEstado",
        "PaloNormal",
        "PaloPlazo",
        "NombreCorredora",
        "IdCorredoraContraparte",
        "IdBolsa",
        "NombreEjecutivo",
        "FechaLiquidacionMovtoContado",
        "PrecioInicial",
        "PrecioAPlazo",
        "suby_INGPrecioMercadoActual",
        "PrecioActualCalculado",
        "NombreLargo",
        "IdCondicionLiquidacion",
        "IdTipoComprobante",
        "IdTipoInstrumentoOperacion",
        "IdTipoOperacion",
        "IdTipoProducto",
        "DocumentoIdentidad",
        "EGRCantidad",
        "EGRCostoRetiroenFactorAjuste",
        "EGRFechaComprobante",
        "suby_IdMonedaInstrumento",
        "INGMontoInteresCompraAnterior",
        "INGMontoInteresCompraAnteriorMonedaInstrumento",
        "INGMontoInteresCompraAnteriorMonedaAdicional",
        "INGMontoInteresCorridoCompraActual",
        "INGMontoInteresCorridoCompraActualMonedaInstrumento",
        "INGMontoInteresCorridoCompraActualMonedaAdicional",
        "INGMontoInteresCompraProximo",
        "INGMontoInteresCompraProximoMonedaInstrumento",
        "INGMontoInteresCompraProximoMonedaAdicional",
        "INGMontoInteresMercadoAnterior",
        "INGMontoInteresMercadoAnteriorMonedaInstrumento",
        "INGMontoInteresMercadoAnteriorMonedaAdicional",
        "INGMontoInteresCorridoMercadoActual",
        "INGMontoInteresCorridoMercadoActualMonedaInstrumento",
        "INGMontoInteresCorridoMercadoActualMonedaAdicional",
        "INGMontoInteresMercadoProximo",
        "INGMontoInteresMercadoProximoMonedaInstrumento",
        "INGMontoInteresMercadoProximoMonedaAdicional",
        CASE 
	        WHEN "FechaLiquidacionMovtoContado" IS NULL OR "FechaVencimientoOperacion" IS NULL THEN '-'
	        ELSE TO_VARCHAR(DAYS_BETWEEN("FechaLiquidacionMovtoContado", :INGFechaOperacion)) 
	             || '/' || TO_VARCHAR(DAYS_BETWEEN("FechaLiquidacionMovtoContado", "FechaVencimientoOperacion"))
    	END AS "NumeroDias",
        COALESCE(DETERIORO."FlagDeterioro",'N') AS "FlagDeterioro",
        COALESCE(DETERIORO."PorcentajeDeterioro",0 ) AS "PorcentajeDeterioro",
        CASE DETERIORO."FlagDeterioro" WHEN 'S' 
            THEN CAST((COALESCE(DETERIORO."PorcentajeDeterioro" ,0)/100) * COALESCE("INGCantidad",0) AS DECIMAL(26,8))
            ELSE 0 
        END AS "Deterioro",
        COALESCE(DETERIORO."Fase",0) AS "Fase",
        "NombreLargoCliente"
        FROM CarteraSimultanea AS CARSIM
        LEFT JOIN "BSCL.Plataforma.BD::MER.DeterioroEmisor" AS DETERIORO ON DETERIORO."Emisor" = CARSIM."suby_IdEmisor" AND DETERIORO."IdEstado" = 'ACT'
        WHERE CARSIM."FechaRespaldo" = :INGFechaOperacion;