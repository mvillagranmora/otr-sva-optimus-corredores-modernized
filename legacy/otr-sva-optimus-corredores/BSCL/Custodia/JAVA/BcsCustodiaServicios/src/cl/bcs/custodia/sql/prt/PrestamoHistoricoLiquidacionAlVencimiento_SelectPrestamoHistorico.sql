FROM "BSCL.Custodia.BD.Vistas::PRT.ConsultarResumenPrestamoHistorico" prt
WHERE   prt."IdEmpresa" = :p_IdEmpresa
	AND ( prt."FolioPrestamo" = :p_FolioCartera OR :p_FolioCartera IS NULL )
	AND prt."FechaPrestamo" BETWEEN IFNULL(:p_FechaConsultaDesde, prt."FechaPrestamo") AND IFNULL(:p_FechaConsultaHasta, prt."FechaPrestamo")
	AND ( prt."IdEstado" = :p_IdEstado OR :p_IdEstado IS NULL )
	AND ( prt."IdTipoPrestamo" = :p_IdTipoPrestamo OR :p_IdTipoPrestamo IS NULL )
	AND ( prt."IdCliente" = :p_IdCliente OR :p_IdCliente IS NULL )
	AND ( prt."IdPortafolio" = :p_IdPortafolio OR :p_IdPortafolio IS NULL )
	AND IFNULL(prt."CantidadPorAsignar", 0) >= IFNULL(:p_CantidadPorAsignar, IFNULL(prt."CantidadPorAsignar", 0));