SELECT
	MOV."IdMovimientoCarteraEnTransito",
	GAR."IdMovimientoCarteraEnTransito" AS "IdMovimientoCarteraEnTransitoOrigen",
	COALESCE(GAR."IdGarantia", 0) AS "IdGarantiaOrigen",
	COALESCE(GAR."IdGarantia", 0) AS "IdGarantia",
	CASE WHEN MOV."IdTipoOperacion" = 'RETGTA' THEN GAR."MontoGarantia" ELSE 0.0 END AS "MontoGarantia",
	COALESCE(GAR."INGCantidad", 0.0) AS "INGCantidad",
	GAR."IdMonedaInstrumento" AS "IdMonedaInstrumento",
	COALESCE(GAR."IdEstado" ,'') AS "IdEstado",
	GAR."IdOrigenGarantia" AS "IdOrigenGarantia",
	GAR."IdPortafolio" AS "IdPortafolio",
	GAR."FolioGarantia" AS "FolioGarantia",
	TO_NVARCHAR(COALESCE(MOV."FechaOperacion", GAR."FechaOperacion"), 'YYYY-MM-DD') AS "FechaOperacion",
	TO_NVARCHAR(GAR."FechaEmisionInstrumento", 'YYYY-MM-DD') AS "FechaEmisionInstrumento", 
	TO_NVARCHAR(GAR."FechaEmisionInstrumento", 'YYYY-MM-DD') AS "FechaVencimientoInstrumento",
	GAR."FolioCarteraOrigen" AS "FolioCarteraOrigen",
	GAR."NemoSVS"  AS "NemoSVS",
	GAR."IdInstrumento" AS "IdInstrumento",
	GAR."IdMonedaEmision" AS "IdMonedaEmision",
	GAR."INGValorRescate" AS "ValorRescate",
	GAR."IdClasificacionTipoInstrumento" AS "IdClasificacionTipoInstrumento",
	GAR."IdTipoReajuste" AS "IdTipoReajuste",
	GAR."IdEmisor" AS "IdEmisor",
	MOV."PlazoEnDiasOperacion",
	GAR."EsFungible" AS "EsFungible",
	GAR."IdCliente" AS "IdCliente",
	GAR."IdAgente" AS "IdAgente",
	GAR."IdTipoInstrumento" AS "IdTipoInstrumento",
	MOV."IdBolsa",
	GAR."IdInstrumentoCarteraGarantizada" AS "IdInstrumentoGarantizado",
	MOV."IdConcepto",
	GAR."IdContraparteGarantia" AS "IdContraparteGarantia",
	GAR."PrecioGarantia" AS "Precio",
	GAR."TasaGarantia" AS "Tasa",
	MOV."IdOperacion",
	GAR."CorteMinimo" AS "CorteMinimo",
	MOV."MontoCompraMonedaInstrumento",
	MOV."Cantidad" AS "MovimientoCantidad",
	MOV."ValorRescate" AS "MovimientoValorRescate",
	MOV."IdTipoOperacion"
FROM "BSCL.Custodia.BD::CUS.MovimientoCarteraEnTransito" AS MOV
INNER JOIN "BSCL.Custodia.BD::GTA.Garantia" AS GAR ON (GAR."EGRIdMovimientoCarteraEnTransito" = MOV."IdMovimientoCarteraEnTransito" AND MOV."IdTipoOperacion" = 'RETGTA')
WHERE MOV."IdMovimientoCarteraEnTransito" IN (:idsMovimientoCarteraTransito) AND (GAR."IdEstado" = 'VIG' OR GAR."IdEstado" = 'LIQ');