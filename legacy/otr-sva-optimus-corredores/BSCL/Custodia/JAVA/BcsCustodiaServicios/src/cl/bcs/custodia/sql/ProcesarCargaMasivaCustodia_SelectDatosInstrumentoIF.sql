
SELECT 
	 GAR."IdInstrumento"
    ,GAR."NemoSVS" AS "Nemotecnico"
    ,GAR."ISIN"
    ,GAR."CorteMinimo"
    ,INS."EstaInscrito"
    ,INS."EsDivisible"
    ,INS."RazonSocial"
    ,CAR."FechaOperacion" AS "FechaEmision"
    ,CAR."FechaVencimientoInstrumento" AS "FechaVencimiento"
    ,INS."IdInstrumentoRelacionado"
    ,GAR."IdEmisor"
    ,GAR."IdTipoReajuste"
    ,INS."Reajustable"
    ,INS."IdMoneda"
    ,CAR."IdMonedaEmision"
    ,CAR."IdTipoInstrumento"
    ,GAR."IdEstado"
    ,INS."DecimalesPrecio"
    ,CAR."Tamano" AS "Tamano"
    ,CAR."TipoValorizacion"
    ,INS."IndicadorBolson"
    ,CAR."INGTasaMercadoActual" AS "Tasa"
    ,CAR."INGPrecioMercadoActual" AS "Precio"
    ,CAR."ValorizaPor"
    ,INS."TieneCupon"
    ,INS."PorcentajeCastigo"
    ,INS."FrecuenciaCupon"
    ,INS."InstrumentoAcreditado"
    ,INS."PrecioStrike"
    ,INS."EsPutEsCall"
    ,INS."EsAutorizado"
    ,INS."IdInstrumentoRaiz"
    ,INS."EsInstrumentoCalificado"
    ,CAR."IdClasificacionTipoInstrumento"
FROM "BSCL.Custodia.BD::GTA.Garantia" AS GAR
INNER JOIN "BSCL.Custodia.BD::CUS.Cartera" AS CAR ON CAR."FolioCartera" = GAR."FolioCarteraOrigen" AND CAR."IdEstado" IN ('VIG','LIQ')
INNER JOIN "BSCL.Plataforma.BD::INS.Instrumento" AS INS ON INS."IdInstrumento" = CAR."IdInstrumento" 
INNER JOIN #TablaFoliosCarteras AS FOL ON FOL."FolioCartera" = GAR."FolioGarantia" 
WHERE GAR."IdClasificacionTipoInstrumento" = 'IF'