SELECT
	 CAR."IdEmpresa" AS "p_IdEmpresa"
	,CAR."IdUsuario" AS "p_IdUsuario" 
	--,0 AS "p_IdEmpleadoDigitador"
	,CAR."IdModulo" AS "p_IdModulo" 
	,'' AS "p_UsaReglasNegocio"
	,CAR."IdCliente" AS "p_IdClienteSolicita"
	,CAR."IdPortafolio" AS "p_IdPortafolioSolicita"
	,CAR."IdBolsa" AS  "p_IdBolsa" 
	,TO_CHAR(CAR."FechaOperacion") AS "p_FechaMovimiento"
	,TO_CHAR(CAR."FechaVencimientoOperacion") AS "p_FechaVencimiento"
	,CAR."IdInstrumento" AS "p_IdInstrumentoPrestamo"
	,SUB."IdInstrumento" AS "p_IdInstrumento"
	,CAR."IdClasificacionTipoInstrumento" AS "p_IdMercado"
	,SUB."Nemotecnico" AS "p_Nemotecnico"
	,SUB."INGCantidad" AS "p_Cantidad" 
	,CAR."PrecioCompra" AS "p_Precio"
	,CAR."INGMontoATasaCompraActual"  AS "p_Monto"
	,CAR."PrecioAPlazo" AS "p_MontoPrima"
	,CAR."TasaCompra" AS "p_TasaPrima"
	,0.0 AS "p_TasaInstrumento" 
	,CAR."MontoAPlazoMonedaInstrumento" AS "p_MontoAPlazo"
	,'' AS "p_ConGarantiaEspecificaN"
	,'' AS "p_FolioEntidad"
	,'' AS "p_FolioTransaccion"
	,'N' AS "p_CobraPrimaAlInicio"
	,'N' AS "p_TipoCustodiaN"
	,CAR."IdAgente" AS "p_IdAgente" 
	,CAR."IdSucursal" AS "p_IdSucursal" 
	,CAR."PlazoEnDiasOperacion" AS "p_PlazoEnDias"
	,CAR."IdTipoCanalIngreso" AS "p_IdTipoCanalIngreso" 
	,CAR."IdMonedaSistema" AS "p_IdMonedaSistema" 
	,'N' AS "p_esNominal"
	,CAR."IdCondicionLiquidacion" AS "p_IdCondicionLiquidacion" 
	,TO_CHAR(CAR."FechaLiquidacion") AS "p_FechaLiquidacion" 
FROM "BSCL.Custodia.BD::CUS.Cartera" AS CAR
INNER JOIN "BSCL.Custodia.BD::CUS.Subyacente" AS SUB ON  SUB."FolioCarteraRelacionada" = CAR."FolioCartera" 
WHERE "FolioCartera" = :FolioPrestamo
and "IdEmpresa" =:IdEmpresa