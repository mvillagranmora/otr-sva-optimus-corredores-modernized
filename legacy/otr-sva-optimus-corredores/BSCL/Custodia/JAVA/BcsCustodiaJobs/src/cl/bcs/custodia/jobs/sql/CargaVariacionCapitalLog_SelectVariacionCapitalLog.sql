SELECT 
	CONVERT(DATETIME, SUBSTRING(hora_auditoria, 1, 19), 102) AS "HoraAuditoria",
	secuencia 					AS "Secuencia",
	REPLACE(mercado, ' ', '')	AS "Mercado",
	REPLACE(nemo, ' ', '')		AS "Nemo",
	REPLACE(tipo, ' ', '')		AS "Tipo",
	REPLACE(descripcion, ' ', '')		AS "Descripcion",
	REPLACE(nemo_nuevo, ' ', '')		AS "NemoNuevo",
	REPLACE(nemo_opcion, ' ', '')		AS "NemoOpcion",
	REPLACE(moneda, ' ', '')			AS "Moneda",
	CONVERT(DATETIME, SUBSTRING( (CASE WHEN fecha_pago <='1900-01-01' then NULL ELSE fecha_pago END), 1, 10 ), 102) 					AS "FechaPago",
	CONVERT(DATETIME, SUBSTRING( (CASE WHEN fecha_inicio_opcion <='1900-01-01' then NULL ELSE fecha_inicio_opcion END), 1, 10 ), 102) 	AS "FechaInicioOpcion",
	CONVERT(DATETIME, SUBSTRING( (CASE WHEN fecha_limite <='1900-01-01' then NULL ELSE fecha_limite END), 1, 10 ), 102) 				AS "FechaLimite",
	CONVERT(DATETIME, SUBSTRING( (CASE WHEN fecha_movimiento <='1900-01-01' then NULL ELSE fecha_movimiento END), 1, 10 ), 102) 		AS "FechaMovimiento",
	CONVERT(DATETIME, SUBSTRING( (CASE WHEN fecha_fin_opcion <='1900-01-01' then NULL ELSE fecha_fin_opcion END), 1, 10 ), 102) 		AS "FechaFinOpcion",
	CONVERT(DATETIME, SUBSTRING( (CASE WHEN fecha_corte <='1900-01-01' then NULL ELSE fecha_corte END), 1, 10 ), 102) 					AS "FechaCorte",
	acciones_con_derecho 		AS "AccionesConDerecho",
	numero_cupon 				AS "NumeroCupon",
	numero_dividendo 			AS "NumeroDividendo",
	valor_accion 				AS "ValorAccion",
	factor_antiguas 			AS "FactorAntiguas",
	factor_nuevas 				AS "FactorNuevas",
	numero_acciones_antiguas 	AS "NumeroAccionesAntiguas",
	numero_acciones_nuevas 		AS "NumeroAccionesNuevas",
	precio_antes 				AS "PrecioAntes",
	precio_despues 				AS "PrecioDespues",
	valor_antes_division 		AS "ValorAntesDivision",
	valor_despues_division 		AS "ValorDespuesDivision",
	valor_libro_ajustado 		AS "ValorLibroAjustado",
	valor_suscripcion 			AS "ValorSuscripcion",
	REPLACE(actualiza_naa, ' ', '')			AS "ActualizaNaa",
	REPLACE(tipo_prepago, ' ', '')			AS "TipoPrepago",
	REPLACE(tipo_dividendo, ' ', '')		AS "TipoDividendo",
	REPLACE(destino, ' ', '')				AS "Destino",
	REPLACE(indicador_no_inscrito, ' ', '')	AS "IndicadorNoInscrito",
	REPLACE(indicador_proceso, ' ', '')		AS "IndicadorProceso",
	REPLACE(usuario_modifica, ' ', '')		AS "UsuarioModifica",
	REPLACE(terminal_modifica, ' ', '')		AS "TerminalModifica",
	REPLACE(tipo_modificacion, ' ', '')		AS "TipoModificacion",
	CAST(indice AS BIGINT)					AS "Indice"
FROM pt$variacioncapitallog
WHERE CONVERT(DATETIME, SUBSTRING(hora_auditoria, 1, 19), 102) > (:UltimaHoraAuditoriaCargadaOpt)