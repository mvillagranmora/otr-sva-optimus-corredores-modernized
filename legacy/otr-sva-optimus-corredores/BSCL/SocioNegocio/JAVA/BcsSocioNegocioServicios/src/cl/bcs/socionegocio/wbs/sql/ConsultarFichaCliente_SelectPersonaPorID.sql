SELECT 
Persona."IdPersona"
,COALESCE(Cliente."IdCliente",0) AS "IdCliente"
,CASE WHEN Cliente."IdCliente" IS NOT NULL THEN 'CLI' ELSE 'PER' END AS "TipoEntidad"
,DocumentoIdentidad."IdTipoDocumentoIdentidad" AS "TipoDocumentoIdentidad"
,DocumentoIdentidad."DocumentoIdentidad" AS "DocumentoIdentidad"
,COALESCE(Persona."Tipo",'') AS "IdTipoPersona"
,COALESCE(TipoPersona."Descripcion",'') AS "TipoPersona"
,COALESCE(Persona."Nombres",'') AS "Nombres"
,COALESCE(Persona."ApellidoPaterno",'') AS "ApellidoPaterno"
,COALESCE(Persona."ApellidoMaterno",'') AS "ApellidoMaterno"
,COALESCE(Persona."RazonSocial",'') AS "RazonSocial" 
,COALESCE(Persona."Sexo",'') AS "IdGenero"
,COALESCE(Genero."Descripcion",'') AS "Genero"
,COALESCE(Persona."IdEstado",'') AS "IdEstado"
,COALESCE(Estado."Nombre",'') AS "Estado"
,COALESCE(Persona."IdPaisNacimiento",0) AS "IdPaisNacimientoConstitucion"
,COALESCE(Pais."NombrePais",'') AS "PaisNacimientoConstitucion"
,COALESCE(Persona."IdTransparenciaFiscal",'') AS "IdTransparenciaFiscal"
,COALESCE(Persona."ResidenciaTributariaExtranjera",'') AS "ResidenciaTributariaExtranjera"
,COALESCE(Persona."IdPaisResidencia",0) AS "IdPaisResidenciaCasaMatriz"
,COALESCE(PaisResidencia."NombrePais",'') AS "PaisResidenciaCasaMatriz"
,COALESCE(Persona."IdPaisNacionalidadPrincipal",0) AS "IdPaisNacionalidad"
,COALESCE(PaisNacionalidad."NombrePais",'') AS "PaisNacionalidad"
,CAST(Persona."FechaNacimiento" AS VARCHAR(10)) AS "FechaNacimientoConstitucion"
,CAST(Persona."FechaDefuncion" AS VARCHAR(10)) AS "FechaDefuncion"
,CAST(Persona."FechaInicioActividad" AS VARCHAR(10)) AS "FechaInicioActividad"
,COALESCE(Persona."GlobalLegalEntity",'') AS "GlobalLegalEntity"
,COALESCE(Persona."EstadoCivil",'') AS "IdEstadoCivil"
,COALESCE(EstadoCivil."Nombre",'') AS "EstadoCivil"
,COALESCE(Persona."RegimenConyugal",'') AS "IdRegimenConyugal"
,COALESCE(RegimenConyugal."Nombre",'') AS "RegimenConyugal"
,COALESCE(Persona."IdGiroPrincipal",0) AS "IdGiro"
,COALESCE(Giro."Nombre",'') AS "Giro"
,COALESCE(Persona."IdProfesion",0) AS "IdProfesion"
,COALESCE(Profesion."Nombre",'') AS "Profesion"
,COALESCE(Persona."CodigoTipoCargoEmpleado",'') AS "IdCargo"
,COALESCE(TipoCargoPersona."NombreTipoCargoPersona",'') AS "Cargo"
,COALESCE(Persona."IdRangoPatrimonio",0) AS "IdRangoPatrimonio"
,COALESCE(RangoPatrimonio."DescripcionRango",'') AS "RangoPatrimonio"
,COALESCE(Persona."IdTipoBloqueo",'') AS "IdTipoBloqueo"
,COALESCE(Bloqueo."NombreTipoBloqueo",'') AS "NombreTipoBloqueo"
,COALESCE(Persona."IdTipoCanalIngresoCorredor",'') AS "IdTipoCanalIngresoCorredor"
,COALESCE(Persona."IdSituacionLaboral",'') AS "IdSituacionLaboral"
,COALESCE(Persona."CodigoRangoRenta", '') AS "CodigoRangoRenta"
,COALESCE(RangoRenta."Descripcion", '') AS "RangoRenta"
,COALESCE(Persona."CodigoRangoNivelVenta", '') AS "CodigoRangoNivelVenta"
,COALESCE(RangoNivelVenta."Descripcion", '') AS "RangoNivelVenta"
,COALESCE(Persona."CodigoPropositoTransaccion", '') AS "CodigoPropositoTransaccion"
,COALESCE(PropositoTransaccion."Descripcion", '') AS "PropositoTransaccion"
FROM "BSCL.SocioNegocio.BD::PER.Persona" AS Persona
INNER JOIN "BSCL.SocioNegocio.BD::PER.DocumentoIdentidad" AS DocumentoIdentidad ON DocumentoIdentidad."IdDocumentoIdentidad" = Persona."IdDocumentoIdentidad"
LEFT JOIN "BSCL.Plataforma.BD::REG.Giro" AS Giro ON Giro."IdGiro" = Persona."IdGiroPrincipal"
LEFT JOIN "BSCL.Plataforma.BD::REG.TipoEstadoCivil" AS EstadoCivil ON EstadoCivil."IdTipoEstadoCivil" = Persona."EstadoCivil"
LEFT JOIN "BSCL.Plataforma.BD::REG.Pais" AS Pais ON Pais."IdPais" = Persona."IdPaisNacimiento"
LEFT JOIN "BSCL.Plataforma.BD::REG.TipoRegimenConyugal" AS RegimenConyugal ON RegimenConyugal."IdTipoRegimenConyugal" = Persona."RegimenConyugal"
LEFT JOIN "BSCL.Plataforma.BD::REG.Pais" AS PaisNacionalidad ON PaisNacionalidad."IdPais" = Persona."IdPaisNacionalidadPrincipal"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.TipoGenero" AS Genero ON Genero."IdTipoGenero" = Persona."Sexo"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.TipoPersona" AS TipoPersona ON TipoPersona."IdTipoPersona" = Persona."Tipo"
LEFT JOIN "BSCL.Plataforma.BD::REG.Pais" AS PaisResidencia ON PaisResidencia."IdPais" = Persona."IdPaisResidencia"
LEFT JOIN "BSCL.Plataforma.BD::REG.Profesion" AS Profesion ON Profesion."IdProfesion" = Persona."IdProfesion"
LEFT JOIN "BSCL.SocioNegocio.BD::CLI.Cliente" AS Cliente ON Cliente."IdPersona" = Persona."IdPersona"
LEFT JOIN "BSCL.Plataforma.BD::PLA.Estado" AS Estado ON Estado."IdEstado" = Persona."IdEstado"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.TipoCargoPersona" AS TipoCargoPersona ON TipoCargoPersona."CodigoTipoCargoPersona" = Persona."CodigoTipoCargoEmpleado" AND  TipoCargoPersona."IdEmpresa" = :p_IdEmpresa
LEFT JOIN "BSCL.SocioNegocio.BD::PER.RangoPatrimonio" AS RangoPatrimonio ON RangoPatrimonio."IdRangoPatrimonio" = Persona."IdRangoPatrimonio"
LEFT JOIN "BSCL.SocioNegocio.BD::SOC.TipoBloqueoSocioDeNegocio" AS Bloqueo ON
 (Bloqueo."IdTipoBloqueo" = Persona."IdTipoBloqueo" AND Bloqueo."IdTipoEntidad"='PERSONA' AND Bloqueo."IdEmpresa" = :p_IdEmpresa)
LEFT JOIN "BSCL.SocioNegocio.BD::PER.RangoSeleccion" RangoRenta ON RangoRenta."CodigoRangoSeleccion" = Persona."CodigoRangoRenta"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.RangoSeleccion" RangoNivelVenta ON RangoNivelVenta."CodigoRangoSeleccion" = Persona."CodigoRangoNivelVenta"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.RangoSeleccion" PropositoTransaccion ON PropositoTransaccion."CodigoRangoSeleccion" = Persona."CodigoPropositoTransaccion"
WHERE Persona."IdPersona" IN (:p_IdPersonas);
