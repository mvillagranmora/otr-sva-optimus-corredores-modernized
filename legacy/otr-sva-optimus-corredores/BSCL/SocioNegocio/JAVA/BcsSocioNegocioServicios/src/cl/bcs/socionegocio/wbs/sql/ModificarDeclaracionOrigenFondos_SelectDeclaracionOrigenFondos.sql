SELECT "IdDeclaracionOrigenFondos"
,DOF."IdCliente"
,DOF."IdTipoOperacionOrigenFondos"
,TO_DATE("FechaDeclaracion") AS "FechaDeclaracion"
,DOF."Comentario"
,DOF."IdUsuarioCreador"
,DOF."FechaIngreso"
,DOF."FechaCreacion"
,DOF."FechaModificacion"
,DOF."IdEmpresa"
,DOF."IdEstado"
,DOF."IdEstadoAutorizacion"
,DOF."OperacionInscripcion"
,PER."Tipo" AS "TipoPersona"
,CLI."TipoEnrolamiento"
FROM "BSCL.SocioNegocio.BD::CLI.DeclaracionOrigenFondos" AS DOF
LEFT JOIN "BSCL.SocioNegocio.BD::CLI.Cliente" AS CLI ON CLI."IdCliente" = DOF."IdCliente"
LEFT JOIN "BSCL.SocioNegocio.BD::PER.Persona" AS PER ON PER."IdPersona" = CLI."IdPersona"
WHERE DOF."IdDeclaracionOrigenFondos" = :IdDeclaracionOrigenFondos