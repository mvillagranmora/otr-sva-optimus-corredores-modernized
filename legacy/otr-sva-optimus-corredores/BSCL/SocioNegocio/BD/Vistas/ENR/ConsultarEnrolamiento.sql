SET SCHEMA "BSCL";

DROP VIEW "BSCL.SocioNegocio.BD.Vistas::ENR.ConsultarEnrolamiento";

CREATE VIEW "BSCL.SocioNegocio.BD.Vistas::ENR.ConsultarEnrolamiento" AS
SELECT 
ENROLAMIENTO."IdEnrolamiento"
,ENROLAMIENTO."IdEmpresa"
,ENROLAMIENTO."IdUsuario"
,ENROLAMIENTO."IdTipoEntidad"
,ENROLAMIENTO."IdEntidadEnrolada"
,DOCUMENTO_IDENTIDAD."IdTipoDocumentoIdentidad"
,DOCUMENTO_IDENTIDAD."DocumentoIdentidad"
,DOCUMENTO_IDENTIDAD_ADICIONAL."IdTipoDocumentoIdentidad" AS "IdTipoDocumentoIdentidadAdicional"
,DOCUMENTO_IDENTIDAD_ADICIONAL."DocumentoIdentidad" AS "DocumentoIdentidadAdicional"
,ENROLAMIENTO."Tipo"
,ENROLAMIENTO."Nombres"
,ENROLAMIENTO."ApellidoPaterno"
,ENROLAMIENTO."ApellidoMaterno"
,ENROLAMIENTO."RazonSocial"
,ENROLAMIENTO."IdPaisNacimiento"
,ENROLAMIENTO."FechaNacimiento"
,ENROLAMIENTO."Sexo"
,ENROLAMIENTO."EstadoCivil"
,COALESCE(CIUDAD."IdPais", 0) AS "IdPais"
,COALESCE(DIVISION_PAIS."IdDivisionPais", 0) AS "IdDivisionPais"
,DIRECCION_FISICA."IdCiudad"
,TELEFONO."IdTipoTelefono"
,TELEFONO."Numero" AS "Telefono"
,DIRECCION_ELECTRONICA."Direccion" AS "Email"
,DIRECCION_FISICA."Calle" AS "DireccionCalle"
,DIRECCION_FISICA."Numero" AS "DireccionNumero"
,DIRECCION_FISICA."Departamento" AS "DireccionDepartamento"
,ENROLAMIENTO."FechaCreacion"
,ENROLAMIENTO."FechaModificacion"
,ENROLAMIENTO."IdPersonaConyuge"
,ENROLAMIENTO."RegimenConyugal"
,ENROLAMIENTO."CLI_IdCategoriaInversionista"
,ENROLAMIENTO."CLI_IdTipoCliente"
,ENROLAMIENTO."CLI_IdTipoClienteCMF"
,ENROLAMIENTO."CLI_IdClaseCliente"
,ENROLAMIENTO."CLI_IdEmpleadoEjecutivo"
,ENROLAMIENTO."CLI_CodigoAdicionalHolding"
,ENROLAMIENTO."POR_IdPerfilComercial"
,ENROLAMIENTO."EMP_CodigoEmpleado"
,ENROLAMIENTO."EMP_CodigoTipoCargoEmpleado"
,ENROLAMIENTO."EMP_IdEmpleadoSupervisor"
,ENROLAMIENTO."EMP_IdSucursal"
,ENROLAMIENTO."EMP_FechaInicioCargo"
,ENROLAMIENTO."EMP_FechaTerminoCargo"
,ENROLAMIENTO."CNT_CodigoInscripcion"
,ENROLAMIENTO."CNT_Emisor"
,ENROLAMIENTO."CNT_Depositos"
,ENROLAMIENTO."CNT_Bolsa"
,ENROLAMIENTO."CNT_Corredora"
,ENROLAMIENTO."CNT_CamaraDeCompensacion"
,ENROLAMIENTO."CNT_Banco"
,ENROLAMIENTO."CNT_Boveda"
,ENROLAMIENTO."CNT_Otros"
,ENROLAMIENTO."PRO_IdAreaProveedor"
,ENROLAMIENTO."EMP_CargoIndefinido"
,ENROLAMIENTO."TipoEnrolamiento"
,ENROLAMIENTO."CLI_AreaCliente"
,ENROLAMIENTO."RespondioEncuestaInversionista"
FROM "BSCL.SocioNegocio.BD::ENR.Enrolamiento"  AS ENROLAMIENTO
LEFT JOIN "BSCL.SocioNegocio.BD::ENR.DocumentoIdentidad" AS DOCUMENTO_IDENTIDAD ON DOCUMENTO_IDENTIDAD."IdDocumentoIdentidad" = ENROLAMIENTO."IdDocumentoIdentidad"
LEFT JOIN "BSCL.SocioNegocio.BD::ENR.DocumentoIdentidad" AS DOCUMENTO_IDENTIDAD_ADICIONAL ON DOCUMENTO_IDENTIDAD_ADICIONAL."IdDocumentoIdentidad" = ENROLAMIENTO."IdDocumentoIdentidadAdicional"
LEFT JOIN "BSCL.SocioNegocio.BD::ENR.Telefono" TELEFONO ON TELEFONO."IdTelefono" = ENROLAMIENTO."IdTelefonoPrincipal"
LEFT JOIN "BSCL.SocioNegocio.BD::ENR.DireccionFisica" DIRECCION_FISICA ON DIRECCION_FISICA."IdDireccionFisica" = ENROLAMIENTO."IdDireccionFisicaPrincipal"
LEFT JOIN "BSCL.SocioNegocio.BD::ENR.DireccionElectronica" DIRECCION_ELECTRONICA ON DIRECCION_ELECTRONICA."IdDireccionElectronica" = ENROLAMIENTO."IdDireccionElectronicaPrincipal"
LEFT JOIN "BSCL.Plataforma.BD::REG.Ciudad" AS CIUDAD ON (CIUDAD."IdCiudad" = DIRECCION_FISICA."IdCiudad")
LEFT JOIN "BSCL.Plataforma.BD::REG.DivisionPais" AS DIVISION_PAIS ON (DIVISION_PAIS."IdCiudad" = DIRECCION_FISICA."IdCiudad" AND DIVISION_PAIS."IdDivisionPais" = DIRECCION_FISICA."IdDivisionPais")
WITH READ ONLY;

GRANT SELECT ON "BSCL.SocioNegocio.BD.Vistas::ENR.ConsultarEnrolamiento" TO BCS_DESARROLLADOR WITH GRANT OPTION;
