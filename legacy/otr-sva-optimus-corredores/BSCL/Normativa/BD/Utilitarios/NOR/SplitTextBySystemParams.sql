SET SCHEMA "BSCL";

DROP FUNCTION "BSCL.Normativa.BD.Utilitarios::NOR.SplitTextBySystemParams";

CREATE FUNCTION "BSCL.Normativa.BD.Utilitarios::NOR.SplitTextBySystemParams"
(INPUT_STRING VARCHAR(5000), DELIM VARCHAR(1) DEFAULT ';', TIPO VARCHAR(14) DEFAULT 'TEXTO' ) 
	RETURNS TABLE
	(
		"OUTPUT_SPLIT" VARCHAR(5000)
	)
	LANGUAGE SQLSCRIPT
	SQL SECURITY INVOKER AS
BEGIN
	
	IF TIPO = 'PARAMETRO' THEN
	
		IF (SELECT COUNT("Valor") FROM "BSCL.Plataforma.BD.Vistas::PLA.ConsultarParametrosSistema" WHERE "CodigoParametro" = :INPUT_STRING) > 0  
		THEN
			SELECT "Valor" INTO INPUT_STRING FROM "BSCL.Plataforma.BD.Vistas::PLA.ConsultarParametrosSistema" WHERE "CodigoParametro" = :INPUT_STRING;
		ELSE 
		 	INPUT_STRING = '';
		END IF;
	
	
	END IF;
	
	IF LOCATE(:INPUT_STRING,:DELIM) = 0
	
	THEN
		SPLIT_VALUES = SELECT :INPUT_STRING AS SINGLE_VAL FROM DUMMY;
		
	ELSE
		SPLIT_VALUES = SELECT SUBSTR_BEFORE(:INPUT_STRING,:DELIM) AS SINGLE_VAL FROM DUMMY;
	
		SELECT SUBSTR_AFTER(:INPUT_STRING,:DELIM) || :DELIM INTO INPUT_STRING FROM DUMMY;
	
		WHILE( LENGTH(:INPUT_STRING) > 0 )	
		DO
			SPLIT_VALUES =
				SELECT SINGLE_VAL FROM :SPLIT_VALUES
				UNION
				SELECT SUBSTR_BEFORE(:INPUT_STRING,:DELIM) AS SINGLE_VAL FROM DUMMY;
				
	
			SELECT SUBSTR_AFTER(:INPUT_STRING,:DELIM) INTO INPUT_STRING FROM DUMMY;
	   	
		END WHILE;
	
	END IF;
	
	RETURN
	
	SELECT SINGLE_VAL AS "OUTPUT_SPLIT" FROM :SPLIT_VALUES;


END;