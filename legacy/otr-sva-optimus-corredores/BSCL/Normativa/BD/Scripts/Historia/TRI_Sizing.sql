
select SCHEMA_NAME as 'Schema', round(sum(MEMORY_SIZE_IN_TOTAL) /1024/1024) as 'MB Used'
from M_CS_TABLES
GROUP by SCHEMA_NAME

order by
“MB Used”
desc

