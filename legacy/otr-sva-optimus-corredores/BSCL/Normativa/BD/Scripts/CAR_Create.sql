   ADD CONSTRAINT "FK_Data_Cartola" foreign key ("IdCartola")
      REFERENCES "BSCL.Normativa.BD::CAR.Cartola" ("IdCartola")
      ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE UNIQUE INDEX "UX01_Datos" ON "BSCL.Normativa.BD::CAR.Datos" ("IdCartola", "Nombre");

CREATE COLUMN TABLE "BSCL.Normativa.BD::CAR.Traza" (
    "IdLog" BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "IdNomina" BIGINT NOT NULL,
    "Timestamp" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "Mensaje" NVARCHAR(1000) NULL
);

ALTER TABLE "BSCL.Normativa.BD::CAR.Traza"
   ADD CONSTRAINT "FK_Log_Nomina" foreign key ("IdNomina")
      REFERENCES "BSCL.Normativa.BD::CAR.Nomina" ("IdNomina")
      ON DELETE RESTRICT ON UPDATE RESTRICT;
