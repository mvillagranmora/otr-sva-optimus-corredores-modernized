SET SCHEMA "BSCL";

DROP TABLE "BSCL.Normativa.BD::CAR.Datos";
DROP TABLE "BSCL.Normativa.BD::CAR.Cartola";
DROP TABLE "BSCL.Normativa.BD::CAR.Traza";
DROP TABLE "BSCL.Normativa.BD::CAR.Parametro";
DROP TABLE "BSCL.Normativa.BD::CAR.Nomina";
DROP TABLE "BSCL.Normativa.BD::CAR.Recurso";
DROP TABLE "BSCL.Normativa.BD::CAR.Plantilla";
DROP TABLE "BSCL.Normativa.BD::CAR.Config";

DROP SEQUENCE "BSCL.Normativa.BD.Secuencias::CAR.Global";
CREATE SEQUENCE "BSCL.Normativa.BD.Secuencias::CAR.Global"
    START WITH 1 INCREMENT BY 1 MINVALUE 1;

CREATE COLUMN TABLE "BSCL.Normativa.BD::CAR.Config" (
    "IdConfig" BIGINT NOT NULL PRIMARY KEY,
    "IdEmpresa" BIGINT NOT NULL,
    "Descripcion" NVARCHAR(100) NULL,
    "Tipo" NVARCHAR(20) NOT NULL,
    "Nombre" NVARCHAR(100) NOT NULL,
    "Valor" NVARCHAR(1000) NULL
);

CREATE COLUMN TABLE "BSCL.Normativa.BD::CAR.Plantilla" (
    "IdPlantilla" BIGINT NOT NULL PRIMARY KEY,
    "IdEmpresa" BIGINT NOT NULL,
    "Nombre" NVARCHAR(100) NOT NULL,
    "Vigente" CHAR(2) NOT NULL DEFAULT 'NO',
    "VigenteDesde" DATE NOT NULL
);

CREATE UNIQUE INDEX "UX01_Plantilla" ON "BSCL.Normativa.BD::CAR.Plantilla" ("Nombre", "VigenteDesde");

CREATE COLUMN TABLE "BSCL.Normativa.BD::CAR.Recurso" (
    "IdRecurso" BIGINT NOT NULL PRIMARY KEY,
    "IdPlantilla" BIGINT NOT NULL,
    "Editable" CHAR(2) NOT NULL DEFAULT 'NO',
    "Descripcion" NVARCHAR(100) NULL,
    "Grupo" NVARCHAR(100) NOT NULL,
    "Nombre" NVARCHAR(100) NOT NULL,
    "Tipo" NVARCHAR(20) NOT NULL,
    "Valor" NCLOB NULL
);

ALTER TABLE "BSCL.Normativa.BD::CAR.Recurso"
   ADD CONSTRAINT "FK_Recurso_Plantilla" foreign key ("IdPlantilla")
      REFERENCES "BSCL.Normativa.BD::CAR.Plantilla" ("IdPlantilla")
      ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE UNIQUE INDEX "UX01_Recurso" ON "BSCL.Normativa.BD::CAR.Recurso" ("IdPlantilla", "Nombre", "Tipo");

CREATE COLUMN TABLE "BSCL.Normativa.BD::CAR.Nomina" (

    -- Identificacion
    "IdNomina" BIGINT NOT NULL PRIMARY KEY,
    "IdEmpresa" BIGINT NOT NULL,
    "IdUsuario" BIGINT NOT NULL,
    "IdPlantilla" BIGINT NOT NULL,
	
	-- Atributos
	"Periodo" CHAR(7) NULL,
    "FechaDesde" DATE NULL,
    "FechaHasta" DATE NULL,
    "Comentario" NVARCHAR(100) NULL,
	
	-- Certificacion
    "Certificada" CHAR(2) NOT NULL DEFAULT 'NO',
    "FechaCertificacion" DATE NULL,
    "IdUsuarioCertificador" BIGINT NULL,
    "NombreUsuarioCertificador" NVARCHAR(100) NULL,
    "NotaCertificacion" NVARCHAR(100) NULL,
	
	-- Proceso
    "TipoProceso" NVARCHAR(20) NOT NULL,
    "EstadoProceso" NVARCHAR(20) NOT NULL,
    "MensajeProceso" NVARCHAR(1000) NULL,
    "FechaProgramadaProceso" DATETIME NULL,
    "FechaInicioProceso" DATETIME NULL,
    "FechaTerminoProceso" DATETIME NULL
);

ALTER TABLE "BSCL.Normativa.BD::CAR.Nomina"
   ADD CONSTRAINT "FK_Nomina_Plantilla" foreign key ("IdPlantilla")
      REFERENCES "BSCL.Normativa.BD::CAR.Plantilla" ("IdPlantilla")
      ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE COLUMN TABLE "BSCL.Normativa.BD::CAR.Parametro" (
    "IdParametro" BIGINT NOT NULL PRIMARY KEY,
    "IdNomina" BIGINT NOT NULL,
    "Nombre" NVARCHAR(100) NOT NULL,
    "Valor" NVARCHAR(1000) NULL
);

ALTER TABLE "BSCL.Normativa.BD::CAR.Parametro"
   ADD CONSTRAINT "FK_Parametro_Nomina" foreign key ("IdNomina")
      REFERENCES "BSCL.Normativa.BD::CAR.Nomina" ("IdNomina")
      ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE UNIQUE INDEX "UX01_Parametro" ON "BSCL.Normativa.BD::CAR.Parametro" ("IdNomina", "Nombre");

CREATE COLUMN TABLE "BSCL.Normativa.BD::CAR.Cartola" (
    "IdCartola" BIGINT NOT NULL PRIMARY KEY,
    "IdNomina" BIGINT NOT NULL,
    "IdCliente" BIGINT NOT NULL,
    "IdPortafolio" BIGINT NOT NULL,
    "Reprocesar" CHAR(2) NOT NULL DEFAULT 'NO',
    "Notificar" CHAR(2) NOT NULL DEFAULT 'NO',
    "EstadoProceso" NVARCHAR(20) NULL,
    "MensajeProceso" NVARCHAR(1000) NULL
);

ALTER TABLE "BSCL.Normativa.BD::CAR.Cartola"
   ADD CONSTRAINT "FK_Cartola_Nomina" foreign key ("IdNomina")
      REFERENCES "BSCL.Normativa.BD::CAR.Nomina" ("IdNomina")
      ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE UNIQUE INDEX "UX01_Cartola" ON "BSCL.Normativa.BD::CAR.Cartola" ("IdNomina", "IdPortafolio");

CREATE COLUMN TABLE "BSCL.Normativa.BD::CAR.Datos" (
    "IdDatos" BIGINT NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "IdCartola" BIGINT NOT NULL,
    "Timestamp" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "Nombre" NVARCHAR(100) NOT NULL,
    "Formato" NVARCHAR(20) NOT NULL,
    "Valor" NCLOB NULL
);

