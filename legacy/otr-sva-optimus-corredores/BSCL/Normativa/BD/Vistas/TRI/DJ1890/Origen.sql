SET SCHEMA "BSCL";

DROP VIEW "BSCL.Normativa.BD.Vistas::TRI.DJ1890.Origen";

CREATE VIEW "BSCL.Normativa.BD.Vistas::TRI.DJ1890.Origen" (
    "ID"
    ,"IdDocumento"
    ,"VboUsuario"
    ,"Observaciones"
    ,"FuenteDatos"
   	,"Numero"											
	,"RutInversionista"									
	,"InteresesRealesDepositosPositivo"					
	,"InteresesRealesDepositosNegativo"					
	,"InteresesRealesMantencionPositivo"					
	,"InteresesRealesMantencionNegativo"					
	,"InteresesRealesOperacionesCaptacionPositivo"		
	,"InteresesRealesOperacionesCaptacionNegativo"		
	,"InteresesMonedaNacionalExtranjeraNominal"			
	,"ImpuestoAdicionalMondaNacionalExtranjeraNominal"	
	,"NumeroCertificado"																	
	,"TipoDocumento"
	,"NumeroDocumento"
	,"IdBaseDocumento"
	,"IdCliente"
	,"IdPortafolio"
	,"TipoTransaccion"
	,"IdTipoOperacion"
	,"IdTipoProducto"
	,"FechaOperacion"
	,"InteresesRealesDepositosPositivoActualizado"
	,"InteresesRealesDepositosNegativoActualizado"
	,"InteresesRealesMantencionPositivoActualizado"
	,"InteresesRealesMantencionNegativoActualizado"
	,"InteresesRealesOperacionesCaptacionPositivoActualizado"
	,"InteresesRealesOperacionesCaptacionNegativoActualizado"
	,"FechaVencimiento"
	,"FolioOperacion"	
	,"MontoOperacionCaptacion"
	,"MontoPercibidoFechaVencimiento"	
	,"InteresesRentasPagadas"	
	,"InteresesRealesPositivosNegativos"	
	,"FactorActualizacion"
	,"IdEmpresa"
) AS
SELECT
     0 AS "ID"
    ,1 AS "IdDocumento"
    ,'S' AS "VboUsuario"
    ,'' AS "Observaciones"
    ,'' AS "FuenteDatos"
    ,1 AS "Numero"											
	,"ConsultarCliente"."DocumentoIdentidad" AS "RutInversionista"									
	,0 AS "InteresesRealesDepositosPositivo"					
	,0 AS "InteresesRealesDepositosNegativo"					
	,0 AS "InteresesRealesMantencionPositivo"					
	,0 AS "InteresesRealesMantencionNegativo"					
	,0 AS "InteresesRealesOperacionesCaptacionPositivo"		
	,0 AS "InteresesRealesOperacionesCaptacionNegativo"		
	,0 AS "InteresesMonedaNacionalExtranjeraNominal"			
	,0 AS "ImpuestoAdicionalMondaNacionalExtranjeraNominal"	
	,0 AS "NumeroCertificado"																														
	,'' AS "TipoDocumento"
	,0 AS "NumeroDocumento"
	,0 AS "IdBaseDocumento"
	,"ConsultarOperaciones"."IdCliente" AS "IdCliente"
	,"ConsultarOperaciones"."IdPortafolio" AS "IdPortafolio"
	,'' AS "TipoTransaccion"
	,"ConsultarOperaciones"."IdTipoOperacion" AS "IdTipoOperacion"
	,'' AS "IdTipoProducto"
	,TO_DATE ("ConsultarOperaciones"."FechaMovimiento") AS "FechaOperacion"
	,0 AS "InteresesRealesDepositosPositivoActualizado"
	,0 AS "InteresesRealesDepositosNegativoActualizado"
	,0 AS "InteresesRealesMantencionPositivoActualizado"
	,0 AS "InteresesRealesMantencionNegativoActualizado"
	,0 AS "InteresesRealesOperacionesCaptacionPositivoActualizado"
	,0 AS "InteresesRealesOperacionesCaptacionNegativoActualizado"
	,TO_DATE("ConsultarOperaciones"."FechaVencimiento") AS "FechaVencimiento"
	,"ConsultarOperaciones"."IdOperacion" AS "FolioOperacion"	
	,CASE "ConsultarOperaciones"."IdTipoOperacion" WHEN 'COMTER' THEN "ConsultarOperaciones"."MontoCompra"
												   WHEN 'COMPAC' THEN "ConsultarOperaciones"."MontoCompra"
												   ELSE "ConsultarOperaciones"."MontoVenta" END AS "MontoOperacionCaptacion"
	,CASE "ConsultarOperaciones"."IdTipoOperacion" WHEN 'COMTER' THEN "ConsultarOperaciones"."TotalCompraVencimiento"
												   WHEN 'COMPAC' THEN "ConsultarOperaciones"."TotalCompraVencimiento"
												   ELSE "ConsultarOperaciones"."TotalVentaVencimiento" END AS "MontoPercibidoFechaVencimiento"	
	,0 AS "InteresesRentasPagadas"	
	,0 AS "InteresesRealesPositivosNegativos"	
	,0 AS "FactorActualizacion"
	,1 AS "IdEmpresa"
FROM "BSCL.Mesa.BD.Vistas::MRF.ConsultarOperaciones" "ConsultarOperaciones"
INNER JOIN "BSCL.SocioNegocio.BD.Vistas::CLI.ConsultarCliente" "ConsultarCliente" ON ("ConsultarCliente"."IdCliente" = "ConsultarOperaciones"."IdCliente")
WITH read ONLY;

GRANT SELECT ON "BSCL.Normativa.BD.Vistas::TRI.DJ1890.Origen" TO bcs_desarrollador WITH GRANT OPTION;
