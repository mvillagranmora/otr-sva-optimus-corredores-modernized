SET SCHEMA "BSCL";

DROP VIEW "BSCL.Normativa.BD.Vistas::TRI.ConsultarAnexoCalificacionTributaria";

CREATE VIEW "BSCL.Normativa.BD.Vistas::TRI.ConsultarAnexoCalificacionTributaria" (
"IdCalificacionTributaria"	
,"IdClasificacionTipoInstrumento"			
,"IdInstrumento"				
,"ValorHistorico"			
,"FechaPago"					
,"IdEventoCapital"			
,"Descripcion"				
,"SecuenciaEvento"			
,"AnioOrigen"				
,"TasaCredito"				
,"PorcentajeDividendo"		
,"IdTipoUtilidades"			
,"Factor06"					
,"Factor07"					
,"Factor08"					
,"Factor16"					
,"Factor17"					
,"Factor11"					
,"Factor09"					
,"Factor13"					
,"Factor12"					
,"Factor14"					
,"Factor15"					
,"Factor10"					
,"FechaIngresoSistema"		
,"FechaIngresoRegistro"		
,"FechaModificacionSistema"	
,"FechaModificacionRegistro"	
,"TipoRegistro"				
,"IdEstado"	
,"NombreEstado"	
,"Nemotecnico"
,"Mercado"
,"TipoUtilidad"				
)
AS 
SELECT 
	CALIFICACION."IdCalificacionTributaria"	
	,CALIFICACION."IdClasificacionTipoInstrumento"			
	,CALIFICACION."IdInstrumento"				
	,CALIFICACION."ValorHistorico"			
	,CALIFICACION."FechaPago"					
	,CALIFICACION."IdEventoCapital"			
	,CALIFICACION."Descripcion"				
	,CALIFICACION."SecuenciaEvento"			
	,CALIFICACION."AnioOrigen"				
	,CALIFICACION."TasaCredito"				
	,CALIFICACION."PorcentajeDividendo"		
	,CALIFICACION."IdTipoUtilidades"			
	,CALIFICACION."Factor06"					
	,CALIFICACION."Factor07"					
	,CALIFICACION."Factor08"					
	,CALIFICACION."Factor16"					
	,CALIFICACION."Factor17"					
	,CALIFICACION."Factor11"					
	,CALIFICACION."Factor09"					
	,CALIFICACION."Factor13"					
	,CALIFICACION."Factor12"					
	,CALIFICACION."Factor14"					
	,CALIFICACION."Factor15"					
	,CALIFICACION."Factor10"					
	,CALIFICACION."FechaIngresoSistema"		
	,CALIFICACION."FechaIngresoRegistro"		
	,CALIFICACION."FechaModificacionSistema"	
	,CALIFICACION."FechaModificacionRegistro"	
	,CALIFICACION."TipoRegistro"				
	,CALIFICACION."IdEstado"
	,ESTADO."Nombre" AS "NombreEstado"
	,INSTRUMENTO."Nemotecnico"
	,CLASIFICACION."Nombre" AS "Mercado"
	,TIPO_UTILIDAD."Descripcion" AS "TipoUtilidad"	
FROM "BSCL.Normativa.BD::TRI.CalificacionTributaria" CALIFICACION
LEFT OUTER JOIN "BSCL.Plataforma.BD.Vistas::PLA.ConsultarEstado" AS ESTADO ON CALIFICACION."IdEstado" = ESTADO."IdEstado"
LEFT OUTER JOIN "BSCL.Plataforma.BD.Vistas::INS.ConsultarInstrumento" AS INSTRUMENTO ON INSTRUMENTO."IdInstrumento" = CALIFICACION."IdInstrumento"
LEFT OUTER JOIN (SELECT DISTINCT "IdClasificacionTipoInstrumento", "Nombre" FROM "BSCL.Plataforma.BD.Vistas::INS.ConsultarClasificacionTipoInstrumento") AS CLASIFICACION ON CLASIFICACION."IdClasificacionTipoInstrumento" = CALIFICACION."IdClasificacionTipoInstrumento"
LEFT OUTER JOIN "BSCL.Normativa.BD::TRI.TipoUtilidadesCalificacionTributaria" AS TIPO_UTILIDAD ON (TIPO_UTILIDAD."IdTipoUtilidadesCalificacionTributaria" = CALIFICACION."IdTipoUtilidades")
WHERE CALIFICACION."TipoRegistro" = 'ANEXO' AND CALIFICACION."IdEstado" = 'ACT'
WITH read ONLY;

GRANT SELECT ON "BSCL.Normativa.BD.Vistas::TRI.ConsultarAnexoCalificacionTributaria" TO bcs_desarrollador WITH GRANT OPTION;
