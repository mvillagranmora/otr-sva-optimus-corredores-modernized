SET SCHEMA "BSCL"; 
 
DROP VIEW "BSCL.Normativa.BD.Vistas::TRI.ConsultarTBSICAVC";

CREATE VIEW "BSCL.Normativa.BD.Vistas::TRI.ConsultarTBSICAVC" AS
SELECT 
	CAL."EJERCICIO",
	CAL."MERCADO",
	CAL."NEMO",
    TO_VARCHAR(CAL."FEC_PAGO", 'YYYY-MM-DD') AS FEC_PAGO,
	CAL."SEC_EVE",
	CAL."IDORIGEN"
FROM "BSCL.Normativa.BD::TRI.TBSICAVC" CAL
WITH read ONLY;

GRANT SELECT ON "BSCL.Normativa.BD.Vistas::TRI.ConsultarTBSICAVC" TO bcs_desarrollador WITH GRANT OPTION;
