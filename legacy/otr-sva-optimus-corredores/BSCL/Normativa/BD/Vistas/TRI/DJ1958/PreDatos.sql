		ID
		, "IdDocumento"
		, "VboUsuario"
		, "Observaciones"
		, "FuenteDatos"
		, "PaisResidenciaDeclarante"
		, "PaisResidenciaDeclaranteDescripcion"
		, "TipoInstitucion"
		, "TipoInstitucionDescripcion"
		, "PoseeCuentasFinanciera"
		, "PoseeCuentasFinancieraDescripcion"
		, "PeriodoReporte"
		, "PaisResidencia"
		, "PaisResidenciaDescripcion"
		, "TipoPersona"
		, "TipoPersonaDescripcion"
		, "TipoJuridico"
		, "TipoJuridicoDescripcion"
		, "Nombres"
		, "Apellidos"
		, "RazonSocial"
		, "PaisTaxID"
