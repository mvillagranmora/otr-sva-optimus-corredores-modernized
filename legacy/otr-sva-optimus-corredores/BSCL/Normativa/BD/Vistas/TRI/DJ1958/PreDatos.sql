SELECT ID
	, a."IdDocumento"
	, "VboUsuario"
	, COALESCE(VAL."CodigoValidacion", a."Observaciones") AS "Observaciones"
	, "FuenteDatos"
	, "PaisResidenciaDeclarante"
	, COALESCE(b."Descripcion",'') 				AS	"PaisResidenciaDeclaranteDescripcion"
	, "TipoInstitucion"
	, COALESCE(g."Descripcion",'') 				AS	"TipoInstitucionDescripcion"
	, "PoseeCuentasFinanciera"
	, COALESCE(h."Descripcion",'') 				AS	"PoseeCuentasFinancieraDescripcion"
	, "PeriodoReporte"
	, "PaisResidencia"
	, COALESCE(c."Descripcion",'') 				AS	"PaisResidenciaDescripcion"
	, "TipoPersona"
	, COALESCE(i."Descripcion",'') 				AS	"TipoPersonaDescripcion"
	, "TipoJuridico"
	, COALESCE(j."Descripcion",'') 				AS	"TipoJuridicoDescripcion"
	, "Nombres"
	, "Apellidos"
	, "RazonSocial"
	, "PaisTaxID"
	, COALESCE(p."Descripcion",'') 				AS	"PaisTaxIDDescripcion"
	, "TaxID"
	, "PaisDomicilio"
	, COALESCE(d."Descripcion",'') 				AS	"PaisDomicilioDescripcion"
	, "TipoDomicilio"
	, COALESCE(k."Descripcion",'') 				AS	"TipoDomicilioDescripcion"
	, "Domicilio"
	, "FechaNacimiento"
	, a."NumeroCuenta"
	, "CuentaNoDocumentada"
	, COALESCE(l."Descripcion",'') 				AS	"CuentaNoDocumentadaDescripcion"
	, "CuentaCerrada"
	, COALESCE(m."Descripcion",'') 				AS	"CuentaCerradaDescripcion"
	, a."DivisaSaldo"
	, COALESCE(n."Descripcion",'') 				AS	"DivisaSaldoDescripcion"
	, ROUND("SaldoActualizado",2)				AS  "SaldoActualizado"
	, "PaisResidenciaControlador"
	, COALESCE(e."Descripcion",'') 				AS	"PaisResidenciaControladorDescripcion"
	, "NombreControlador"
	, "ApellidosControlador"
	, "PaisTaxIDControlador"
	, COALESCE(O."Descripcion",'') 				AS	"PaisTaxIDControladorDescripcion"
	, "TaxIDControlador"
	, "PaisDomicilioControlador"
	, COALESCE(f."Descripcion",'') 				AS	"PaisDomicilioControladorDescripcion"
	, "TipoDomicilioControlador"
	, COALESCE(q."Descripcion",'') 				AS	"TipoDomicilioControladorDescripcion"
	, "DomicilioControlador"
	, "FechaNacimientoControlador"
	, a."TipoPagoCuentaFinanciera"
	, COALESCE(r."Descripcion",'') 		AS	"TipoPagoCuentaFinancieraDescripcion"
	, a."DivisaPagoCuentaFinanciera"
	, COALESCE(s."Descripcion",'') 				AS	"DivisaPagoCuentaFinancieraDescripcion"
	, ROUND("MontoPagoActualizado",2)			AS  "MontoPagoActualizado"
	, "IdCliente"
	--, "Portafolio"
	, "Nemo"
	, "IdTipoInstrumento"
	, COALESCE(u."Descripcion",'') 				AS	"IdTipoInstrumentoDescripcion"
	, "IdClasificacionTipoInstrumento"
	, COALESCE(x."Descripcion",'') 				AS	"IdClasificacionTipoInstrumentoDescripcion"
	--, "IdTipoProducto"
	, "TipoRegistro"
	, COALESCE(t."Descripcion",'') 				AS	"TipoRegistroDescripcion"
	, a."RutFondo"
FROM "BSCL.Normativa.BD::TRI.DatosDJ1958" a
left join "BSCL.Normativa.BD::DOC.Diccionario" b on b."Tipo"='DJ1958PAISDECLARANTE' 	and a."PaisResidenciaDeclarante"=b."Codigo" 
left join "BSCL.Normativa.BD::DOC.Diccionario" c on c."Tipo"='DJ1958PAISDECLARANTE' 	and a."PaisResidencia"=c."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" d on d."Tipo"='DJ1958PAISDECLARANTE'		and a."PaisDomicilio"=d."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" e on e."Tipo"='DJ1958PAISDECLARANTE'		and a."PaisResidenciaControlador"=e."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" f on f."Tipo"='DJ1958PAISDECLARANTE'		and a."PaisDomicilioControlador"=f."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" g on g."Tipo"='DJ1958TIPOINSTITUCION'	and a."TipoInstitucion"=g."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" h on h."Tipo"='DJ1958POSEECUENTA' 		and a."PoseeCuentasFinanciera"=h."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" i on i."Tipo"='DJ1958TIPOPERSONA' 		and a."TipoPersona"=i."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" j on j."Tipo"='DJ1958TIPOJURIDICO' 		and a."TipoJuridico"=j."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" k on k."Tipo"='DJ1958TIPODOMICILIO' 		and a."TipoDomicilio"=k."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" l on l."Tipo"='DJ1958CUENTANODOCUM' 		and a."CuentaNoDocumentada"=l."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" m on m."Tipo"='DJ1958CUENTACERRADA' 		and a."CuentaCerrada"=m."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" n on n."Tipo"='DJ1958DIVISASALDO' 		and a."DivisaSaldo"=n."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" o on o."Tipo"='DJ1958PAISDECLARANTE'		and a."PaisTaxIDControlador"=o."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" p on p."Tipo"='DJ1958PAISDECLARANTE'		and a."PaisTaxID"=p."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" q on q."Tipo"='DJ1958TIPODOMICILIO' 		and a."TipoDomicilioControlador"=q."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" r on r."Tipo"='DJ1958TIPOPAGO' 			and a."TipoPagoCuentaFinanciera"=r."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" s on s."Tipo"='DJ1958DIVISASALDO' 		and a."DivisaPagoCuentaFinanciera"=s."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" t on t."Tipo"='DJ1958TIPOREGISTRO' 		and a."TipoRegistro"=t."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" u on u."Tipo"='DJ1958TIPOINSTRUMENTO' 	and a."IdTipoInstrumento"=u."Codigo"
left join "BSCL.Normativa.BD::DOC.Diccionario" x on x."Tipo"='DJ1958CLASIFICACIONINSTRUMENTO' 	and a."IdClasificacionTipoInstrumento"=x."Codigo"
LEFT JOIN (
           	SELECT "CodigoValidacion", "IdDocumento" ,"NumeroCuenta","DivisaSaldo", "TipoPagoCuentaFinanciera","DivisaPagoCuentaFinanciera"
			FROM (
			    SELECT 
			        R."CodigoValidacion", 
			        DT."IdDocumento",
			        DT."NumeroCuenta", 
			        DT."DivisaSaldo",
			        DT."TipoPagoCuentaFinanciera",
					DT."DivisaPagoCuentaFinanciera",
			        ROW_NUMBER() OVER (
			            PARTITION BY DT."IdCliente" 
			            ORDER BY R."ID" ASC
			        ) AS rn
			    FROM "BSCL.Normativa.BD::TRI.ResumenValidacion" AS R
			    INNER JOIN "BSCL.Normativa.BD::TRI.DatosDJ1958" AS DT ON DT."IdDocumento" = R."IdDocumento"
			    INNER JOIN "BSCL.Normativa.BD::TRI.DetalleValidacion" AS DV ON DV."IdResumenValidacion" = R."ID" AND DV."IdDetalleDocumento" = DT."ID" 
			) AS t
			WHERE t.rn = 1
        ) AS VAL ON  a."IdDocumento" = VAL."IdDocumento" AND a."NumeroCuenta" = VAL."NumeroCuenta" AND a."DivisaSaldo" = VAL."DivisaSaldo" 
        	AND a."TipoPagoCuentaFinanciera" = VAL."TipoPagoCuentaFinanciera" AND a."DivisaPagoCuentaFinanciera" = VAL."DivisaPagoCuentaFinanciera"
ORDER BY a."TipoRegistro",a."NumeroCuenta";
