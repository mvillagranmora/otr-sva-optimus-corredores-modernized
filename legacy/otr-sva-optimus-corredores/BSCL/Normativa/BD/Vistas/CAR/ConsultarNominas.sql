SET SCHEMA "BSCL";

DROP VIEW "BSCL.Normativa.BD.Vistas::CAR.ConsultarNominas";

CREATE VIEW "BSCL.Normativa.BD.Vistas::CAR.ConsultarNominas" AS
SELECT X.*, COUNT(Y."IdNomina") AS "CantidadCartolasErroneas" FROM (
SELECT A.*, COUNT(B."IdNomina") AS "CantidadCartolasTerminadas" FROM (
    SELECT
		NOM."IdNomina",
		COALESCE(NOM."CartolaConsolidada", 'n') AS "CartolaConsolidada",
		NOM."IdEmpresa",
		NOM."IdUsuario",
		NOM."IdPlantilla",
		NOM."Periodo",
		NOM."FechaDesde",
		NOM."FechaHasta",
		NOM."Comentario",
		NOM."Certificada",
		CASE NOM."Certificada" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "CertificadaUI",
		NOM."FechaCertificacion",
		NOM."IdUsuarioCertificador",
		NOM."NombreUsuarioCertificador",
		NOM."NotaCertificacion",
		NOM."TipoProceso",
		NOM."EstadoProceso",
		EST."Nombre" AS "NombreEstado",
		NOM."FechaProgramadaProceso",
		NOM."FechaInicioProceso",
		NOM."FechaTerminoProceso",
		NOM."MensajeProceso",
		NOM."Ano",
		NOM."Mes",
		NOM."IncluirPortafoliosConSaldo",
		CASE NOM."IncluirPortafoliosConSaldo" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "IncluirPortafoliosConSaldoUI",
		NOM."IncluirPortafoliosConCustodia",
		CASE NOM."IncluirPortafoliosConCustodia" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "IncluirPortafoliosConCustodiaUI",
		NOM."IncluirPortafoliosConMovimientoCuentaInversion",
		CASE NOM."IncluirPortafoliosConMovimientoCuentaInversion" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "IncluirPortafoliosConMovimientoCuentaInversionUI",
		NOM."IncluirCategoriaInversionista",
		CASE NOM."IncluirCategoriaInversionista" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "IncluirCategoriaInversionistaUI",
		NOM."CategoriaInversionista",
		NOM."IncluirTipoPersona",
		CASE NOM."IncluirTipoPersona" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "IncluirTipoPersonaUI",
		NOM."TipoPersona",
		NOM."IncluirTipoCliente",
		CASE NOM."IncluirTipoCliente" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "IncluirTipoClienteUI",
		NOM."TipoCliente",
		NOM."IncluirPortafoliosExcluidos",
		CASE NOM."IncluirPortafoliosExcluidos" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "IncluirPortafoliosExcluidosUI",
		NOM."EnvioAutomatico",
		CASE NOM."EnvioAutomatico" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "EnvioAutomaticoUI",
		NOM."ExcluirPortafoliosIncluidosOtraNomina",
		CASE NOM."ExcluirPortafoliosIncluidosOtraNomina" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "ExcluirPortafoliosIncluidosOtraNominaUI",
		NOM."ExcluirOperadoresDirectos",
		CASE NOM."ExcluirOperadoresDirectos" WHEN 'S' THEN 'UI_SI' ELSE 'UI_NO' END AS "ExcluirOperadoresDirectosUI",
		NOM."OpcionProceso",
		COUNT(CAR."IdNomina") AS "CantidadCartolas"
    FROM "BSCL.Normativa.BD::CAR.Nomina" NOM
    LEFT JOIN "BSCL.Plataforma.BD::PLA.Estado" EST ON NOM."EstadoProceso" = EST."IdEstado" 
	LEFT JOIN "BSCL.Normativa.BD::CAR.Cartola" CAR ON NOM."IdNomina" = CAR."IdNomina"
	GROUP BY
		NOM."IdNomina",
		NOM."CartolaConsolidada",
		NOM."IdEmpresa",
		NOM."IdUsuario",
		NOM."IdPlantilla",
		NOM."Periodo",
		NOM."FechaDesde",
		NOM."FechaHasta",
		NOM."Comentario",
		NOM."Certificada",
		NOM."FechaCertificacion",
		NOM."IdUsuarioCertificador",
		NOM."NombreUsuarioCertificador",
		NOM."NotaCertificacion",
		NOM."TipoProceso",
		NOM."EstadoProceso",
		NOM."FechaProgramadaProceso",
		NOM."FechaInicioProceso",
		NOM."FechaTerminoProceso",
		NOM."MensajeProceso",
		NOM."Ano",
		NOM."Mes",
		NOM."IncluirPortafoliosConSaldo",
		NOM."IncluirPortafoliosConCustodia",
		NOM."IncluirPortafoliosConMovimientoCuentaInversion",
		NOM."IncluirCategoriaInversionista",
		NOM."CategoriaInversionista",
		NOM."IncluirTipoPersona",
		NOM."TipoPersona",
		NOM."IncluirTipoCliente",
		NOM."TipoCliente",
		NOM."IncluirPortafoliosExcluidos",
		NOM."EnvioAutomatico",
		NOM."ExcluirPortafoliosIncluidosOtraNomina",
		NOM."ExcluirOperadoresDirectos",
		EST."Nombre",
		NOM."OpcionProceso"
) A
LEFT JOIN "BSCL.Normativa.BD::CAR.Cartola" B ON A."IdNomina" = B."IdNomina" AND COALESCE(B."EstadoProceso", '') = 'TER'
GROUP BY
	A."IdNomina",
	A."CartolaConsolidada",
	A."IdEmpresa",
	A."IdUsuario",
	A."IdPlantilla",
	A."Periodo",
	A."FechaDesde",
	A."FechaHasta",
	A."Comentario",
	A."Certificada",
	A."FechaCertificacion",
	A."IdUsuarioCertificador",
	A."NombreUsuarioCertificador",
	A."NotaCertificacion",
	A."TipoProceso",
	A."EstadoProceso",
	A."FechaProgramadaProceso",
	A."FechaInicioProceso",
	A."FechaTerminoProceso",
	A."MensajeProceso",
	A."CantidadCartolas",
	A."Ano",
	A."Mes",
	A."IncluirPortafoliosConSaldo",
	A."IncluirPortafoliosConCustodia",
	A."IncluirPortafoliosConMovimientoCuentaInversion",
	A."IncluirCategoriaInversionista",
	A."CategoriaInversionista",
	A."IncluirTipoPersona",
	A."TipoPersona",
	A."IncluirTipoCliente",
	A."TipoCliente",
	A."IncluirPortafoliosExcluidos",
	A."EnvioAutomatico",
	A."ExcluirPortafoliosIncluidosOtraNomina",
	A."ExcluirOperadoresDirectos",
	A."CertificadaUI",
	A."NombreEstado",
	A."IncluirPortafoliosConSaldoUI",
	A."IncluirPortafoliosConCustodiaUI",
	A."IncluirPortafoliosConMovimientoCuentaInversionUI",
	A."IncluirCategoriaInversionistaUI",
	A."IncluirTipoPersonaUI",
	A."IncluirTipoClienteUI",
	A."IncluirPortafoliosExcluidosUI",
	A."EnvioAutomaticoUI",
	A."ExcluirPortafoliosIncluidosOtraNominaUI",
	A."ExcluirOperadoresDirectosUI",
	A."OpcionProceso") X
LEFT JOIN "BSCL.Normativa.BD::CAR.Cartola" Y ON X."IdNomina" = Y."IdNomina" AND COALESCE(Y."EstadoProceso", '') = 'ERR'
GROUP BY
	X."IdNomina",
	X."CartolaConsolidada",
	X."IdEmpresa",
	X."IdUsuario",
	X."IdPlantilla",
	X."Periodo",
	X."FechaDesde",
	X."FechaHasta",
	X."Comentario",
	X."Certificada",
	X."FechaCertificacion",
	X."IdUsuarioCertificador",
	X."NombreUsuarioCertificador",
	X."NotaCertificacion",
	X."TipoProceso",
	X."EstadoProceso",
	X."FechaProgramadaProceso",
	X."FechaInicioProceso",
	X."FechaTerminoProceso",
	X."MensajeProceso",
	X."CantidadCartolas",
	X."CantidadCartolasTerminadas",
	X."Ano",
	X."Mes",
	X."IncluirPortafoliosConSaldo",
	X."IncluirPortafoliosConCustodia",
	X."IncluirPortafoliosConMovimientoCuentaInversion",
	X."IncluirCategoriaInversionista",
	X."CategoriaInversionista",
	X."IncluirTipoPersona",
	X."TipoPersona",
	X."IncluirTipoCliente",
	X."TipoCliente",
	X."IncluirPortafoliosExcluidos",
	X."EnvioAutomatico",
	X."ExcluirPortafoliosIncluidosOtraNomina",
	X."ExcluirOperadoresDirectos",
	X."CertificadaUI",
	X."NombreEstado",
	X."IncluirPortafoliosConSaldoUI",
	X."IncluirPortafoliosConCustodiaUI",
	X."IncluirPortafoliosConMovimientoCuentaInversionUI",
	X."IncluirCategoriaInversionistaUI",
	X."IncluirTipoPersonaUI",
	X."IncluirTipoClienteUI",
	X."IncluirPortafoliosExcluidosUI",
	X."EnvioAutomaticoUI",
	X."ExcluirPortafoliosIncluidosOtraNominaUI",
	X."ExcluirOperadoresDirectosUI",
	X."OpcionProceso"
;

GRANT SELECT ON "BSCL.Normativa.BD.Vistas::CAR.ConsultarNominas" TO  BCS_DESARROLLADOR WITH GRANT OPTION;
