SELECT
OSP."IdOperacion" AS "IdOperacionSpot"
,POR."IdCliente"
,CC."IdPersona" AS "IDCLIENTEPERSONA"
,OSP."IdPortafolio" AS "IdPortafolioCliente"
,CC."IdEmpleadoEjecutivo" AS "IdEmpleadoDigitador"
,CE."IdPersona" AS "IDEMPLEADOPERSONA"
,CE."IdDireccionElectronicaPrincipal" AS "IDCORREOEMPLEADO"
,CE."NombreCompleto" AS "AGENTE"
,TO_VARCHAR(ADD_SECONDS(CURRENT_UTCTIMESTAMP,:SegundosZonaHoraria), 'DD-MM-YYYY') AS "FECHA"
,TO_VARCHAR(ADD_SECONDS(CURRENT_UTCTIMESTAMP,:SegundosZonaHoraria), 'HH24:MI:SS') AS "HORA"
,CC."NombreCompleto" AS "CLIENTE"
,CCDG."RazonSocial" AS "CORREDORA"
,CCDG."Telefono" AS "ATENCIONCLIENTE"
,CC."DocumentoIdentidad" AS "DOCUMENTOIDENTIDAD"
,CPDE."IdDireccionElectronica" AS "IDCORREOCLIENTE"
,OSP."IdOperacion" AS "FOLIO"
,OSP."TipoOperacion" AS "TIPOOPERACION"
,OSP."ParidadCosto" AS "PARIDAD"
,OSP."MontoMonedaPrincipal" AS "MONTORECIBIR"
,OSP."TipoCambioCierre" AS "TIPOCAMBIO"
,OSP."MontoMonedaSecundaria" AS "MONTOENTREGAR"
,EST."Nombre" AS "ESTADO"
,POR."CodigoPortafolio" AS "PORTAFOLIO"
,OSP."IdMonedaPrincipal" AS "MONEDA_PRINCIPAL"
,OSP."IdMonedaSecundaria" AS "MONEDA_SECUNDARIA"
FROM "BSCL.Mesa.BD.Vistas::SPT.ConsultarMovimientosSpot" OSP
INNER JOIN "BSCL.Portafolio.BD.Vistas::ConsultarPortafolio" POR ON POR."IdPortafolio" = OSP."IdPortafolio"
INNER JOIN "BSCL.SocioNegocio.BD.Vistas::CLI.ConsultarCliente" CC ON CC."IdCliente" = POR."IdCliente"
INNER JOIN "BSCL.SocioNegocio.BD.Vistas::EMP.ConsultarEmpleado" CE ON CE."IdEmpleado" = CC."IdEmpleadoEjecutivo"
INNER JOIN "BSCL.Plataforma.BD.Vistas::CTT.ConsultarContratoDatosGenerales" CCDG ON CCDG."IdEmpresa"  = :IdEmpresa
INNER JOIN "BSCL.SocioNegocio.BD.Vistas::PER.ConsultarPersonaDireccionElectronica" CPDE ON CPDE."IdDireccionElectronica" = CC."IdDireccionElectronicaPrincipal"
INNER JOIN "BSCL.Plataforma.BD::PLA.Estado" EST ON EST."IdEstado" = OSP."Estado"
WHERE OSP."IdEmpresa" = :IdEmpresa AND OSP."IdOperacion" IN (:IdOperacion)