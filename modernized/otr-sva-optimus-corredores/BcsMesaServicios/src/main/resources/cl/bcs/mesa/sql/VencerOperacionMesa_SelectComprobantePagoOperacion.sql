SELECT COM."IdComprobantePagoOperacion"
    ,COM."IdEmpresa"
    ,COM."IdOperacion"
    ,COM."IdIngresoEgreso"
    ,COM."IdTipoProducto"
    ,COM."IdFormaDePago"
    ,COM."RecibePaga"
    ,COM."IdModalidadPago"
    ,COM."IdMoneda"
    ,COM."Monto"
    ,COM."FechaIngresoComprobantePagoOperacion"
    ,COM."FechaLiquidacionComprobantePagoOperacion"
    ,COM."IdEstado"
    ,COM."IdAbono"
    ,COM."IdCargo"
    ,COM."AfectarTesoreria"
    ,COM."IdIngresoEgresoAnticipo"
    ,COM."IdAbonoAnticipo"
    ,COM."IdCargoAnticipo"
    ,COM."IdCuentaBanco"
    ,OPE."IdTipoOperacion"
FROM "BSCL.Mesa.BD::MES.ComprobantePagoOperacion" AS COM
LEFT JOIN "BSCL.Mesa.BD::MES.Operacion" AS OPE
	ON OPE."IdOperacion" = COM."IdOperacion"
WHERE COM."IdTipoProducto" = 'MERF' AND  COM."IdOperacion" IN (:IdOperacion);