SELECT ccpo."IdOperacion"
	, ccpo."IdComprobantePagoOperacion"
	, 'S' "AfectarCuentaInversion"
	, ccpo."RecibePaga"
	, ccpo."IdMonedaComprobantePago" AS "IdMoneda"
	, ccpo."Monto"
	, ccpo."IdMedioDePago"
	, ccpo."IdModalidadPago"
	, ccpo."IdCuentaBancaria"
	, ccpo."IdBanco"
	, ccpo."NumeroCuentaBancaria"
	, ccpo."IdTipoCuentaBancaria"
	, ccpo."FechaLiquidacionComprobantePagoOperacion"
	, tcb."NombreTipoCuentaBancaria"
	, tb."IdTarjetaBancaria"
	, tb."IdTipoTarjetaBancaria"
	, ttb."NombreTipoTarjetaBancaria"
	, tb."NumeroTarjetaBancaria"
	, ccpo."AfectarTesoreria"
FROM "BSCL.Mesa.BD.Vistas::ConsultarComprobantePagoOperacion" ccpo
LEFT JOIN "BSCL.Plataforma.BD::BAN.TipoCuentaBancaria" tcb ON tcb."IdTipoCuentaBancaria" = ccpo."IdTipoCuentaBancaria"
INNER JOIN "BSCL.Custodia.BD::CUS.Cartera" AS car ON car."IdCartera" = ccpo."IdOperacion" AND car."IdTipoProducto" = ccpo."IdTipoProducto"
INNER JOIN "BSCL.Portafolio.BD.Vistas::ConsultarPortafolio" port ON port."IdPortafolio" = car."IdPortafolio"
LEFT JOIN (SELECT RANK() OVER(PARTITION BY t."IdPersona", t."IdBanco" ORDER BY t."IdTarjetaBancaria" DESC) AS "Rank"
	, t."IdTarjetaBancaria"
	, t."IdTipoTarjetaBancaria"
	, t."NumeroTarjetaBancaria"
	, t."IdPersona"
	, t."IdBanco"
	FROM "BSCL.SocioNegocio.BD::PER.TarjetaBancaria" t
		) tb ON tb."IdPersona" = port."IdPersona" AND tb."IdBanco" = ccpo."IdBanco" AND tb."Rank" = 1
LEFT JOIN "BSCL.Plataforma.BD::BAN.TipoTarjetaBancaria" ttb ON ttb."IdTipoTarjetaBancaria" = tb."IdTipoTarjetaBancaria"
WHERE ccpo."IdTipoProducto" = 'MEFW' AND ccpo."IdOperacion" IN (:p_IdOperacion);