#!/usr/bin/env python3
"""Generates the JUnit 5 test classes of APV family C from the case directories (one class per legacy class, one method per case).
Usage: python mktests.py <apv-c resources dir> <output java dir (cl/bcs/apv/familia_c)>

Every method is named after its behaviour id (apvC<NNN>_<slug>, DisplayName 'APV-C-NNN title') and carries a comment with the legacy file:line the case
pins (the citation was resolved from the legacy source when the case was generated, see casegen/lib.py L()). The test body is identical for every case:
load the case, run the WHOLE path through ApvPipelineDeCaso (support/Equivalencia), compare output, table dumps, collaborator calls and sequences with the
golden recorded from the legacy.
"""
import json
import os
import re
import sys

RES = sys.argv[1]
OUT = sys.argv[2]

casos = []
for d in sorted(os.listdir(os.path.join(RES, 'cases'))):
    p = os.path.join(RES, 'cases', d, 'case.json')
    if os.path.isfile(p):
        j = json.load(open(p, encoding='utf-8'))
        j['_dir'] = d
        casos.append(j)

por_clase = {}
for j in casos:
    por_clase.setdefault(j['servicio'] + ('.' + j['metodo'] if j.get('metodo') else ''), []).append(j)


def camel(slug):
    partes = re.split(r'[^A-Za-z0-9]+', slug)
    return partes[0].lower() + ''.join(x[:1].upper() + x[1:] for x in partes[1:] if x)


def esc(t):
    return t.replace('\\', '\\\\').replace('"', "'")


viejos = [f for f in os.listdir(OUT) if f.endswith('Test.java') and f not in ('FamiliaCSelfCheckTest.java',)]
for f in viejos:
    os.remove(os.path.join(OUT, f))

for servicio, lista in sorted(por_clase.items()):
    cn = servicio.replace('_', '').replace('.logica', 'Logica') + 'Test'
    java = []
    java.append('package cl.bcs.apv.familia_c;')
    java.append('')
    java.append('import static org.assertj.core.api.Assertions.assertThat;')
    java.append('')
    java.append('import java.util.List;')
    java.append('')
    java.append('import org.junit.jupiter.api.AfterAll;')
    java.append('import org.junit.jupiter.api.DisplayName;')
    java.append('import org.junit.jupiter.api.Test;')
    java.append('import org.junit.jupiter.api.extension.ExtendWith;')
    java.append('')
    java.append('import cl.bcs.apv.familia_c.support.Caso;')
    java.append('import cl.bcs.apv.familia_c.support.Equivalencia;')
    java.append('import cl.bcs.apv.familia_c.support.ZonaUtc;')
    java.append('')
    java.append('/**')
    java.append(' * Characterization of the legacy {@code cl.bcs.APV.%s} through the WHOLE path legacy JSON -> adapter -> real use case on H2 -> adapter -> JSON.' % servicio)
    java.append(' * Goldens: {@code src/test/resources/apv-c/cases/APV-C-*} (recorded by EXECUTING the unmodified legacy class; never written by hand).')
    java.append(' * GENERATED by legacy-oracle/tools/mktests.py from the case directories: do not edit by hand, add a case and regenerate.')
    java.append(' */')
    java.append('@ExtendWith(ZonaUtc.class)')
    java.append('class %s {' % cn)
    java.append('')
    java.append('    static final List<String> CASOS = List.of(')
    java.append(',\n'.join('            "%s"' % j['_dir'] for j in lista) + ');')
    java.append('')
    java.append('    private static final Caso.Contador EJECUTADOS = new Caso.Contador();')
    java.append('')
    java.append('    @AfterAll')
    java.append('    static void resumen() {')
    java.append('        EJECUTADOS.imprimir("%s");' % servicio)
    java.append('        assertThat(EJECUTADOS.total()).as("equivalence cases executed (zero = not proven)").isGreaterThan(0);')
    java.append('    }')
    for i, j in enumerate(lista):
        num = j['id'].split('-')[-1]
        java.append('')
        java.append('    // legacy %s' % j['pina'])
        java.append('    @Test')
        java.append('    @DisplayName("%s %s")' % (j['id'], esc(j['titulo'])))
        java.append('    void apvC%s_%s() {' % (num, camel(j['_dir'].split('_', 1)[1])))
        java.append('        Equivalencia.verificar(EJECUTADOS, CASOS.get(%d));' % i)
        java.append('    }')
    java.append('}')
    open(os.path.join(OUT, cn + '.java'), 'w', encoding='utf-8', newline='\n').write('\n'.join(java) + '\n')

print('test classes:', len(por_clase), 'cases:', len(casos))
