#!/usr/bin/env python3
"""Generates the JUnit 5 test classes of APV family A from the case directories (one class per legacy class, one method per case).
Usage: python mktests.py <apv-a resources dir> <output java dir (cl/bcs/apv/familia_a)>

Every method is named after its behaviour id (apvA<NNN>_<slug>, DisplayName 'APV-A-NNN title') and carries a comment with the legacy file:line the case
pins (the citation was resolved from the legacy source when the case was generated, see casegen/lib.py L()). The test body is identical for every case:
load the case, run the WHOLE path through ApvPipelineDeCaso, compare output, table dumps and collaborator calls with the golden recorded from the legacy.
"""
import json
import os
import re
import sys

RES = sys.argv[1]
OUT = sys.argv[2]

casos = []
for d in sorted(os.listdir(os.path.join(RES, 'cases'))):
    p = os.path.join(RES, 'cases', d, 'case.json')
    if os.path.isfile(p):
        j = json.load(open(p, encoding='utf-8'))
        j['_dir'] = d
        casos.append(j)

por_clase = {}
for j in casos:
    por_clase.setdefault(j['servicio'], []).append(j)


def camel(slug):
    partes = re.split(r'[^A-Za-z0-9]+', slug)
    return partes[0].lower() + ''.join(x[:1].upper() + x[1:] for x in partes[1:] if x)


def esc(t):
    return t.replace('\\', '\\\\').replace('"', "'")


clases = []
for servicio, lista in sorted(por_clase.items()):
    cn = servicio + 'CasosTest'
    clases.append(cn)
    sin = sorted({k for j in lista for k in j.get('sinOrden', [])})
    java = []
    java.append('package cl.bcs.apv.familia_a;')
    java.append('')
    java.append('import static org.assertj.core.api.Assertions.assertThat;')
    java.append('')
    java.append('import java.util.List;')
    java.append('')
    java.append('import org.junit.jupiter.api.AfterAll;')
    java.append('import org.junit.jupiter.api.DisplayName;')
    java.append('import org.junit.jupiter.api.Test;')
    java.append('import org.junit.jupiter.api.extension.ExtendWith;')
    java.append('')
    if all(j.get('metodo') in ('autorizarEvento', 'rechazarEvento') for j in lista):
        java.append('import cl.bcs.apv.familia_a.support.AutorizacionDeCaso;')
    java.append('import cl.bcs.apv.familia_a.support.Caso;')
    java.append('import cl.bcs.apv.familia_a.support.Dobles;')
    java.append('import cl.bcs.apv.familia_a.support.Verifica;')
    java.append('import cl.bcs.apv.familia_a.support.ZonaUtc;')
    java.append('')
    java.append('/**')
    java.append(' * Characterization of the legacy {@code cl.bcs.APV.%s} through the WHOLE path legacy JSON -> adapter -> real use case on H2 -> adapter -> JSON.' % servicio)
    java.append(' * Goldens: {@code src/test/resources/apv-a/cases/APV-A-*} (recorded by EXECUTING the unmodified legacy class; never written by hand).')
    java.append(' * GENERATED by legacy-oracle/tools/mktests.py from the case directories: do not edit by hand, add a case and regenerate.')
    java.append(' */')
    java.append('@ExtendWith(ZonaUtc.class)')
    java.append('class %s {' % cn)
    java.append('')
    java.append('    static final List<String> CASOS = List.of(')
    java.append(',\n'.join('            "%s"' % j['_dir'] for j in lista) + ');')
    java.append('')
    java.append('    private static final Caso.Contador EJECUTADOS = new Caso.Contador();')
    java.append('    private static final String[] SIN_ORDEN = {%s};' % ', '.join('"%s"' % s for s in sin))
    java.append('')
    java.append('    private static void verificar(String nombre) throws Exception {')
    java.append('        Caso caso = Caso.cargar(nombre);')
    java.append('        Dobles d = Dobles.de(caso);')
    java.append('        Verifica.Ejecucion r = Verifica.Ejecucion.de(caso,')
    if all(j.get('metodo') in ('autorizarEvento', 'rechazarEvento') for j in lista):
        # BcsAutorizaciones hook: not a JavaCall operation (no registry entry), called in process by the platform: typed service on the case's H2
        java.append('                () -> AutorizacionDeCaso.invocar(d, caso));')
    else:
        java.append('                () -> d.pipeline(caso).invocar("cl.bcs.APV.' + servicio + '", caso.entrada().deepCopy()));')
    java.append('        EJECUTADOS.ejecutado(nombre);')
    java.append('        Verifica.comparar(caso, r, d.colaboradores().traza(), SIN_ORDEN);')
    java.append('    }')
    java.append('')
    java.append('    @AfterAll')
    java.append('    static void resumen() {')
    java.append('        EJECUTADOS.imprimir("%s");' % servicio)
    java.append('        assertThat(EJECUTADOS.total()).as("equivalence cases executed (zero = not proven)").isGreaterThan(0);')
    java.append('    }')
    for i, j in enumerate(lista):
        num = j['id'].split('-')[-1]
        java.append('')
        java.append('    // legacy %s' % j['pina'])
        java.append('    @Test')
        java.append('    @DisplayName("%s %s")' % (j['id'], esc(j['titulo'])))
        java.append('    void apvA%s_%s() throws Exception {' % (num, camel(j['_dir'].split('_', 1)[1])))
        java.append('        verificar(CASOS.get(%d));' % i)
        java.append('    }')
    java.append('}')
    open(os.path.join(OUT, cn + '.java'), 'w', encoding='utf-8', newline='\n').write('\n'.join(java) + '\n')

inv = ['package cl.bcs.apv.familia_a;', '', 'import java.util.List;', '',
       '/** GENERATED by legacy-oracle/tools/mktests.py: every generated case test class (ApvAInventarioTest checks the case directories against them). */',
       'final class ApvAClases {', '', '    private ApvAClases() {', '    }', '',
       '    static final List<List<String>> CASOS = List.of(']
inv.append(',\n'.join('            %s.CASOS' % c for c in clases))
inv.append('    );')
inv.append('}')
open(os.path.join(OUT, 'ApvAClases.java'), 'w', encoding='utf-8', newline='\n').write('\n'.join(inv) + '\n')
print('test classes:', len(clases), 'cases:', len(casos))
