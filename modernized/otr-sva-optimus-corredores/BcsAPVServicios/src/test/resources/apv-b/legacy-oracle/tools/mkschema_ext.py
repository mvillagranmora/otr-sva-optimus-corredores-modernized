#!/usr/bin/env python3
"""Generates apv-b/schema-apv-b-ext.sql: the objects family C (recaudacion) needs that schema-apv-b.sql does not define.

  python mkschema_ext.py <schema-apv-b.sql> <schema-apv-c.sql (READ ONLY, family C)> <schema-apv-b-ext.sql>

- a table only family C defines is copied verbatim;
- a table both define gets the columns only family C has as INVISIBLE columns (an INVISIBLE column is not part of SELECT * nor of an INSERT without
  column list, so the dumps and goldens of the family B cases that were recorded before this file existed do not change);
- the columns listed in WIDEN (BIGINT columns that hold codes, such as REC.Recaudacion.IdTipoDeposito) become family C's text type;
- sequences only family C defines are copied; the aliases it needs (TO_NUMBER, HANA_NEXTVAL) are registered against THIS package's H2Hana.
Family C's file is read, never edited. The result is executed by BOTH the oracle runner and the modern tests, right after schema-apv-b.sql.
"""
import re
import sys

# family B inferred these REC.Recaudacion columns as BIGINT from the "--BIGINT" comments of the legacy INSERT; the recaudacion classes store codes and an account text in them
WIDEN = {("REC.Recaudacion", "CuentaCorriente"), ("REC.Recaudacion", "IdTipoDeposito"), ("REC.Recaudacion", "IdEstado")}

HEAD = re.compile(r'CREATE TABLE ("[^"]+")\s*\(')


def split_top(body):
    items, depth, start = [], 0, 0
    for k, ch in enumerate(body):
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        elif ch == ',' and depth == 0:
            items.append(body[start:k])
            start = k + 1
    items.append(body[start:])
    return items


def parse(text):
    """{table name: (full statement text, [(column, type text)])}; the definitions are free format (several columns per line)."""
    out = {}
    for m in HEAD.finditer(text):
        depth, k = 1, m.end()
        while depth:
            ch = text[k]
            depth += (ch == '(') - (ch == ')')
            k += 1
        body = text[m.end():k - 1]
        cols = []
        for item in split_top(body):
            item = item.strip()
            cm = re.match(r'("[^"]+")\s+(.*)$', item, re.S)
            if cm:
                cols.append((cm.group(1), " ".join(cm.group(2).split())))
        out[m.group(1)] = (text[m.start():k] + ";", cols)
    return out


def main(b_path, c_path, out_path):
    b = open(b_path, encoding="utf-8").read()
    c = open(c_path, encoding="utf-8").read()
    tb, tc = parse(b), parse(c)
    o = []
    o.append("-- GENERATED by legacy-oracle/tools/mkschema_ext.py from schema-apv-b.sql and (read only) family C's schema-apv-c.sql. Do not edit by hand.")
    o.append("-- Objects the family C classes run for real inside GrabarRecaudacionTraspaso / IngresoRecaudacionTraspaso / ReaperturarTraspaso need.")
    o.append("-- Columns that family B's tables lack are INVISIBLE (not in SELECT * nor in INSERT without a column list): the earlier family B goldens do not change.")
    o.append("-- INFERRED from the legacy SQL like the rest of the schema (the HANA DDL is not in the repository).")
    o.append("")
    o.append('CREATE ALIAS TO_NUMBER FOR "cl.bcs.apv.familia_b.support.H2Hana.toNumber";')
    o.append('CREATE ALIAS HANA_NEXTVAL FOR "cl.bcs.apv.familia_b.support.H2Hana.nextVal";')
    o.append("")
    seq_b = set(re.findall(r'CREATE SEQUENCE ("[^"]+")', b))
    for m in re.finditer(r'CREATE SEQUENCE ("[^"]+")[^;]*;', c):
        if m.group(1) not in seq_b:
            o.append(m.group(0))
    o.append("")
    new = 0
    ext = 0
    widened = 0
    for name in sorted(tc):
        if name not in tb:
            o.append(tc[name][0])
            o.append("")
            new += 1
        else:
            have = dict(tb[name][1])
            for col, typ in tc[name][1]:
                typ = re.sub(r'\s+(NOT NULL|PRIMARY KEY).*$', '', typ)
                if col not in have:
                    o.append("ALTER TABLE %s ADD COLUMN %s %s INVISIBLE;" % (name, col, typ))
                    ext += 1
                else:
                    btyp = re.sub(r'\s+(NOT NULL|PRIMARY KEY).*$', '', have[col])
                    # only the columns of the allow list change type: widening a VARCHAR(3) would remove the "value too long" failure some family B goldens pin
                    if (name.split("::")[-1].strip('"'), col.strip('"')) in WIDEN:
                        o.append("ALTER TABLE %s ALTER COLUMN %s SET DATA TYPE %s;" % (name, col, typ))
                        widened += 1
    o.append("-- work tables IngresoRecaudacionTraspaso empties after a recaudacion (SELECT * / TRUNCATE / DELETE only): the real column lists are NOT known and not needed; one inferred key column")
    o.append('CREATE TABLE "BSCL.Mesa.BD::SPT.CrearOperacionSpot_Proceso" ("IdOperacionSpot" BIGINT);')
    o.append('CREATE TABLE "BSCL.Plataforma.BD::GBL.SaldoFlujoCaja_Proceso_Paso" ("IdSaldoFlujoCaja" BIGINT);')
    o.append("")
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(o))
    print("new tables", new, "invisible columns added", ext, "columns widened", widened)


if __name__ == "__main__":
    main(*sys.argv[1:4])
