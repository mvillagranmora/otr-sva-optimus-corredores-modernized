package cl.bcs.apv.api;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.TimeUnit;
import java.util.stream.Collectors;
import java.util.stream.Stream;

import org.junit.jupiter.api.Test;

/**
 * Pins the STABILITY of the generator for what this module owns: the generated code of BcsAPVApi ({@code dto/}, {@code casouso/}), the adapter
 * mappers of BcsApvJavaCallAdapter and the contract documents are exactly what {@code tools/generar.py} / {@code generar_contrato.py} produce from the
 * legacy sources, except ONE documented hand override. The real generator is executed (nothing is written); a machine without Python makes the
 * tests FAIL, never skip, because a skipped check would hide a hand edit of generated code.
 *
 * <p>Why not simply {@code generar_todo.py --check == 0}: that command also compares the skeleton {@code BcsAPVServicios/.../application}, which was
 * replaced by the real services (finding of the 2026-10-29 reinforcement: it reports 100+ differences and a plain {@code generar_todo.py} would DELETE
 * those services). That drift is outside this module and is reported in TRANSFORMATION_NOTES.md, not asserted here.
 *
 * <p>Rule ids: B-APVAPI-13 (generator vs tree: only the documented override of {@code ValidarContratoEntrada} differs; adapter mappers: no
 * difference), B-APVAPI-14 (contract documents: {@code generar_contrato.py --check} = 0), B-APVAPI-24 ({@code generar_todo.py --check} is stable:
 * two runs print the same), B-APVAPI-22 (the override is really in the code: legacy default {@code [null]}), B-APVAPI-23 (header, encoding and
 * line endings of the generated files; the hand written files are exactly the known ones).
 */
class ApvApiGeneradorDeterminismoTest {

    private static final String HEADER = "/* GENERATED by BcsAPVApi/tools/generar.py from the legacy sources. DO NOT EDIT: re-run the generator. */";

    private static final String SNIPPET = """
            import os, difflib, generar
            generar.generar()
            dif = generar.comprobar()
            sep = os.sep
            print('files', len(generar.FILES))
            print('api_files', sum(1 for p in generar.FILES if sep + 'BcsAPVApi' + sep in p))
            print('adapter_files', sum(1 for p in generar.FILES if sep + 'BcsApvJavaCallAdapter' + sep in p))
            print('servicios_diffs', sum(1 for d in dif if sep + 'BcsAPVServicios' + sep in d))
            for d in dif:
                if sep + 'BcsAPVApi' + sep in d or sep + 'BcsApvJavaCallAdapter' + sep in d:
                    print('DIFF', os.path.basename(d))
                    if not d.startswith('EXTRA') and d in generar.FILES:
                        a = open(d, encoding='utf-8', newline='').read().replace(chr(13) + chr(10), chr(10)).splitlines()
                        for l in difflib.unified_diff(a, generar.FILES[d].splitlines(), lineterm='', n=0):
                            if l[:1] in '+-' and l[:3] not in ('+++', '---'):
                                print('LINE', l.strip())
            """;

    private record Salida(int rc, String texto) {
    }

    // B-APVAPI-13
    @Test
    void b_apvapi_13_el_generador_reproduce_el_codigo_salvo_el_override_documentado() throws Exception {
        Salida s = python("-c", SNIPPET);
        assertEquals(0, s.rc(), s.texto());
        assertTrue(s.texto().contains("api_files 299"), "the generator must emit 299 files for BcsAPVApi (234 records + 64 interfaces + CasosUso):\n" + s.texto());
        List<String> diffs = new ArrayList<>();
        List<String> lineas = new ArrayList<>();
        for (String l : s.texto().split("\n")) {
            if (l.startsWith("DIFF ")) {
                diffs.add(l.substring(5).trim());
            } else if (l.startsWith("LINE ")) {
                lineas.add(l.substring(5).trim());
            }
        }
        assertEquals(List.of("ValidarContratoEntrada.java"), diffs,
                "files of BcsAPVApi / BcsApvJavaCallAdapter that differ from the generator output (only the documented override may):\n" + s.texto());
        assertEquals(3, lineas.size(), "the override changes exactly: comment line, singletonList default, and the generator's plain list\n" + s.texto());
        assertTrue(lineas.stream().anyMatch(l -> l.startsWith("-") && l.contains("OVERRIDE (tools/overrides/ValidarContrato.md)")), s.texto());
        assertTrue(lineas.stream().anyMatch(l -> l.startsWith("-") && l.contains("singletonList((ContratosSAAPV) null)")), s.texto());
        assertTrue(lineas.stream().anyMatch(l -> l.startsWith("+") && l.contains("new ArrayList<>(),")), s.texto());
        assertTrue(Files.isRegularFile(LegacyApv.modulo().resolve("tools/overrides/ValidarContrato.md")), "the override must stay documented");
        System.out.println("[B-APVAPI-13] generator comparison:\n" + s.texto());
    }

    // B-APVAPI-14
    @Test
    void b_apvapi_14_los_documentos_del_contrato_son_los_que_genera_generar_contrato() throws Exception {
        Salida s = python("generar_contrato.py", "--check");
        assertEquals(0, s.rc(), "generar_contrato.py --check\n" + s.texto());
        assertTrue(s.texto().contains("contract docs differences: 0"), s.texto());
    }

    // B-APVAPI-24
    @Test
    void b_apvapi_24_generar_todo_check_es_estable_entre_corridas() throws Exception {
        Salida a = python("generar_todo.py", "--check");
        Salida b = python("generar_todo.py", "--check");
        assertEquals(a.rc(), b.rc());
        assertEquals(a.texto(), b.texto(), "two consecutive --check runs must print exactly the same");
        assertTrue(a.texto().contains("contract docs differences: 0"), a.texto());
        System.out.println("[B-APVAPI-24] generar_todo.py --check (rc=" + a.rc() + "):\n" + a.texto());
    }

    // B-APVAPI-22
    @Test
    void b_apvapi_22_ValidarContrato_conserva_el_default_legacy_lista_con_un_null() throws Exception {
        Class<?> r = Class.forName("cl.bcs.apv.api.dto.validarcontrato.ValidarContratoEntrada");
        Object d = r.getMethod("porDefecto").invoke(null);
        Object lista = r.getMethod("contratosSAAPV").invoke(d);
        assertEquals(java.util.Collections.singletonList(null), lista,
                "legacy ValidaContratoSAAPV_Entrada does p_ContratosSAAPV = new ArrayList<>(); p_ContratosSAAPV.add(null): default is [null]");
    }

    // B-APVAPI-23
    @Test
    void b_apvapi_23_los_archivos_generados_llevan_cabecera_utf8_sin_BOM_y_fin_de_linea_uniforme() throws Exception {
        Path base = LegacyApv.modulo().resolve("src/main/java/cl/bcs/apv/api");
        List<Path> generados;
        try (Stream<Path> s = Files.walk(base.resolve("dto"))) {
            generados = s.filter(p -> p.toString().endsWith(".java")).collect(Collectors.toCollection(ArrayList::new));
        }
        try (Stream<Path> s = Files.list(base.resolve("casouso"))) {
            s.filter(p -> p.toString().endsWith(".java")).forEach(generados::add);
        }
        assertEquals(234 + 64 + 1, generados.size(), "generated files: 234 records + 64 interfaces + CasosUso");
        int crlf = 0;
        for (Path p : generados) {
            byte[] b = Files.readAllBytes(p);
            assertFalse(b.length >= 3 && (b[0] & 0xFF) == 0xEF && (b[1] & 0xFF) == 0xBB && (b[2] & 0xFF) == 0xBF, p + ": BOM");
            String t = new String(b, StandardCharsets.UTF_8);
            assertFalse(t.replace("\r\n", "").contains("\r"), p + ": lone CR (only LF or CRLF line ends are allowed)");
            if (t.contains("\r\n")) {
                crlf++;
            }
            assertTrue(t.replace("\r\n", "\n").startsWith(HEADER + "\n"), p + ": missing GENERATED header");
        }
        // one line-ending style for the whole generated tree (the generator emits LF; a checkout may convert to CRLF, never a mix)
        System.out.println("[B-APVAPI-23] generated files=" + generados.size() + " with CRLF=" + crlf);
        assertTrue(crlf == 0 || crlf == generados.size(), "mixed line endings in the generated tree: " + crlf + " of " + generados.size() + " use CRLF");
        // hand written files of the module: exactly these, and they do NOT carry the header
        List<String> manuales;
        try (Stream<Path> s = Files.walk(base)) {
            manuales = s.filter(p -> p.toString().endsWith(".java") && !generados.contains(p)).map(p -> base.relativize(p).toString().replace('\\', '/'))
                    .sorted().toList();
        }
        assertEquals(List.of("CasoUso.java", "comun/Mensaje.java", "logica/RegistroMandatoPAC.java", "logica/ValidarMandatosPACLogica.java",
                "logica/ValidarMandatosPACLogicaEntrada.java"), manuales, "hand written main files");
        for (String m : manuales) {
            assertFalse(LegacyApv.leer(base.resolve(m)).contains("GENERATED by"), m + " is hand written and must not claim to be generated");
        }
    }

    // ------------------------------------------------------------------------------------------------

    private static Salida python(String... args) throws Exception {
        Path tools = LegacyApv.modulo().resolve("tools");
        assertTrue(Files.isRegularFile(tools.resolve("generar_todo.py")), "generar_todo.py not found in " + tools);
        List<List<String>> candidatos = List.of(List.of("py", "-3"), List.of("python3"), List.of("python"));
        IOException ultimo = null;
        for (List<String> py : candidatos) {
            List<String> cmd = new ArrayList<>(py);
            cmd.add("-B");
            cmd.addAll(List.of(args));
            ProcessBuilder pb = new ProcessBuilder(cmd).directory(tools.toFile()).redirectErrorStream(true);
            pb.environment().put("PYTHONIOENCODING", "utf-8");
            pb.environment().put("PYTHONUTF8", "1");
            pb.environment().put("PYTHONDONTWRITEBYTECODE", "1");
            Process p;
            try {
                p = pb.start();
            } catch (IOException e) {
                ultimo = e;
                continue;
            }
            String salida = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8).replace("\r\n", "\n");
            if (!p.waitFor(300, TimeUnit.SECONDS)) {
                p.destroyForcibly();
                throw new AssertionError("python timed out\n" + salida);
            }
            return new Salida(p.exitValue(), salida);
        }
        throw new AssertionError("no Python interpreter found (py -3, python3, python): the generator check cannot be skipped", ultimo);
    }
}
