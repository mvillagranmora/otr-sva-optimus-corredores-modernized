def nonblank(texto):
    return sum(1 for l in texto.splitlines() if l.strip())


def default_txt(f, p):
    d = f.default
    if d is None:
        return 'null' if f.lista or not f.prim else ('false' if f.prim == 'boolean' else '0')
    k = d[0]
    if k == 'lista':
        return 'empty list'
    if k == 'nuevo':
        return 'new %s()' % d[1].nombre
    if k == 'long':
        return d[1] + 'L'
    if k == 'bd':
        return 'BigDecimal.%s' % d[1] if d[1] in ('ZERO', 'ONE', 'TEN') else 'new BigDecimal(%s)' % d[1]
    return str(d[1])


def tipo_legacy(f):
    return f.tipo_java.replace('\n', ' ')


def gson_fecha(f, p):
    if f.base != 'Date':
        return ''
    if f.fecha == 'sql':
        return 'java.sql.Date: "MMM d, yyyy" (Gson plain default)' if p.sabor == 'PLANO' else 'java.sql.Date: pattern yyyy-MM-dd HH:mm:ss.SSS'
    return 'java.util.Date: Gson plain default date-time' if p.sabor == 'PLANO' else 'java.util.Date: yyyy-MM-dd HH:mm:ss.SSS'


def clasif_colab(op):
    c = op.collab
    internos = [x for x in c['javacall'] if x in catalogo.OPS]
    externos = [x for x in c['javacall'] if x not in catalogo.OPS]
    return internos, externos


def esfuerzo(planes, familia):
    """heuristic person-days (NOT calibrated): implementation 1 pd / 100 non-blank lines, characterization + goldens 1 pd / 150, adapter+REST+review 0.5 pd per operation,
    +0.25 pd per external collaborator and per stored procedure (contract with its shim)."""
    imp = tes = adp = col = 0.0
    n = 0
    lineas = 0
    for p in planes.values():
        if p.familia != familia:
            continue
        nb = p.nonblank
        lineas += nb
        if p.caso is None:
            imp += nb / 100.0
            tes += nb / 150.0
            continue
        n += 1
        imp += nb / 100.0
        tes += nb / 150.0
        adp += 0.5
        ie, ex = clasif_colab(p.op)
        col += 0.25 * (len(ex) + len(p.op.collab['storedprocs']))
    tot = imp + tes + adp + col
    return n, lineas, imp, tes, adp, col, tot


