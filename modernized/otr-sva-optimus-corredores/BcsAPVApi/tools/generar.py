SRV = os.path.join(MOD, 'BcsAPVServicios')
P_API = 'cl.bcs.apv.api'
P_ADP = 'cl.bcs.apv.adapter.javacall'
P_APP = 'cl.bcs.apv.application'
HEADER = '/* GENERATED by BcsAPVApi/tools/generar.py from the legacy sources. DO NOT EDIT: re-run the generator. */\n'

FILES = {}   # path -> content (written at the end, or compared with --check)


def emit(path, content):
    assert path not in FILES, path
    FILES[path] = content


def pascal(n):
    parts = re.split(r'[_\W]+', n)
    return ''.join(p[:1].upper() + p[1:] for p in parts if p)


RESERVED_TYPES = {'String', 'Long', 'Integer', 'Double', 'Boolean', 'Object', 'List', 'Date', 'BigDecimal', 'Math', 'Mensaje', 'ArrayList',
                  'LocalDate', 'LocalDateTime', 'JsonObject', 'Float', 'Short', 'Byte', 'Character', 'Record', 'Override'}
BAD_COMPONENTS = {'clone', 'finalize', 'getClass', 'hashCode', 'notify', 'notifyAll', 'toString', 'wait'}


class Plan:
    """everything the generators need for one invocable operation"""


def construir_plan():
    idx, ops = modelo.construir()
    unknown = [n for n in ops if n not in catalogo.OPS and ops[n].javacall]
    assert not unknown, 'legacy JavaCall classes missing in catalogo.OPS: %s' % unknown
    extra = [n for n in catalogo.OPS if n not in ops]
    assert not extra, 'catalogo.OPS names not in legacy: %s' % extra
    planes = {}
    for nombre in sorted(ops):
        o = ops[nombre]
        if not o.javacall:
            continue
        fam, caso, ruta, verbo = catalogo.OPS[nombre]
        p = Plan()
        p.op = o
        p.nombre = nombre
        p.familia = fam
        p.caso = caso
        p.ruta = ruta
        p.pkg_dto = None if caso is None else P_API + '.dto.' + caso.lower()
        p.clases = []
        p.nombres = {}
        if caso is not None:
            assert o.entrada is not None and o.salida is not None, nombre
            usados = {caso + 'Entrada', caso + 'Resultado'} | RESERVED_TYPES
            p.nombres[o.entrada.key] = caso + 'Entrada'
            p.nombres[o.salida.key] = caso + 'Resultado'
            vistos = set()
            orden = []
            for raiz in (o.entrada, o.salida):
                for c in modelo.grafo(idx, raiz):
                    if c.key not in vistos:
                        vistos.add(c.key)
                        orden.append(c)
            for c in orden:
                if c.key not in p.nombres:
                    nom = pascal(c.nombre)
                    if nom in usados:
                        nom = pascal(c.ruta[-2]) + nom if len(c.ruta) > 1 else nom + 'Dto'
                    while nom in usados:
                        nom += '2'
                    usados.add(nom)
                    p.nombres[c.key] = nom
            p.clases = orden
            p.campos = {}
            for c in orden:
                cs = modelo.campos_de(idx, c)
                for f in cs:
                    if f.nombre in BAD_COMPONENTS:
                        f.nombre += 'Valor'
                p.campos[c.key] = cs
            p.sabor = 'PLANO' if o.call['gson'] == 'plain' else 'CONSTRUCTOR'
            p.plana = all(f.escalar for f in p.campos[o.entrada.key])
            p.verbo = catalogo.verbo_de(nombre, p.plana)
        planes[nombre] = p
    return idx, planes


# ---------------------------------------------------------------- java type / default / mapper expressions
def tipo_java(f, p):
    if f.clase_ref is not None:
        t = p.nombres[f.clase_ref.key]
    elif f.base == 'MensajeSalida':
        t = 'Mensaje'
    elif f.base == 'Date':
        t = 'LocalDate' if f.fecha == 'sql' else 'LocalDateTime'
    elif f.base == 'Timestamp':
        raise AssertionError('Timestamp field not supported yet: ' + f.legacy)
    elif f.externo:
        t = 'JsonObject'
    elif f.mapa:
        raise AssertionError('Map field not supported yet: ' + f.legacy)
    elif f.prim and not f.lista:
        return f.prim
    else:
        t = f.base
    return 'List<%s>' % t if f.lista else t


def clase_escalar(f):
    """class literal used to ask Gson for the element (boxed)."""
    if f.base == 'MensajeSalida' or f.clase_ref is not None:
        raise AssertionError
    if f.externo:
        return 'JsonObject'
    return f.base


def default_java(f, p):
    d = f.default
    if f.lista and d is None:
        return 'null'
    if d is None:
        if f.prim:
            return {'boolean': 'false', 'double': '0.0', 'float': '0.0f'}.get(f.prim, '0L' if f.prim == 'long' else '0')
        return 'null'
    k = d[0]
    if k == 'null':
        return 'null'
    if k == 'lista':
        return 'new ArrayList<>()'
    if k == 'lista_nula':   # hand override (tools/overrides/<file>): the legacy constructor does lista.add(null)
        elem = p.nombres[f.clase_ref.key] if f.clase_ref is not None else f.base
        return ('// OVERRIDE (tools/overrides/%s): the legacy constructor does %s.add(null): the default is [null]\n                '
                'new ArrayList<>(java.util.Collections.singletonList((%s) null))') % (d[1], f.legacy, elem)
    if k == 'nuevo':
        return p.nombres[d[1].key] + '.porDefecto()'
    if k == 'str':
        return d[1]
    if k == 'bool':
        return d[1]
    if k == 'bd':
        if d[1] in ('ZERO', 'ONE', 'TEN'):
            return 'BigDecimal.' + d[1]
        return 'new BigDecimal("%s")' % d[1]
    if f.base == 'BigDecimal':
        return 'new BigDecimal("%s")' % d[1]
    if k == 'long':
        return d[1] + 'L' if f.base in ('Long',) or f.prim == 'long' else d[1]
    if k == 'int':
        if f.base == 'Long' or f.prim == 'long':
            return d[1] + 'L'
        if f.base == 'Double' or f.prim == 'double':
            return d[1] + '.0'
        return d[1]
    if k == 'double':
        return d[1]
    raise AssertionError('default not translatable: %s %s' % (f.legacy, d))


def imports_de(tipos):
    imp = set()
    txt = ' '.join(tipos)
    if 'List<' in txt:
        imp.add('java.util.List')
    if 'ArrayList' in txt:
        imp.add('java.util.ArrayList')
    if 'BigDecimal' in txt:
        imp.add('java.math.BigDecimal')
    if 'LocalDateTime' in txt:
        imp.add('java.time.LocalDateTime')
    if re.search(r'\bLocalDate\b', txt):
        imp.add('java.time.LocalDate')
    if 'JsonObject' in txt:
        imp.add('com.google.gson.JsonObject')
    if 'Mensaje' in txt:
        imp.add(P_API + '.comun.Mensaje')
    return sorted(imp)


# ---------------------------------------------------------------- BcsAPVApi
def gen_api(planes):
    base = os.path.join(API, 'src', 'main', 'java', *P_API.split('.'))
    casos = []
    for nombre, p in planes.items():
        if p.caso is None:
            continue
        casos.append(p.caso)
        ddir = os.path.join(base, 'dto', p.caso.lower())
        for c in p.clases:
            rn = p.nombres[c.key]
            cs = p.campos[c.key]
            tipos = [tipo_java(f, p) for f in cs]
            defs = [default_java(f, p) for f in cs]
            imps = imports_de(tipos + defs)
            comps = ',\n'.join('        %s %s' % (t, f.nombre) for t, f in zip(tipos, cs))
            args = ',\n'.join('                %s' % d for d in defs)
            src = HEADER + 'package %s;\n\n' % p.pkg_dto
            if imps:
                src += ''.join('import %s;\n' % i for i in imps) + '\n'
            src += '/**\n * Typed record of the legacy class {@code %s} (operation {@code %s}).\n * The legacy JSON names live only in the adapter mapper of this operation.\n */\n' % (c.fqn, o_fqn(p))
            if cs:
                src += 'public record %s(\n%s) {\n\n' % (rn, comps)
            else:
                src += 'public record %s() {\n\n' % rn
            src += '    /** Legacy constructor defaults (empty lists, counters, empty strings); every other component is null, 0 or false. */\n'
            if cs:
                src += '    public static %s porDefecto() {\n        return new %s(\n%s);\n    }\n}\n' % (rn, rn, args)
            else:
                src += '    public static %s porDefecto() {\n        return new %s();\n    }\n}\n' % (rn, rn)
            emit(os.path.join(ddir, rn + '.java'), src)
        # use case interface
        ent, res = p.nombres[p.op.entrada.key], p.nombres[p.op.salida.key]
        src = HEADER + 'package %s.casouso;\n\n' % P_API
        src += 'import %s.CasoUso;\nimport %s.%s;\nimport %s.%s;\n\n' % (P_API, p.pkg_dto, ent, p.pkg_dto, res)
        src += ('/**\n * Use case {@code %s} (family %s). Legacy JavaCall class {@code %s}.\n * Proposed REST adapter: {@code %s %s}.\n */\n'
                % (p.caso, p.familia, o_fqn(p), p.verbo, p.ruta))
        src += 'public interface %s extends CasoUso<%s, %s> {\n\n    @Override\n    %s ejecutar(%s entrada);\n}\n' % (p.caso, ent, res, res, ent)
        emit(os.path.join(base, 'casouso', p.caso + '.java'), src)
    casos.sort()
    src = HEADER + 'package %s.casouso;\n\nimport java.util.List;\n\nimport %s.CasoUso;\n\n' % (P_API, P_API)
    src += '/** Every use case interface of the module (one per invocable legacy operation). */\npublic final class CasosUso {\n\n    private CasosUso() {\n    }\n\n'
    src += '    public static final List<Class<? extends CasoUso<?, ?>>> TODOS = List.of(\n' + ',\n'.join('            %s.class' % c for c in casos) + ');\n}\n'
    emit(os.path.join(base, 'casouso', 'CasosUso.java'), src)


def o_fqn(p):
    return p.op.fqn


# ---------------------------------------------------------------- BcsApvJavaCallAdapter
def expr_leer(f, p, mapeo):
    k = '"%s"' % f.legacy
    d = 'd.%s()' % f.nombre
    if f.base == 'MensajeSalida':
        return 'MapeoJson.listaObjeto(S, o, %s, x -> MensajeMapeo.desdeJson(S, x), %s)' % (k, d)
    if f.clase_ref is not None:
        fn = 'Mapeo::leer' + p.nombres[f.clase_ref.key]
        fn = '%s::leer%s' % (mapeo, p.nombres[f.clase_ref.key])
        return ('MapeoJson.listaObjeto(S, o, %s, %s, %s)' if f.lista else 'MapeoJson.objeto(S, o, %s, %s, %s)') % (k, fn, d)
    if f.base == 'Date':
        return 'MapeoJson.fecha%s(S, o, %s, %s)' % ('Sql' if f.fecha == 'sql' else 'Util', k, d)
    cl = clase_escalar(f) + '.class'
    if f.lista:
        return 'MapeoJson.listaEscalar(S, o, %s, %s, %s)' % (k, cl, d)
    if f.prim:
        return 'MapeoJson.primitivo(S, o, %s, %s.class, %s)' % (k, modelo.PRIMS[f.prim], d)
    return 'MapeoJson.escalar(S, o, %s, %s, %s)' % (k, cl, d)


def expr_escribir(f, p, mapeo):
    k = '"%s"' % f.legacy
    v = 'r.%s()' % f.nombre
    if f.base == 'MensajeSalida':
        return 'MapeoJson.ponerListaObjeto(S, j, %s, %s, x -> MensajeMapeo.aJson(S, x))' % (k, v)
    if f.clase_ref is not None:
        fn = '%s::escribir%s' % (mapeo, p.nombres[f.clase_ref.key])
        return ('MapeoJson.ponerListaObjeto(S, j, %s, %s, %s)' if f.lista else 'MapeoJson.ponerObjeto(S, j, %s, %s, %s)') % (k, v, fn)
    if f.base == 'Date':
        return 'MapeoJson.ponerFecha%s(S, j, %s, %s)' % ('Sql' if f.fecha == 'sql' else 'Util', k, v)
    if f.lista:
        return 'MapeoJson.ponerLista(S, j, %s, %s)' % (k, v)
    return 'MapeoJson.poner(S, j, %s, %s)' % (k, v)


