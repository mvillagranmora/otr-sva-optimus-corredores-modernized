CREATE TABLE WORKSTACK_T (
    ID_STACK   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    KEY_VALUE  VARCHAR(50),
    TABLE_NAME VARCHAR(100),
    ACTION     VARCHAR(10),
    STATUS     INTEGER,
    STAMP      TIMESTAMP,
    PARAMETERS VARCHAR(500)
);

CREATE TABLE CONFIGURACION_T (
    ID_EMPRESA BIGINT,
    CLAVE      VARCHAR(100),
    VALOR      VARCHAR(200),
    PRIMARY KEY (ID_EMPRESA, CLAVE)
);
