-- H2 schema for BcsPortalConfirmacionWeb integration tests.
-- These tables mirror the HANA tables used by NotificationJdbcAdapter
-- (with H2-friendly names and column casing).

CREATE TABLE IF NOT EXISTS EVT_TAG_GENERALES (
    LLAVE         VARCHAR(255) NOT NULL PRIMARY KEY,
    VALOR_DEFAULT VARCHAR(4000)
);

CREATE TABLE IF NOT EXISTS PLA_CONFIGURACION (
    ID_EMPRESA       BIGINT       NOT NULL,
    CODIGO_PARAMETRO VARCHAR(255) NOT NULL,
    VALOR            VARCHAR(4000),
    PRIMARY KEY (ID_EMPRESA, CODIGO_PARAMETRO)
);

CREATE TABLE IF NOT EXISTS EVT_NOTIFICACION (
    TOKEN_CONFIRMACION VARCHAR(255) NOT NULL PRIMARY KEY,
    OBSERVACION        VARCHAR(4000),
    CONFIRMADO         VARCHAR(1),
    ACCION_CONFIRMADA  VARCHAR(10),
    FECHA_CONFIRMADO   TIMESTAMP
);
