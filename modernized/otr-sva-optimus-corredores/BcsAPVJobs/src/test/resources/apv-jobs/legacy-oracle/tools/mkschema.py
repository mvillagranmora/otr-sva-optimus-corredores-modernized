#!/usr/bin/env python3
"""Generates schema-apv-jobs.sql: the H2 (MODE=LEGACY) stand-in of the SAP HANA objects the four APV jobs read and write.

The COLUMNS AND TYPES of every table are copied from the legacy DDL scripts (BSCL/<Modulo>/BD/Scripts/*_Create_Tables.sql). NOT NULL, DEFAULT,
column-store attributes, keys and constraints are dropped (a seed names every column it needs). The HANA VIEW the legacy SQL joins
(BSCL.Portafolio.BD.Vistas::ConsultarPortafolio) has no DDL in the repository: it is modelled as a table with the five columns the SQL reads
(ASSUMPTION, see the README). Likewise POR.MatrizAgrupadorAPV (its DDL is not in the scripts): two columns, the key of the view and the regime id (type of REC.RegimenTributario).

Usage: python mkschema.py <legacy BSCL root> <output schema-apv-jobs.sql>
"""
import re
import sys

LEG = sys.argv[1]
OUT = sys.argv[2]

TABLAS = [
    ("Plataforma/BD/Scripts/BAT_Create_Tables.sql", "BSCL.Plataforma.BD::BAT.Programa"),
    ("Plataforma/BD/Scripts/BAT_Create_Tables.sql", "BSCL.Plataforma.BD::BAT.ParametrosPrograma"),
    ("Plataforma/BD/Scripts/BAT_Create_Tables.sql", "BSCL.Plataforma.BD::BAT.LogPrograma"),
    ("Orden/BD/Scripts/ORD_Create_Tables.sql", "BSCL.Orden.BD::ORD.Orden"),
    ("FondoMutuo/BD/Scripts/FMM_Create_Tables.sql", "BSCL.FondoMutuo.BD::FMM.SolicitudAporteRescate"),
    ("FondoMutuo/BD/Scripts/FMM_Create_Tables.sql", "BSCL.FondoMutuo.BD::FMM.SerieDeFondo"),
    ("FondoMutuo/BD/Scripts/FMM_Create_Tables.sql", "BSCL.FondoMutuo.BD::FMM.Fondo"),
    ("FondoMutuo/BD/Scripts/FMM_Create_Tables.sql", "BSCL.FondoMutuo.BD::FMM.TipoFondo"),
    ("Plataforma/BD/Scripts/PLA_Create_Tables.sql", "BSCL.Plataforma.BD::PLA.Configuracion"),
    ("Plataforma/BD/Scripts/PLA_Create_Tables.sql", "BSCL.Plataforma.BD::PLA.MonedaFormato"),
    ("Plataforma/BD/Scripts/INS_Create_Tables.sql", "BSCL.Plataforma.BD::INS.TipoOperacion"),
    ("APV/BD/Scripts/Create_Tables.sql", "BSCL.APV.BD::REC.RegimenTributario"),
]

VISTAS = {
    "BSCL.Portafolio.BD.Vistas::ConsultarPortafolio": [
        ("IdCliente", "BIGINT"), ("IdPortafolio", "BIGINT"), ("TienePropositoAPV", "NVARCHAR(1)"), ("IdEstado", "NVARCHAR(3)"),
        ("IdMatrizAgrupadorAPV", "BIGINT")],
}


# columns the legacy code uses that the DDL scripts do not declare (added to the table later in HANA): ASSUMPTION, see the README
EXTRAS = {"BSCL.Plataforma.BD::BAT.Programa": [("RutaSalida", "NVARCHAR(500)")],
          "BSCL.Plataforma.BD::INS.TipoOperacion": [("AccionOrden", "NVARCHAR(10)")],
          "BSCL.Orden.BD::ORD.Orden": [("BaseTasa", "BIGINT"), ("EsFungible", "NVARCHAR(1)"), ("EsOrdenEspecial", "NVARCHAR(1)"), ("EsPorMonto", "NVARCHAR(1)"),
                                       ("IdBoveda", "NVARCHAR(10)"), ("IdCuentaCustodioPortafolio", "BIGINT"), ("IdPersonaAutorizadoDarOrdenes", "BIGINT"),
                                       ("TipoInteres", "NVARCHAR(1)"), ("CodigoClaseOrden", "NVARCHAR(10)")],
          "BSCL.FondoMutuo.BD::FMM.SerieDeFondo": [("AportesAltos", "NVARCHAR(1)"), ("EsAPV", "NVARCHAR(1)"), ("PatrimonioAltos", "NVARCHAR(1)"),
                                                   ("RestringeAporte", "NVARCHAR(1)"), ("RestringeRescate", "NVARCHAR(1)")],
          "BSCL.FondoMutuo.BD::FMM.Fondo": [("IdMercadoFondoMutuo", "NVARCHAR(10)")],
          "BSCL.FondoMutuo.BD::FMM.SolicitudAporteRescate": [("FolioContratoOperacion", "NVARCHAR(40)"), ("TipoContratoOperacion", "NVARCHAR(40)"),
                                                             ("IdMonedaPago", "NVARCHAR(3)")]}


def cuerpo_tabla(texto, nombre):
    m = re.search(r'CREATE\s+(?:COLUMN\s+|ROW\s+)?TABLE\s+"' + re.escape(nombre) + r'"\s*\(', texto, re.I)
    if not m:
        raise SystemExit("DDL not found: " + nombre)
    i = m.end()
    depth = 1
    j = i
    while depth:
        c = texto[j]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        j += 1
    return texto[i:j - 1]


def separar(cuerpo):
    partes, depth, ini = [], 0, 0
    for k, c in enumerate(cuerpo):
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif c == "," and depth == 0:
            partes.append(cuerpo[ini:k])
            ini = k + 1
    partes.append(cuerpo[ini:])
    return partes


def columna(parte):
    p = re.sub(r"--[^\n]*", "", parte)
    p = re.sub(r"/\*.*?\*/", "", p, flags=re.S).strip()
    m = re.match(r'"([^"]+)"\s+([A-Za-z]+(?:\s*\(\s*\d+\s*(?:,\s*\d+\s*)?\))?)', p)
    if not m:
        return None
    tipo = re.sub(r"\s+", "", m.group(2))
    tipo = {"SECONDDATE": "TIMESTAMP"}.get(tipo.upper(), tipo)
    return m.group(1), tipo


def main():
    sql = ["-- H2 (MODE=LEGACY) stand-in of the SAP HANA objects of the four APV jobs (BcsAPVJobs).",
           "-- GENERATED by legacy-oracle/tools/mkschema.py: column names and types come from the legacy DDL scripts (BSCL/*/BD/Scripts/*_Create_Tables.sql);",
           "-- NOT NULL, DEFAULT, keys and column-store attributes are dropped. The view ConsultarPortafolio is modelled as a table (no DDL in the repository).",
           "-- This file is executed by BOTH the legacy oracle runner and the modern tests.", "",
           "CREATE TABLE DUMMY (X VARCHAR(1));", "INSERT INTO DUMMY VALUES ('X');", "",
           'CREATE ALIAS TO_NVARCHAR FOR "cl.bcs.apv.jobs.support.H2Hana.toNvarchar";',
           'CREATE ALIAS TO_VARCHAR FOR "cl.bcs.apv.jobs.support.H2Hana.toVarchar";',
           'CREATE ALIAS TO_BIGINT FOR "cl.bcs.apv.jobs.support.H2Hana.toBigint";',
           'CREATE ALIAS HANA_UTCNOW FOR "cl.bcs.apv.jobs.support.H2Hana.utcNow";', ""]
    cache = {}
    for ruta, nombre in TABLAS:
        if ruta not in cache:
            with open(LEG + "/" + ruta, encoding="utf-8", errors="replace") as f:
                cache[ruta] = f.read()
        cols = [c for c in (columna(p) for p in separar(cuerpo_tabla(cache[ruta], nombre))) if c]
        cols = cols + [c for c in EXTRAS.get(nombre, []) if c[0] not in [x[0] for x in cols]]
        if nombre.endswith("REC.RegimenTributario"):
            tipos_regimen = cols
        sql.append('-- DDL: %s (%s)' % (ruta, nombre))
        sql.append('CREATE TABLE "%s" (' % nombre)
        sql.append(",\n".join('  "%s" %s' % c for c in cols))
        sql.append(");")
        sql.append("")
    tipo_regimen = next(t for n, t in tipos_regimen if n == "IdRegimenTributario")
    VISTAS["BSCL.Portafolio.BD::POR.MatrizAgrupadorAPV"] = [("IdMatrizAgrupadorAPV", "BIGINT"), ("IdRegimenTributario", tipo_regimen)]
    for nombre, cols in VISTAS.items():
        sql.append('-- VIEW modelled as a table (assumption): ' + nombre)
        sql.append('CREATE TABLE "%s" (' % nombre)
        sql.append(",\n".join('  "%s" %s' % c for c in cols))
        sql.append(");")
        sql.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(sql) + "\n")
    print("schema written:", OUT, "tables:", len(TABLAS) + len(VISTAS))


main()
