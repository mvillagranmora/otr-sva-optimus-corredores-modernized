#!/usr/bin/env python3
"""Generates the four case-driven test classes from the case directories. Usage: python mktests.py <apv-jobs resources dir> <java dir cl/bcs/apv/jobs/job>."""
import json
import os
import re
import sys

RES, OUT = sys.argv[1], sys.argv[2]
JOBS = [('BcsJobCargaMasivaPrevired', 'CMP'), ('IngresarOrdenBonificacionFiscal', 'OBF'),
        ('IngresarOrdenFMBonificacionFiscal', 'FMB'), ('IngresarOrdenRVBonificacionFiscal', 'RVB')]

CAB = '''package cl.bcs.apv.jobs.job;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.List;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;

import cl.bcs.apv.jobs.support.CasoJob;
import cl.bcs.apv.jobs.support.EjecucionJob;
import cl.bcs.apv.jobs.support.VerificaJob;
import cl.bcs.apv.jobs.support.ZonaUtc;

/**
 * Characterization of the legacy {{@code cl.bcs.APV.jobs.{job}}} run by the legacy {{@code BcsJob.run()}} (one transaction, commit / rollback / error,
 * status): legacy parameters, new in-process job on H2 with scripted collaborators, compared with the golden RECORDED by executing the UNMODIFIED legacy
 * class ({{@code src/test/resources/apv-jobs/cases/APVJ-{pre}-*}}; never written by hand). Each test cites the legacy line it pins.
 * GENERATED by legacy-oracle/tools/mktests.py from the case directories: do not edit by hand, add a case and regenerate.
 */
@ExtendWith(ZonaUtc.class)
class {job}CasosTest {{

    static final List<String> CASOS = VerificaJob.casosDe("{job}");
    private static final CasoJob.Contador EJECUTADOS = new CasoJob.Contador();

    private static void verificar(String nombre) {{
        assertThat(CASOS).as("case directory present").contains(nombre);
        CasoJob caso = CasoJob.cargar(nombre);
        EJECUTADOS.ejecutado(nombre);
        EjecucionJob.Corrida r = EjecucionJob.ejecutar(caso);
        VerificaJob.comparar(caso, r);
    }}

    @AfterAll
    static void resumen() {{
        EJECUTADOS.imprimir("{job}");
        assertThat(EJECUTADOS.total()).as("equivalence cases executed (zero = not proven)").isGreaterThan(0);
    }}
'''


def java(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


for job, pre in JOBS:
    d = os.path.join(RES, 'cases')
    dirs = sorted(x for x in os.listdir(d) if x.startswith('APVJ-%s-' % pre))
    partes = [CAB.format(job=job, pre=pre)]
    for nombre in dirs:
        c = json.load(open(os.path.join(d, nombre, 'case.json'), encoding='utf-8'))
        cid = c['id']
        num = cid.split('-')[-1]
        slug = re.sub(r'-(\w)', lambda m: m.group(1).upper(), c['slug'])
        rule = (' [' + c['rule'] + ']') if c.get('rule') else ''
        partes.append('''
    // legacy %s
    @Test
    @DisplayName("%s%s %s")
    void apvj%s%s_%s() {
        verificar("%s");
    }
''' % (c['pina'], cid, rule, java(c['titulo']), pre.lower(), num, slug, nombre))
    partes.append('}\n')
    with open(os.path.join(OUT, job + 'CasosTest.java'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(''.join(partes))
    print(job, len(dirs))
