CREATE TABLE IF NOT EXISTS CLIENTES_T (
    ID_CLIENTE BIGINT      NOT NULL PRIMARY KEY,
    NOMBRE     VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS INDICADORES_FINANCIEROS_T (
    CODIGO_INDICADOR VARCHAR(10)   NOT NULL,
    FECHA_SISTEMA    VARCHAR(10)   NOT NULL,
    VALOR            DECIMAL(20,6) NOT NULL,
    PRIMARY KEY (CODIGO_INDICADOR, FECHA_SISTEMA)
);
