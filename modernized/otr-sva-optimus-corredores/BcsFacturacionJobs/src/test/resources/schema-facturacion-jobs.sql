CREATE TABLE CONFIGURACION_T (
    ID_EMPRESA BIGINT       NOT NULL,
    CLAVE      VARCHAR(100) NOT NULL,
    VALOR      VARCHAR(200),
    PRIMARY KEY (ID_EMPRESA, CLAVE)
);

CREATE TABLE COMPROBANTES_T (
    ID_COMPROBANTE   BIGINT         NOT NULL PRIMARY KEY,
    ID_EMPRESA       BIGINT         NOT NULL,
    ID_CLIENTE       BIGINT,
    MONTO_TOTAL      DECIMAL(18, 2),
    FECHA_COMPROBANTE DATE
);
