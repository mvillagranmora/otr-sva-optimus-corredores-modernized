    @Test
    @DisplayName("LOGIN-PG2 oracle integrity: the view-column fixtures hash to what the generator recorded (line endings ignored); 148 columns in 7 views (17, 13, 4, 5, 30, 8, 71)")
    void integridad_del_oraculo_de_vistas() throws Exception {
        JsonObject m = JsonParser.parseString(LoginPg2Recursos.texto("ORACULO_VISTAS_MANIFEST.json")).getAsJsonObject();
        for (String f : List.of("oraculo-vistas-columnas.csv", "vistas-columnas-pg-qa-20261103.tsv", "rutinas-y-tipos-postgres-qa-20261103.txt")) {
            String t = LoginPg2Recursos.texto(f).replace("\r", "");
            String h = java.util.HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(t.getBytes(StandardCharsets.UTF_8)));
            assertEquals(m.getAsJsonObject("sha256").get(f).getAsString(), h, "sha256 of " + f);
        }
        assertEquals(148, m.get("columnas_total").getAsInt());
        assertEquals(148, VISTAS.filas.size());
        Map<String, Integer> porVista = new LinkedHashMap<>();
        VISTAS.filas.forEach(f -> porVista.merge(f.vistaPg(), 1, Integer::sum));
        assertEquals(Map.of("v_pla_acc_consultar_usuario_acceso", 17, "v_pla_ctt_consultar_contrato_datos_generales", 13, "v_pla_pla_consultar_configuracion_grilla", 4,
                "v_pla_pla_consultar_configuracion_usuario", 5, "v_pla_pla_consultar_empresa", 30, "v_pla_pla_consultar_imagen", 8, "v_socneg_per_consultar_persona", 71), porVista);
    }

    @Test
    @DisplayName("LOGIN-PG2 oracle: the 7 views are exactly the 7 views of the login scope, with the Postgres name of the xlsx; no view column repeats; names are snake_case")
    void las_siete_vistas_y_sus_nombres() {
        Set<String> alcance = new HashSet<>();
        vistasLogin().forEach(alcance::add);
        assertEquals(7, alcance.size());
        assertEquals(alcance, VISTAS.columnas.keySet());
        VISTAS.vistaPg.forEach((hana, pg) -> assertEquals(XLSX.objeto(hana).postgres(), pg, "Postgres name of " + hana));
        VISTAS.columnas.forEach((v, cols) -> {
            assertEquals(cols.size(), new HashSet<>(cols.values()).size(), "Postgres column names unique in " + v);
            assertEquals(cols.size(), new HashSet<>(cols.keySet()).size(), "HANA column names unique in " + v);
            cols.values().forEach(c -> assertTrue(c.matches("[a-z][a-z0-9_]*"), "column format " + c));
        });
    }

    @Test
    @DisplayName("LOGIN-PG2 oracle: the Postgres columns of the oracle are exactly the ones of the QA catalog rows (name and count), and the derivation rule reproduces every cited column")
    void el_oraculo_coincide_con_las_filas_del_catalogo_y_la_regla_con_lo_citado() {
        VISTAS.tiposPg.forEach((vistaPg, cols) -> {
            String hana = VISTAS.vistaPg.entrySet().stream().filter(e -> e.getValue().equals(vistaPg)).findFirst().orElseThrow().getKey();
            assertEquals(new HashSet<>(cols.keySet()), new HashSet<>(VISTAS.columnas.get(hana).values()), "columns of " + vistaPg);
        });
        for (String[] c : CITADAS) {
            assertEquals(c[2], VISTAS.columnas.get(c[0]).get(c[1]), "cited column " + c[0] + "." + c[1]);
        }
        VISTAS.columnas.forEach((v, cols) -> cols.forEach((h, p) -> assertEquals(LoginPg2Recursos.pascal(p), h, "derivation rule in " + v)));
    }

    @Test
    @DisplayName("LOGIN-PG2 the xlsx oracle is untouched: it still has NO column for a view (the view columns come from the QA catalog, a second source)")
    void el_xlsx_sigue_sin_vistas() {
        for (String v : VISTAS.columnas.keySet()) assertFalse(XLSX.columnas.containsKey(v), v);
    }

    @Test
    @DisplayName("LOGIN-PG2 a missing view-column fixture FAILS (FIXTURE MISSING), never skipped")
    void fixture_ausente_falla() {
        assertThatThrownBy(() -> LoginPg2Recursos.texto("no-existe.csv")).isInstanceOf(AssertionError.class).hasMessageContaining("FIXTURE MISSING");
    }

    @ParameterizedTest(name = "A3-6(a) cited view column {0}.{1} -> {2} is in the QA catalog oracle (pinned by hand from the HANA text and the catalog)")
    @MethodSource("citadas")
    void columnas_citadas_existen_en_el_oraculo(String vista, String hana, String pg) {
        assertEquals(pg, VISTAS.columnas.get(vista).get(hana));
        assertThat(VISTAS.tiposPg.get(XLSX.objeto(vista).postgres())).containsKey(pg);
    }

    @Test
    @DisplayName("LOGIN-PG2 view columns of the oracle: the same HANA column name appears in several views (resolved per object, never globally)")
    void mismas_columnas_en_varios_objetos() {
        Map<String, Set<String>> porNombre = new HashMap<>();
        VISTAS.columnas.forEach((v, cols) -> cols.keySet().forEach(c -> porNombre.computeIfAbsent(c, k -> new HashSet<>()).add(v)));
        assertThat(porNombre.get("IdEmpresa")).hasSizeGreaterThanOrEqualTo(4);
        assertThat(porNombre.get("Llave")).hasSize(2);
    }
