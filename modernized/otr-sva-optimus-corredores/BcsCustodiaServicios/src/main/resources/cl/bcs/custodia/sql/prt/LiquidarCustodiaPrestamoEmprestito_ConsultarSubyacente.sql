SELECT DISTINCT
     SUB."IdSubyacente"
    ,SUB."FolioSubyacente"
    ,SUB."FolioCarteraRelacionada" 
    ,SUB."IdEstado"
    ,SUB."INGCantidad" AS "Cantidad"
    ,SUB."INGValorRescate" AS "ValorRescate" 
    ,SUB."IdInstrumento"
    ,SUB."PrecioCompraOperacionRelacionada"    
    ,SUB."TasaCompraOperacionRelacionada"
    ,CAR."IdCartera" AS "IdCarteraOrigen" 
    ,CAR."IdTipoOperacion" AS "IdTipoOperacionOrigen"
    ,CAR."IdCliente"
	,CAR."IdPortafolio"
	,CAR."IdBoveda"
    ,SUB."IdInstrumento"
    ,SUB."IdMonedaInstrumento"
    ,SUB."IdEmisor"
    ,SUB."IdTipoCanalIngreso"
    ,SUB."Nemotecnico"
    ,SUB."IdTipoReajuste"
    ,SUB."EsFungible"
    ,SUB."FechaVencimientoInstrumento"
    ,SUB."FechaEmisionInstrumento"
    ,SUB."NemoSVS"
    ,SUB."CorteMinimo"
    ,SUB."INGPrecioSubyacente" AS "PrecioSubyacente"
    ,SUB."INGTasaSubyacente" AS "TasaSubyacente" 
    ,SUB."INGMontoATasaSubyacenteActual" AS "MontoATasaSubyacenteActual"
    ,SUB."INGMontoSubyacenteActualMonedaInstrumento" AS "MontoATasaSubyacenteActualMonedaInstrumento" 
    ,CAR."Cantidad" as "CantidadInicial"
    ,CAR."MontoCompraMonedaInstrumento"
    ,CAR."INGCantidad"
    ,SUB."IdMonedaEmision"    
    ,COALESCE(ip."ValorIndicador",'N') AS "OperaContraCuentaInversion"
    ,IFNULL(ATR."ValorIndicador",'N') AS "ConCustodiaPrestatario"
    ,SUB."IdCarteraRetirada"
    ,CAR."IdTipoProducto"
    ,SUB."IdTipoInstrumento"
    , CAR."INGMontoCompraActualMonedaInstrumento" AS "INGMontoCompraMonedaInstrumento"
     ,TO_NVARCHAR(CAR."FechaOperacion", 'YYYY-MM-DD') AS "FechaOperacion"
FROM "BSCL.Custodia.BD.Vistas::CUS.ConsultarTablaSubyacente" AS SUB
INNER JOIN "BSCL.Custodia.BD::CUS.Cartera" AS CAR ON (CAR."FolioCartera" = SUB."FolioCarteraRelacionada" AND CAR."IdEstado" = 'VIG')
LEFT JOIN "BSCL.Plataforma.BD.Vistas::IND.ConsultarIndicadoresPortafolio" ip on ip."IdPortafolio" = CAR."IdPortafolio" and ip."CodigoTipoIndicador" = 'GEN_OCCINV'
LEFT JOIN "BSCL.Plataforma.BD::IND.TipoIndicador" TPO ON TPO."CodigoTipoIndicador" = 'CC'
LEFT JOIN "BSCL.Plataforma.BD::IND.Indicador" ATR ON ATR."IdTipoIndicador" = TPO."IdTipoIndicador" AND ATR."IdTipoEntidad" = 'CLIENTE' AND ATR."IdEntidad" = TO_VARCHAR(CAR."IdCliente")
WHERE SUB."IdEstado" = 'VIG' AND SUB."FolioCarteraRelacionada" IN (:FolioCarteras)
