-- Obtiene EVC desde Ruebas
 SELECT 
	 ACF.MERCADO AS ACF_MERCADO 
	,ACF.NEMO AS ACF_NEMO 
	,CAST(ACF.SEC_VC AS  BIGINT)	AS ACF_SEC_VC 
	,ACF.DESCRIP_VC	AS ACF_DESCRIP_VC 
	,ACF.FAC_ACC_ANT AS ACF_FAC_ACC_ANT 
	,ACF.FAC_ACC_NUE	AS ACF_FAC_ACC_NUE 
	,ACF.FEC_ACT_VC	AS ACF_FEC_ACT_VC 
	,ACF.FEC_LIM	AS ACF_FEC_LIM 
	,ACF.FEC_PAGO	AS ACF_FEC_PAGO 
	,ACF.NEMO_2	AS ACF_NEMO_2 
	,ACF.NUM_ACC_ANT	AS ACF_NUM_ACC_ANT 
	,ACF.NUM_ACC_DER	AS ACF_NUM_ACC_DER 
	,ACF.NUM_ACC_NUE	AS ACF_NUM_ACC_NUE 
	,CAST(ACF.NUM_DIVDO	AS  BIGINT) AS ACF_NUM_DIVDO 
	,ACF.PRE_ANT_VC	AS ACF_PRE_ANT_VC 
	,ACF.PRE_EX_VC	AS ACF_PRE_EX_VC 
	,ACF.TIPO_VC	AS ACF_TIPO_VC 
	,ACF.TIPO_DIV	AS ACF_TIPO_DIV 
	,ACF.VAL_ACC	AS ACF_VAL_ACC 
	,ACF.VAL_AN_DS	AS ACF_VAL_AN_DS 
	,ACF.VAL_EX_DS	AS ACF_VAL_EX_DS 
	,ACF.VAL_LIB_AJU	AS ACF_VAL_LIB_AJU 
	,RTRIM(LTRIM(COALESCE(ACF.VIG_NAA,'')))	AS ACF_VIG_NAA 
	,ACF.VC_PROC	AS ACF_VC_PROC 
	,RTRIM(LTRIM(COALESCE(ACF.MONEDA,'')))	AS ACF_MONEDA 
	,ACV.MERCADO	AS ACV_MERCADO 		
	,RTRIM(LTRIM(COALESCE(ACV.NEMO,'')))	AS ACV_NEMO 
	,CAST(ACV.SEC_VC AS BIGINT)	AS ACV_SEC_VC 
	,CAST(ACV.INDICE AS BIGINT)	AS ACV_INDICE 
	,ACV.DESCRIP_VC	AS ACV_DESCRIP_VC 
	,ACV.FAC_ACC_ANT	AS ACV_FAC_ACC_ANT 
	,ACV.FAC_ACC_NUE	AS ACV_FAC_ACC_NUE 
	,ACV.FEC_ACT_VC	AS ACV_FEC_ACT_VC 
	,ACV.FEC_LIM	AS ACV_FEC_LIM 
	,ACV.FEC_PAGO	AS ACV_FEC_PAGO 
	,RTRIM(LTRIM(COALESCE(ACV.NEMO_2,'')))	AS ACV_NEMO_2 
	,ACV.NUM_ACC_ANT	AS ACV_NUM_ACC_ANT 
	,ACV.NUM_ACC_DER	AS ACV_NUM_ACC_DER 
	,ACV.NUM_ACC_NUE	AS ACV_NUM_ACC_NUE 
	,ACV.NUM_DIVDO	AS ACV_NUM_DIVDO 
	,ACV.PRE_ANT_VC	AS ACV_PRE_ANT_VC 
	,ACV.PRE_EX_VC	AS ACV_PRE_EX_VC 
	,ACV.TIPO_VC	AS ACV_TIPO_VC 
	,ACV.TIPO_DIV	AS ACV_TIPO_DIV 
	,ACV.VAL_ACC	AS ACV_VAL_ACC 
	,ACV.VAL_AN_DS	AS ACV_VAL_AN_DS 
	,ACV.VAL_EX_DS	AS ACV_VAL_EX_DS 
	,ACV.VAL_LIB_AJU	AS ACV_VAL_LIB_AJU
	,ACV.VIG_NAA	AS ACV_VIG_NAA 
	,ACV.VC_PROC	AS ACV_VC_PROC 
	,RTRIM(LTRIM(COALESCE(ACV.MONEDA,'')))	AS ACV_MONEDA 
	,ACV.USUARIO_MOD	AS ACV_USUARIO_MOD
	,ACV.TERMINAL_MOD	AS ACV_TERMINAL_MOD 
	,ACV.TIPO_MOD	AS ACV_TIPO_MOD 
	,ACV.HORA_MOD	AS ACV_HORA_MOD 
FROM TBACFVC ACF
INNER JOIN TBACVCLO ACV
	ON (ACF.MERCADO = ACV.MERCADO AND ACF.NEMO = ACV.NEMO AND ACF.SEC_VC = ACV.SEC_VC)
WHERE 
	(
		ACF.FEC_LIM BETWEEN :p_Fecha_inicio AND :p_Fecha_fin
		OR LEFT(ACV.HORA_MOD,10) BETWEEN :p_Fecha_inicio AND :p_Fecha_fin
	)
	AND RTRIM(LTRIM(COALESCE(ACF.NEMO,''))) <> ''; -- Los dividendos que en Ruebas estn sin factor o sin moneda entran igual a optimus	
	
