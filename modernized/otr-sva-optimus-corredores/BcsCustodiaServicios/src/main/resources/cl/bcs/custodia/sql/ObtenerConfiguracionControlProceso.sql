SELECT "ControlProceso"
FROM "BSCL.Plataforma.BD::EVT.ConfiguracionEvento" ce
WHERE "Descripcion" IN (:CodigoEvento) OR "Descripcion" IN (
CASE 
	WHEN 'CIERRE_EVENTO_CAPITAL_CC' IN(:CodigoEvento) THEN 'NOT_CIERRE_EVENTO_CC' 
	WHEN 'CIERRE_EVENTO_CAPITAL_VARIOS' IN(:CodigoEvento) THEN 'NOT_CIERRE_EVENTO_VARIOS'
	WHEN 'CIERRE_EVENTO_CAPITAL_DV' IN(:CodigoEvento) THEN 'NOT_CIERRE_EVENTO_DV'
	WHEN 'CIERRE_EVENTO_CAPITAL_SL' IN(:CodigoEvento) THEN 'NOT_CIERRE_EVENTO_SL'
END)