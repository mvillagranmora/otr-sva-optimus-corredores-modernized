CREATE TABLE IF NOT EXISTS CONFIGURACION_T (
  ID_EMPRESA BIGINT NOT NULL,
  ID_CONFIGURACION VARCHAR(100) NOT NULL,
  VALOR VARCHAR(500),
  PRIMARY KEY (ID_EMPRESA, ID_CONFIGURACION)
);

CREATE TABLE IF NOT EXISTS COMPROBANTES_T (
  ID_COMPROBANTE BIGINT NOT NULL PRIMARY KEY,
  ID_EMPRESA BIGINT,
  ID_TIPO_COMPROBANTE VARCHAR(10),
  ESTADO VARCHAR(20),
  FECHA_COMPROBANTE VARCHAR(10)
);
