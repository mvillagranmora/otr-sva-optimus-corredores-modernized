	  ,"IdTipoContrato"
	  ,"NombreContrato"
	  ,"IdCliente"
	  ,"IdPortafolio"
	  ,"IdFormatoCobro"
	  ,"IdMoneda"
	  ,"IdEmpresa"
	  ,"IdEstado"
	  ,"IdClasificacionTipoInstrumento"
	  ,"IdDetalleContratoComision"
	  ,"CodigoCobroClasificacion"
	  ,"IdCobro"
	  ,"IdConcepto"
	  ,"EsPorRangos"
	  ,"MontoMinimo"
	  ,"MontoMaximo"
	  ,"MontoRango"
	  ,"PorcentajeRango"
	  ,"MontoMaximoRango"
  FROM "BSCL.Facturacion.BD.Vistas::ConsultarResumenContrato"
