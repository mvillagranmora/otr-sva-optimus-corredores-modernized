CREATE TABLE IF NOT EXISTS PORTAFOLIOS_T (
    ID_PORTAFOLIO              BIGINT       NOT NULL PRIMARY KEY,
    ID_CLIENTE                 BIGINT       NOT NULL,
    DOCUMENTO_IDENTIDAD        VARCHAR(20)  NOT NULL,
    ID_INDICADOR               BIGINT       NOT NULL DEFAULT 0,
    ID_FORMA_COBRO             VARCHAR(20),
    ID_CATEGORIA_INVERSIONISTA VARCHAR(20),
    ID_PERFIL_COMERCIAL        VARCHAR(20),
    ID_PERFIL_COBROS           VARCHAR(20),
    ID_PERFIL_PRODUCTOS        VARCHAR(20),
    PROPOSITO                  VARCHAR(50),
    ACTUALIZAR_FORMA_COBRO     VARCHAR(1)   NOT NULL DEFAULT 'S'
);

CREATE TABLE IF NOT EXISTS PERFILES_COMERCIALES_T (
    ID_PORTAFOLIO              BIGINT       NOT NULL PRIMARY KEY,
    ID_CLIENTE                 BIGINT       NOT NULL,
    DOCUMENTO_IDENTIDAD        VARCHAR(20)  NOT NULL,
    ID_INDICADOR               BIGINT       NOT NULL DEFAULT 0,
    ID_FORMA_COBRO             VARCHAR(20),
    ID_CATEGORIA_INVERSIONISTA VARCHAR(20),
    ID_PERFIL_COMERCIAL        VARCHAR(20),
    ID_PERFIL_COBROS           VARCHAR(20),
    ID_PERFIL_PRODUCTOS        VARCHAR(20),
    PROPOSITO                  VARCHAR(50),
    ACTUALIZAR_FORMA_COBRO     VARCHAR(1)   NOT NULL DEFAULT 'S'
);

CREATE TABLE IF NOT EXISTS INDICADORES_PORTAFOLIO_T (
    ID_INDICADOR    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_ENTIDAD      BIGINT       NOT NULL,
    VALOR_INDICADOR VARCHAR(50)  NOT NULL
);
