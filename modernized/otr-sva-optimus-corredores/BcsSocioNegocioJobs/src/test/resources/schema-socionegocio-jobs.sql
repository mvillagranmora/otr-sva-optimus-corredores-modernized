CREATE TABLE IF NOT EXISTS CONFIGURACION_T (
    ID_EMPRESA   BIGINT,
    CLAVE        VARCHAR(100),
    VALOR        VARCHAR(200),
    PRIMARY KEY (ID_EMPRESA, CLAVE)
);

CREATE TABLE IF NOT EXISTS DOCUMENTOS_CLIENTE_T (
    ID_CLIENTE        BIGINT,
    ID_ANEXO          BIGINT PRIMARY KEY,
    ID_ESTADO         VARCHAR(10),
    BLOQUEAR_AL_VENCER VARCHAR(1),
    FECHA_VIGENCIA    DATE,
    FECHA_MODIFICACION DATE
);

CREATE TABLE IF NOT EXISTS CLIENTES_T (
    ID_CLIENTE        BIGINT PRIMARY KEY,
    ID_TIPO_BLOQUEO   VARCHAR(20),
    COMENTARIO_BLOQUEO VARCHAR(500)
);
