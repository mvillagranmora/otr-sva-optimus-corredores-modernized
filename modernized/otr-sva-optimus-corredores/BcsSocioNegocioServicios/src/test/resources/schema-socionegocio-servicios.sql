CREATE TABLE IF NOT EXISTS CONFIGURACION_T (
  ID_EMPRESA BIGINT NOT NULL,
  ID_CONFIGURACION VARCHAR(100) NOT NULL,
  VALOR VARCHAR(500),
  PRIMARY KEY (ID_EMPRESA, ID_CONFIGURACION)
);
CREATE TABLE IF NOT EXISTS SOCIOS_NEGOCIO_T (
  ID_CLIENTE BIGINT NOT NULL PRIMARY KEY,
  DOCUMENTO_IDENTIDAD VARCHAR(50),
  ID_TIPO_DOCUMENTO VARCHAR(20),
  ESTADO VARCHAR(20)
);
