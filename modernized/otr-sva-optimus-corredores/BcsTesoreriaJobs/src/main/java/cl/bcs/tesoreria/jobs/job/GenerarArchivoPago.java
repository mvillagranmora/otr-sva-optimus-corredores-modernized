/**
 * Legacy {@code cl.bcs.tesoreria.generarArchivoPago.GenerarArchivoPago} (418 lines, with {@code Archivo}, {@code FormatoArchivo},
 * {@code FormatoArchivoDetalle}): the bank payment file job. The format is read from the view {@code ConsultarFormatoArchivo} by
 * empresa, banco, moneda and medio de pago ({@link FormatoPago}); BANCO_ESTADO_CLP_TRADVP is generated by
 * {@link GenerarArchivoPagos}; every other format by the stored procedure ({@link ProcedimientoArchivo}), either generic
 * (TXT / txt / DAT lines or CSV) or BCP_PEN_TBC_TELECREDITO ({@link GeneradorPago}). Then
 * {@code TES.NominaTransferencia.NombreArchivo} is updated and {@code BAT.Programa.RutaSalida} gets
 * {@code <RutaTesoreria><file name>}. Rules: RULE-061 (no {@code running} flag), RULE-076 (debug mode not ported).
 *
 * <p>Legacy defects kept bug for bug (README): TES-J-DEF-06 and 07 (format lookup), 08 (file not transactional), 09 and 10 (file
 * creation), 11 and 12 (CSV / BancoEstado); every failure is wrapped twice in {@link Exception}.
 */
public final class GenerarArchivoPago implements TesoreriaJob {

    public static final String CLASE = "cl.bcs.tesoreria.generarArchivoPago.GenerarArchivoPago";

    private static final Logger log = LoggerFactory.getLogger(GenerarArchivoPago.class);

    private final ProcedimientoArchivo procedimientos;
    private final ConfiguracionSistema configuracion;
    private final JdbcTemplate jdbc;
    private final Clock clock;
    private final GenerarArchivoPagos bancoEstado;

    public GenerarArchivoPago(ProcedimientoArchivo procedimientos, ConfiguracionSistema configuracion, JdbcTemplate jdbc,
                              Clock clock) {
        this.procedimientos = Objects.requireNonNull(procedimientos, "procedimientos");
        this.configuracion = Objects.requireNonNull(configuracion, "configuracion");
        this.jdbc = Objects.requireNonNull(jdbc, "jdbc");
        this.clock = Objects.requireNonNull(clock, "clock");
        this.bancoEstado = new GenerarArchivoPagos(jdbc);
    }

    @Override
    public String clase() {
        return CLASE;
    }

    /** Legacy :78-81 {@code transaction} and :253-258 the outer {@code catch}. */
    @Override
    public boolean transaction(JobContext ctx) throws Exception {
        log.info("== INICIO JOB ==");
        try {
            logica(ctx);
        } catch (Exception e) {
            log.error("ERROR GENERAL > {}", e.getMessage());
            throw new Exception(e);
        }
        return true;
    }

    /** Legacy :91-260 {@code logica(false, conn)}. */
    private void logica(JobContext ctx) throws Exception {
        Long idEmpresa = Long.parseLong(ctx.getParam("IdEmpresa"));
        Long idNominaTransferencia = Long.parseLong(ctx.getParam("IdNominaTransferencia"));
        Long idBanco = Long.parseLong(ctx.getParam("IdBanco"));
        String idMoneda = String.valueOf(ctx.getParam("IdMoneda"));
        String idMedioDePago = String.valueOf(ctx.getParam("IdMedioDePago"));

        FormatoPago formatoArchivo = new FormatoPago(jdbc, idEmpresa, idNominaTransferencia, idBanco, idMoneda, idMedioDePago);
        formatoArchivo.setIdEmpresa(idEmpresa);
        formatoArchivo.setIdNominaTransferencia(idNominaTransferencia);
        formatoArchivo.setIdBanco(idBanco);
        formatoArchivo.setIdMoneda(idMoneda);
        formatoArchivo.setIdMedioDePago(idMedioDePago);

        if (formatoArchivo.getCantidadDeTiposDeRegistro() == 0) { // NPE when the format was not loaded (TES-J-DEF-06)
            log.info("NO EXISTE FORMATO CONFIGURADO PARA GENERAR EL ARCHIVO");
            return;
        }
        ArchivoPago archivo = new ArchivoPago(formatoArchivo, clock);
        try {
            if (formatoArchivo.getCodigoFormatoArchivo().equalsIgnoreCase("BANCO_ESTADO_CLP_TRADVP")) {
                EntradaGenerarArchivoPagos entrada = new EntradaGenerarArchivoPagos();
                entrada.p_Fecha = ConfiguracionLegacy.parametro(configuracion, Long.parseLong(ctx.getParam("IdEmpresa")),
                        ConfiguracionLegacy.PLATAFORMA, "PLA.FechaSistema");
                entrada.p_IdEmpresa = idEmpresa;
                entrada.p_IdModulo = "TES";
                entrada.p_IdNominaTransferencia = idNominaTransferencia;
                entrada.p_Archivo = archivo;
                bancoEstado.logica(entrada);
            } else {
                String paramSp = "?,?,?,?,?";
                for (int i = 0; i < formatoArchivo.getCantidadDeTiposDeRegistro(); i++) {
                    paramSp = paramSp + ",?";
                }
                String callSp = String.format("CALL \"%s\"(%s)", formatoArchivo.getServicio(), paramSp);
                List<Object> parametros = new ArrayList<>();
                parametros.add((long) formatoArchivo.getIdEmpresa());
                parametros.add((long) formatoArchivo.getIdNominaTransferencia());
                parametros.add((long) formatoArchivo.getIdFormatoArchivo());
                parametros.add(formatoArchivo.getIdMoneda());
                parametros.add(formatoArchivo.getIdMedioDePago());

                List<ResultadoProcedimiento> resultados = procedimientos.ejecutar(callSp, parametros);
                if (resultados.isEmpty()) {
                    log.info("NO EXISTE DATA PARA GENERAR EL ARCHIVO");
                    return;
                }
                archivo.crear();
                if (formatoArchivo.getCodigoFormatoArchivo().equalsIgnoreCase("BCP_PEN_TBC_TELECREDITO")) {
                    GeneradorPago.bcpTelecredito(resultados, formatoArchivo, archivo);
                } else {
                    GeneradorPago.generico(resultados, formatoArchivo, archivo);
                }
                archivo.cerrar();
                log.info("ARCHIVO CREADO EXITOSAMENTE EN > {}{}", formatoArchivo.getRutaCompleta(), archivo.getNombreArchivo());
            }
            formatoArchivo.actualizarTransferencia(archivo.getNombreArchivo());
            ctx.updateRutaSalida(formatoArchivo.getRutaTesoreria() + archivo.getNombreArchivo(), ctx.idPrograma());
            ctx.commit();
        } catch (Exception ex) {
            log.error("ERROR AL GENERAR ARCHIVO > {}", ex.getMessage());
            archivo.abandonar();
            throw new Exception(ex);
        }
        log.info("== FIN JOB ==");
    }
}
