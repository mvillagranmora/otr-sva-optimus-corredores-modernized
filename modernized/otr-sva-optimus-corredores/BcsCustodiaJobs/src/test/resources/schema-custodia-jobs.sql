CREATE TABLE IF NOT EXISTS CONFIGURACION_T (
    ID_EMPRESA BIGINT      NOT NULL,
    CLAVE      VARCHAR(100) NOT NULL,
    VALOR      VARCHAR(200),
    PRIMARY KEY (ID_EMPRESA, CLAVE)
);

CREATE TABLE IF NOT EXISTS INSTRUMENTOS_PRECIO_T (
    ID_INSTRUMENTO BIGINT          NOT NULL,
    ID_EMPRESA     BIGINT          NOT NULL,
    CODIGO_NEMO    VARCHAR(20),
    PRECIO         DECIMAL(18, 6),
    FECHA_PRECIO   DATE,
    PRIMARY KEY (ID_INSTRUMENTO, FECHA_PRECIO)
);

CREATE TABLE IF NOT EXISTS POSICION_CUSTODIA_T (
    ID_CLIENTE     BIGINT          NOT NULL,
    ID_EMPRESA     BIGINT          NOT NULL,
    ID_MONEDA      VARCHAR(10)     NOT NULL,
    CANTIDAD       DECIMAL(18, 4),
    VALOR_MERCADO  DECIMAL(18, 2),
    FECHA_POSICION DATE            NOT NULL,
    PRIMARY KEY (ID_CLIENTE, ID_MONEDA, FECHA_POSICION)
);
